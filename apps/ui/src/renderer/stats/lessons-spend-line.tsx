import type { UsageGroup } from '../autogenerated';
import { formatTokens, formatUsd, markEstimate } from '../chats/agent-activity';

function stepText(label: string, group: UsageGroup): string {
  const { costUsd, estimatedCostUsd, turns, inputTokens, outputTokens } =
    group.totals;
  const tokens =
    inputTokens === null && outputTokens === null
      ? null
      : (inputTokens ?? 0) + (outputTokens ?? 0);
  const cost =
    costUsd === null
      ? null
      : markEstimate(formatUsd(costUsd), estimatedCostUsd);
  const detail = [
    tokens === null ? null : `${formatTokens(tokens)} tokens`,
    `${turns} ${turns === 1 ? 'turn' : 'turns'}`,
  ]
    .filter((part): part is string => part !== null)
    .join(' · ');
  return cost === null ? `${label} ${detail}` : `${label} ${cost} (${detail})`;
}

/**
 * The period's spend on lessons, as the daemon summed it (`byPurpose`): the
 * reflections and, when one ran, the check. Nothing when neither ran. Kept out
 * of the breakdowns above, which read the user's own work.
 */
export function LessonsSpendLine({
  groups,
}: {
  groups: readonly UsageGroup[];
}): React.JSX.Element | null {
  const reflections = groups.find((group) => group.key === 'lessons');
  const check = groups.find((group) => group.key === 'lessons_check');
  if (reflections === undefined && check === undefined) {
    return null;
  }
  const steps = [
    reflections === undefined
      ? null
      : stepText('reflections spent', reflections),
    check === undefined ? null : stepText('check', check),
  ].filter((step): step is string => step !== null);
  return (
    <p data-slot="lessons-spend" className="px-1 text-xs text-muted-foreground">
      <span className="font-medium text-foreground">Lessons</span> —{' '}
      {steps.join(' · ')} in this period.
    </p>
  );
}
