/**
 * Every stat on the page, as `label → value` — the hero, its supporting
 * figures, and the metric grid alike.
 *
 * Read off the `stat` / `stat-label` / `stat-value` slots rather than by
 * counting spans, which is what the previous helper did: it silently matched
 * only cards with exactly two spans, so adding an icon to a card would have
 * dropped it out of the map and every assertion about it with it.
 */
function cards(el: HTMLElement): Record<string, string> {
  const entries: Record<string, string> = {};
  for (const stat of el.querySelectorAll('[data-slot="stat"]')) {
    const label = stat.querySelector('[data-slot="stat-label"]')?.textContent;
    const value = stat.querySelector('[data-slot="stat-value"]')?.textContent;
    if (label !== null && label !== undefined) {
      entries[label] = value ?? '';
    }
  }
  return entries;
}

const buttonNamed = (el: HTMLElement, label: string): HTMLButtonElement =>
  [...el.querySelectorAll('button')].find(
    (node) => node.textContent === label,
  ) as HTMLButtonElement;

describe('Stats', () => {
  beforeEach(() => {
    mocks.readUsageStats.mockResolvedValue(stats());
    mocks.listTeams.mockResolvedValue([{ slug: 'dev-team', name: 'Dev Team' }]);
  });

  it('shows the period’s headline figures', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    expect(cards(el)).toMatchObject({
      Spent: '$2.50',
      Turns: '4',
      'Tokens in': '1k',
      'Agent time': '1h 0m',
    });
  });

  it('says what lessons reflections spent in the period, and nothing when none ran', async () => {
    const quiet = await render(<Stats handle={HANDLE} />);
    expect(quiet.querySelector('[data-slot="lessons-spend"]')).toBeNull();

    mocks.readUsageStats.mockResolvedValue(
      stats({
        byPurpose: [
          {
            key: 'lessons',
            totals: {
              ...totals(),
              costUsd: 0.31,
              estimatedCostUsd: null,
              turns: 14,
            },
          },
        ],
      }),
    );
    const el = await render(<Stats handle={HANDLE} />);

    const line = el.querySelector('[data-slot="lessons-spend"]');
    expect(line?.textContent).toContain('$0.31');
    expect(line?.textContent).toContain('14 turns');
  });

  it('shows the goals of the period’s threads and every tool and MCP server called', async () => {
    const base = stats();
    mocks.readUsageStats.mockResolvedValue(
      stats({
        metrics: {
          ...base.metrics,
          goals: {
            ...base.metrics.goals,
            recorded: 4,
            achieved: 3,
            achievedShare: 0.75,
            runsWithGoals: 2,
            measuredRuns: 3,
            coverage: 2 / 3,
          },
          tools: [
            { tool: 'Bash', mcpServer: null, calls: 7, errors: 1, avgMs: 900 },
            {
              tool: 'codegraph_explore',
              mcpServer: 'codegraph',
              calls: 3,
              errors: 0,
              avgMs: null,
            },
          ],
          mcpServers: [{ server: 'codegraph', calls: 3, errors: 0, tools: 1 }],
        },
      }),
    );
    const el = await render(<Stats handle={HANDLE} />);

    expect(cards(el)).toMatchObject({
      'Threads with goals': '67%',
      'Goals achieved': '75%',
      'Thread outcomes': '—',
    });
    expect(
      el.querySelector('table[aria-label="Tools"]')?.textContent,
    ).toContain('codegraph_explore · codegraph');
    expect(
      el.querySelector('table[aria-label="MCP servers"]')?.textContent,
    ).toContain('codegraph');
  });

  it('puts the measured figures above the charts, not below them', async () => {
    // REPORTED as "move those to the top". They qualify the headline figure, so
    // they belong under it — before, the split of the hero's own token count
    // was the LAST thing on the page, three sections and a scroll away from the
    // number it belonged to.
    //
    // Read off DOCUMENT ORDER rather than a class name: jsdom computes no
    // layout, so where a card is on screen is unobservable here, but which of
    // two nodes comes first is exactly what the grid order is made of.
    const el = await render(<Stats handle={HANDLE} />);

    const tokensIn = [...el.querySelectorAll('[data-slot="stat-label"]')].find(
      (node) => node.textContent === 'Tokens in',
    )!;
    const titled = (text: string): Element =>
      [...el.querySelectorAll('h3, [data-slot="card-title"]')].find(
        (node) => node.textContent === text,
      )!;
    const perDay = titled('Per day');
    const byAgent = titled('By agent');

    for (const later of [perDay, byAgent]) {
      expect(
        tokensIn.compareDocumentPosition(later) &
          Node.DOCUMENT_POSITION_FOLLOWING,
      ).toBeTruthy();
    }
  });

  it('renders an unreported figure as not-measured, never as zero', async () => {
    // The cursor-agent shape. A "$0.00" here would be a false statement about
    // money, and it is the single thing this page must never say.
    mocks.readUsageStats.mockResolvedValue(
      stats({ totals: totals({ costUsd: null, workedMs: null }) }),
    );

    const el = await render(<Stats handle={HANDLE} />);

    expect(cards(el).Spent).toBe('—');
    expect(cards(el)['Agent time']).toBe('—');
    expect(cards(el)['Cost per turn']).toBe('—');
  });

  it('marks the headline spend as an estimate, and says which part, when geniro priced some of it', async () => {
    mocks.readUsageStats.mockResolvedValue(
      stats({
        totals: totals({
          turns: 4,
          costedTurns: 4,
          costUsd: 8,
          estimatedCostUsd: 2,
        }),
      }),
    );

    const el = await render(<Stats handle={HANDLE} />);

    expect(cards(el).Spent).toBe('≈$8.00');
    expect(cards(el)['Cost per turn']).toBe('≈$2.00');
    const spent = [...el.querySelectorAll('[data-slot="stat"]')].find(
      (stat) =>
        stat.querySelector('[data-slot="stat-label"]')?.textContent === 'Spent',
    );
    expect(spent?.getAttribute('title')).toContain('geniro estimated');
  });

  it('leaves the headline spend plain when none of it was geniro’s estimate', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    expect(cards(el).Spent).toBe('$2.50');
    const spent = [...el.querySelectorAll('[data-slot="stat"]')].find(
      (stat) =>
        stat.querySelector('[data-slot="stat-label"]')?.textContent === 'Spent',
    );
    expect(spent?.getAttribute('title')).toBeNull();
  });

  it('averages cost over the turns that were priced, not over all of them', async () => {
    mocks.readUsageStats.mockResolvedValue(
      stats({
        totals: totals({ turns: 10, costedTurns: 4, costUsd: 8 }),
      }),
    );

    const el = await render(<Stats handle={HANDLE} />);

    // $2.00 (8/4), not $0.80 (8/10): the six turns that reported no cost
    // contributed nothing to the numerator, so counting them below the line
    // would understate what a priced turn actually costs.
    expect(cards(el)['Cost per turn']).toBe('$2.00');
  });

  it('derives the cache hit rate from what was reported', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    // 3000 cached against 1000 fresh.
    expect(cards(el)['Cache hit rate']).toBe('75%');
  });

  it('asks the daemon again when the period changes', async () => {
    const el = await render(<Stats handle={HANDLE} />);
    expect(mocks.readUsageStats).toHaveBeenCalledTimes(1);

    await act(async () => {
      buttonNamed(el, '7 days').click();
    });

    expect(mocks.readUsageStats).toHaveBeenCalledTimes(2);
    // "All time" is the only period that names no lower bound, so a 7-day pick
    // must carry one.
    expect(mocks.readUsageStats.mock.calls[1]![0]).toHaveProperty('from');
  });

  it('offers Today, and asks for that one calendar day', async () => {
    // REPORTED as "we need to add today". The narrowest period used to be a
    // week, in which today is one column of seven and the headline figure is
    // six other days — so "what has this cost me so far today" had no answer.
    const el = await render(<Stats handle={HANDLE} />);

    await act(async () => {
      buttonNamed(el, 'Today').click();
    });

    const asked = mocks.readUsageStats.mock.calls[1]![0] as {
      from?: string;
      to: string;
    };
    // A whole calendar day, not a rolling 24 hours: the lower bound is this
    // morning's local midnight, so the period does not slide into yesterday as
    // the afternoon wears on.
    const from = new Date(asked.from!);
    expect(from.getHours()).toBe(0);
    expect(from.getMinutes()).toBe(0);
    expect(from.toDateString()).toBe(new Date(asked.to).toDateString());
  });

  it('asks for the whole history when All time is picked', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    await act(async () => {
      buttonNamed(el, 'All time').click();
    });

    expect(mocks.readUsageStats.mock.calls[1]![0].from).toBeUndefined();
  });

  it('re-plots the daily chart without refetching when the metric changes', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    await act(async () => {
      buttonNamed(el, 'Tokens').click();
    });

    // Same period, different projection of data already in hand — a refetch
    // here would cost a round trip for a value the client already holds.
    expect(mocks.readUsageStats).toHaveBeenCalledTimes(1);
    // The toggle moved, which is what "re-plots" means from here. The plotted
    // series itself is asserted in `chart-data.spec.ts`: Recharts measures its
    // container to lay out, and jsdom reports every box as 0×0, so a chart
    // never paints under this environment. Asserting on the SVG here would pin
    // nothing — it is absent whether or not the metric switch works.
    expect(buttonNamed(el, 'Tokens').getAttribute('aria-pressed')).toBe('true');
    expect(buttonNamed(el, 'Spend').getAttribute('aria-pressed')).toBe('false');
  });

  it('offers the same metric choice as a dropdown, for a phone’s column', async () => {
    const el = await render(<Stats handle={HANDLE} />);
    const trigger = el.querySelector<HTMLButtonElement>(
      '[data-menu-trigger][aria-label="Daily metric"]',
    );
    expect(trigger).not.toBeNull();

    await act(async () => {
      trigger!.click();
    });
    const option = [
      ...el.querySelectorAll<HTMLElement>('[role="option"]'),
    ].find((candidate) => candidate.textContent?.includes('Tokens'));
    await act(async () => {
      option!.click();
    });

    // One choice, two renderings: the pick reaches the switch beside it.
    expect(buttonNamed(el, 'Tokens').getAttribute('aria-pressed')).toBe('true');
    expect(mocks.readUsageStats).toHaveBeenCalledTimes(1);
  });

  it('names each thread by its title, and says when one is deleted or untitled', async () => {
    // A thread is keyed by its run id, which names nothing a reader knows.
    const el = await render(<Stats handle={HANDLE} />);

    expect(el.textContent).toContain('By thread');
    expect(el.textContent).toContain('Fix the parser');
    expect(el.textContent).toContain('Deleted thread');
    expect(el.textContent).toContain('Untitled thread');
    expect(el.textContent).not.toContain('run-1');
  });

  it('lists each team bucket in the By team column, by name when it has one', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    expect(el.textContent).toContain('By team');
    expect(el.textContent).toContain('Dev Team');
    expect(el.textContent).not.toContain('dev-team');
    expect(el.textContent).toContain('review-team');
  });

  it('shortens a project path in the breakdown', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    expect(el.textContent).toContain('…/work/geniro-app');
  });

  it('surfaces a failed read instead of an empty page', async () => {
    mocks.readUsageStats.mockRejectedValue(
      new Error('daemon GET failed (500)'),
    );

    const el = await render(<Stats handle={HANDLE} />);

    expect(el.textContent).toContain('daemon GET failed (500)');
  });

  it('lets a failed read be dismissed, not only retried', async () => {
    mocks.readUsageStats.mockRejectedValue(
      new Error('daemon GET failed (500)'),
    );
    const el = await render(<Stats handle={HANDLE} />);

    const dismiss = [...el.querySelectorAll('button')].find(
      (node) => node.getAttribute('aria-label') === 'Dismiss error',
    ) as HTMLButtonElement;
    await act(async () => {
      dismiss.click();
    });
    // Flush whatever the click set in motion, so "the strip is still there"
    // is an observation rather than a race.
    await act(async () => {});

    // The strip's close control is the only way off a failure nothing the user
    // can type will clear (`ErrorBanner`) — and this screen already offers a
    // Retry beside it. Wired to the retry as well, the daemon being down means
    // the banner cannot be dismissed at all.
    expect(el.textContent).not.toContain('daemon GET failed (500)');
  });

  it('shows the period the daemon actually reported on', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    // The daemon clamps a request to what its ledger can answer for, so the
    // page must show the RESOLVED span — otherwise a short history under a long
    // period reads as a quiet quarter.
    expect(el.textContent).toContain('2026');
    expect(el.textContent).not.toContain('What your agents have used');
  });

  it('ignores a superseded response that lands after a newer one', async () => {
    // Two overlapping reads: the slow 30-day request must not overwrite the
    // 7-day figures the user is now looking at, and its failure must not raise
    // a banner for a period they already left. Nothing entered that guard
    // before, so deleting it left the suite green.
    let settleFirst: (value: UsageStatsDto) => void = () => undefined;
    let failFirst: (err: Error) => void = () => undefined;
    mocks.readUsageStats.mockReturnValueOnce(
      new Promise<UsageStatsDto>((resolve, reject) => {
        settleFirst = resolve;
        failFirst = reject;
      }),
    );
    mocks.readUsageStats.mockResolvedValueOnce(
      stats({ totals: totals({ turns: 99, costUsd: 7 }) }),
    );

    const el = await render(<Stats handle={HANDLE} />);
    await act(async () => {
      buttonNamed(el, '7 days').click();
    });

    // The newer read resolved; now let the superseded one land, both ways.
    await act(async () => {
      settleFirst(stats({ totals: totals({ turns: 1, costUsd: 0.01 }) }));
      failFirst(new Error('superseded failure'));
      await Promise.resolve();
    });

    expect(cards(el).Turns).toBe('99');
    expect(cards(el).Spent).toBe('$7.00');
    expect(el.textContent).not.toContain('superseded failure');
  });

  it('shows what the threads did over the period', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    expect(cards(el)).toMatchObject({
      Threads: '3',
      'Pull requests': '2',
      Lines: '+1,234',
      'Avg time per thread': '4m',
    });
  });

  it('states the lines removed beneath the lines added, flagged when they are a lower bound', async () => {
    mocks.readUsageStats.mockResolvedValue(
      stats({ activity: activity({ linesPartial: true }) }),
    );

    const el = await render(<Stats handle={HANDLE} />);

    expect(el.textContent).toContain('−56 removed · lower bound');
  });

  it('shows lines and average time as not measured when nothing was, never as zero', async () => {
    // A period with no snapshot taken has nothing to total: "+0" would claim the
    // threads changed no lines, which nobody measured.
    mocks.readUsageStats.mockResolvedValue(
      stats({
        activity: activity({
          linesAdded: null,
          linesRemoved: null,
          avgWorkedMs: null,
          threadsWithWorkedTime: 0,
        }),
      }),
    );

    const el = await render(<Stats handle={HANDLE} />);

    expect(cards(el).Lines).toBe('—');
    expect(cards(el)['Avg time per thread']).toBe('—');
    // With no thread's timing in the average there is no divisor to state.
    expect(el.textContent).not.toContain('over 0 threads');
  });

  it('names the threads an average is over, singular for one', async () => {
    mocks.readUsageStats.mockResolvedValue(
      stats({ activity: activity({ threadsWithWorkedTime: 1 }) }),
    );

    const el = await render(<Stats handle={HANDLE} />);

    expect(el.textContent).toContain('over 1 thread');
    expect(el.textContent).not.toContain('over 1 threads');
  });

  it('offers every daily figure on the switch, not only money and tokens', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    for (const label of [
      'Spend',
      'Tokens',
      'Threads',
      'Pull requests',
      'Lines',
      'Avg time',
    ]) {
      expect(buttonNamed(el, label)).toBeDefined();
    }
  });

  it('says it is connecting when there is no daemon handle yet', async () => {
    const el = await render(<Stats handle={null} />);

    expect(el.textContent).toContain('Connecting to the daemon');
    expect(mocks.readUsageStats).not.toHaveBeenCalled();
  });
});
