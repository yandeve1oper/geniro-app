import { describe, expect, it } from 'vitest';

import { LESSON_CORRECTION } from '../__fixtures__/lessons';
import type { ItemDto as ChatItem } from '../autogenerated';
import {
  foldLessonOutcomes,
  readLessonOutcome,
  readLessons,
} from './lessons-payload';

function row(seq: number, kind: ChatItem['kind'], payload: unknown): ChatItem {
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    memberId: null,
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

const PROPOSAL = {
  id: 'p-correction',
  title: LESSON_CORRECTION.title,
  rule: LESSON_CORRECTION.rule,
  why: LESSON_CORRECTION.why,
  signalKind: 'user_correction',
  evidence: { seq: 31, quote: 'не запускай vitest напрямую' },
  target: { kind: 'memory', scope: 'project', type: 'feedback' },
  dedup: { verdict: 'refines', handle: 'm12' },
};

const PLACES = {
  project: true,
  team: false,
  projectId: 'proj-1',
  members: [{ id: 'member-reviewer', name: 'Reviewer' }],
};

const LESSONS_PAYLOAD = {
  reflectionRunId: 'refl-1',
  segmentId: 'seg-1',
  fromSeq: 1,
  toSeq: 40,
  agentKind: 'claude',
  model: 'claude-haiku-5-5',
  proposals: [PROPOSAL],
  places: PLACES,
  check: null,
};

const CHECK = { runId: 'chk-1', agentKind: 'claude', model: 'claude-opus-5-5' };

const OUTCOME = {
  proposalId: 'p-correction',
  status: 'saved',
  by: 'user',
  title: LESSON_CORRECTION.title,
  rule: LESSON_CORRECTION.rule,
  target: { kind: 'memory', scope: 'team', type: 'feedback' },
  memoryHandle: 'm40',
  resultRef: null,
  reason: null,
};

function proposalWithTarget(target: unknown): unknown {
  return { ...PROPOSAL, target };
}

describe('readLessons', () => {
  it('reads a reflection with its proposals as the card draws them', () => {
    expect(readLessons(row(50, 'lessons', LESSONS_PAYLOAD))).toEqual({
      reflectionRunId: 'refl-1',
      segmentId: 'seg-1',
      agentKind: 'claude',
      model: 'claude-haiku-5-5',
      proposals: [
        {
          id: 'p-correction',
          title: LESSON_CORRECTION.title,
          rule: LESSON_CORRECTION.rule,
          why: LESSON_CORRECTION.why,
          signalKind: 'user_correction',
          evidence: { seq: 31, quote: 'не запускай vitest напрямую' },
          target: { kind: 'memory', scope: 'project', type: 'feedback' },
          dedup: { verdict: 'refines', handle: 'm12' },
        },
      ],
      places: PLACES,
      check: null,
    });
  });

  it('reads the check that re-read the lessons, when one ran', () => {
    expect(
      readLessons(row(50, 'lessons', { ...LESSONS_PAYLOAD, check: CHECK }))
        ?.check,
    ).toEqual(CHECK);
  });

  it('reads no check for a row written before the check existed', () => {
    const { check: _check, ...older } = LESSONS_PAYLOAD;

    expect(readLessons(row(50, 'lessons', older))?.check).toBeNull();
  });

  it('reads the places the thread has as the daemon wrote them', () => {
    expect(
      readLessons(
        row(50, 'lessons', {
          ...LESSONS_PAYLOAD,
          places: {
            ...PLACES,
            project: false,
            team: true,
            projectId: null,
            members: [],
          },
        }),
      )?.places,
    ).toEqual({
      project: false,
      team: true,
      projectId: null,
      members: [],
    });
  });

  it('offers every place a row written before the places were named', () => {
    expect(
      readLessons(row(50, 'lessons', { ...LESSONS_PAYLOAD, places: undefined }))
        ?.places,
    ).toEqual({
      project: true,
      team: true,
      projectId: null,
      members: [],
    });
  });

  it('reads a row written before the project and members were named with neither', () => {
    expect(
      readLessons(
        row(50, 'lessons', {
          ...LESSONS_PAYLOAD,
          places: { project: true, team: false },
        }),
      )?.places,
    ).toEqual({
      project: true,
      team: false,
      projectId: null,
      members: [],
    });
  });

  it('offers a place whose flag does not read as a boolean', () => {
    expect(
      readLessons(
        row(50, 'lessons', {
          ...LESSONS_PAYLOAD,
          places: { ...PLACES, project: 'no' },
        }),
      )?.places,
    ).toEqual({ ...PLACES, project: true });
  });

  it('drops a member that does not read and keeps the ones that do', () => {
    expect(
      readLessons(
        row(50, 'lessons', {
          ...LESSONS_PAYLOAD,
          places: {
            ...PLACES,
            members: [{ id: 'member-broken' }, { id: 'm-2', name: 'Writer' }],
          },
        }),
      )?.places.members,
    ).toEqual([{ id: 'm-2', name: 'Writer' }]);
  });

  it('reads a project-instructions target', () => {
    const card = readLessons(
      row(50, 'lessons', {
        ...LESSONS_PAYLOAD,
        proposals: [proposalWithTarget({ kind: 'project_instructions' })],
      }),
    );

    expect(card?.proposals[0]?.target).toEqual({
      kind: 'project_instructions',
    });
  });

  it('reads a member-instructions target with its member', () => {
    const card = readLessons(
      row(50, 'lessons', {
        ...LESSONS_PAYLOAD,
        proposals: [
          proposalWithTarget({
            kind: 'member_instructions',
            memberId: 'member-reviewer',
          }),
        ],
      }),
    );

    expect(card?.proposals[0]?.target).toEqual({
      kind: 'member_instructions',
      memberId: 'member-reviewer',
    });
  });

  it('reads a knowledge target, whether it files a new document or appends to one', () => {
    const card = readLessons(
      row(50, 'lessons', {
        ...LESSONS_PAYLOAD,
        proposals: [
          {
            ...PROPOSAL,
            id: 'p-new',
            target: { kind: 'knowledge', handle: null },
          },
          {
            ...PROPOSAL,
            id: 'p-append',
            target: { kind: 'knowledge', handle: 'k-release' },
          },
        ],
      }),
    );

    expect(card?.proposals.map((proposal) => proposal.target)).toEqual([
      { kind: 'knowledge', handle: null },
      { kind: 'knowledge', handle: 'k-release' },
    ]);
  });

  it('drops a proposal whose target kind it does not know and keeps the others', () => {
    const card = readLessons(
      row(50, 'lessons', {
        ...LESSONS_PAYLOAD,
        proposals: [proposalWithTarget({ kind: 'mystery' }), PROPOSAL],
      }),
    );

    expect(card?.proposals.map((proposal) => proposal.id)).toEqual([
      'p-correction',
    ]);
  });

  it('reads an empty proposal list as a reflection that proposed nothing', () => {
    const card = readLessons(
      row(50, 'lessons', { ...LESSONS_PAYLOAD, proposals: [] }),
    );

    expect(card).not.toBeNull();
    expect(card!.proposals).toEqual([]);
  });

  it('drops a proposal that does not read and keeps the ones that do', () => {
    const card = readLessons(
      row(50, 'lessons', {
        ...LESSONS_PAYLOAD,
        proposals: [{ id: 'broken' }, PROPOSAL],
      }),
    );

    expect(card!.proposals.map((proposal) => proposal.id)).toEqual([
      'p-correction',
    ]);
  });

  it.each([
    ['a payload that is not an object', 'junk'],
    [
      'a payload with no reflection',
      { ...LESSONS_PAYLOAD, reflectionRunId: '' },
    ],
    [
      'a proposals field that is not a list',
      { ...LESSONS_PAYLOAD, proposals: 'x' },
    ],
    ['an unknown agent kind', { ...LESSONS_PAYLOAD, agentKind: 'mystery-cli' }],
    [
      'proposals that all fail to read',
      { ...LESSONS_PAYLOAD, proposals: [{ id: 'broken' }] },
    ],
  ])('answers null for %s', (_label, payload) => {
    expect(readLessons(row(50, 'lessons', payload))).toBeNull();
  });
});

describe('readLessonOutcome', () => {
  it('reads a saved outcome and the user as its author', () => {
    expect(readLessonOutcome(row(60, 'lesson_outcome', OUTCOME))).toEqual({
      proposalId: 'p-correction',
      status: 'saved',
      by: 'user',
      title: LESSON_CORRECTION.title,
      rule: LESSON_CORRECTION.rule,
      target: { kind: 'memory', scope: 'team', type: 'feedback' },
      memoryHandle: 'm40',
      resultRef: null,
      reason: null,
    });
  });

  it('reads where a save outside memory landed', () => {
    expect(
      readLessonOutcome(
        row(60, 'lesson_outcome', {
          ...OUTCOME,
          target: { kind: 'knowledge', handle: 'k-release' },
          memoryHandle: null,
          resultRef: 'k-release',
        }),
      )?.resultRef,
    ).toBe('k-release');
  });

  it('reads a save to project or member instructions as its own target', () => {
    expect(
      readLessonOutcome(
        row(60, 'lesson_outcome', {
          ...OUTCOME,
          target: {
            kind: 'member_instructions',
            memberId: 'member-reviewer',
          },
          memoryHandle: null,
        }),
      )?.target,
    ).toEqual({ kind: 'member_instructions', memberId: 'member-reviewer' });
  });

  it('reads an outcome written before resultRef existed with none', () => {
    const { resultRef: _resultRef, ...older } = OUTCOME;

    expect(
      readLessonOutcome(row(60, 'lesson_outcome', older))?.resultRef,
    ).toBeNull();
  });

  it('reads an automatic outcome as written by the run', () => {
    expect(
      readLessonOutcome(row(60, 'lesson_outcome', { ...OUTCOME, by: 'auto' }))
        ?.by,
    ).toBe('auto');
  });

  it('reads the user as the author of an outcome written before the author was named', () => {
    const { by: _by, ...older } = OUTCOME;

    expect(readLessonOutcome(row(60, 'lesson_outcome', older))?.by).toBe(
      'user',
    );
  });

  it.each([
    'saved',
    'pending',
    'rejected',
    'undone',
    'skipped_duplicate',
    'dropped_by_check',
  ])('reads the %s status', (status) => {
    expect(
      readLessonOutcome(row(60, 'lesson_outcome', { ...OUTCOME, status }))
        ?.status,
    ).toBe(status);
  });

  it('reads the reason a check gave for dropping a lesson', () => {
    expect(
      readLessonOutcome(
        row(61, 'lesson_outcome', {
          ...OUTCOME,
          status: 'dropped_by_check',
          reason: 'the user never corrected this',
        }),
      )?.reason,
    ).toBe('the user never corrected this');
  });

  it('answers null for a status it does not know', () => {
    expect(
      readLessonOutcome(
        row(60, 'lesson_outcome', { ...OUTCOME, status: 'maybe' }),
      ),
    ).toBeNull();
  });

  it('answers null for an outcome whose target kind it does not know', () => {
    expect(
      readLessonOutcome(
        row(60, 'lesson_outcome', { ...OUTCOME, target: { kind: 'mystery' } }),
      ),
    ).toBeNull();
  });

  it('answers null for an outcome that names no lesson', () => {
    const { title: _title, ...nameless } = OUTCOME;

    expect(readLessonOutcome(row(60, 'lesson_outcome', nameless))).toBeNull();
  });
});

describe('foldLessonOutcomes', () => {
  it('keys each lesson’s decision by its proposal', () => {
    const folded = foldLessonOutcomes([
      row(60, 'lesson_outcome', OUTCOME),
      row(61, 'lesson_outcome', {
        ...OUTCOME,
        proposalId: 'p-other',
        status: 'rejected',
      }),
    ]);

    expect(Object.keys(folded).sort()).toEqual(['p-correction', 'p-other']);
    expect(folded['p-other']?.status).toBe('rejected');
  });

  it('keeps the newest outcome where a proposal has several', () => {
    const folded = foldLessonOutcomes([
      row(70, 'lesson_outcome', { ...OUTCOME, status: 'saved', by: 'auto' }),
      row(80, 'lesson_outcome', { ...OUTCOME, status: 'undone' }),
    ]);

    expect(folded['p-correction']?.status).toBe('undone');
  });

  it('ignores rows of other kinds', () => {
    expect(foldLessonOutcomes([row(50, 'lessons', LESSONS_PAYLOAD)])).toEqual(
      {},
    );
  });
});
