import { describe, expect, it } from 'vitest';

import type {
  ItemDto as ChatItem,
  RunDelegateState,
  RunDto,
} from '../autogenerated';
import {
  anySubagentRunning,
  applyDaemonReadings,
  daemonSubagentReadings,
  foldDurableTranscript,
  withDaemonStartedCalls,
} from './durable-transcript';
import {
  callBlockSubagentsRunning,
  collectCallBlocks,
  collectSubagentBlocks,
  subagentBlockStatus,
  type TranscriptEntry,
} from './transcript-groups';

function row(
  id: string,
  kind: string,
  payload: unknown,
  seq: number,
  runId = 'run-1',
): ChatItem {
  return {
    id,
    runId,
    memberId: null,
    seq,
    kind: kind as ChatItem['kind'],
    role: null,
    payload,
    createdAt: '2026-09-14T10:00:00.000Z',
  };
}

function foldOf(
  items: readonly ChatItem[],
  collapseToolSteps: boolean,
  run: { runId?: string; taskList?: RunDto['taskList'] } = {},
): TranscriptEntry[] {
  return foldDurableTranscript({
    items,
    foldItems: items,
    anchorIds: new Set(),
    runId: run.runId ?? 'run-1',
    taskList: run.taskList,
    collapseToolSteps,
  });
}

/** Every entry the fold drew, nested ones included, depth first. */
function flattenEntries(
  entries: readonly TranscriptEntry[],
): TranscriptEntry[] {
  return entries.flatMap((entry) => [
    entry,
    ...('entries' in entry && Array.isArray(entry.entries)
      ? flattenEntries(entry.entries)
      : []),
  ]);
}

/** The ids of the rows the fold draws as items, wherever they sit. */
function drawnIds(entries: readonly TranscriptEntry[]): string[] {
  return flattenEntries(entries).flatMap((entry) =>
    entry.type === 'item' ? [entry.item.id] : [],
  );
}

describe('foldDurableTranscript', () => {
  it('drops a turn that only compacted the conversation from the fold, and leaves the window as it was', () => {
    // The `✓ done` under a compaction says what the compaction row already says.
    // The turn is still in `items`, so it still counts toward the totals.
    const compaction = row(
      'c1',
      'system',
      { compaction: { preTokens: 100000, postTokens: 9000 } },
      1,
    );
    const turnEnd = row('t1', 'turn_complete', {}, 2);
    const items = [compaction, turnEnd];

    expect(drawnIds(foldOf(items, true))).not.toContain('t1');
    expect(drawnIds(foldOf([turnEnd], true))).toContain('t1');
    // The fold reads the window and never edits it.
    expect(items.map((item) => item.id)).toEqual(['c1', 't1']);
  });

  it('pulls a file change out of its tool group only while tool steps are not collapsed', () => {
    // A file change is pulled out of a group of several calls, so the group has
    // to hold a read before the edit.
    const group = [
      row(
        'q1',
        'tool_call',
        { id: 'q1', name: 'Read', input: { file_path: '/a.ts' } },
        1,
      ),
      row('q2', 'tool_result', { id: 'q1', output: 'a' }, 2),
      row(
        'e1',
        'tool_call',
        {
          id: 'e1',
          name: 'Edit',
          input: { file_path: '/a.ts', old_string: 'a', new_string: 'b' },
        },
        3,
      ),
      row('e2', 'tool_result', { id: 'e1', output: 'ok' }, 4),
    ];
    // A pulled-out change is a `tools` entry marked `standalone`.
    const hasStandalone = (entries: readonly TranscriptEntry[]): boolean =>
      flattenEntries(entries).some(
        (entry) => entry.type === 'tools' && entry.standalone === true,
      );

    expect(hasStandalone(foldOf(group, false))).toBe(true);
    expect(hasStandalone(foldOf(group, true))).toBe(false);
  });

  it("titles a task card from the run's own task list only while the rows belong to that run", () => {
    // The window cannot name a task whose announcement it does not hold, so the
    // daemon's list titles it. A switch can leave one run's rows under another
    // run's id for a render, and the guard keeps that run's list out of it.
    const announced = row(
      'k1',
      'task_list',
      {
        mode: 'patch',
        tasks: [{ id: '1', status: 'completed' }],
        toolCallId: null,
      },
      1,
    );
    const runTasks: RunDto['taskList'] = [
      {
        memberId: null,
        callId: null,
        snapshot: true,
        tasks: [
          {
            id: '1',
            title: 'Write the plan',
            status: 'completed',
            activeForm: null,
          },
        ],
      },
    ];
    const titleFor = (runId: string): string | null | undefined =>
      flattenEntries(foldOf([announced], false, { runId, taskList: runTasks }))
        .flatMap((entry) => (entry.type === 'task-list' ? entry.tasks : []))
        .map((task) => task.title)[0];

    expect(titleFor('run-1')).toBe('Write the plan');
    expect(titleFor('run-2')).toBeNull();
  });
});

describe('anySubagentRunning', () => {
  // A `Task` call nothing has returned: the delegate was launched and has not
  // reported back.
  const launched = row(
    'task-1',
    'tool_call',
    {
      id: 'task-1',
      name: 'Task',
      input: { description: 'Review', prompt: 'Look at the diff' },
    },
    1,
  );
  const entries = foldOf([launched], false);

  it('reports a delegate working while the run has not settled', () => {
    expect(anySubagentRunning(entries, null)).toBe(true);
  });

  it('does not report it once the run settled after the delegate last wrote a row', () => {
    expect(
      anySubagentRunning(entries, Date.parse('2026-09-14T11:00:00.000Z')),
    ).toBe(false);
  });

  it('does not report a delegate working on a settle nobody can date', () => {
    // A settle whose moment cannot be read makes nothing audible, so no delegate
    // is reported working on a stop it cannot place.
    expect(anySubagentRunning(entries, 'unknown')).toBe(false);
  });
});

describe('daemon subagent lifecycle', () => {
  it('uses the daemon snapshot for a missing ending inside a folded turn, without overriding newer rows', () => {
    const launch = row(
      'launch',
      'tool_call',
      { id: 'delegate', name: 'Task', input: { description: 'Review' } },
      1,
    );
    const ending = row('turn-end', 'turn_complete', {}, 2);
    const rows = [launch, ending];
    const state = {
      throughSeq: 2,
      delegates: [
        {
          id: 'delegate',
          memberId: null,
          callId: null,
          label: 'Review',
          kind: null,
          status: 'untracked' as const,
          processEnded: false,
          launchSeq: 1,
          toolCalls: 0,
          startedAt: launch.createdAt,
          ...UNMEASURED_FIGURES,
        },
      ],
    };
    const [block] = collectSubagentBlocks(
      applyDaemonReadings(
        foldOf(rows, true),
        daemonSubagentReadings(state, rows),
      ),
    );
    expect(block).toBeDefined();
    expect(subagentBlockStatus(block!)).toBe('untracked');
    const fresh = [
      ...rows,
      row(
        'later',
        'subagent_info',
        { id: 'delegate', backgroundOpen: true },
        3,
      ),
    ];
    const [reopened] = collectSubagentBlocks(
      applyDaemonReadings(
        foldOf(fresh, true),
        daemonSubagentReadings(state, fresh),
      ),
    );
    expect(subagentBlockStatus(reopened!)).toBe('running');
  });

  it('carries the daemon’s word that a delegate’s process ended onto its block', () => {
    const launch = row(
      'launch',
      'tool_call',
      { id: 'delegate', name: 'Task', input: { description: 'Review' } },
      1,
    );
    const [block] = collectSubagentBlocks(
      applyDaemonReadings(
        foldOf([launch], true),
        daemonSubagentReadings(
          { throughSeq: 1, delegates: [delegateState('untracked', true)] },
          [launch],
        ),
      ),
    );
    expect(block!.processEnded).toBe(true);
  });

  it('counts a delegate’s tools from the daemon, plus only its rows written after the read', () => {
    // The daemon counted 40 through seq 3 — most of them above the loaded
    // page. Seq 3 is inside that count; seq 4 arrived after the read.
    const launch = row(
      'launch',
      'tool_call',
      { id: 'delegate', name: 'Task', input: { description: 'Review' } },
      1,
    );
    const tool = (id: string, seq: number, parentToolUseId = 'delegate') =>
      row(id, 'tool_call', { id, name: 'Read', parentToolUseId }, seq);
    const rows = [
      launch,
      tool('counted', 3),
      tool('since', 4),
      tool('elsewhere', 5, 'other-delegate'),
      // Its other rows carry its id too, and are not tool calls.
      row(
        'since-result',
        'tool_result',
        { id: 'since', parentToolUseId: 'delegate' },
        6,
      ),
    ];
    const [block] = collectSubagentBlocks(
      applyDaemonReadings(
        foldOf(rows, true),
        daemonSubagentReadings(
          {
            throughSeq: 3,
            delegates: [{ ...delegateState('running'), toolCalls: 40 }],
          },
          rows,
        ),
      ),
    );
    expect(block!.durableToolCalls).toBe(41);
  });
});

const UNMEASURED_FIGURES = {
  messages: 0,
  requests: null,
  inputTokens: null,
  outputTokens: null,
  cacheReadTokens: null,
  cacheCreationTokens: null,
  contextTokens: null,
  costUsd: null,
  estimatedCostUsd: null,
  cumulative: false,
};

function delegateState(
  status: RunDelegateState['status'],
  processEnded = false,
): RunDelegateState {
  return {
    id: 'delegate',
    memberId: null,
    callId: null,
    label: 'Review',
    kind: null,
    status,
    processEnded,
    launchSeq: 1,
    toolCalls: 0,
    startedAt: '2026-09-14T10:00:00.000Z',
    ...UNMEASURED_FIGURES,
  };
}

describe('withDaemonStartedCalls', () => {
  const queuedCall = (): TranscriptEntry[] =>
    foldOf(
      [
        {
          ...row(
            's',
            'call_started',
            {
              callId: 'call-1',
              calleeNodeId: 'poet',
              message: 'go',
            },
            1,
          ),
          memberId: 'orch',
        },
        {
          ...row(
            'q',
            'system',
            {
              callId: 'call-1',
              severity: 'info',
              queuedCall: { cap: 1 },
            },
            2,
          ),
          memberId: 'poet',
        },
      ],
      false,
    );
  const blockOf = (entries: readonly TranscriptEntry[]) =>
    flattenEntries(entries).find((entry) => entry.type === 'call-block');

  it('drops QUEUED from a card once a read that covered its queued row says the call started', () => {
    // Off the tail the window never takes the call's first status row.
    const entries = queuedCall();
    expect(blockOf(entries)).toMatchObject({ queued: true, queuedSeq: 2 });
    const started = withDaemonStartedCalls(entries, {
      throughSeq: 2,
      ids: new Set(['call-1']),
    });
    expect(blockOf(started)).not.toHaveProperty('queued');
  });

  it('keeps it for a read older than the queued row, or one that lists no start', () => {
    const entries = queuedCall();
    expect(
      blockOf(
        withDaemonStartedCalls(entries, {
          throughSeq: 1,
          ids: new Set(['call-1']),
        }),
      ),
    ).toMatchObject({ queued: true });
    expect(
      blockOf(
        withDaemonStartedCalls(entries, {
          throughSeq: 9,
          ids: new Set(['call-7']),
        }),
      ),
    ).toMatchObject({ queued: true });
  });
});

describe('the daemon’s figures on a delegate', () => {
  const launch = row(
    'launch',
    'tool_call',
    { id: 'delegate', name: 'Task', input: { description: 'Review' } },
    1,
  );
  const declared = row(
    'declared',
    'subagent_info',
    { id: 'delegate', requests: 9, inputTokens: 90, costUsd: 0.1 },
    2,
  );
  const rows = [launch, declared];
  const withFigures = (cumulative: boolean) => ({
    throughSeq: 2,
    delegates: [
      {
        ...delegateState('completed'),
        requests: 4,
        inputTokens: 400,
        outputTokens: 40,
        cacheReadTokens: 900,
        cacheCreationTokens: 0,
        contextTokens: 1_300,
        costUsd: 0.2,
        estimatedCostUsd: 0.25,
        cumulative,
      },
    ],
  });
  const blockOf = (state: ReturnType<typeof withFigures>) => {
    const [block] = collectSubagentBlocks(
      applyDaemonReadings(
        foldOf(rows, true),
        daemonSubagentReadings(state, rows),
      ),
    );
    return block!;
  };

  it('carries the daemon’s figures, and its message count with the window’s rows above the read added', () => {
    const readings = daemonSubagentReadings(
      {
        throughSeq: 3,
        delegates: [
          {
            ...withFigures(true).delegates[0]!,
            messages: 2,
          },
        ],
      },
      [
        launch,
        {
          ...row(
            'at-read',
            'message',
            { text: 'at the read', parentToolUseId: 'delegate' },
            3,
          ),
          role: 'assistant',
        },
        {
          ...row(
            'after-read',
            'message',
            { text: 'after the read', parentToolUseId: 'delegate' },
            4,
          ),
          role: 'assistant',
        },
        {
          ...row(
            'prompt',
            'message',
            { text: 'the prompt', parentToolUseId: 'delegate' },
            5,
          ),
          role: 'user',
        },
      ],
    );

    expect(readings.get('delegate')).toMatchObject({
      requests: 4,
      inputTokens: 400,
      outputTokens: 40,
      cacheReadTokens: 900,
      cacheCreationTokens: 0,
      contextTokens: 1_300,
      costUsd: 0.2,
      estimatedCostUsd: 0.25,
      cumulative: true,
      messages: 3,
    });
  });

  it('replaces the row-derived figures only with a reading that sums every request', () => {
    expect(blockOf(withFigures(true))).toMatchObject({
      requests: 4,
      inputTokens: 400,
      costUsd: 0.2,
      cumulative: true,
    });
    expect(blockOf(withFigures(false))).toMatchObject({
      requests: 9,
      inputTokens: 90,
      costUsd: 0.1,
      cumulative: false,
    });
  });
});

describe('applyDaemonReadings', () => {
  const rows = [
    row(
      'launch',
      'tool_call',
      { id: 'delegate', name: 'Task', input: { description: 'Review' } },
      1,
    ),
    row('other', 'message', { text: 'meanwhile' }, 2),
  ];

  it('hands back the very same entries when the daemon names no delegate', () => {
    const entries = foldOf(rows, true);
    expect(
      applyDaemonReadings(
        entries,
        daemonSubagentReadings({ throughSeq: 2, delegates: [] }, rows),
      ),
    ).toBe(entries);
  });

  it('copies only the block it changes, and nothing once it already says so', () => {
    const entries = foldOf(rows, true);
    const readings = daemonSubagentReadings(
      { throughSeq: 2, delegates: [delegateState('completed')] },
      rows,
    );
    const applied = applyDaemonReadings(entries, readings);
    expect(applied).not.toBe(entries);
    // The row the daemon says nothing about is the same object.
    const untouched = (list: readonly TranscriptEntry[]) =>
      flattenEntries(list).find(
        (entry) => entry.type === 'item' && entry.item.id === 'other',
      );
    expect(untouched(entries)).toBeDefined();
    expect(untouched(applied)).toBe(untouched(entries));
    expect(applyDaemonReadings(applied, readings)).toBe(applied);
  });

  describe("a call card's sub-agents past the loaded window", () => {
    const inCall = (
      id: string,
      kind: string,
      payload: Record<string, unknown>,
      seq: number,
    ): ChatItem => ({
      ...row(id, kind, { ...payload, callId: 'call-1' }, seq),
      memberId: 'poet',
    });
    const card = [
      {
        ...row(
          'start',
          'call_started',
          { callId: 'call-1', calleeNodeId: 'poet', message: 'Review it.' },
          10,
        ),
        memberId: 'orch',
      },
      inCall('status', 'status', { status: 'running' }, 11),
      inCall(
        'held',
        'tool_call',
        { id: 'held', name: 'Agent', input: { description: 'On screen' } },
        12,
      ),
    ];
    const delegate = (
      id: string,
      status: RunDelegateState['status'],
      callId: string | null = 'call-1',
    ): RunDelegateState => ({
      ...delegateState(status),
      id,
      memberId: 'poet',
      callId,
    });
    const countOf = (delegates: RunDelegateState[]): number => {
      const [block] = collectCallBlocks(
        applyDaemonReadings(
          foldOf(card, true),
          daemonSubagentReadings({ throughSeq: 12, delegates }, card),
        ),
      );
      return callBlockSubagentsRunning(block!);
    };

    it('adds what the daemon says runs with no block on the page', () => {
      expect(
        countOf([
          delegate('above-1', 'running'),
          delegate('above-2', 'running'),
        ]),
      ).toBe(3);
    });

    it('counts a sub-agent the window holds once', () => {
      expect(countOf([delegate('held', 'running')])).toBe(1);
    });

    it('takes the daemon’s word that a block on the page has ended', () => {
      expect(countOf([delegate('held', 'completed')])).toBe(0);
    });

    it('leaves out what ended, and what another call or the member’s own conversation launched', () => {
      expect(
        countOf([
          delegate('ended', 'completed'),
          delegate('elsewhere', 'running', 'call-9'),
          delegate('own', 'running', null),
        ]),
      ).toBe(1);
    });

    it('keeps the delegate of an earlier call of the conversation', () => {
      const [block] = collectCallBlocks(foldOf(card, true));
      const later = { ...block!, conversationCallIds: ['call-0', 'call-1'] };

      const [read] = collectCallBlocks(
        applyDaemonReadings(
          [later],
          daemonSubagentReadings(
            {
              throughSeq: 12,
              delegates: [delegate('old', 'running', 'call-0')],
            },
            card,
          ),
        ),
      );

      expect(callBlockSubagentsRunning(read!)).toBe(2);
    });

    it('hands the same card back once it already says so', () => {
      const readings = daemonSubagentReadings(
        { throughSeq: 12, delegates: [delegate('above-1', 'running')] },
        card,
      );
      const applied = applyDaemonReadings(foldOf(card, true), readings);

      expect(applyDaemonReadings(applied, readings)).toBe(applied);
    });

    it('drops the count once the daemon stops saying it runs', () => {
      const running = applyDaemonReadings(
        foldOf(card, true),
        daemonSubagentReadings(
          { throughSeq: 12, delegates: [delegate('above-1', 'running')] },
          card,
        ),
      );
      const ended = applyDaemonReadings(
        running,
        daemonSubagentReadings(
          { throughSeq: 12, delegates: [delegate('above-1', 'completed')] },
          card,
        ),
      );

      expect(callBlockSubagentsRunning(collectCallBlocks(ended)[0]!)).toBe(1);
    });
  });
});
