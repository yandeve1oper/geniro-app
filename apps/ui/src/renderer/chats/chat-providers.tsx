/** The values only a transcript row reads, provided by {@link TranscriptContexts}. */
export interface TranscriptValues {
  /** Whether a turn's tool rows start folded — see `CollapseToolStepsContext`. */
  collapseToolSteps: boolean;
  /** What the run is doing, for its live rows — see `RunActivityContext`. */
  runActivity: string | null;
  /** How long each turn worked — see `TurnDurationContext`. */
  turnDurations: ReadonlyMap<string, TurnDuration>;
  /** Jump to a call block's card, or null with no scroller to jump within. */
  revealCallBlock: ((cardId: string) => void) | null;
  /** The same jump addressed by call id. */
  revealCall: ((callId: string) => (() => void) | null) | null;
  /** Open a sub-agent's detail, or null with no detail dialog. */
  openSubagentDetail: ((block: SubagentBlockEntry) => void) | null;
  /** Each pull request's newest recorded outcome — see `RunOutcomesContext`. */
  runOutcomes: RunOutcomes;
  runStages: StageProgress | null;
  /** Open the notes popup on one note — see `TeamNoteOpenContext`. */
  openTeamNote: ((seq: number) => void) | null;
  /** Open another thread by its run id, or null where none opens — see `ThreadOpenContext`. */
  openThread: ((runId: string) => void) | null;
  /** Open Settings → Memory on one entry — see `MemoryOpenContext`. */
  openMemory?: ((handle: string) => void) | null;
  /** Open the Knowledge page on one document — see `KnowledgeOpenContext`. */
  openKnowledge?: ((target: KnowledgeOpenTarget) => void) | null;
}

/**
 * What a transcript row reaches for without being handed it as a prop.
 *
 * One component rather than nested providers at the call site, and the reason
 * is the diff rather than the runtime: `Chats.tsx`'s returned tree is ~1,900
 * lines, so each further provider wrapped around it re-indents every one of
 * them and buries the change in a file nobody can then review. MEASURED when
 * the third value below was added by nesting instead: 1,663 changed lines, of
 * which 80 were the change. A fourth belongs here too.
 *
 * It began as the two things a row can DO about a failed turn, which is why the
 * name was `ChatActionProviders`; `callContext` is data rather than an action,
 * and the widened name is what the whole set has in common — a row deep inside
 * a memoized tree needing something only `Chats` can compute.
 */
export function ChatProviders({
  signIn,
  retry,
  callContext,
  callChannel,
  artifactUrl,
  artifactSharing = null,
  threadId,
  runSettledAt,
  loadAttachment = null,
  callConversations = null,
  delegateConversations = null,
  liveText = null,
  jumpMark = null,
  applyRecommendations = null,
  memberVerdicts = null,
  notSent = null,
  chatActions = null,
  loadMemory = null,
  loadKnowledge = null,
  lessonsApi = null,
  lessonsAgentsApi = null,
  lessonsJump = null,
  children,
}: {
  /**
   * The open run, whose folds every surface below remembers — see
   * `ThreadUiMemoryContext`. Here for the reason this component exists: the
   * agents panel, the shelf and the transcript are all inside it, and a new
   * provider around `Chats.tsx`'s tree would re-indent all of it.
   */
  threadId: string | null;
  /**
   * When the open run stopped, or null while it has not — see
   * `RunSettledContext`. The transcript, the shelf and the agents panel all
   * read it, so it is provided for the whole surface.
   */
  runSettledAt: RunSettleAt;
  /** Which sign-in cures a given row's failure — see `SignInResolver`. */
  signIn: SignInResolver | null;
  retry: (() => void) | null;
  /**
   * How a call block resolves its callee's context window while the call is
   * still open — see `CalleeContextResolverContext`. Provided HERE rather than
   * around the transcript itself because a call block is rendered from three
   * separate subtrees (the transcript, the sub-agent detail dialog, and the
   * team card), and this component wraps all of them.
   */
  callContext: CalleeContextResolver | null;
  /** The direct line to a running call's callee — see `CallMessageBox`. */
  callChannel: CallMessageChannel | null;
  /**
   * How a published page is addressed on the daemon — see
   * `ArtifactUrlContext`. Here for this component's own reason and one more:
   * the transcript card, the popup and the agents panel all frame the same
   * artifact, and all three are inside this tree.
   */
  artifactUrl: ArtifactUrlBuilder | null;
  /**
   * How a page's Share control reaches the daemon — see
   * `ArtifactShareContext`. Absent (or null) draws no Share control.
   */
  artifactSharing?: ArtifactSharing | null;
  /** Read images attached to this conversation. */
  loadAttachment?: AttachmentLoader | null;
  /**
   * How an opened call card reads its own conversation — see
   * `CallConversationContext`. Here for `callContext`'s reason: a call block is
   * drawn from three subtrees. Absent where the window holds every row.
   */
  callConversations?: CallConversationLoader | null;
  /**
   * How an opened sub-agent card reads its own rows — see
   * `DelegateConversationContext`. Absent where the window holds every row.
   */
  delegateConversations?: DelegateConversationLoader | null;
  /**
   * The live plane of the run on screen. Its delegates' figures are mounted as
   * {@link LiveDelegatesContext}, which is what a sub-agent card reads.
   */
  liveText?: ReadonlyMap<string, LiveState> | null;
  /**
   * Where a jump landed — see `JumpMarkContext`. Here for `callContext`'s
   * reason: the rows that mark themselves are drawn deep inside call cards.
   */
  jumpMark?: JumpMark | null;
  /**
   * A recommendations card's Apply — see `RecommendationsApplyContext`.
   * Absent draws the card read-only.
   */
  applyRecommendations?: RecommendationsApplier | null;
  /**
   * The user's verdicts on a card's member assessments — see
   * `MemberVerdictsContext`. Absent draws no verdict control.
   */
  memberVerdicts?: MemberVerdicts | null;
  /**
   * The user messages a turn dropped, and how to resend one — see
   * `NotSentMessagesContext`. Absent marks no message.
   */
  notSent?: NotSentMessages | null;
  /** The open chat's buttons and their press — see `ChatActionsContext`. */
  chatActions?: ChatActions | null;
  /**
   * How a memory row reads the entries it names — see `MemoryLoaderContext`.
   * Here for `callContext`'s reason: memory rows are drawn in the transcript,
   * the sub-agent detail dialog and call cards alike.
   */
  loadMemory?: MemoryLoader | null;
  /** How a knowledge row reads its documents — see `KnowledgeLoaderContext`. */
  loadKnowledge?: KnowledgeLoader | null;
  /** A lessons card's Save and Reject — see `LessonsApiContext`. */
  lessonsApi?: DaemonApis['lessons'] | null;
  /** A lessons card's model names — see `LessonsAgentsApiContext`. */
  lessonsAgentsApi?: DaemonApis['agents'] | null;
  /** A lesson's "Show in thread" — see `LessonsJumpContext`. */
  lessonsJump?: ((seq: number) => void) | null;
  children: React.ReactNode;
}): React.JSX.Element {
  const liveDelegates = useLiveDelegates(liveText);
  return (
    <CliLoginContext.Provider value={signIn}>
      <RetryContext.Provider value={retry}>
        <CalleeContextResolverContext.Provider value={callContext}>
          <LiveDelegatesContext.Provider value={liveDelegates}>
            <DelegateConversationContext.Provider value={delegateConversations}>
              <CallConversationContext.Provider value={callConversations}>
                <JumpMarkContext.Provider value={jumpMark}>
                  <CallMessageChannelContext.Provider value={callChannel}>
                    <ArtifactUrlContext.Provider value={artifactUrl}>
                      <ArtifactShareContext.Provider value={artifactSharing}>
                        <ThreadUiMemoryContext.Provider value={threadId}>
                          <AttachmentLoaderContext.Provider
                            value={loadAttachment}>
                            <RunSettledContext.Provider value={runSettledAt}>
                              <RecommendationsApplyContext.Provider
                                value={applyRecommendations}>
                                <MemberVerdictsContext.Provider
                                  value={memberVerdicts}>
                                  <NotSentMessagesContext.Provider
                                    value={notSent}>
                                    <ChatActionsContext.Provider
                                      value={chatActions}>
                                      <MemoryLoaderContext.Provider
                                        value={loadMemory}>
                                        <KnowledgeLoaderContext.Provider
                                          value={loadKnowledge}>
                                          <LessonsApiContext.Provider
                                            value={lessonsApi}>
                                            <LessonsAgentsApiContext.Provider
                                              value={lessonsAgentsApi}>
                                              <LessonsJumpContext.Provider
                                                value={lessonsJump}>
                                                {children}
                                              </LessonsJumpContext.Provider>
                                            </LessonsAgentsApiContext.Provider>
                                          </LessonsApiContext.Provider>
                                          {chatActions === null ? null : (
                                            <CommandConfirmDialog
                                              action={chatActions.confirming}
                                              changed={
                                                chatActions.confirming !==
                                                  null &&
                                                !chatActions.actions.some(
                                                  (a) =>
                                                    a.seq ===
                                                    chatActions.confirming?.seq,
                                                )
                                              }
                                              onCancel={
                                                chatActions.cancelCommand
                                              }
                                              onConfirm={
                                                chatActions.confirmCommand
                                              }
                                            />
                                          )}
                                        </KnowledgeLoaderContext.Provider>
                                      </MemoryLoaderContext.Provider>
                                    </ChatActionsContext.Provider>
                                  </NotSentMessagesContext.Provider>
                                </MemberVerdictsContext.Provider>
                              </RecommendationsApplyContext.Provider>
                            </RunSettledContext.Provider>
                          </AttachmentLoaderContext.Provider>
                        </ThreadUiMemoryContext.Provider>
                      </ArtifactShareContext.Provider>
                    </ArtifactUrlContext.Provider>
                  </CallMessageChannelContext.Provider>
                </JumpMarkContext.Provider>
              </CallConversationContext.Provider>
            </DelegateConversationContext.Provider>
          </LiveDelegatesContext.Provider>
        </CalleeContextResolverContext.Provider>
      </RetryContext.Provider>
    </CliLoginContext.Provider>
  );
}

/** Provides the {@link TranscriptValues} — see there for who passes them where. */
export function TranscriptContexts({
  collapseToolSteps,
  runActivity,
  turnDurations,
  revealCallBlock,
  revealCall,
  openSubagentDetail,
  runOutcomes,
  runStages,
  openTeamNote,
  openThread,
  openMemory = null,
  openKnowledge = null,
  children,
}: TranscriptValues & { children: React.ReactNode }): React.JSX.Element {
  return (
    <RunOutcomesContext.Provider value={runOutcomes}>
      <TeamNoteOpenContext.Provider value={openTeamNote}>
        <MemoryOpenContext.Provider value={openMemory}>
          <RunStagesContext.Provider value={runStages}>
            <CollapseToolStepsContext.Provider value={collapseToolSteps}>
              <RunActivityContext.Provider value={runActivity}>
                <TurnDurationContext.Provider value={turnDurations}>
                  <RevealCallBlockContext.Provider value={revealCallBlock}>
                    <RevealCallContext.Provider value={revealCall}>
                      <SubagentDetailContext.Provider
                        value={openSubagentDetail}>
                        <KnowledgeOpenContext.Provider value={openKnowledge}>
                          <ThreadOpenContext.Provider value={openThread}>
                            {children}
                          </ThreadOpenContext.Provider>
                        </KnowledgeOpenContext.Provider>
                      </SubagentDetailContext.Provider>
                    </RevealCallContext.Provider>
                  </RevealCallBlockContext.Provider>
                </TurnDurationContext.Provider>
              </RunActivityContext.Provider>
            </CollapseToolStepsContext.Provider>
          </RunStagesContext.Provider>
        </MemoryOpenContext.Provider>
      </TeamNoteOpenContext.Provider>
    </RunOutcomesContext.Provider>
  );
}
