import type { LiveAction, OpenMonitor } from '../autogenerated';
import { ChatActionChips } from './action-chip';
import {
  RunningMonitorChips,
  RunningShellChips,
  RunningSubagentChips,
  TaskListChip,
  TeamNotesChip,
} from './composer-shelf';
import type { ConversationWork } from './conversation-work';
import { SHELF_STATUS_GROUP_CLASS } from './shelf-chip';
import type { ShellRun } from './shell-activity';
import { taskProgress } from './task-payload';
import type { ActionPressPhase } from './use-chat-actions';
import type { WorkingAgentRow } from './working-agents';

/** Where a conversation's own work comes from, and what its chips do when pressed. */
export interface ConversationWorkSource {
  of: (callIds: readonly string[]) => ConversationWork;
  agentName: (memberId: string) => string;
  phases: ReadonlyMap<number, ActionPressPhase>;
  onPressAction: (action: LiveAction) => void;
  onDismissAction: (action: LiveAction) => void;
  onOpenNote: (seq: number | null) => void;
  onOpenShell: (shell: ShellRun) => void;
  onKillShell?: (shell: ShellRun) => void | Promise<void>;
  onStopMonitor?: (monitor: OpenMonitor) => void | Promise<void>;
  onOpenSubagent?: (subagentId: string) => void;
}

function hasCounters(work: ConversationWork): boolean {
  return (
    work.shells.length +
      work.monitors.length +
      work.subagents.length +
      work.tasks.length >
    0
  );
}

function StatusCounters({
  live,
  work,
  source,
  withNotes,
}: {
  live: boolean;
  work: ConversationWork;
  source: ConversationWorkSource;
  withNotes: boolean;
}): React.JSX.Element {
  const progress = taskProgress(work.tasks);
  return (
    <>
      <RunningShellChips
        shells={work.shells}
        onOpen={source.onOpenShell}
        onKill={source.onKillShell}
      />
      <RunningMonitorChips
        monitors={work.monitors}
        onStop={source.onStopMonitor}
      />
      <RunningSubagentChips
        running={
          work.subagents.filter((each) => each.status === 'running').length
        }
        threads={work.subagents}
        onOpen={source.onOpenSubagent}
      />
      {withNotes ? (
        <TeamNotesChip
          notes={work.notes}
          agentName={source.agentName}
          onOpen={source.onOpenNote}
        />
      ) : null}
      <TaskListChip
        done={progress.done}
        total={progress.total}
        tasks={work.tasks}
        live={live}
      />
    </>
  );
}

/** The shelf's status counters, counting only what this one conversation runs and keeps. */
export function ConversationWorkChips({
  row,
  source,
}: {
  row: WorkingAgentRow;
  source: ConversationWorkSource;
}): React.JSX.Element | null {
  const work = source.of(row.callIds);
  if (!hasCounters(work)) {
    return null;
  }
  return (
    <span
      data-slot="working-agent-work"
      className={SHELF_STATUS_GROUP_CLASS}
      onClick={(event) => event.stopPropagation()}>
      <StatusCounters
        live={row.state === 'working'}
        work={work}
        source={source}
        withNotes={false}
      />
    </span>
  );
}

export function hasConversationWork(work: ConversationWork): boolean {
  return hasCounters(work) || work.notes.length > 0 || work.actions.length > 0;
}

export function ConversationWorkBar({
  row,
  work,
  source,
}: {
  row: WorkingAgentRow;
  work: ConversationWork;
  source: ConversationWorkSource;
}): React.JSX.Element {
  return (
    <div
      data-slot="call-conversation-work"
      className="flex min-w-0 flex-wrap items-center gap-2">
      <ChatActionChips
        actions={work.actions}
        phases={source.phases}
        onPress={source.onPressAction}
        onDismiss={source.onDismissAction}
      />
      <span className={SHELF_STATUS_GROUP_CLASS}>
        <StatusCounters
          live={row.state === 'working'}
          work={work}
          source={source}
          withNotes
        />
      </span>
    </div>
  );
}
