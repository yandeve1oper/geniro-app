// @vitest-environment jsdom
import { act, useRef, useState } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type {
  ChatHistoryDto,
  ChatsApi,
  ItemDto as ChatItem,
} from '../autogenerated';
import type {
  CallConversationLoader,
  CallConversationState,
} from './call-conversation';
import { useCallPages } from './use-call-pages';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const CALL = 'call-1';

function row(seq: number): ChatItem {
  return {
    id: `r-${seq}`,
    runId: 'run-1',
    memberId: null,
    seq,
    kind: 'tool_call',
    role: null,
    payload: { id: `t-${seq}`, name: 'Grep', input: {}, callId: CALL },
    createdAt: 'now',
  };
}

function page(rows: ChatItem[]): ChatHistoryDto {
  return { items: rows, anchors: [] };
}

interface Handle {
  loader: CallConversationLoader;
  forget: () => void;
}

function Harness({
  api,
  onReady,
}: {
  api: Pick<ChatsApi, 'listRunItems'>;
  onReady: (handle: Handle) => void;
}): null {
  const runIdRef = useRef<string | null>('run-1');
  const pageSizeRef = useRef(2);
  const [, setRows] = useState<ChatItem[]>([]);
  const { callConversations, forgetCallPages } = useCallPages({
    runIdRef,
    api,
    pageSizeRef,
    commitRows: setRows,
  });
  onReady({ loader: callConversations, forget: forgetCallPages });
  return null;
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

async function settle(): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0));
  });
}

function mount(api: Pick<ChatsApi, 'listRunItems'>): Handle {
  const box: { handle: Handle | null } = { handle: null };
  act(() => {
    root.render(
      <Harness
        api={api}
        onReady={(ready) => {
          box.handle = ready;
        }}
      />,
    );
  });
  if (box.handle === null) {
    throw new Error('the harness did not mount');
  }
  return box.handle;
}

describe('a call card reads its conversation through the shared pages', () => {
  it('asks the daemon for the call’s rows, page by page from the oldest held', async () => {
    const listRunItems = vi.fn<ChatsApi['listRunItems']>(async () =>
      page([row(5), row(6)]),
    );
    const { loader } = mount({ listRunItems });

    await act(async () => loader.load(CALL, false));
    await settle();

    expect(listRunItems.mock.calls[0]?.[0]).toEqual({
      runId: 'run-1',
      limit: 2,
      call: CALL,
    });
    const held: CallConversationState | null = loader.stateOf(CALL);
    expect(held).toMatchObject({
      loading: false,
      hasOlder: true,
      oldestSeq: 5,
    });

    await act(async () => loader.load(CALL, true));
    await settle();

    expect(listRunItems.mock.calls[1]?.[0]).toEqual({
      runId: 'run-1',
      limit: 2,
      call: CALL,
      beforeSeq: 5,
    });
  });

  it('parks a failed read until it is asked again, and forgets what it read on request', async () => {
    const listRunItems = vi
      .fn<ChatsApi['listRunItems']>()
      .mockRejectedValueOnce(new Error('daemon unreachable'))
      .mockResolvedValue(page([row(7)]));
    const { loader, forget } = mount({ listRunItems });

    await act(async () => loader.load(CALL, false));
    await settle();
    expect(loader.stateOf(CALL)).toMatchObject({ failed: true });
    expect(listRunItems).toHaveBeenCalledTimes(1);

    await act(async () => loader.retry(CALL));
    await settle();
    expect(listRunItems).toHaveBeenCalledTimes(2);
    expect(loader.stateOf(CALL)).toMatchObject({
      failed: false,
      hasOlder: false,
    });

    await act(async () => forget());
    expect(loader.stateOf(CALL)).toBeNull();
  });
});
