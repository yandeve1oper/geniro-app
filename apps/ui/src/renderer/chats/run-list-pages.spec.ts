import { describe, expect, it } from 'vitest';

import type { RunDto as ChatRun } from '../autogenerated';
import type { ActivityWindow } from './activity-window';
import { inScope, olderPageQuery, reconcileListing } from './run-list-pages';

/** A run created `day` days into 2026; `archived` puts it on the shelf. */
function run(id: string, day: number, archived = true): ChatRun {
  return {
    id,
    createdAt: new Date(Date.UTC(2026, 0, day)).toISOString(),
    archivedAt: archived ? '2026-12-31T00:00:00.000Z' : null,
  } as ChatRun;
}

const horizon = run('edge', 50).createdAt;
const none = new Set<string>();
const never = (): boolean => false;

describe('reconcileListing', () => {
  it('shows the listing down to the horizon and holds what lies below it', () => {
    const { shown, held } = reconcileListing({
      all: [run('a', 60), run('b', 40)],
      known: [],
      heldBefore: [],
      horizon,
      scope: 'archived',
      deleted: none,
      window: null,
      takenInSince: never,
    });

    expect(shown.map((row) => row.id)).toEqual(['a']);
    expect(held.map((row) => row.id)).toEqual(['b']);
  });

  it('keeps a known row below the horizon on screen, and one above it off scope', () => {
    const { shown, kept } = reconcileListing({
      all: [run('a', 60)],
      known: [run('deep', 10), run('gone', 70)],
      heldBefore: [],
      horizon,
      scope: 'archived',
      deleted: none,
      window: null,
      takenInSince: never,
    });

    expect(shown.map((row) => row.id)).toEqual(['a', 'deep']);
    expect(kept.map((row) => row.id)).toEqual(['gone']);
  });

  it('keeps a row taken in after the listing was asked for, wherever it lies', () => {
    const { shown } = reconcileListing({
      all: [run('a', 60)],
      known: [run('new', 80, false)],
      heldBefore: [],
      horizon: null,
      scope: 'active',
      deleted: none,
      window: null,
      takenInSince: (id) => id === 'new',
    });

    expect(shown.map((row) => row.id)).toEqual(['new', 'a']);
  });

  it('carries held rows the listing does not reach, and never a deleted one', () => {
    const { held } = reconcileListing({
      all: [run('a', 60)],
      known: [],
      heldBefore: [run('older', 20), run('dropped', 15), run('covered', 55)],
      horizon,
      scope: 'archived',
      deleted: new Set(['dropped']),
      window: null,
      takenInSince: never,
    });

    expect(held.map((row) => row.id)).toEqual(['older']);
  });

  it('never keeps a known row of another scope on screen', () => {
    const { shown, kept } = reconcileListing({
      all: [run('a', 60)],
      known: [run('desk', 10, false)],
      heldBefore: [],
      horizon,
      scope: 'archived',
      deleted: none,
      window: null,
      takenInSince: never,
    });

    expect(shown.map((row) => row.id)).toEqual(['a']);
    expect(kept.map((row) => row.id)).toEqual(['desk']);
  });
});

const window: ActivityWindow = {
  since: '2026-11-16T00:00:00.000Z',
  until: '2026-11-17T00:00:00.000Z',
};

function active(id: string, lastActivityAt: string | null): ChatRun {
  return { ...run(id, 10, false), lastActivityAt };
}

describe('inScope with an activity window', () => {
  const inside = '2026-11-16T12:00:00.000Z';
  const outside = '2026-11-10T12:00:00.000Z';

  it.each(['active', 'all'] as const)(
    'keeps a row inside the window and drops one outside it under %s',
    (scope) => {
      expect(inScope(active('a', inside), scope, window)).toBe(true);
      expect(inScope(active('b', outside), scope, window)).toBe(false);
    },
  );

  it('applies the window under archived too', () => {
    const shelved = (at: string): ChatRun => ({
      ...run('s', 10),
      lastActivityAt: at,
    });
    expect(inScope(shelved(inside), 'archived', window)).toBe(true);
    expect(inScope(shelved(outside), 'archived', window)).toBe(false);
  });

  it('still applies the archive scope inside the window', () => {
    expect(inScope(active('a', inside), 'archived', window)).toBe(false);
  });

  it('ignores the window when it is null', () => {
    expect(inScope(active('a', null), 'active', null)).toBe(true);
  });
});

describe('olderPageQuery', () => {
  it('carries the window beside the cursor', () => {
    const query = olderPageQuery('all', window, run('edge', 5));
    expect(query.activeSince).toBe(window.since);
    expect(query.activeUntil).toBe(window.until);
    expect(query.beforeId).toBe('edge');
  });

  it('sends no window bounds without one', () => {
    const query = olderPageQuery('all', null, run('edge', 5));
    expect(query).not.toHaveProperty('activeSince');
    expect(query).not.toHaveProperty('activeUntil');
  });
});

describe('reconcileListing with a window', () => {
  it('keeps a known row outside the window off screen, in kept', () => {
    const { shown, kept } = reconcileListing({
      all: [active('in', '2026-11-16T12:00:00.000Z')],
      known: [active('stale', '2026-11-10T12:00:00.000Z')],
      heldBefore: [],
      horizon: null,
      scope: 'active',
      window,
      deleted: none,
      takenInSince: (id) => id === 'stale',
    });

    expect(shown.map((row) => row.id)).toEqual(['in']);
    expect(kept.map((row) => row.id)).toEqual(['stale']);
  });
});
