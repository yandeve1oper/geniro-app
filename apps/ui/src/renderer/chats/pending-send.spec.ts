import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { type PendingSend, withPendingSend } from './pending-send';
import type { TranscriptEntry } from './transcript-groups';

function userRow(seq: number, text: string): ChatItem {
  return {
    id: `item-${seq}`,
    runId: 'r1',
    memberId: null,
    seq,
    kind: 'message',
    role: 'user',
    payload: { text },
    createdAt: '2026-11-17T10:00:00.000Z',
  };
}

const held: PendingSend = {
  runId: 'r1',
  text: 'and this?',
  imageCount: 0,
  sentAt: '2026-11-17T10:01:00.000Z',
  afterSeq: 5,
};

const earlier: TranscriptEntry[] = [{ type: 'item', item: userRow(0, 'hi') }];

function appended(entries: TranscriptEntry[]): ChatItem | null {
  const last = entries.at(-1);
  return entries.length > earlier.length && last?.type === 'item'
    ? last.item
    : null;
}

describe('withPendingSend', () => {
  it('draws the held message as the user’s own row at the end', () => {
    const row = appended(withPendingSend(earlier, held, [userRow(0, 'hi')]));

    expect(row).toMatchObject({
      runId: 'r1',
      kind: 'message',
      role: 'user',
      payload: { text: 'and this?' },
      createdAt: held.sentAt,
    });
  });

  it('leaves the transcript alone when nothing is held', () => {
    const entries = withPendingSend(earlier, undefined, []);

    expect(entries).toBe(earlier);
  });

  it('stands down once the daemon’s row for it is in the window', () => {
    const entries = withPendingSend(earlier, held, [
      userRow(0, 'hi'),
      userRow(6, 'and this?'),
    ]);

    expect(entries).toBe(earlier);
  });

  it('is not hidden by the same words sent before it', () => {
    const row = appended(
      withPendingSend(earlier, held, [userRow(3, 'and this?')]),
    );

    expect(row?.payload).toEqual({ text: 'and this?' });
  });

  it('names the pictures of a message that is only pictures', () => {
    const row = appended(
      withPendingSend(earlier, { ...held, text: '', imageCount: 2 }, []),
    );

    expect(row?.payload).toEqual({ text: '2 images' });
  });
});
