describe('groupTranscript — closing a group whose turn ended', () => {
  const toolsOf = (entries: TranscriptEntry[]): ToolGroupEntry[] =>
    entries.filter((entry): entry is ToolGroupEntry => entry.type === 'tools');

  it('leaves a group OPEN while its turn is still running', () => {
    const entries = groupTranscript([
      item('tool_call', { id: 't1', name: 'Bash', input: {} }),
    ]);
    expect(toolsOf(entries)[0]?.closed).toBe(false);
  });

  it('closes a group once a turn_complete follows it', () => {
    // The reported bug's data shape: a call whose result never arrived,
    // followed by the turn ending. Nothing more is coming for it.
    const entries = groupTranscript([
      item('tool_call', { id: 't1', name: 'Bash', input: {} }),
      item('turn_complete', {}),
    ]);
    expect(toolsOf(entries)[0]?.closed).toBe(true);
  });

  it('closes only the groups the turn end came AFTER', () => {
    // The per-turn part, which a run-level flag could not express: turn 1's
    // orphaned group stays closed while turn 2's group is genuinely live.
    const entries = groupTranscript([
      item('tool_call', { id: 't1', name: 'Bash', input: {} }),
      item('turn_complete', {}),
      item('message', { text: 'next turn' }, 'orch', 'assistant'),
      item('tool_call', { id: 't2', name: 'Bash', input: {} }),
    ]);
    const groups = toolsOf(entries);
    expect(groups).toHaveLength(2);
    expect(groups[0]?.closed).toBe(true);
    expect(groups[1]?.closed).toBe(false);
  });

  it('treats a cancelled or errored turn as an end too', () => {
    for (const kind of ['turn_cancelled', 'error'] as const) {
      const entries = groupTranscript([
        item('tool_call', { id: 't1', name: 'Bash', input: {} }),
        item(kind, {}),
      ]);
      expect(toolsOf(entries)[0]?.closed, kind).toBe(true);
    }
  });

  it("does NOT let one node's turn end close another node's live group", () => {
    // Under graph fan-out nodes settle independently. Unscoped, node A's
    // `turn_complete` closed node B's still-open group and dropped the spinner
    // off a tool call genuinely in flight — the stale-spinner bug inverted.
    const entries = groupTranscript([
      item('tool_call', { id: 'b1', name: 'Bash', input: {} }, 'coder'),
      item('turn_complete', {}, 'reviewer'),
    ]);
    const group = toolsOf(entries)[0];
    expect(group?.memberId).toBe('coder');
    expect(group?.closed).toBe(false);
  });

  it("closes a group when its OWN node's turn ends", () => {
    // The other half — scoping must not stop a node closing its own groups.
    const entries = groupTranscript([
      item('tool_call', { id: 'b1', name: 'Bash', input: {} }, 'coder'),
      item('turn_complete', {}, 'coder'),
    ]);
    expect(toolsOf(entries)[0]?.closed).toBe(true);
  });

  /** The first tool group anywhere inside one call's card. */
  const groupInCall = (
    entries: readonly TranscriptEntry[],
    callId: string,
  ): ToolGroupEntry | undefined => {
    const find = (
      list: readonly TranscriptEntry[],
    ): ToolGroupEntry | undefined => {
      for (const entry of list) {
        if (entry.type === 'tools') {
          return entry;
        }
        if ('entries' in entry) {
          const nested = find(entry.entries);
          if (nested !== undefined) {
            return nested;
          }
        }
      }
      return undefined;
    };
    const card = collectCallBlocks(entries).find(
      (block) => block.callId === callId,
    );
    return card === undefined ? undefined : find(card.entries);
  };

  it("does NOT let one call's turn end close a SIBLING call's live group", () => {
    // Two calls to one node at once. Judged from the main flow against every
    // item, call-1 finishing closed call-2's in-flight command, and the group
    // drew it `stopped` while it ran.
    const entries = groupTranscript([
      item('call_started', { callId: 'call-1', calleeNodeId: 'eng' }, 'mgr'),
      item('call_started', { callId: 'call-2', calleeNodeId: 'eng' }, 'mgr'),
      item('status', { status: 'running', callId: 'call-1' }, 'eng'),
      item('status', { status: 'running', callId: 'call-2' }, 'eng'),
      item(
        'tool_call',
        { id: 't1', name: 'Bash', input: {}, callId: 'call-1' },
        'eng',
      ),
      item(
        'tool_call',
        { id: 't2', name: 'Bash', input: {}, callId: 'call-2' },
        'eng',
      ),
      item('turn_complete', { callId: 'call-1' }, 'eng'),
      item('status', { status: 'completed', callId: 'call-1' }, 'eng'),
    ]);
    expect(groupInCall(entries, 'call-2')?.closed).toBe(false);
    // The ending still closes the group of the call it belongs to.
    expect(groupInCall(entries, 'call-1')?.closed).toBe(true);
  });

  it("does NOT let a call's turn end close the node's OWN conversation's group", () => {
    // The same node, a different conversation: its own turn is still running.
    const entries = groupTranscript([
      item('tool_call', { id: 'own', name: 'Bash', input: {} }, 'eng'),
      item('call_started', { callId: 'call-1', calleeNodeId: 'eng' }, 'mgr'),
      item('status', { status: 'running', callId: 'call-1' }, 'eng'),
      item('turn_complete', { callId: 'call-1' }, 'eng'),
      item('status', { status: 'completed', callId: 'call-1' }, 'eng'),
    ]);
    const own = toolsOf(entries)[0];
    expect(own?.memberId).toBe('eng');
    expect(own?.closed).toBe(false);
  });
});

