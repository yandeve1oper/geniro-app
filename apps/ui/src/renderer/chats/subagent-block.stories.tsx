function finishedBlock(
  overrides: Partial<SubagentBlockEntry>,
): SubagentBlockEntry {
  const rows: ItemDto[] = [
    {
      id: 'launch',
      runId: 'story',
      memberId: null,
      seq: 1,
      kind: 'tool_call',
      role: null,
      createdAt: '2026-10-18T10:00:00.000Z',
      payload: {
        id: 'review',
        name: 'Task',
        input: {
          description: 'Review the changes',
          prompt: 'Check the changes for bugs.',
        },
      },
    },
    {
      id: 'step',
      runId: 'story',
      memberId: null,
      seq: 2,
      kind: 'tool_call',
      role: null,
      createdAt: '2026-10-18T10:00:30.000Z',
      payload: {
        id: 'grep',
        name: 'Grep',
        input: { pattern: 'off-by-one' },
        parentToolUseId: 'review',
      },
    },
    {
      id: 'done',
      runId: 'story',
      memberId: null,
      seq: 3,
      kind: 'tool_result',
      role: null,
      createdAt: '2026-10-18T10:01:00.000Z',
      payload: {
        id: 'review',
        name: null,
        result: 'Found one.',
        isError: false,
      },
    },
  ];
  const [block] = collectSubagentBlocks(
    buildTurnBlocks(buildSubagentBlocks(groupTranscript(rows), rows)),
  );
  if (block === undefined) {
    throw new Error('Missing story subagent');
  }
  return { ...block, ...overrides };
}

function withLiveFigures(delegates: LiveDelegates) {
  const figures = new Map(Object.entries(delegates));
  return (story: () => React.JSX.Element) => (
    <LiveDelegatesContext.Provider value={figures}>
      {story()}
    </LiveDelegatesContext.Provider>
  );
}

