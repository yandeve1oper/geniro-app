/**
 * One agent-to-agent call folded into a single nested block: the
 * call_started row becomes the header (callee, mode, ask, LIVE status) and
 * every item of the callee's sub-turn renders inside — so two parallel
 * callees never interleave their messages in the main flow.
 *
 * One block is one CONVERSATION, not one call: a call that continues an earlier
 * call's thread joins that call's block (see {@link resolveCallChains}).
 * REPORTED as three stacked `Manager → Engineer` cards read as three Engineers
 * at work, when they were one Engineer conversation continued twice. So the
 * header facts below are the LATEST call's, and `entries` holds every call's
 * sub-turn in order.
 */
export interface CallBlockEntry {
  type: 'call-block';
  /**
   * Stable identity for keys and expansion: the FIRST call's `call_started`
   * id, so a continuation arriving does not remount a card the reader opened.
   * First within the loaded window — an older page bringing earlier calls of
   * the conversation in moves it back once, costing the card its fold state.
   */
  id: string;
  /**
   * The LATEST call's `call_started` timestamp — the block is drawn at that
   * row's position, so its time matches where it sits.
   */
  createdAt: string;
  /**
   * The LATEST call — the one whose sub-turn is live, and the key the per-call
   * live plane is read by. Matching a call id to a block goes through
   * {@link callIds}, never this alone.
   */
  callId: string;
  /** Every call folded into this block, oldest first; `callId` is the last. */
  callIds: string[];
  /**
   * Every call of the CONVERSATION, oldest first — including the ones whose
   * rows are older than the loaded window, which {@link callIds} cannot name.
   *
   * The two differ by exactly what the window holds, and that difference is a
   * FIGURE rather than a rendering detail. A card's spend is summed over the
   * calls it names (`resolveConversationSpend`), so while it named only the
   * windowed ones the money shrank as the window rolled forward, with nothing
   * on screen saying so. MEASURED on a real run whose Engineer held three
   * conversations: the daemon reported $188.96 / $289.33 / $150.50 (its node
   * total, $628.79) while the three cards drew $7.34 / $29.13 / $11.95 — the
   * newest call of each chain, the only one still loaded — and an hour later
   * two of them drew no cost at all. REPORTED as "стоимость читается
   * некорректно… когда он только вызывал агентов, там была другая цифра".
   *
   * The daemon knows the whole chain: `calls[].start.thread` on the nodes route
   * is what {@link resolveCallChains} already walks, so this costs no fetch —
   * only the decision to keep what that walk found. `callIds` stays the
   * WINDOWED list, because everything else about a block is drawn from rows
   * (its entries, its open calls, its task lists) and a call with no rows here
   * has nothing to draw.
   */
  conversationCallIds: string[];
  calleeMemberId: string | null;
  /** The caller node the call_started row was attributed to. */
  callerMemberId: string | null;
  mode: string | null;
  /**
   * The FIRST call's ask — the block's REQUEST. A continuation's own ask stays
   * in {@link entries} as its `call_started` row, at the point it was sent (see
   * {@link isCallContinuation}).
   */
  message: string | null;
  /**
   * A short, human-readable reason for the LATEST call, shown as the card's
   * prominent header line.
   *
   * TWIN PARSER: written by `CallBroker.callAgent`'s `call_started` payload —
   * see `apps/daemon/src/v1/teams/services/call-broker.service.ts`. Null on
   * an older row (written before this field existed) or on a caller that
   * skipped MCP validation — never treated as "no reason", just as absent.
   */
  title: string | null;
  /** The LATEST call's sub-turn lifecycle, from its callId-tagged status items. */
  status: 'pending' | 'running' | 'completed' | 'failed' | 'cancelled';
  /**
   * The callee's final message once the LATEST call's sub-turn COMPLETED — the
   * block's RESULT, pulled out of {@link entries} (geniro-style request →
   * result framing). Null while running or when the sub-turn did not complete.
   * An earlier call's final message stays in `entries` where it was said: it is
   * what the next ask was answering.
   */
  result: string | null;
  /**
   * The daemon has said the LATEST call's callee stopped producing.
   *
   * TWIN PARSER: written by `CallBroker`'s silence watchdog as a `system` row
   * carrying `stalledCall: true` and this call's id — see
   * `apps/daemon/src/v1/teams/services/call-broker.service.ts`
   * (`announceStall`). It is a claim about the CALL, not about the run: the
   * call is still open and nothing has been cancelled, so the block goes on
   * running and only says that it has gone quiet.
   *
   * A later row from the same call CLEARS it — the daemon announces a silence
   * once and never retracts it, so the supersession is this side's job.
   *
   * The row itself deliberately stays in the caller's MAIN flow rather than
   * claiming into this block — a warning folded inside a collapsed card is a
   * warning nobody reads.
   */
  stalled: boolean;
  /**
   * How many of the conversation's sub-agents the daemon says are running with
   * no block in {@link entries}: launched above the loaded window. Added on top
   * of the blocks' own readings, see {@link callBlockSubagentsRunning}.
   */
  offWindowSubagents?: number;
  /**
   * How many calls of its own the callee is WAITING for: it ended its turn
   * with them still running, so the call stays open until they finish and the
   * callee is continued inside it. Absent while it is not waiting.
   *
   * TWIN PARSER: written by `CallBroker.holdCall` as a `system` row carrying
   * `heldCall: { waitingOn }` and this call's id — see
   * `apps/daemon/src/v1/teams/services/call-broker.service.ts`. Ended by the
   * callee being continued (its wake notice), a status row, or the call's
   * result — never by an unrelated row its process writes meanwhile.
   */
  heldOn?: number;
  /**
   * The callee ended its turn while its call stays open, so nothing of it runs
   * until what the call is held for reports: calls of its own ({@link heldOn})
   * or monitors it started, listed here by description while their start is on
   * the page and their end is not. Absent while the callee is mid-turn.
   *
   * Read from the call's own rows, its sub-agents' left out: its statuses are
   * anchored on every page, so a turn still running always shows its `running`
   * row after its last ending. TWIN PARSER: the daemon's hold is `CallBroker.holdCall` (calls) and `monitorsOwed`
   * (monitors), which writes no row of its own for a monitor; the monitor rows
   * are `readMonitorNotice`'s.
   */
  waiting?: { monitors: readonly string[] };
  /**
   * The callee was woken inside this open call — by its monitors or the calls
   * it waited for — and has said nothing since, so its words from before the
   * wake are not what it is doing now. Absent otherwise.
   */
  quietSinceWake?: true;
  /**
   * The LATEST call is waiting for room under its run's active-turn cap
   * (`Workflow.maxActiveTurns`): asked for, not started. Set only while the
   * call is still `pending` — its first status row ends it.
   *
   * TWIN PARSER: written by `GraphExecutorService`'s `launchCalleeTurn` as a
   * `system` row carrying `queuedCall: { cap }` and this call's id — see
   * `apps/daemon/src/v1/teams/services/graph-executor.service.ts`; the
   * daemon's whole-run reading of the same row is `RunCallState.queued`
   * (`ItemDao.callQueueRows`, `foldRunCalls`).
   */
  queued?: true;
  /**
   * The seq of the `queuedCall` row behind {@link queued} — what a run-state
   * read must have covered before it may say the call has since started
   * (`withDaemonStartedCalls`).
   */
  queuedSeq?: number;
  /**
   * The LATEST call has SETTLED and its callee is working in it again.
   *
   * A callee's process outlives its call's turn, and it routinely carries on
   * by itself — cursor's background reviewers report back after the call has
   * already handed its result over, and the agent answers them under the same
   * `callId` (the executor's off-turn `running` row). The call stays settled:
   * the caller has its answer and nothing reopens it. What must not happen is
   * what did: that callee counts as WORKING and has no open call, so its live
   * row opened a turn block of its own at the end of the transcript — an
   * empty `QA · Forging…` card beside the settled card its rows were actually
   * landing in. REPORTED as a "suspicious empty agent block". This is what
   * lets the live row find the card instead.
   */
  calleeWorking: boolean;
  /**
   * The callee pool member the call ran on — the settle's `member`, else the
   * one its newest hand-off moved it to, else the one it started on; absent
   * for a callee with no pool.
   */
  member?: number;
  /** Latest pool handoff, retained even when its row is only an anchor. */
  poolHandOff?: { message: string; seq: number };
  /**
   * Every call's sub-turn in order, each continuation's preceded by its own
   * `call_started` row (see {@link isCallContinuation}).
   */
  entries: TranscriptEntry[];
}

