/**
 * A CARD entry: a folded row that stands on its own — not a raw item, not a
 * block enclosing other rows.
 *
 * They share one shape (`id`/`createdAt`/`seq`/`nodeId`/`parentToolUseId`) and,
 * more to the point, share how the readers below have to treat them: who owns
 * it, which thread it belongs to, its `seq` for ordering nested work, its
 * `createdAt` for "has anything spoken since", and the fact that it holds no
 * tool invocations to count.
 *
 * Extracted once there were several. Each of those readers spelled the same
 * `entry.type === …` chain by hand, so a new card kind was an edit per reader,
 * every one of them silent when missed — a card left out of the `lastRowAt`
 * fold does not fail, it just stops a spinner from noticing that work has
 * happened. One predicate made the next card a single line.
 *
 * The union and the predicate must list the SAME kinds, and the COMPILER is
 * what enforces it: adding `comparison` to the predicate alone — which is how
 * the fifth card actually went in — narrowed nothing, and five call sites
 * stopped compiling because a `ComparisonEntry` reached a branch expecting
 * `.entries`. That is the trade this abstraction makes, and it is the whole
 * point of it: six silent misses became one loud one.
 */
export type CardEntry =
  | TaskListEntry
  | FindingsEntry
  | RecommendationsEntry
  | LessonsEntry
  | ChartEntry
  | MetricsEntry
  | ComparisonEntry
  | GalleryEntry
  | BrowserScreenshotEntry
  | ArtifactEntry
  | ActionEntry
  | WorkflowEntry;

export function isCardEntry(entry: TranscriptEntry): entry is CardEntry {
  return (
    entry.type === 'task-list' ||
    entry.type === 'findings' ||
    entry.type === 'recommendations' ||
    entry.type === 'lessons' ||
    entry.type === 'chart' ||
    entry.type === 'metrics' ||
    entry.type === 'comparison' ||
    entry.type === 'gallery' ||
    entry.type === 'browser-screenshot' ||
    entry.type === 'artifact' ||
    entry.type === 'action' ||
    entry.type === 'workflow'
  );
}

/** Sentinel: entry has no agent owner and breaks a turn block. */
const NO_OWNER = Symbol('no-owner');

/**
 * The node AND originating thread an entry belongs to — the same pairing
 * {@link groupKey} folds tool groups by. `nodeId` alone is not enough: a
 * sub-agent's rows carry the MAIN agent's nodeId, so keying on it alone
 * folded a delegate's words into the main agent's block under its own
 * SenderRow.
 */
interface EntryOwner {
  memberId: string | null;
  subagentId: string | null;
}

function sameOwner(a: EntryOwner, b: EntryOwner): boolean {
  return a.memberId === b.memberId && a.subagentId === b.subagentId;
}

/** The agent a top-level entry belongs to (NO_OWNER breaks the block). */
function ownerOf(entry: TranscriptEntry): EntryOwner | typeof NO_OWNER {
  if (entry.type === 'tools') {
    return { memberId: entry.memberId, subagentId: entry.parentToolUseId };
  }
  if (entry.type === 'call-block') {
    // A call is ALWAYS its own top-level card, never part of the caller's
    // block. The card names both sides and carries the caller's `title`, so a
    // block around it is a second frame holding one card — REPORTED twice, as
    // "не должно быть блока менеджера в этом случае" and "там два блока в
    // одном, такого не должно быть". The caller's own words keep their block
    // on either side of it.
    return NO_OWNER;
  }
  if (entry.type === 'subagent-block') {
    // The DELEGATING agent's, not the delegate's — the block belongs in the
    // turn where the delegation happened, which is what puts it beside the
    // tool row that launched it. Its own rows are already inside it.
    return { memberId: entry.memberId, subagentId: null };
  }
  if (entry.type === 'turn-block') {
    return { memberId: entry.memberId, subagentId: null };
  }
  if (isCardEntry(entry)) {
    return { memberId: entry.memberId, subagentId: entry.parentToolUseId };
  }
  const item = entry.item;
  if (item.kind === 'message' && item.role !== 'user') {
    return { memberId: item.memberId, subagentId: subagentIdOf(item) };
  }
  if (
    item.kind === 'reasoning' ||
    item.kind === 'error' ||
    item.kind === 'system'
  ) {
    return { memberId: item.memberId, subagentId: subagentIdOf(item) };
  }
  return NO_OWNER;
}

/**
 * The identity a top-level entry is keyed and tracked by.
 *
 * An item is its row's id and every folded entry carries its own — EXCEPT the
 * pointer an earlier call of a continued conversation leaves behind
 * (`ItemEntry.continuedIn`): that row is the conversation's FIRST
 * `call_started`, whose id is also the card's identity, so keying both by it
 * handed React two children with one key and let it swap them.
 */
export function transcriptEntryKey(entry: TranscriptEntry): string {
  if (entry.type !== 'item') {
    return entry.id;
  }
  return entry.continuedIn === undefined
    ? entry.item.id
    : `continued:${entry.item.id}`;
}

function entryId(entry: TranscriptEntry): string {
  return transcriptEntryKey(entry);
}

function entryCreatedAt(entry: TranscriptEntry): string {
  if (entry.type === 'item') {
    return entry.item.createdAt;
  }
  if (entry.type === 'tools') {
    return entry.pairs[0]?.call.createdAt ?? '';
  }
  return entry.createdAt;
}

/**
 * Fold consecutive same-agent entries into turn blocks. Applied by the
 * MAIN flow only (a communication card's inner content is already one
 * story); user messages, notes and approval cards break a block.
 */
export function buildTurnBlocks(
  entries: readonly TranscriptEntry[],
): TranscriptEntry[] {
  const out: TranscriptEntry[] = [];
  let open: TurnBlockEntry | null = null;
  let openOwner: EntryOwner | null = null;
  for (const entry of entries) {
    const owner = ownerOf(entry);
    if (owner === NO_OWNER) {
      open = null;
      openOwner = null;
      out.push(entry);
      continue;
    }
    if (open && openOwner && sameOwner(openOwner, owner)) {
      open.entries.push(entry);
      continue;
    }
    open = {
      type: 'turn-block',
      id: entryId(entry),
      createdAt: entryCreatedAt(entry),
      memberId: owner.memberId,
      subagentId: owner.subagentId,
      entries: [entry],
    };
    openOwner = owner;
    out.push(open);
  }
  return out;
}

/**
 * Kinds that stay in the MAIN flow even when a delegate produced them — the
 * same carve-out {@link UNCLAIMABLE_KINDS} makes for call blocks, and for the
 * same reason: a permission card folded into a collapsed block is a card
 * nobody can see they have to answer.
 */
const SUBAGENT_UNCLAIMABLE_KINDS = new Set<ChatItem['kind']>([
  'approval_request',
  'approval_verdict',
]);

/** The sub-agent an already-folded entry belongs to, or null for the main thread. */
function subagentOwnerOf(entry: TranscriptEntry): string | null {
  if (entry.type === 'tools') {
    return entry.parentToolUseId;
  }
  if (entry.type === 'item') {
    return SUBAGENT_UNCLAIMABLE_KINDS.has(entry.item.kind)
      ? null
      : subagentIdOf(entry.item);
  }
  if (entry.type === 'turn-block') {
    return entry.subagentId;
  }
  if (isCardEntry(entry)) {
    return entry.parentToolUseId;
  }
  // A call block is a NODE-to-node call and a sub-agent block is already an
  // enclosure — neither is a delegate's row needing one.
  return null;
}

/** The node an already-folded entry belongs to. */
function entryNodeId(entry: TranscriptEntry): string | null {
  if (entry.type === 'item') {
    return entry.item.memberId;
  }
  if (entry.type === 'call-block') {
    return entry.callerMemberId;
  }
  return entry.memberId;
}

/**
 * The call thread one entry's rows were streamed in, for the one caller that
 * has an entry and no launching call to read it from — the twin of
 * {@link entryNodeId} for `payload.callId`.
 *
 * Only the two shapes a delegate's first row can take are read: a plain row,
 * and a tool group (whose calls all share one thread, a group being keyed by
 * node and thread). Anything else answers null — the node's own conversation —
 * which is where the rows it describes were filed before calls were told apart.
 */
function entryCallId(entry: TranscriptEntry): string | null {
  if (entry.type === 'item') {
    return payloadString(entry.item.payload, 'callId');
  }
  if (entry.type === 'tools') {
    const first = entry.pairs[0];
    return first ? payloadString(first.call.payload, 'callId') : null;
  }
  return null;
}

/**
 * The LOWEST `seq` any row inside one entry carries — where that entry BEGINS
 * in the transcript — or null when it encloses no row at all.
 *
 * What makes a rendered entry addressable by seq, which is what a search hit
 * names. The lowest rather than the highest because the lookup that uses it is
 * nearest-at-or-below: an entry is the right landing place for every row it
 * holds, and a block spanning 480–520 has to answer for a hit at 500.
 *
 * A range rather than a point is the whole difficulty — the fold collapses runs
 * of rows into one turn block, one tool group, one card — so an exact match is
 * not available and must not be assumed by callers.
 */
export function entryStartSeq(entry: TranscriptEntry): number | null {
  if (entry.type === 'item') {
    return entry.item.seq;
  }
  if (entry.type === 'tools') {
    // The CALL's seq: a pair begins where it was invoked, and its result may be
    // thousands of rows later on a long-running command.
    return entry.pairs.reduce<number | null>(
      (min, pair) =>
        min === null ? pair.call.seq : Math.min(min, pair.call.seq),
      null,
    );
  }
  if (isCardEntry(entry)) {
    return entry.seq;
  }
  return entry.entries.reduce<number | null>((min, inner) => {
    const seq = entryStartSeq(inner);
    if (seq === null) {
      return min;
    }
    return min === null ? seq : Math.min(min, seq);
  }, null);
}

/**
 * The newest row an entry draws — {@link entryStartSeq}'s other end, a tool
 * pair's result included.
 */
export function entryEndSeq(entry: TranscriptEntry): number | null {
  if (entry.type === 'item') {
    return entry.item.seq;
  }
  if (entry.type === 'tools') {
    return entry.pairs.reduce<number | null>((max, pair) => {
      const end = Math.max(pair.call.seq, pair.result?.seq ?? pair.call.seq);
      return max === null ? end : Math.max(max, end);
    }, null);
  }
  if (entry.type === 'browser-screenshot') {
    return Math.max(entry.seq, entry.pair.result?.seq ?? entry.seq);
  }
  if (isCardEntry(entry)) {
    return entry.seq;
  }
  return entry.entries.reduce<number | null>((max, inner) => {
    const seq = entryEndSeq(inner);
    if (seq === null) {
      return max;
    }
    return max === null ? seq : Math.max(max, seq);
  }, null);
}

/** The highest `seq` any row inside these entries carries (0 when empty). */
function maxSeqOf(list: readonly TranscriptEntry[]): number {
  let max = 0;
  for (const entry of list) {
    if (entry.type === 'item') {
      max = Math.max(max, entry.item.seq);
      continue;
    }
    if (entry.type === 'tools') {
      for (const pair of entry.pairs) {
        max = Math.max(max, pair.result?.seq ?? pair.call.seq);
      }
      continue;
    }
    if (entry.type === 'browser-screenshot') {
      max = Math.max(max, entry.pair.result?.seq ?? entry.seq);
      continue;
    }
    if (isCardEntry(entry)) {
      max = Math.max(max, entry.seq);
      continue;
    }
    max = Math.max(max, maxSeqOf(entry.entries));
  }
  return max;
}

/**
 * When a run stopped, for the readers that must ask whether a piece of nested
 * work has spoken SINCE.
 *
 * Three states, not two, because a settle with no readable moment is not the
 * same as no settle. Folding them lost the FACT the moment was meant to refine:
 * an unparseable `updatedAt` silently re-enabled every spinner on a cancelled
 * run. `'unknown'` keeps the old, conservative reading — the run is over and
 * everything unreturned is stopped — while a number allows the exception.
 */
export type RunSettleAt = number | 'unknown' | null;

/** The newest `createdAt` (ms) any row inside these entries carries. */
function lastRowAtOf(list: readonly TranscriptEntry[]): number | null {
  let latest: number | null = null;
  const consider = (createdAt: string): void => {
    const at = Date.parse(createdAt);
    if (Number.isFinite(at) && (latest === null || at > latest)) {
      latest = at;
    }
  };
  for (const entry of list) {
    if (entry.type === 'item') {
      consider(entry.item.createdAt);
      continue;
    }
    if (entry.type === 'tools') {
      for (const pair of entry.pairs) {
        consider(pair.result?.createdAt ?? pair.call.createdAt);
      }
      continue;
    }
    if (entry.type === 'browser-screenshot') {
      consider(entry.pair.result?.createdAt ?? entry.createdAt);
      continue;
    }
    if (isCardEntry(entry)) {
      consider(entry.createdAt);
      continue;
    }
    const nested = lastRowAtOf(entry.entries);
    if (nested !== null && (latest === null || nested > latest)) {
      latest = nested;
    }
  }
  return latest;
}

/**
 * Whether a delegate has produced a row SINCE the run settled — "is it
 * audible", not "is it over".
 *
 * The two questions were one predicate until the daemon took over stating a
 * delegate's ending: silence past the settle used to mean the work was
 * unreportable and the block was downgraded for it. It no longer decides
 * anything about the WORK — a declared-open delegate is working until an
 * outcome says otherwise ({@link subagentBlockStatus}) — and what it decides
 * instead is which reading the turn-end notification takes: a delegate writing
 * rows keeps the run `running`, while one merely declared out, which the run
 * row counts (`subagentsOut`), does not. A run that has not settled is all
 * live, so everything is audible; a settle nobody can place makes nothing
 * audible, which is the conservative half of {@link RunSettleAt} in its new
 * job.
 */
export function subagentSpokeSince(
  block: SubagentBlockEntry,
  runSettledAt: RunSettleAt = null,
): boolean {
  if (runSettledAt === null) {
    return true;
  }
  if (runSettledAt === 'unknown') {
    return false;
  }
  return block.lastRowAt !== null && block.lastRowAt > runSettledAt;
}

/**
 * How a delegate stands. The daemon's whole-conversation reading wins; without
 * it, the block's own rows supply explicit outcomes, and a parent settling or
 * disappearing is left for that reading to resolve.
 *
 * TWIN PARSER: `delegateStatus` in
 * apps/daemon/src/v1/agents/utils/run-state-folds.ts — a close naming no
 * outcome reads `untracked` only while a recovery ref stands, and `completed`
 * otherwise.
 */
export function subagentBlockStatus(
  block: SubagentBlockEntry,
): 'running' | BackgroundOutcome {
  if (block.daemonStatus !== undefined) {
    return block.daemonStatus;
  }
  if (block.failed) {
    return 'failed';
  }
  if (block.backgroundOutcome !== null) {
    return block.backgroundOutcome;
  }
  if (block.backgroundOpen === true) {
    return 'running';
  }
  if (block.backgroundOpen === false) {
    return block.recoverable ? 'untracked' : 'completed';
  }
  if (block.returned) {
    return 'completed';
  }
  return 'running';
}

/**
 * What to call a delegate: its own description, else its type, else generic.
 *
 * One derivation, beside the status one and for the same reason — the block
 * header, the panel row and the dialog title must never disagree about a
 * delegate's name.
 */
export function subagentTitle(block: SubagentBlockEntry): string {
  return (
    block.label ??
    block.kind ??
    // NOT the bare word. Nothing here is guessing at a name — the point is that
    // an unnamed delegate is still a DISTINCT delegate, and a constant made
    // every one of them the same row: reported against a panel listing one
    // "Review: optimizations" over seven identical `sub-agent`s, where the only
    // question a reader has ("which spinner is which piece of work") had no
    // answer on screen and no way to get one.
    //
    // Both fields being null is ordinary rather than exotic. The launching call
    // is the only thing that ever carries a description, so any delegate whose
    // launch is outside the loaded window — a transcript opened mid-run, or a
    // backgrounded agent later RESUMED by a different call — arrives with
    // neither. The daemon's own `subagent_info` cannot cover for it: measured
    // across all 76 declarations on the user's ledger, every one carries
    // `label: null, kind: null` and speaks only about `backgroundOpen`.
    //
    // So the identity is what is shown, because it is what is known. Its tail
    // rather than the whole: `toolu_01AD1kjdJCqfkzGRTjn5M6mo` is twenty-odd
    // characters of prefix shared by every row, and it is the end that differs.
    `Sub-agent ${subagentRef(block.id)}`
  );
}

/**
 * Whether a delegate carries a name of its OWN, or only the identity
 * {@link subagentTitle} falls back to.
 *
 * Exists so a surface that prefixes the title with its category — the detail
 * dialog's `Sub-agent · …` — can drop the prefix rather than stutter it, which
 * is what produced the reported `Sub-agent · sub-agent`.
 */
export function subagentNamed(block: SubagentBlockEntry): boolean {
  return block.label !== null || block.kind !== null;
}

/**
 * How many tool invocations these entries hold, at any depth.
 *
 * One recursion, shared by both block kinds: a shallow count and a deep count
 * of the same "N tools" label meant different things per card.
 */
/**
 * The last thing the CALLEE said in a call block — what a COLLAPSED one shows
 * as its current state.
 *
 * ASKED FOR alongside the fold: "we always should see last message there, like
 * its current state". A shut card whose header names only `Manager → QA` says
 * that a call happened and nothing about where it has got to, which for a call
 * still running is the one thing a reader wants without opening it.
 *
 * The RESULT wins when there is one, because it lands after every row in
 * {@link CallBlockEntry.entries} and is the callee's final answer — the block
 * pulls it out of those entries for exactly that reason. Otherwise the newest
 * assistant message, found by walking backwards through the callee's own turn
 * blocks, which its rows are routinely folded into. A sub-agent's thread is
 * never entered: it has a card and a spinner of its own, and its words are not
 * the callee's.
 *
 * Null when the callee has not spoken yet, and never the caller's own ask: that
 * is what the block was ASKED, not where it has got to, and the header already
 * names both ends of the call. A block with no summary is one whose header's
 * spinner is the whole of the answer.
 *
 * Read from the LATEST call's rows alone ({@link latestCallTurn}): a
 * continuation that has not spoken yet is thinking about the new ask, and the
 * answer to the previous one would report it as already done.
 */
export function callBlockSummary(block: CallBlockEntry): string | null {
  if (block.result !== null) {
    return block.result;
  }
  if (block.quietSinceWake === true) {
    return null;
  }
  const spoken = lastSpokenIn(latestCallTurn(block));
  if (
    block.poolHandOff !== undefined &&
    (spoken === null || block.poolHandOff.seq > spoken.seq)
  ) {
    return block.poolHandOff.message;
  }
  return spoken?.text ?? null;
}

/**
 * Narrowed to the KIND rather than to `ItemEntry`, so the other branch of
 * {@link isCallContinuation} keeps every ordinary row.
 */
type CallContinuationEntry = ItemEntry & {
  item: { kind: 'call_started' };
};

/**
 * A continued call's `call_started` row inside a conversation block — the
 * marker of where that call's ask was sent. The block's bucket never holds a
 * call row of its own (`call_started` is unclaimable), so at a block's top
 * level this kind is only ever that marker.
 */
export function isCallContinuation(
  entry: TranscriptEntry,
): entry is CallContinuationEntry {
  return entry.type === 'item' && entry.item.kind === 'call_started';
}

/** A block's entries split at its continuation markers — one run per call. */
function callSegments(block: CallBlockEntry): TranscriptEntry[][] {
  const segments: TranscriptEntry[][] = [[]];
  for (const entry of block.entries) {
    if (isCallContinuation(entry)) {
      segments.push([]);
      continue;
    }
    segments[segments.length - 1]!.push(entry);
  }
  return segments;
}

/** The entries after a block's last continuation marker — its LATEST call's. */
function latestCallTurn(block: CallBlockEntry): readonly TranscriptEntry[] {
  const segments = callSegments(block);
  return segments[segments.length - 1]!;
}

function lastSpokenIn(
  entries: readonly TranscriptEntry[],
): { text: string; seq: number } | null {
  for (let i = entries.length - 1; i >= 0; i -= 1) {
    const entry = entries[i]!;
    if (entry.type === 'item') {
      // The only user rows in a call block are messages the user sent straight
      // to the callee, which are not where the callee has got to. Excluded by
      // `role === 'user'` rather than admitted by `role === 'assistant'`,
      // since a transport may leave the column null on the callee's own rows.
      if (entry.item.kind === 'message' && entry.item.role !== 'user') {
        const text = payloadString(entry.item.payload, 'text');
        if (text !== null && text.trim().length > 0) {
          return { text, seq: entry.item.seq };
        }
      }
      continue;
    }
    if (entry.type !== 'turn-block') {
      continue;
    }
    const nested = lastSpokenIn(entry.entries);
    if (nested !== null) {
      return nested;
    }
  }
  return null;
}

/**
 * What the callee is DOING — the newest tool call still in flight, or null when
 * none is: a tool that has returned is not what the callee is on, and naming it
 * contradicts that tool's own row.
 *
 * A SECOND fold beside {@link callBlockSummary} rather than a fallback inside
 * it, because the two answer different questions: that one is what the callee
 * SAID, and a tool name rendered in the summary slot would read as the callee's
 * own words.
 *
 * It exists because a tool-using callee is wordless for nearly all of a call —
 * its first message routinely lands with the result — so a message-only band
 * says nothing for the whole of the work it is meant to describe.
 *
 * Tool invocations are read from `tools` groups alone: a card entry hides the
 * calls that produced it, and this band names only work with a row to open.
 *
 * The LATEST call's tools alone, on {@link callBlockSummary}'s rule: a tool an
 * earlier call finished is not what the callee is doing now.
 *
 * The callee's OWN tools alone, on the same rule: its sub-agents run theirs at
 * once, so reading them would change this line on each of their tool calls.
 */
export function callBlockActivity(block: CallBlockEntry): string | null {
  return newestToolNameIn(latestCallTurn(block));
}

/**
 * How many of the callee's own sub-agents are still running: the blocks on
 * screen, as each reads, plus those the daemon holds and the window does not.
 */
export function callBlockSubagentsRunning(block: CallBlockEntry): number {
  const onScreen = collectSubagentBlocks(block.entries).filter(
    (entry) => subagentBlockStatus(entry) === 'running',
  );
  return onScreen.length + (block.offWindowSubagents ?? 0);
}

/**
 * Where one call has got to, as ONE line — what the agents panel's instance row
 * says under the call's ask.
 *
 * The same two readings the block's own band draws, in the same order: what
 * the callee last SAID (its result, once it has one), else the tool it is
 * running. Only the FIRST line of the words, with a leading markdown marker
 * dropped, because the row is a single line and a heading's `#` or a list's
 * `-` would otherwise lead it.
 */
export function callBlockLatest(block: CallBlockEntry): string | null {
  const said = callBlockSummary(block);
  if (said !== null) {
    const line = said
      .split('\n')
      .map((part) => part.replace(/^\s*(?:#+|[-*>]|\d+\.)\s*/, '').trim())
      .find((part) => part.length > 0);
    if (line !== undefined) {
      return line;
    }
  }
  const activity = callBlockActivity(block);
  return activity === null ? null : `running ${activity}`;
}

function newestToolNameIn(entries: readonly TranscriptEntry[]): string | null {
  for (let i = entries.length - 1; i >= 0; i -= 1) {
    const entry = entries[i]!;
    if (entry.type === 'tools') {
      // Backwards through the group's OWN pairs, not just its last one: a run
      // of tool calls from one node folds into a single group, so reading only
      // the newest pair lets a call that disclosed no name hide the named one
      // before it — and an ACP agent routinely discloses none.
      if (entry.closed) {
        continue;
      }
      for (let p = entry.pairs.length - 1; p >= 0; p -= 1) {
        const pair = entry.pairs[p]!;
        if (pair.result !== null) {
          continue;
        }
        const name = payloadString(pair.call.payload, 'name');
        if (name !== null && name.trim().length > 0) {
          return name;
        }
      }
      continue;
    }
    if (entry.type !== 'turn-block') {
      continue;
    }
    const nested = newestToolNameIn(entry.entries);
    if (nested !== null) {
      return nested;
    }
  }
  return null;
}

/** What one call block's own turns have spent — the footer's two figures. */
export interface CallBlockUsage {
  /** Input + output, on the agent card's own rule — never the cache reads. */
  tokens: number | null;
  costUsd: number | null;
  /** Of {@link costUsd}, the part geniro priced itself; absent when none. */
  estimatedCostUsd?: number | null;
}

/**
 * What the callee has SPENT inside this block, summed from its own
 * `turn_complete` rows.
 *
 * ASKED FOR on the block footer beside the tool count: "for footer lets write
 * also tokens and money". The figures were in the block already — every
 * `turn_complete` carries them — and were readable only by opening that row.
 *
 * The token figure is INPUT + OUTPUT, the same reading the agents panel's own
 * spend line takes, so the two surfaces cannot state different numbers about
 * one agent's work. Cache reads are left out there for a measured reason and
 * the same one holds here.
 *
 * Null means UNMEASURED, never zero: a call whose turn has not ended yet has
 * reported nothing — there is no live token or cost channel on either CLI, so
 * the figures appear when the turn lands — and cursor-agent reports no cost at
 * all, which is why the two halves are independent.
 *
 * Summed across EVERY call of a continued conversation: it is one callee
 * session, and its spend accumulates across the asks as it does across turns.
 */
export function callBlockUsage(block: CallBlockEntry): CallBlockUsage {
  const usage: CallBlockUsage = { tokens: null, costUsd: null };
  addCallUsage(block.entries, usage);
  return usage;
}

function addCallUsage(
  entries: readonly TranscriptEntry[],
  into: CallBlockUsage,
): void {
  for (const entry of entries) {
    if (entry.type === 'item') {
      if (entry.item.kind !== 'turn_complete') {
        continue;
      }
      const usage = recordOf(recordOf(entry.item.payload)?.usage);
      if (usage === undefined) {
        continue;
      }
      const tokens = addFigure(
        addFigure(into.tokens, usage.inputTokens),
        usage.outputTokens,
      );
      into.tokens = tokens;
      into.costUsd = addFigure(into.costUsd, usage.costUsd);
      // A zero priced part is none at all.
      if ((measured(usage.estimatedCostUsd) ?? 0) > 0) {
        into.estimatedCostUsd = addFigure(
          into.estimatedCostUsd ?? null,
          usage.estimatedCostUsd,
        );
      }
      continue;
    }
    if (entry.type === 'tools' || isCardEntry(entry)) {
      continue;
    }
    addCallUsage(entry.entries, into);
  }
}

/** How full the CALLEE's window was when it last reported, for its own ring. */
export interface CallBlockContext {
  contextTokens: number | null;
  contextWindowTokens: number | null;
  /** Whether {@link contextTokens} is geniro's stand-in for a reading. */
  contextEstimated?: boolean;
}

/**
 * The callee's own context reading, folded out of this block.
 *
 * The LAST turn's figures rather than a sum, which is what separates this from
 * `callBlockUsage` beside it: spend ACCUMULATES across a callee's turns, while
 * a context reading is a LEVEL — adding two of them produces a number the
 * callee never held, and one over a window would read as a ring past full.
 *
 * Folded rather than passed in as a prop, because neither other source reaches
 * here: the live per-call plane is keyed `<nodeId>::<callId>` and reaches no
 * ancestor of a call block, and the durable row the sidebar's rings read is
 * fetched per NODE. The block's own `turn_complete` rows are already in hand.
 *
 * Each figure is carried independently, on the daemon's own rule: a reading
 * that omits one half says nothing about it, so a later turn reporting only a
 * count must not erase the window an earlier one reported.
 *
 * Across a continued conversation the walk runs over every call in order, so
 * the reading is the newest turn's — the one session's current level.
 */
export function callBlockContext(block: CallBlockEntry): CallBlockContext {
  const found: CallBlockContext = {
    contextTokens: null,
    contextWindowTokens: null,
  };
  readCallContext(block.entries, found);
  return found;
}

function readCallContext(
  entries: readonly TranscriptEntry[],
  into: CallBlockContext,
): void {
  for (const entry of entries) {
    if (entry.type === 'item') {
      if (entry.item.kind !== 'turn_complete') {
        continue;
      }
      const usage = recordOf(recordOf(entry.item.payload)?.usage);
      if (usage === undefined) {
        continue;
      }
      const tokens = measured(usage.contextTokens);
      const window = measured(usage.contextWindowTokens);
      if (tokens !== null) {
        into.contextTokens = tokens;
        if (usage.contextEstimated === true) {
          into.contextEstimated = true;
        } else {
          delete into.contextEstimated;
        }
      }
      if (window !== null) {
        into.contextWindowTokens = window;
      }
      continue;
    }
    if (entry.type === 'tools' || isCardEntry(entry)) {
      continue;
    }
    readCallContext(entry.entries, into);
  }
}

/**
 * A figure worth drawing — the renderer's half of the rule the daemon's own
 * `positive` states: a turn that reported `0` measured nothing, and both halves
 * of a ring read it as a numerator or a denominator that cannot be right.
 */
function measured(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) && value > 0
    ? value
    : null;
}

function recordOf(value: unknown): Record<string, unknown> | undefined {
  return typeof value === 'object' && value !== null
    ? (value as Record<string, unknown>)
    : undefined;
}

/** Add a reported figure to a running total, where null means UNMEASURED. */
function addFigure(total: number | null, next: unknown): number | null {
  if (typeof next !== 'number' || !Number.isFinite(next) || next < 0) {
    return total;
  }
  return (total ?? 0) + next;
}

/**
 * The callee's task list as it stands INSIDE this call block — what the shut
 * card's own tasks chip lists.
 *
 * Each call's LAST card wins for that call, on `TaskListCard`'s own rule: a
 * list is announced many times over a turn and every card but the newest is a
 * step on the way there. A continued conversation's calls are then combined in
 * call order through `combineTaskLists` — the rule the agents panel's instance
 * applies — so the shut card and the instance state one list, not the latest
 * call's partial one beside the whole. Empty when the callee keeps none, which
 * is what withholds the chip.
 *
 * The callee's OWN list alone: a sub-agent keeps one of its own in its block.
 */
export function callBlockTasks(block: CallBlockEntry): readonly AgentTaskRow[] {
  let tasks: readonly AgentTaskRow[] = [];
  for (const segment of callSegments(block)) {
    const last = lastTaskListIn(segment);
    if (last !== null) {
      tasks = combineTaskLists(tasks, last.tasks, last.snapshot);
    }
  }
  return tasks;
}

function lastTaskListIn(
  entries: readonly TranscriptEntry[],
): TaskListEntry | null {
  for (let i = entries.length - 1; i >= 0; i -= 1) {
    const entry = entries[i]!;
    if (entry.type === 'task-list') {
      return entry;
    }
    if (entry.type !== 'turn-block') {
      continue;
    }
    const nested = lastTaskListIn(entry.entries);
    if (nested !== null) {
      return nested;
    }
  }
  return null;
}

/**
 * The tools the agent a card is about called, as far as the loaded rows show —
 * the fallback while the daemon has no figure. A nested sub-agent or call is
 * another agent with a count of its own, so it is not added, as the daemon's
 * figures do not add it.
 */
export function countTools(entries: readonly TranscriptEntry[]): number {
  return entries.reduce((sum, entry) => {
    if (entry.type === 'tools') {
      return sum + entry.pairs.length;
    }
    if (entry.type === 'subagent-block' || entry.type === 'call-block') {
      // Another agent's work, with a count of its own.
      return sum;
    }
    if (entry.type === 'item' || isCardEntry(entry)) {
      // A card hides the calls that produced it, so the loaded rows cannot
      // show them; the daemon's figure counts them, and this reads low until
      // it lands.
      return sum;
    }
    return sum + countTools(entry.entries);
  }, 0);
}

/** Every sub-agent block in a folded transcript, at any depth. */
export function collectSubagentBlocks(
  entries: readonly TranscriptEntry[],
): SubagentBlockEntry[] {
  const out: SubagentBlockEntry[] = [];
  const walk = (list: readonly TranscriptEntry[]): void => {
    for (const entry of list) {
      if (entry.type === 'subagent-block') {
        out.push(entry);
        continue;
      }
      if (entry.type === 'turn-block' || entry.type === 'call-block') {
        walk(entry.entries);
      }
    }
  };
  walk(entries);
  return out;
}

/**
 * Every call block in a folded transcript, at any depth — the twin of
 * {@link collectSubagentBlocks} for `call_agent` conversations.
 *
 * The agents panel reads one row per call thread off it, so each INSTANCE of a
 * called agent can say where it has got to and what it has spent without the
 * panel re-deriving the claiming rules the fold already applied. A callee can
 * itself call, so blocks nested inside a block are collected too.
 */
export function collectCallBlocks(
  entries: readonly TranscriptEntry[],
): CallBlockEntry[] {
  const out: CallBlockEntry[] = [];
  const walk = (list: readonly TranscriptEntry[]): void => {
    for (const entry of list) {
      if (entry.type === 'call-block') {
        out.push(entry);
        walk(entry.entries);
        continue;
      }
      if (entry.type === 'turn-block' || entry.type === 'subagent-block') {
        walk(entry.entries);
      }
    }
  };
  walk(entries);
  return out;
}

/**
 * The call cards a reader opens to reach the one holding `callId`, outermost
 * first and that card last — a card drawn inside another's conversation is
 * mounted only while every card around it is open. Empty when none holds it.
 */
export function callBlockPath(
  entries: readonly TranscriptEntry[],
  callId: string,
): CallBlockEntry[] {
  const walk = (list: readonly TranscriptEntry[]): CallBlockEntry[] | null => {
    for (const entry of list) {
      if (entry.type === 'call-block') {
        if (entry.callIds.includes(callId)) {
          return [entry];
        }
        const inner = walk(entry.entries);
        if (inner !== null) {
          return [entry, ...inner];
        }
        continue;
      }
      if (entry.type === 'turn-block' || entry.type === 'subagent-block') {
        const inner = walk(entry.entries);
        if (inner !== null) {
          return inner;
        }
      }
    }
    return null;
  };
  return walk(entries) ?? [];
}

/**
 * Every call block of a folded transcript, keyed by EVERY call it holds — a
 * continued conversation is one block, reachable by whichever of its calls a
 * reader asks with.
 */
export function indexCallBlocks(
  entries: readonly TranscriptEntry[],
): Map<string, CallBlockEntry> {
  const index = new Map<string, CallBlockEntry>();
  for (const block of collectCallBlocks(entries)) {
    for (const callId of block.callIds) {
      index.set(callId, block);
    }
  }
  return index;
}

/**
 * A conversation's block, asked by its calls NEWEST first.
 *
 * Newest first rather than by the latest id alone: a continuation that has not
 * streamed a row yet is not in its block — it stays a flat row until it does —
 * while the conversation's panel thread already names it, so asking with the
 * latest id alone would leave the instance's line and spend blank until then.
 */
export function callBlockOfConversation(
  index: ReadonlyMap<string, CallBlockEntry>,
  callIds: readonly string[],
): CallBlockEntry | undefined {
  for (let i = callIds.length - 1; i >= 0; i -= 1) {
    const block = index.get(callIds[i]!);
    if (block !== undefined) {
      return block;
    }
  }
  return undefined;
}

/** One sub-agent block under assembly. */
interface SubagentLaunch {
  call: ChatItem;
  result: ChatItem | null;
}

/**
 * Read one string field off a tool call's `input` object.
 *
 * TWIN PARSER: the keys read through this — `subagent_type`, `description`,
 * `prompt`, `model` — are claude's own Task-tool argument schema, which reaches the
 * renderer inside a `tool_call` payload's `input` and so carries no generated
 * type (`apps/daemon/src/v1/agents/utils/event-to-item.ts` forwards
 * `event.input` verbatim; the shape originates in
 * `apps/daemon/src/v1/agents/adapters/claude/`). If that CLI renames one of
 * them, it must be renamed here, and vice versa — nothing type-checks the two
 * against each other. Every key is read defensively, so a rename degrades to
 * an unlabelled block rather than a crash.
 */
function inputString(call: ChatItem | undefined, key: string): string | null {
  const input = (call?.payload as { input?: unknown } | null)?.input;
  if (typeof input !== 'object' || input === null) {
    return null;
  }
  const value = (input as Record<string, unknown>)[key];
  return typeof value === 'string' && value !== '' ? value : null;
}

/**
 * What model the LAUNCHING call asked this delegate to run on — the stand-in
 * until its CLI says which one actually did.
 *
 * The declaration OUTRANKS this, which inverts the rule its three neighbours
 * follow (`kind`, `label` and `prompt` all prefer the call). The two sources
 * are not the same fact here: the call carries the caller's own word for a
 * model — an ALIAS like `sonnet` — while the declaration carries what the CLI
 * resolved it to (`claude-sonnet-5`), which is the one a reader can look up.
 * That declaration only arrives when the launching call RETURNS, so a delegate
 * is otherwise unattributed for the whole time it runs, which is precisely
 * when a column of a dozen of them is being read.
 *
 * `inherit` is dropped rather than shown: it is the schema's way of naming no
 * model at all, and printing it would answer "which model" with a word about
 * where the answer comes from.
 */
function requestedModel(call: ChatItem | undefined): string | null {
  const model = inputString(call, 'model');
  return model === 'inherit' ? null : model;
}

/**
 * Fold every background sub-agent's rows into one {@link SubagentBlockEntry},
 * placed where that delegate's FIRST row appeared — which is directly after
 * the tool call that launched it.
 *
 * Runs BETWEEN {@link groupTranscript} and {@link buildTurnBlocks}: the former
 * has already split each delegate's tool runs onto their own groups, and the
 * latter must see the finished block as a single entry of the DELEGATING
 * agent's turn rather than fold the delegate's loose rows into it.
 *
 * The launching `tool_call` supplies the block's identity and its request; its
 * paired `tool_result` supplies the result and is the only "the delegate
 * finished" signal on the wire. Rows whose launcher is missing entirely (a
 * transcript replayed from mid-run, a `Task` call the fold dropped) still get
 * a block — an unlabelled enclosure beats spilling a delegate's work back into
 * the main conversation, which is the defect this whole fold exists to fix.
 *
 * A launch is recognised TWO ways, because CLIs disclose a delegation
 * differently and neither reading covers the other:
 * - by the tool's NAME ({@link isAgentToolName}), whose own arguments carry the
 *   description, the prompt and the type — claude's `Task`;
 * - by a `subagent_info` row the DAEMON wrote, which names the launching tool
 *   call explicitly — for a CLI whose delegation frame carries no usable name
 *   and whose brief arrives later on its own channel (cursor over ACP, where the
 *   call is titled `Task: Subagent task` and its input holds only `_toolName`).
 *
 * The second is why nothing here needs a second CLI's tool-name spellings: which
 * calls launched delegates is the adapter layer's fact, and it is stated on the
 * wire rather than pattern-matched at this end.
 *
 * One level deep, like the other blocks: a claude sub-agent is a leaf and
 * cannot itself delegate, so no block nests inside another.
 */
export function buildSubagentBlocks(
  entries: readonly TranscriptEntry[],
  items: readonly ChatItem[],
): TranscriptEntry[] {
  // Merged rather than taken: a CLI announces the same delegate once at launch
  // (anchor only) and again with its brief, so the last non-null field wins.
  const declarations = new Map<string, SubagentDeclaration>();
  for (const item of items) {
    if (item.kind !== 'subagent_info') {
      continue;
    }
    const declaration = readSubagentDeclaration(item);
    if (declaration === null) {
      continue;
    }
    const previous = declarations.get(declaration.id);
    declarations.set(
      declaration.id,
      previous === undefined
        ? declaration
        : mergeSubagentDeclarations(previous, declaration),
    );
  }
  const assistantMessages = new Map<string, number>();
  for (const item of items) {
    if (item.kind !== 'message' || item.role !== 'assistant') {
      continue;
    }
    const id = subagentIdOf(item);
    if (id !== null) {
      assistantMessages.set(id, (assistantMessages.get(id) ?? 0) + 1);
    }
  }
  const launches = new Map<string, SubagentLaunch>();
  /**
   * Of those launches, the ones whose tool is a DELEGATION by name.
   *
   * The two admission routes are not equally strong and only this one is
   * self-evidencing. A call admitted by its name launched a delegate and its
   * reply is that delegate's report; a call admitted only because the daemon
   * declared background work against it may be anything the CLI ran an agent
   * FOR — measured on the user's own ledger, a `SendMessage` resuming an
   * already-running agent, whose reply is the receipt `{"success":true,
   * "message":"Resuming agent a3249b7"…}` and whose block therefore had no
   * name, no prompt, no conversation, and that receipt where its result
   * should be.
   */
  const byDelegationTool = new Set<string>();
  for (const item of items) {
    if (item.kind !== 'tool_call') {
      continue;
    }
    const id = payloadString(item.payload, 'id');
    const name = payloadString(item.payload, 'name') ?? '';
    if (id && (isAgentToolName(name) || declarations.has(id))) {
      launches.set(id, { call: item, result: null });
      if (isAgentToolName(name)) {
        byDelegationTool.add(id);
      }
    }
  }
  for (const item of items) {
    if (item.kind !== 'tool_result') {
      continue;
    }
    const id = payloadString(item.payload, 'id');
    const launch = id ? launches.get(id) : undefined;
    if (launch) {
      launch.result = item;
    }
  }

  const out: TranscriptEntry[] = [];
  const blocks = new Map<string, SubagentBlockEntry>();
  /**
   * The `seq` the delegation was ISSUED at, per block.
   *
   * Only load-bearing while a block has no rows of its own: `maxSeqOf([])` is
   * 0, so without an anchor ANY earlier turn-end of the delegating node reads
   * as "this delegate's turn is over" and a Task call the CLI has not yet
   * produced a single row for renders `stopped` the instant it appears.
   */
  const anchorSeq = new Map<string, number>();
  /**
   * The `seq` at which each block's launching call was ANSWERED, for the blocks
   * that have an answer. Kept apart from {@link anchorSeq}, which coalesces to
   * the call when there is no result — this must stay undefined there, since
   * "never answered" and "answered at the launch" are different facts and only
   * the second can make a result the delegate's own.
   */
  const answeredSeq = new Map<string, number>();
  const openBlock = (
    subagentId: string,
    /** Where to read identity from when the launching call is missing. */
    fallback: TranscriptEntry,
  ): SubagentBlockEntry => {
    const existing = blocks.get(subagentId);
    if (existing) {
      return existing;
    }
    const launch = launches.get(subagentId);
    const payload = launch?.result?.payload as {
      result?: unknown;
      isError?: unknown;
    } | null;
    const body = payload?.result;
    // What the DAEMON said about this delegate, when its CLI announces one apart
    // from the launching call. Read as a FALLBACK per field rather than as an
    // alternative source: claude's Task arguments are richer and already carry
    // three of these, so the declaration fills only what the call did not say.
    const declared = declarations.get(subagentId) ?? null;
    const block: SubagentBlockEntry = {
      type: 'subagent-block',
      id: subagentId,
      // A ternary, not `??`: every 1:1 chat row carries `nodeId: null`
      // legitimately, so coalescing would fall through to the first row's
      // node whenever the launcher IS the chat agent.
      createdAt: launch ? launch.call.createdAt : entryCreatedAt(fallback),
      memberId: launch ? launch.call.memberId : entryNodeId(fallback),
      callId: launch
        ? payloadString(launch.call.payload, 'callId')
        : entryCallId(fallback),
      kind:
        inputString(launch?.call, 'subagent_type') ?? declared?.kind ?? null,
      label:
        inputString(launch?.call, 'description') ?? declared?.label ?? null,
      prompt: inputString(launch?.call, 'prompt') ?? declared?.prompt ?? null,
      // The one field where the DECLARATION wins — see {@link requestedModel}.
      model: declared?.model ?? requestedModel(launch?.call),
      durationMs: declared?.durationMs ?? null,
      tokens: declared?.tokens ?? null,
      toolUses: declared?.toolUses ?? null,
      costUsd: declared?.costUsd ?? null,
      estimatedCostUsd: declared?.estimatedCostUsd ?? null,
      requests: declared?.requests ?? null,
      contextTokens: declared?.contextTokens ?? null,
      inputTokens: declared?.inputTokens ?? null,
      outputTokens: declared?.outputTokens ?? null,
      cacheReadTokens: declared?.cacheReadTokens ?? null,
      cacheCreationTokens: declared?.cacheCreationTokens ?? null,
      cumulative: declared?.cumulative ?? false,
      messages: assistantMessages.get(subagentId) ?? null,
      stepsUnavailableReason: declared?.stepsUnavailableReason ?? null,
      backgroundOpen: declared?.backgroundOpen ?? null,
      backgroundOutcome: declared?.backgroundOutcome ?? null,
      recoverable: declared?.recoverable ?? false,
      processEnded:
        declared?.backgroundOutcome === 'untracked' && declared.processEnded,
      returned: launch?.result != null,
      failed: payload?.isError === true,
      // Only stringify a body that EXISTS. `toolResultText(null)` returns
      // the four characters `null`, which the result panel then framed as
      // the delegate's own answer.
      result: body == null ? null : toolResultText(body),
      // Decided in the pass below, once the delegate's rows are known.
      resultIsOwn: false,
      lastRowAt: null,
      entries: [],
    };
    if (launch) {
      anchorSeq.set(subagentId, launch.result?.seq ?? launch.call.seq);
      // Only a call that was a DELEGATION can have been answered WITH a
      // delegate's report — see {@link byDelegationTool}. A declaration that
      // describes the delegate is the other CLI's way of saying the same thing
      // (cursor's ACP frame carries no usable tool name, so its brief is the
      // evidence), while a declaration that describes nothing is only the
      // daemon noticing background work against some call.
      const describes =
        declared !== null &&
        (declared.label !== null ||
          declared.kind !== null ||
          declared.prompt !== null);
      if (launch.result && (byDelegationTool.has(subagentId) || describes)) {
        answeredSeq.set(subagentId, launch.result.seq);
      }
    }
    blocks.set(subagentId, block);
    out.push(block);
    return block;
  };

  for (const entry of entries) {
    const subagentId = subagentOwnerOf(entry);
    if (subagentId !== null) {
      openBlock(subagentId, entry).entries.push(entry);
      continue;
    }
    // A MAIN-thread tool group is where the delegations were issued. The
    // launching `Task` pair is pulled OUT of it and rendered as the block it
    // opened: the block already says a delegate was started, who it is and
    // how it ended, so leaving the pair in the group produced a second,
    // poorer telling of it directly above ("Delegated to 5 subagents").
    if (entry.type === 'tools') {
      const kept: ToolPair[] = [];
      const launched: string[] = [];
      for (const pair of entry.pairs) {
        const id = payloadString(pair.call.payload, 'id');
        if (id !== null && launches.has(id)) {
          launched.push(id);
          continue;
        }
        kept.push(pair);
      }
      if (kept.length > 0) {
        // `id` is carried over UNCHANGED even when the pair it names was the
        // one just stripped. It is a React key, and re-deriving it from the
        // first surviving pair would change it the moment a delegation is
        // followed by real work in the same group — remounting the row and
        // discarding whatever the reader had expanded.
        out.push({ ...entry, pairs: kept });
      }
      // AFTER the group, so a turn that both worked and delegated still reads
      // in the order it happened.
      for (const id of launched) {
        openBlock(id, entry);
      }
      continue;
    }
    out.push(entry);
  }
  if (blocks.size === 0) {
    return out;
  }

  for (const block of blocks.values()) {
    const lastSeq = Math.max(
      maxSeqOf(block.entries),
      anchorSeq.get(block.id) ?? 0,
    );
    // Whose answer the result is — see {@link SubagentBlockEntry.resultIsOwn}.
    // `lastSeq` already folds in `anchorSeq`, which for an answered block IS
    // that answer's seq, so `lastSeq > answered` says exactly "a row of this
    // delegate's arrived afterwards" — and a delegate that spoke after its call
    // was answered was plainly not reporting through it.
    //
    // The open-background test is what covers the same delegate BEFORE it has
    // spoken at all: an acknowledgement and no rows leaves the seqs equal, and
    // an open background unit is the CLI saying the work is still to come.
    const answered = answeredSeq.get(block.id);
    block.resultIsOwn =
      block.result !== null &&
      answered !== undefined &&
      block.backgroundOpen !== true &&
      lastSeq <= answered;
    // Taken BEFORE the fold, while the rows are still flat. Falls back to the
    // LAUNCH when the delegate has produced nothing yet: a delegation issued
    // after the run settled is itself evidence of life, and reading null there
    // would call a delegate that started one second ago `stopped`.
    const launchedAt = Date.parse(block.createdAt);
    block.lastRowAt =
      lastRowAtOf(block.entries) ??
      (Number.isFinite(launchedAt) ? launchedAt : null);
    // Folded so the nested thread reads exactly like the main flow does.
    block.entries = buildTurnBlocks(block.entries);
  }
  return out;
}

/**
 * Every dynamic workflow this transcript records, in launch order.
 *
 * The ONE reading, and it is exported because there are now three views of it:
 * the transcript's card, the chip above the composer while one is running, and
 * the panel's list. Folded twice they would disagree about how many agents are
 * still out — which is exactly the kind of drift `isCardEntry` exists to
 * prevent one entry-kind lower down.
 *
 * A launch is recognised ONE way — by a `workflow_info` row naming the call —
 * and never by the tool's NAME. Which calls launched a workflow is the adapter
 * layer's fact and it is stated on the wire, so nothing here has to learn that
 * claude spells its orchestrator `Workflow`; a second CLI that grows one is a
 * daemon change alone. That is the stronger of the two admission routes
 * {@link buildSubagentBlocks} documents, and here it is the only one available:
 * a workflow emits no rows of its own, so there is no second reading to fall
 * back on.
 */
export function workflowCardsOf(items: readonly ChatItem[]): WorkflowEntry[] {
  // Merged rather than taken: a workflow announces itself at launch (the name,
  // nothing else) and again on every roster change, so the last non-null field
  // wins — and the roster itself is taken WHOLESALE, per
  // `mergeWorkflowDeclarations`.
  const declarations = new Map<string, WorkflowDeclaration>();
  // The FIRST row about each workflow, which is where a card that has lost its
  // launching call takes its place in the conversation from.
  const anchors = new Map<string, ChatItem>();
  /** The newest row about each workflow — see {@link WorkflowEntry.lastRowAt}. */
  const lastRowAt = new Map<string, number>();
  /** Its `seq`, which is what decides whether a result is the workflow's own. */
  const lastRowSeq = new Map<string, number>();
  for (const item of items) {
    if (item.kind !== 'workflow_info') {
      continue;
    }
    const declaration = readWorkflowDeclaration(item);
    if (declaration === null) {
      continue;
    }
    const previous = declarations.get(declaration.id);
    declarations.set(
      declaration.id,
      previous === undefined
        ? declaration
        : mergeWorkflowDeclarations(previous, declaration),
    );
    if (!anchors.has(declaration.id)) {
      anchors.set(declaration.id, item);
    }
    const at = Date.parse(item.createdAt);
    if (Number.isFinite(at) && at > (lastRowAt.get(declaration.id) ?? 0)) {
      lastRowAt.set(declaration.id, at);
    }
    lastRowSeq.set(
      declaration.id,
      Math.max(lastRowSeq.get(declaration.id) ?? 0, item.seq),
    );
  }
  const launches = new Map<string, SubagentLaunch>();
  for (const item of items) {
    if (item.kind !== 'tool_call') {
      continue;
    }
    const id = payloadString(item.payload, 'id');
    if (id !== null && declarations.has(id)) {
      launches.set(id, { call: item, result: null });
    }
  }
  for (const item of items) {
    if (item.kind !== 'tool_result') {
      continue;
    }
    const id = payloadString(item.payload, 'id');
    const launch = id ? launches.get(id) : undefined;
    if (launch) {
      launch.result = item;
    }
  }

  const cardFor = (
    id: string,
    workflow: WorkflowDeclaration,
  ): WorkflowEntry => {
    const launch = launches.get(id);
    const payload = launch?.result?.payload as {
      result?: unknown;
      isError?: unknown;
    } | null;
    const body = payload?.result;
    // The launching call when there is one, else the first row the daemon wrote
    // about this workflow — which is a row of the same turn, so the card lands
    // where the work happened either way.
    const anchor = launch?.call ?? anchors.get(id) ?? null;
    return {
      type: 'workflow',
      id,
      createdAt: anchor?.createdAt ?? '',
      seq: anchor?.seq ?? 0,
      memberId: anchor?.memberId ?? null,
      // The launching call's own thread: a workflow started by a delegate is
      // the delegate's, and its card belongs inside that block's flow.
      parentToolUseId: anchor === null ? null : subagentIdOf(anchor),
      workflow,
      script: inputString(launch?.call, 'script'),
      returned: launch?.result != null,
      failed: payload?.isError === true,
      // Only stringify a body that EXISTS. `toolResultText(null)` returns the
      // four characters `null`, which the result panel would then frame as the
      // workflow's own answer.
      result: body == null ? null : toolResultText(body),
      // A roster that arrived AFTER the answer says the workflow was plainly
      // not reporting through it — see {@link WorkflowEntry.resultIsOwn}.
      resultIsOwn:
        launch?.result != null &&
        (lastRowSeq.get(id) ?? 0) <= launch.result.seq,
      lastRowAt: lastRowAt.get(id) ?? null,
    };
  };

  return [...declarations].map(([id, workflow]) => cardFor(id, workflow));
}

/**
 * Replace every dynamic-workflow tool call with the {@link WorkflowEntry} card
 * describing what it actually did.
 *
 * The PLACEMENT half of {@link workflowCardsOf}, which is where the reading
 * itself lives. Runs AFTER {@link buildSubagentBlocks} and before
 * {@link buildTurnBlocks}, for the same reason that one does: the groups are
 * already folded, and the turn fold must see one finished card rather than a
 * tool pair plus a run of invisible rows.
 *
 * The launching pair is pulled OUT of its tool group, exactly as a `Task` pair
 * is: the card already says a workflow ran, what it spawned and how it ended,
 * so leaving the pair in the group would print a poorer telling of it directly
 * above ("Used 1 tool").
 */
export function buildWorkflowCards(
  entries: readonly TranscriptEntry[],
  items: readonly ChatItem[],
): TranscriptEntry[] {
  const cards = new Map(
    workflowCardsOf(items).map((card) => [card.id, card] as const),
  );
  if (cards.size === 0) {
    return [...entries];
  }
  const out: TranscriptEntry[] = [];
  const placed = new Set<string>();
  for (const entry of entries) {
    if (entry.type === 'tools') {
      const kept: ToolPair[] = [];
      const launched: string[] = [];
      for (const pair of entry.pairs) {
        const id = payloadString(pair.call.payload, 'id');
        if (id !== null && cards.has(id)) {
          launched.push(id);
          continue;
        }
        kept.push(pair);
      }
      if (kept.length > 0) {
        // `id` carried over UNCHANGED even when the pair it names was the one
        // stripped — it is a React key, and re-deriving it would remount the
        // row and discard whatever the reader had expanded.
        out.push({ ...entry, pairs: kept });
      }
      // AFTER the group, so a turn that both worked and launched a workflow
      // still reads in the order it happened.
      for (const id of launched) {
        const card = cards.get(id);
        if (card === undefined) {
          continue;
        }
        placed.add(id);
        out.push(card);
      }
      continue;
    }
    out.push(entry);
  }
  // A workflow whose launching call never reached this fold still gets a card:
  // the daemon's rows are the evidence it ran, and a transcript replayed from
  // mid-run — or one whose tool pair the group fold consumed — would otherwise
  // drop the most expensive thing in the conversation entirely.
  for (const card of cards.values()) {
    if (!placed.has(card.id)) {
      out.push(card);
    }
  }
  return out;
}

/**
 * Caller-attributed rows of the SAME call (the parked question, its answer,
 * the settle envelope) — everything about a sub-agent call belongs inside
 * its block, so these claim into the bucket by callId alone (their nodeId
 * is the CALLER's).
 */
const CALL_FOLLOWUP_KINDS = new Set<ChatItem['kind']>([
  'call_question',
  'call_answer',
  'call_result',
]);

/**
 * Kinds that must stay in the MAIN flow even when callId-tagged: the block
 * anchor itself, the broker's pickup note (renders as nothing), approval
 * requests/verdicts — a pending card hidden inside a block's flow could never
 * be answered — and published pages and buttons: they are made for the user,
 * and inside a shut call card (or a card nested in one) nobody would see them.
 * Left here, a revision anywhere in the run also folds the older card, since
 * the newest-card sweep runs over this flow.
 *
 * TWIN PARSER: `callMembershipOf` in
 * apps/daemon/src/v1/agents/utils/call-membership.ts decides the same claim on
 * the daemon, which serves a team run's rows one conversation at a time on
 * its answer. A kind moved between these sets moves there too, with a bump of
 * its `CALL_MEMBERSHIP_VERSION` so the rows already stamped are stamped again
 * — unless no stored row of the kind answers differently, as the daemon's
 * note on `action` / `action_outcome` records.
 */
const UNCLAIMABLE_KINDS = new Set<ChatItem['kind']>([
  'call_started',
  'await_collected',
  'approval_request',
  'approval_verdict',
  'show_artifact',
  'action',
  'action_outcome',
]);

const BLOCK_STATUSES = new Set(['running', 'completed', 'failed', 'cancelled']);

/**
 * A row of a call, held only to build that call's card, whose card is not in
 * the fold yet: a live row that arrived before the anchors its start is asked
 * for. It is drawn nowhere until the start lands, never as its callee's block
 * in the run's own flow.
 */
function isUnplacedCallRow(
  item: ChatItem,
  anchorIds: ReadonlySet<string> | undefined,
): boolean {
  return (
    anchorIds !== undefined &&
    anchorIds.has(item.id) &&
    isCallRow(item) &&
    !UNCLAIMABLE_KINDS.has(item.kind)
  );
}

/** A pending agent-call block under assembly (one per call_started). */
interface CallShell {
  started: ChatItem;
  calleeMemberId: string | null;
  bucket: ChatItem[];
  /** The calls its callee made, each with its own rows: drawn inside the card, never read for its status. */
  nested: ChatItem[];
}

/**
 * The call whose card a call made by a callee is drawn in, or null for a call
 * made from a member's own conversation.
 *
 * TWIN PARSER: `parentCallOf` in apps/daemon/src/v1/agents/utils/call-membership.ts,
 * whose answer the row carries as `inCall`; a row no build stamped is matched
 * the same way the daemon matches it — the newest call of the calling
 * conversation started before it, whose callee is the caller.
 */
function parentCallOf(
  started: ChatItem,
  shells: ReadonlyMap<string, CallShell>,
  chains: ReadonlyMap<string, readonly string[]>,
): string | null {
  const before = (callId: string): boolean => {
    const shell = shells.get(callId);
    return shell !== undefined && shell.started.seq < started.seq;
  };
  if (typeof started.inCall === 'string') {
    return before(started.inCall) ? started.inCall : null;
  }
  if (started.inCall === null) {
    return null;
  }
  const calling = payloadString(started.payload, 'callerConversationId');
  if (calling === null || started.memberId === null) {
    return null;
  }
  let parent: CallShell | null = null;
  for (const [callId, shell] of shells) {
    if (
      before(callId) &&
      shell.calleeMemberId === started.memberId &&
      (chains.get(callId)?.[0] ?? callId) === calling &&
      (parent === null || shell.started.seq > parent.started.seq)
    ) {
      parent = shell;
    }
  }
  return parent === null
    ? null
    : payloadString(parent.started.payload, 'callId');
}

/** One thread's task list as folded so far, mid-scan. */
interface RunningTaskList {
  tasks: AgentTaskRow[];
  /** Some announcement so far was a snapshot — see `TaskListEntry.snapshot`. */
  snapshot: boolean;
}

/**
 * `foldTaskList` over a thread's whole history, given the fold of everything
 * before `next` rather than the history itself.
 *
 * The list so far goes back in as a SNAPSHOT because that is the one
 * announcement that lays rows onto an empty list verbatim (fresh objects, same
 * order, same fields), so the result is exactly the whole-history fold's. The
 * merge rule stays `task-payload.ts`'s alone — restating it here is how the two
 * would come to disagree.
 */
function foldOneMore(
  list: readonly AgentTaskRow[],
  next: TaskAnnouncement,
): AgentTaskRow[] {
  return foldTaskList([
    { mode: 'snapshot', tasks: [...list], toolCallId: null },
    next,
  ]);
}

/**
 * Fold a transcript into render entries: agent calls collapse into nested
 * call blocks, tool calls collapse into per-node groups (Claude/Cursor-style
 * "used N tools" rows), everything else stays a plain item entry.
 *
 * Call-block rules:
 * - a `call_started` opens a block; every item TAGGED with that callId and
 *   attributed to the callee node folds inside it (its status items drive
 *   the block's live status instead of rendering as rows — merging the old
 *   redundant "call → B" + "B started" pair into one block header).
 * - the caller-attributed rows about the call (question/answer/settle)
 *   claim in too — the WHOLE exchange lives in the block; only the anchor
 *   and approval requests/verdicts stay out (see {@link UNCLAIMABLE_KINDS}),
 *   and items with no `callId` keep the flat flow.
 * - a call continuing an earlier call's `thread` joins that call's block, and
 *   the block is drawn at the conversation's NEWEST `call_started` — earlier
 *   anchors draw nothing (see {@link resolveCallChains}).
 *
 * Tool-grouping rules:
 * - a `tool_call` joins its node's OPEN group (or opens one); any other
 *   rendered kind from the SAME node closes that node's group — another
 *   node's interleaved rows do not, so a parallel branch doesn't shred the
 *   caller's tool run into fragments.
 * - a `tool_result` attaches to its call by payload id wherever that call
 *   lives (the pairing survives a closed group); an orphan result (no known
 *   call) stays a plain item entry.
 * - geniro's own tool calls and their results are dropped entirely (see
 *   `isGeniroToolName`).
 */
export function groupTranscript(
  items: readonly ChatItem[],
  {
    anchorIds,
  }: {
    /**
     * Rows that are ANCHORS rather than the window's own (`history-anchors.ts`)
     * — the start of a call whose rows the window holds, a delegate's launch. They
     * build the structure they belong to and are never drawn as a row of their
     * own: a reader did not scroll to them, and a conversation's earlier starts
     * would otherwise stack up as markers at the top of the window.
     */
    anchorIds?: ReadonlySet<string>;
  } = {},
): TranscriptEntry[] {
  // An analysis card's Apply and outcomes come in rows AFTER it; read once.
  const appliedByCard = new Map<number, string[]>();
  const outcomesByCard = new Map<
    number,
    Record<string, RecommendationOutcomeView>
  >();
  const outcomesByAction = new Map<number, ActionOutcomeView>();
  const lessonOutcomes: Readonly<Record<string, LessonOutcomeView>> =
    foldLessonOutcomes(items);
  for (const item of items) {
    const actionOutcome = readActionOutcome(item);
    if (actionOutcome !== null) {
      // Oldest first, so the last one read is the newest.
      outcomesByAction.set(actionOutcome.actionSeq, actionOutcome);
      continue;
    }
    const apply = readApply(item);
    if (apply !== null) {
      appliedByCard.set(apply.cardSeq, apply.ids);
      continue;
    }
    if (item.kind === 'recommendation_outcome') {
      const marks = readRecommendationOutcomes(item);
      if (marks !== null) {
        outcomesByCard.set(marks.cardSeq, {
          ...outcomesByCard.get(marks.cardSeq),
          ...marks.outcomes,
        });
      }
    }
  }
  // Pass 1 — collect the call shells and claim each callee sub-turn's items.
  const shells = new Map<string, CallShell>();
  for (const item of items) {
    if (item.kind !== 'call_started') {
      continue;
    }
    const callId = payloadString(item.payload, 'callId');
    if (callId && !shells.has(callId)) {
      shells.set(callId, {
        started: item,
        calleeMemberId: payloadString(item.payload, 'calleeNodeId'),
        bucket: [],
        nested: [],
      });
    }
  }
  const chains = resolveCallChains(items);
  // The daemon's silence advisories, read as a SET of call ids rather than
  // claimed into their blocks: the row stays in the caller's main flow, where
  // it is visible without opening anything, and the block reads the fact off
  // this set. See `CallBlockEntry.stalled` for the twin it parses.
  //
  // A LATER row from the same call SUPERSEDES the advisory. The daemon says a
  // call went quiet once and never retracts it — its own recovery story is
  // "the callee simply produces a row" — so without this the marker would
  // outlive what it describes, and a callee streaming tool calls again, or a
  // call that settled minutes ago, would still be reported as silent. Items
  // arrive in seq order, so one pass decides it.
  const stalledCalls = new Set<string>();
  for (const item of items) {
    const callId = payloadString(item.payload, 'callId');
    if (callId === null) {
      continue;
    }
    if (
      item.kind === 'system' &&
      payloadBoolean(item.payload, 'stalledCall') === true
    ) {
      stalledCalls.add(callId);
      continue;
    }
    // The user writing to a quiet callee is not the callee producing anything.
    if (item.kind === 'message' && item.role === 'user') {
      continue;
    }
    stalledCalls.delete(callId);
  }
  // Calls held for their callee's own calls, read the same way and for the
  // same reason — see `CallBlockEntry.heldOn` for the twin it parses.
  const heldCalls = new Map<string, number>();
  for (const item of items) {
    const callId = payloadString(item.payload, 'callId');
    if (callId === null) {
      continue;
    }
    const waitingOn =
      item.kind === 'system' ? heldCallWaitingOn(item.payload) : null;
    if (waitingOn !== null) {
      heldCalls.set(callId, waitingOn);
      continue;
    }
    // Only the callee being continued, or the call ending, ends the wait: its
    // still-running process can write rows of its own meanwhile (a command it
    // started closing), and those say nothing about the calls it waits for.
    if (endsHeldWait(item)) {
      heldCalls.delete(callId);
    }
  }
  // Calls that waited under the run's active-turn cap — see
  // `CallBlockEntry.queued` for the twin it parses. Whether one still waits is
  // its block's status to say: a call that started has a status row.
  const queuedCalls = new Map<string, number>();
  for (const item of items) {
    const callId = payloadString(item.payload, 'callId');
    if (callId !== null && item.kind === 'system' && isQueuedCall(item)) {
      queuedCalls.set(callId, item.seq);
    }
  }
  // The call each delegate was LAUNCHED in, for a later row about it that names
  // none. A close the daemon wrote on a delegate's behalf can carry the node
  // and no call id (every one written before it stamped the call), and would
  // otherwise be claimed into the main flow while the delegate sits in the call
  // block, never hearing its own ending. The launch always names its call; a
  // row about the same delegate belongs with it.
  const delegateCalls = new Map<string, string>();
  for (const item of items) {
    if (item.kind !== 'subagent_info') {
      continue;
    }
    const id = payloadString(item.payload, 'id');
    const callId = payloadString(item.payload, 'callId');
    if (id && callId && !delegateCalls.has(id)) {
      delegateCalls.set(id, callId);
    }
  }
  const claimed = new Set<string>();
  if (shells.size > 0) {
    for (const item of items) {
      if (UNCLAIMABLE_KINDS.has(item.kind)) {
        continue;
      }
      const callId =
        payloadString(item.payload, 'callId') ??
        (item.kind === 'subagent_info'
          ? (delegateCalls.get(payloadString(item.payload, 'id') ?? '') ?? null)
          : null);
      const shell = callId ? shells.get(callId) : undefined;
      if (!shell) {
        continue;
      }
      // The callee's own streamed items claim by callId + callee nodeId; the
      // caller-attributed rows ABOUT this call (question/answer/settle)
      // claim by callId alone — the whole exchange lives in the block.
      if (
        CALL_FOLLOWUP_KINDS.has(item.kind) ||
        (item.memberId !== null && item.memberId === shell.calleeMemberId)
      ) {
        claimed.add(item.id);
        shell.bucket.push(item);
      }
    }
    const deepestFirst = [...shells.values()].sort(
      (a, b) => b.started.seq - a.started.seq,
    );
    for (const shell of deepestFirst) {
      const parent = parentCallOf(shell.started, shells, chains);
      if (parent === null) {
        continue;
      }
      claimed.add(shell.started.id);
      shells
        .get(parent)!
        .nested.push(shell.started, ...shell.bucket, ...shell.nested);
    }
  }

  // Pass 2 — which tool calls a task announcement SPEAKS FOR.
  //
  // The list is rendered INSTEAD of the row that produced it, not beside it,
  // because that row is the whole complaint: claude's `TaskUpdate` collapses to
  // `TaskUpdate` in a tool group, and cursor's discloses no arguments at all
  // (`rawInput:{_toolName:"updateTodos"}`), so the reader learns that a tool
  // ran and nothing about the work. Both halves of the pair go, which is why
  // this has to be known BEFORE the fold: the result arrives later in the
  // stream than the announcement that claims it.
  const taskToolCallIds = new Set<string>();
  for (const item of items) {
    if (item.kind !== 'task_list') {
      continue;
    }
    const toolCallId = readTaskAnnouncement(item)?.toolCallId;
    if (toolCallId) {
      taskToolCallIds.add(toolCallId);
    }
  }
  // A `team_note` or `record_outcome` call is hidden because its row tells the
  // story — but a REFUSED one writes no row, so its call and the refusal stay
  // on screen.
  const refusedCallIds = new Set<string>();
  for (const item of items) {
    const id = payloadString(item.payload, 'id');
    if (
      item.kind === 'tool_result' &&
      id !== null &&
      (item.payload as { isError?: unknown } | null)?.isError === true
    ) {
      refusedCallIds.add(id);
    }
  }

  // Pass 3 — the main fold over everything not claimed into a block.
  const entries: TranscriptEntry[] = [];
  const hiddenCallIds = new Set<string>();
  // The running fold per thread, and the card currently open for it. Kept per
  // thread because both CLIs number tasks from 1, so a delegate's task `1` and
  // the main agent's are different tasks.
  const taskLists = new Map<string, RunningTaskList>();
  const openTaskCards = new Map<string, TaskListEntry>();
  const pairsByCallId = new Map<string, ToolPair>();
  // Keyed by node AND by originating thread, so a sub-agent's calls collapse
  // into their own row and neither thread's narrative closes the other's group.
  const openGroups = new Map<string, ToolGroupEntry>();

  for (const item of items) {
    if (claimed.has(item.id) || isUnplacedCallRow(item, anchorIds)) {
      continue;
    }
    if (item.kind === 'call_started') {
      const callId = payloadString(item.payload, 'callId');
      const shell = callId ? shells.get(callId) : undefined;
      openGroups.delete(groupKey(item));
      if (callId && shell && shell.started.id === item.id) {
        // One card per conversation, drawn where its NEWEST call was made, so
        // work in flight stays at the tail rather than above everything the
        // caller wrote between the calls.
        //
        // A call with no sub-turn yet is a card TOO, and a member of its
        // conversation like any other. It used to keep a flat `call → X` row
        // until the callee's first row landed, on the reading that the gap was
        // a spawn racing the render — but a callee busy with another call
        // QUEUES the new one for as long as that call runs, so the brief sat
        // in the caller's flow as a bare message, outside the callee's card,
        // for minutes. REPORTED as exactly that: a Manager → Researcher ask
        // continuing an earlier thread, drawn in the root thread while the
        // Researcher finished a different call.
        const conversation = chains.get(callId) ?? [callId];
        const members = conversation.filter((id) => shells.has(id));
        if (members[members.length - 1] === callId) {
          entries.push(
            buildConversationBlock(
              members,
              shells,
              stalledCalls,
              heldCalls,
              queuedCalls,
              // The WHOLE conversation, not the drawn part: what this card
              // COST is summed over every call of it, and the calls whose
              // rows page out are the expensive ones — see
              // `CallBlockEntry.conversationCallIds`.
              conversation,
            ),
          );
        } else if (members.includes(callId)) {
          // An EARLIER call of the conversation: where it was made stays
          // visible, pointing at the card it continues in — see
          // `ItemEntry.continuedIn`. The card's id is its FIRST member's
          // anchor, which `buildConversationBlock` keeps as its identity.
          entries.push({
            type: 'item',
            item,
            continuedIn: shells.get(members[0]!)!.started.id,
          });
        }
      } else {
        // A start row naming no call id, or a second start row for one —
        // nothing to key a card on, so the flat row is all it can be.
        entries.push({ type: 'item', item });
      }
      continue;
    }
    if (
      item.kind === 'shell_open' ||
      item.kind === 'shell_info' ||
      item.kind === 'workflow_info' ||
      item.kind === 'subagent_info' ||
      isHeldCountUpdate(item) ||
      isUndrawnMonitorNotice(item)
    ) {
      // Bookkeeping, not narrative: the first two are the open and the close of
      // a detached command (`shell-activity.ts` is their only reader), the third
      // describes a running workflow and is folded into that workflow's own card
      // by `buildWorkflowCards`, the fourth declares a delegate and is read off
      // `items` by `buildSubagentBlocks`. None renders anything here. Skipped
      // OUTRIGHT rather than left to the fall-through below, which treats any
      // other kind as the node having "said something" and closes its open tool
      // group — so a burst of them would chop one turn's tools into a run of
      // one-call rows for rows nobody can see. A workflow announces itself once
      // per roster change, dozens of times over its run, so it is precisely
      // such a burst. A `heldCall` row with no message only moves a held
      // call's count (read by the `heldCalls` fold) and is the same kind.
      //
      // Left in the fold, a row is also a TURN-BLOCK boundary: `ownerOf` gives
      // an item nobody owns NO_OWNER, and `TranscriptItem` draws these as
      // nothing — so the agent's block ended and a second one opened, under a
      // fresh avatar and `name · time` line, with nothing visible between the
      // two. REPORTED for `subagent_info` as two `Engineer` blocks back to back
      // on a team run, the second holding only a task card: the daemon
      // wrote a declaration two rows above it, and 69 of them across that run.
      continue;
    }
    if (item.kind === 'tool_call') {
      const name = payloadString(item.payload, 'name') ?? '';
      const callId = payloadString(item.payload, 'id');
      const tool = geniroToolOf(name, item.runId);
      if (tool === BROWSER_SCREENSHOT) {
        // The card is drawn from this pair, so the result must find it: the
        // call is hidden from the tool group, never from the pairing.
        const pair: ToolPair = { call: item, result: null };
        if (callId) {
          pairsByCallId.set(callId, pair);
        }
        // Closes both open runs, for the reason the findings card does.
        openGroups.delete(groupKey(item));
        openTaskCards.delete(groupKey(item));
        entries.push({
          type: 'browser-screenshot',
          id: item.id,
          createdAt: item.createdAt,
          seq: item.seq,
          memberId: item.memberId,
          parentToolUseId: subagentIdOf(item),
          pair,
        });
        continue;
      }
      const refusedNote =
        callId !== null &&
        refusedCallIds.has(callId) &&
        (tool === 'team_note' ||
          tool === 'record_outcome' ||
          tool === 'move_stage' ||
          tool === SAVE_PROJECT_INSTRUCTIONS ||
          tool === MESSAGE_THREAD);
      if (
        (isGeniroToolName(name, item.runId) && !refusedNote) ||
        (callId !== null && taskToolCallIds.has(callId))
      ) {
        if (callId) {
          hiddenCallIds.add(callId);
        }
        continue;
      }
      const pair: ToolPair = { call: item, result: null };
      if (callId) {
        pairsByCallId.set(callId, pair);
      }
      const key = groupKey(item);
      // A VISIBLE tool call closes this thread's open task card, so the next
      // announcement starts a fresh one. Without it a card floated above the
      // work done after it while showing the list as it stood afterwards. A
      // HIDDEN call never reaches here, which is what keeps a burst of task
      // tools — every one of them hidden — collapsed into the single card.
      openTaskCards.delete(key);
      const open = openGroups.get(key);
      if (open) {
        open.pairs.push(pair);
      } else {
        const group: ToolGroupEntry = {
          type: 'tools',
          id: item.id,
          memberId: item.memberId,
          parentToolUseId: subagentIdOf(item),
          // Filled by the closing sweep below, once the whole stream is known.
          closed: false,
          pairs: [pair],
        };
        openGroups.set(key, group);
        entries.push(group);
      }
      continue;
    }
    if (item.kind === 'tool_result') {
      const callId = payloadString(item.payload, 'id');
      if (callId && hiddenCallIds.has(callId)) {
        continue;
      }
      const pair = callId ? pairsByCallId.get(callId) : undefined;
      if (pair) {
        pair.result = item;
        continue;
      }
      // An ORPHAN — its `tool_call` is not in this window — and if that call was
      // one of GENIRO'S OWN, hiding it is still owed. `hiddenCallIds` is filled
      // as the calls go past, so it can only ever know about calls the window
      // holds: measured on a real run, the `await_agent` sat at seq 899 and its
      // result at 1099, with the window starting near 926, so the result
      // arrived with nothing to suppress it and the raw envelope was printed
      // into the transcript under a `RESULT` caption. REPORTED as "I see raw
      // tool result", over `{"status":"ok","result":{"call_id":"call-3",…}}`.
      //
      // The result row cannot be matched by NAME — the CLI writes `name: null`
      // on it (verified on that row) — so the envelope itself is the only
      // signal present, and it is geniro's OWN shape rather than any CLI's
      // prose: see {@link isCallEnvelopeResult}.
      if (isCallEnvelopeResult(item.payload)) {
        continue;
      }
      entries.push({ type: 'item', item });
      continue;
    }
    if (item.kind === 'report_findings') {
      const report = readFindingsReport(item);
      if (report === null) {
        continue;
      }
      // A card is a narrative row of its own, so it closes BOTH of the thread's
      // open runs — the tool group and the task card — exactly as every other
      // rendered row does. Leaving the task card open lets a later announcement
      // rewrite the card ABOVE this one in place, so it ends up showing state
      // from after the findings it sits over.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'findings',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        memberId: item.memberId,
        parentToolUseId: subagentIdOf(item),
        report,
      });
      continue;
    }
    if (item.kind === 'recommendation_outcome') {
      // Folded into its card above; it draws nothing of its own.
      continue;
    }
    if (item.kind === 'action_outcome') {
      // Folded into its action card above, like a recommendation's outcome.
      continue;
    }
    if (item.kind === 'lesson_outcome') {
      // Folded into its lessons card above; it draws nothing of its own.
      continue;
    }
    if (item.kind === 'lessons') {
      const card = readLessons(item);
      if (card === null) {
        continue;
      }
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'lessons',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        memberId: item.memberId,
        parentToolUseId: subagentIdOf(item),
        card,
        outcomes: lessonOutcomes,
      });
      continue;
    }
    if (item.kind === 'action') {
      const action = readActionPayload(item);
      if (action === null) {
        continue;
      }
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'action',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        memberId: item.memberId,
        // Always the chat's own flow: a button is the chat's, whoever wrote
        // it, and the daemon stamps no delegate on these rows.
        parentToolUseId: null,
        action,
        outcome: outcomesByAction.get(item.seq) ?? null,
      });
      continue;
    }
    if (item.kind === 'recommendations') {
      const card = readRecommendations(item);
      if (card === null) {
        continue;
      }
      // Closes both open runs, for the reason the findings card does.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'recommendations',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        memberId: item.memberId,
        parentToolUseId: subagentIdOf(item),
        runId: item.runId,
        card,
        applied: appliedByCard.get(item.seq) ?? null,
        outcomes: outcomesByCard.get(item.seq) ?? {},
      });
      continue;
    }
    if (item.kind === 'show_chart') {
      const chart = readChart(item);
      if (chart === null) {
        continue;
      }
      // Closes both open runs, for the reason the findings card does.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'chart',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        memberId: item.memberId,
        parentToolUseId: subagentIdOf(item),
        chart,
      });
      continue;
    }
    if (item.kind === 'show_metrics') {
      const metrics = readMetrics(item);
      if (metrics === null) {
        continue;
      }
      // Closes both open runs, for the reason the findings card does.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'metrics',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        memberId: item.memberId,
        parentToolUseId: subagentIdOf(item),
        metrics,
      });
      continue;
    }
    if (item.kind === 'show_comparison') {
      const comparison = readComparison(item);
      if (comparison === null) {
        continue;
      }
      // Closes both open runs, for the reason the findings card does.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'comparison',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        memberId: item.memberId,
        parentToolUseId: subagentIdOf(item),
        comparison,
      });
      continue;
    }
    if (item.kind === 'show_gallery') {
      const gallery = readGallery(item);
      if (gallery === null) {
        continue;
      }
      // Closes both open runs, for the reason the findings card does.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'gallery',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        memberId: item.memberId,
        parentToolUseId: subagentIdOf(item),
        gallery,
      });
      continue;
    }
    if (item.kind === 'show_artifact') {
      const artifact = readPublishedArtifact(item);
      if (artifact === null) {
        continue;
      }
      // Closes both open runs, for the reason the findings card does.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'artifact',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        memberId: item.memberId,
        parentToolUseId: subagentIdOf(item),
        artifact,
        // Decided by the sweep below, once the whole stream is known.
        latest: false,
      });
      continue;
    }
    if (item.kind === 'task_list') {
      const announcement = readTaskAnnouncement(item);
      if (announcement === null) {
        continue;
      }
      const thread = subagentIdOf(item);
      // Keyed by NODE and thread, the pair the cards themselves are keyed by.
      // By thread alone every team node shared the main-thread history, so
      // an Engineer's `TaskUpdate {taskId: "1"}` ticked the Manager's task 1
      // on the Engineer's card while the side panel said otherwise.
      const historyKey = groupKey(item);
      // Folded from the thread's WHOLE history rather than this run's rows: a
      // run holding one `TaskUpdate` knows about one task, and the list is only
      // ever the fold of everything before it. RUNNING rather than re-folded
      // from the start on each announcement, which made the fold quadratic in
      // them — measured at 310ms for 4,000 patches, paid again on every item
      // that arrived.
      const previous = taskLists.get(historyKey);
      const tasks = foldOneMore(previous?.tasks ?? [], announcement);
      const snapshot =
        (previous?.snapshot ?? false) || announcement.mode === 'snapshot';
      taskLists.set(historyKey, { tasks, snapshot });
      const key = groupKey(item);
      const open = openTaskCards.get(key);
      if (open) {
        open.tasks = tasks;
        open.snapshot = snapshot;
        open.seq = Math.max(open.seq, item.seq);
        continue;
      }
      // A card is a narrative row of its own, so it closes the tool group of the
      // thread that produced it — the same boundary any other rendered row is.
      openGroups.delete(key);
      const card: TaskListEntry = {
        type: 'task-list',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        memberId: item.memberId,
        parentToolUseId: thread,
        callId: payloadString(item.payload, 'callId'),
        tasks,
        snapshot,
        // Decided by the sweep below, once the whole stream is known — the same
        // shape `closed` on a tool group takes, and for the same reason: a card
        // cannot know whether a later one exists while it is being built.
        latest: false,
      };
      openTaskCards.set(key, card);
      entries.push(card);
      continue;
    }
    // Any other rendered kind from this node is a narrative boundary — the
    // node "said something", so its next tool call starts a fresh group. Only
    // for the thread that said it: a sub-agent reporting mid-way must not
    // split the main thread's group, which is what produced runs of one-call
    // rows while several sub-agents were talking at once.
    openGroups.delete(groupKey(item));
    openTaskCards.delete(groupKey(item));
    entries.push({ type: 'item', item });
  }
  closeGroupsBeforeTurnEnds(entries, items);
  // The last card of each thread is the current list. Keyed by the same
  // (node, thread) pair the cards were folded on, so a delegate's last card and
  // the agent's own are both current — they are different lists.
  const lastCard = new Map<string, TaskListEntry>();
  for (const entry of entries) {
    if (entry.type === 'task-list') {
      lastCard.set(
        `${entry.memberId ?? ''}\u0000${entry.parentToolUseId ?? ''}`,
        entry,
      );
    }
  }
  for (const card of lastCard.values()) {
    card.latest = true;
  }
  // The same sweep for artifacts, and it buys something different. A card is
  // an open sandboxed DOCUMENT, so a plan revised ten times would hold ten of
  // them live at once — a cost no other card in the family carries, since this
  // is the only revisable one. Every row still gets its card, opening the
  // version it announced; a superseded one starts folded. Keyed by artifact
  // rather than by thread, because that is the identity a revision shares.
  const lastArtifact = new Map<string, ArtifactEntry>();
  for (const entry of entries) {
    if (entry.type === 'artifact') {
      lastArtifact.set(entry.artifact.artifactId, entry);
    }
  }
  for (const card of lastArtifact.values()) {
    card.latest = true;
  }
  return anchorIds === undefined || anchorIds.size === 0
    ? entries
    : entries.filter(
        (entry) => entry.type !== 'item' || !anchorIds.has(entry.item.id),
      );
}

/**
 * Whether anything is still working through the list this card shows.
 *
 * Two conditions, and both are needed. An earlier card is a SNAPSHOT of a list
 * that has since moved on, so its in-progress row is history however live the
 * run is. And the latest card is only live while the run is: a turn that ended
 * with a task still in progress leaves a row that will never advance, and a
 * spinner on it claims work that stopped — the reported "finished one task,
 * still in progress for some reason".
 *
 * `runSettledAt` is read exactly as {@link subagentBlockStatus} reads it: a
 * MOMENT rather than a flag, so a card written AFTER the settle (the CLI
 * carrying on by itself past its own turn-end line) is still live, and an
 * unparseable settle keeps the conservative reading rather than putting every
 * spinner back.
 */
export function taskCardIsLive(
  entry: TaskListEntry,
  runSettledAt: RunSettleAt,
): boolean {
  if (!entry.latest) {
    return false;
  }
  if (runSettledAt === null) {
    return true;
  }
  if (runSettledAt === 'unknown') {
    return false;
  }
  const at = Date.parse(entry.createdAt);
  return Number.isFinite(at) && at > runSettledAt;
}

/**
 * The transcript's task cards, completed from the DAEMON's fold of the whole
 * run (`Run.taskList`).
 *
 * A card is folded from the items this client LOADED, and a long thread loads
 * only its newest `HISTORY_PAGE` of them — while a task's words are stated once,
 * in the announcement that created it, and never again: claude's `TaskUpdate`
 * names an id and a status and nothing else. So past the window a card knew a
 * task by its number alone and drew `Task 1`, `Task 2` where the agent's own
 * words belong. REPORTED against a team run whose engineer created its
 * first three tasks at seq 1000–1006 of a 2,421-row transcript: all three drew
 * as bare numbers, and in first-sighting order (`Task 2` above `Task 1`, `Task
 * 3` below task 9), beside a side panel naming every one of them off this same
 * fold — which is the rule the panel already follows (`tasksByAgent` in
 * `Chats.tsx`: the daemon's fold wins).
 *
 * The two kinds of card mean different things, so they are completed
 * differently:
 * - the LATEST card IS the current list, and the daemon's fold is the whole of
 *   that answer — so the card takes its rows, its ORDER and its total, and the
 *   card and the panel can no longer disagree about what the list is. The
 *   card's own rows still win per task: every patch this window holds is the
 *   newest word on the task it names, while the daemon's copy trails a live
 *   announcement by one broadcast. A task the daemon has not folded yet is kept
 *   for the same reason, rather than dropped for a moment and redrawn.
 * - an EARLIER card is a snapshot of the list as it stood then, so only its
 *   missing TITLES are filled — its rows, count and order stay what they were.
 *   The title is the task's current one, the only one the daemon keeps; a CLI
 *   that renumbers from 1 mid-run could name an old card's task after its
 *   successor, which still says more than a bare number.
 *
 * Matched on the node AND the call thread, the pair the daemon folds on: a node
 * called several times keeps one list per call, each numbering from 1, so a
 * node-only match would title one call's card from another call's list. A
 * delegate's card is left alone — the daemon skips a delegate's rows, whose
 * list is its own.
 *
 * Walks INTO call and turn blocks, because a callee's cards are never
 * top-level: every row a call streams is claimed into its block, which folds
 * them into turn blocks of its own. Mapping the top level alone left exactly
 * the cards the per-call match exists for as bare numbers. A block holding no
 * card that changed is handed back as the same object, so the memo on every
 * other block survives.
 */
export function withDurableTaskLists(
  entries: TranscriptEntry[],
  groups: readonly RunTaskGroup[],
): TranscriptEntry[] {
  if (groups.length === 0) {
    return entries;
  }
  // A JSON pair, as on the daemon: a node id is any non-empty string, so no
  // separator character is safe to join on.
  const threadKey = (memberId: string | null, callId: string | null): string =>
    JSON.stringify([memberId, callId]);
  const byThread = new Map<string, readonly AgentTaskRow[]>(
    groups.map((group) => [
      threadKey(group.memberId, group.callId),
      group.tasks,
    ]),
  );
  const complete = (entry: TranscriptEntry): TranscriptEntry => {
    if (entry.type === 'call-block' || entry.type === 'turn-block') {
      const inner = completeAll(entry.entries);
      return inner === entry.entries ? entry : { ...entry, entries: inner };
    }
    if (entry.type !== 'task-list' || entry.parentToolUseId !== null) {
      return entry;
    }
    const durable = byThread.get(threadKey(entry.memberId, entry.callId));
    if (durable === undefined || durable.length === 0) {
      return entry;
    }
    return {
      ...entry,
      tasks: entry.latest
        ? currentTaskList(durable, entry.tasks)
        : withTaskTitles(entry.tasks, durable),
    };
  };
  const completeAll = (list: TranscriptEntry[]): TranscriptEntry[] => {
    let changed = false;
    const out = list.map((entry) => {
      const next = complete(entry);
      changed ||= next !== entry;
      return next;
    });
    return changed ? out : list;
  };
  return completeAll(entries);
}

function currentTaskList(
  durable: readonly AgentTaskRow[],
  seen: readonly AgentTaskRow[],
): AgentTaskRow[] {
  const seenById = new Map(seen.map((task) => [task.id, task]));
  const known = new Set(durable.map((task) => task.id));
  return [
    ...durable.map((task) => {
      const own = seenById.get(task.id);
      return own === undefined
        ? task
        : {
            ...own,
            title: own.title ?? task.title,
            activeForm: own.activeForm ?? task.activeForm,
          };
    }),
    ...seen.filter((task) => !known.has(task.id)),
  ];
}

function withTaskTitles(
  tasks: readonly AgentTaskRow[],
  durable: readonly AgentTaskRow[],
): AgentTaskRow[] {
  const titles = new Map(durable.map((task) => [task.id, task.title]));
  return tasks.map((task) =>
    task.title === null
      ? { ...task, title: titles.get(task.id) ?? null }
      : task,
  );
}

/** Item kinds that end a turn — after one, nothing more is coming for it. */
const TURN_END_KINDS = new Set(['turn_complete', 'turn_cancelled', 'error']);

/**
 * Mark every tool group that a turn ended after.
 *
 * Answered against the ITEM stream rather than the run's status, because the
 * question is per-turn: the run goes back to `running` on the user's next
 * message, and a group left open by turn 1 must stay closed through turn 5
 * rather than start spinning again with it.
 *
 * Recursive over turn blocks, and deliberately NOT into call blocks: a call
 * block has already had this pass run over its own rows, by the re-fold in
 * {@link buildCallBlock}, and that is the only item list that can close its
 * groups. Walked from here it was judged against EVERY item of the run, so one
 * call finishing closed the tool group of a SIBLING call to the same node —
 * the same node, a different conversation — and `tool-group.tsx` drew a
 * command still running as `stopped`.
 *
 * Scoped to the group's own NODE and CALL, for the same reason {@link
 * buildSubagentBlocks} scopes its own turn-end read: under graph fan-out each
 * node settles independently, so an unscoped comparison let node A's
 * `turn_complete` close node B's still-open group and drop the spinner off a
 * tool call genuinely in flight — and a node serving two calls at once, or a
 * call beside its own conversation, is that fan-out one level down. In a 1:1
 * chat every `nodeId` and `callId` is null, so the scoping is a no-op there —
 * which is why it went unnoticed.
 */
function closeGroupsBeforeTurnEnds(
  entries: readonly TranscriptEntry[],
  items: readonly ChatItem[],
): void {
  const turnEnds = items.filter((item) => TURN_END_KINDS.has(item.kind));
  if (turnEnds.length === 0) {
    return;
  }
  const walk = (list: readonly TranscriptEntry[]): void => {
    for (const entry of list) {
      if (entry.type === 'tools') {
        const lastSeq = entry.pairs.reduce(
          (max, pair) => Math.max(max, pair.result?.seq ?? pair.call.seq),
          0,
        );
        const callId = entryCallId(entry);
        // A turn of THIS node, in THIS conversation, ended after this group's
        // last row, so this group's turn is among the ones that finished.
        entry.closed = turnEnds.some(
          (item) =>
            item.memberId === entry.memberId &&
            payloadString(item.payload, 'callId') === callId &&
            item.seq > lastSeq,
        );
        continue;
      }
      if (entry.type === 'turn-block') {
        walk(entry.entries);
      }
    }
  };
  walk(entries);
}

/**
 * The status a `call_result` envelope states. TWIN PARSER: the broker
 * (`call-broker.service.ts`) writes `{status: 'ok' | 'error', error}`, and a
 * cancel's error carries the `CALLEE_CANCELLED` code.
 *
 * The ONE reading of how a settled call ended: the transcript's call card and
 * the agents panel's instance both go through it, so a call stopped by its
 * caller cannot read `cancelled` on the card and `failed` beside it.
 *
 * TWIN PARSER: `callEndStatus` in
 * apps/daemon/src/v1/agents/utils/run-state-folds.ts — the run's own list of
 * calls, which the working-agents card and the panel read for calls off the window.
 */
export function callResultStatus(
  payload: unknown,
): 'completed' | 'failed' | 'cancelled' {
  if (payloadString(payload, 'status') === 'ok') {
    return 'completed';
  }
  return payloadString(payload, 'error')?.startsWith('CALLEE_CANCELLED')
    ? 'cancelled'
    : 'failed';
}

/**
 * The answer a settled call handed its caller, as the broker's `call_result`
 * envelope carries it (`result.text`), or null.
 *
 * TWIN PARSER: the `ok` arm of `CallEnvelope` in
 * `apps/daemon/src/v1/teams/teams.types.ts`.
 */
function callEnvelopeText(payload: unknown): string | null {
  const text = recordOf(recordOf(payload)?.result)?.text;
  return typeof text === 'string' && text.trim() !== '' ? text : null;
}

/**
 * Assemble one call's block: status items drive the header's live status
 * (they never render as rows — the old "▸ B started"/"✓ B finished" pair
 * folds into the header icon), everything else re-folds recursively (tool
 * groups work inside a block; the bucket holds no call rows, so no blocks
 * nest from here).
 *
 * `pullResult` is false for an earlier call of a continued conversation, whose
 * final message stays in its flow rather than becoming the card's RESULT.
 */
/**
 * The pool member a call ran on — see {@link CallBlockEntry.member}.
 *
 * A call still running after a hand-off is on the member its newest `system`
 * hand-off row names: `call_started` names the member it began on, and only
 * the settle names the one that answered — so without the hand-off row a
 * call member 1 handed to another CLI was credited to member 1's for as long
 * as it ran. An anchored hand-off counts as much as one the window holds — a
 * long call's hand-off is routinely above the loaded page.
 */
function callMemberOf(
  shell: CallShell,
  settle: ChatItem | null,
  handOff: ChatItem | null,
): number | null {
  for (const payload of [
    settle?.payload,
    handOff?.payload,
    shell.started.payload,
  ]) {
    if (payload !== null && typeof payload === 'object') {
      const member = (payload as { member?: unknown }).member;
      if (typeof member === 'number' && Number.isInteger(member)) {
        return member;
      }
    }
  }
  return null;
}

function latestPoolHandOff(shell: CallShell): ChatItem | null {
  let handOff: ChatItem | null = null;
  for (const item of shell.bucket) {
    if (isPoolHandOff(item) && (handOff === null || item.seq > handOff.seq)) {
      handOff = item;
    }
  }
  return handOff;
}

/**
 * Whether a row is the daemon's pool HAND-OFF notice: a `system` row on a call
 * naming the member the call moved to.
 *
 * TWIN PARSER: the row is written by the hand-off in
 * apps/daemon/src/v1/teams/services/graph-executor.service.ts and anchored by
 * `ItemDao.callHandOffRows`.
 */
function isPoolHandOff(item: ChatItem): boolean {
  if (item.kind !== 'system') {
    return false;
  }
  const member = (item.payload as { member?: unknown } | null)?.member;
  return typeof member === 'number' && Number.isInteger(member);
}

/**
 * TWIN PARSER: `CARD_READS` / `cardRowsFor` in
 * apps/daemon/src/v1/agents/services/chat-history.service.ts pick the rows a
 * FOLDED card is built from on a team run, whose window never holds a
 * callee's rows: its status rows, turn endings of every terminal kind and
 * notices, its task lists since the newest whole one, the tool calls of a turn
 * still running, and its newest row, newest words and newest named tool calls.
 * A reading taken from anything else goes empty there until it is added on
 * that side.
 */
function buildCallBlock(
  callId: string,
  shell: CallShell,
  stalled: boolean,
  heldOn: number | null,
  queuedSeq: number | null,
  pullResult: boolean,
): CallBlockEntry {
  let status: CallBlockEntry['status'] = 'pending';
  const inner: ChatItem[] = [];
  // Where the sub-turn's own ending falls in `inner`: rows after it (the CLI
  // answering a message on its own, after the call returned) never reached
  // the caller, so none of them can be the call's result. The FIRST ending,
  // never the last — see `ended`. Null when neither a terminal status row nor
  // the settle envelope is in the window.
  let settledAt: number | null = null;
  // How the call's ONE sub-turn ended — its first terminal status row. Every
  // status row after it is the callee carrying on by itself under the same
  // call id (the executor's off-turn rows), and that stretch's own `completed`
  // is not how the call ended: taking the LAST terminal row made a background
  // reviewer's later "nothing new" the card's RESULT, in place of the answer
  // the caller actually received.
  let ended: CallBlockEntry['status'] | null = null;
  // What the callee's own status ROWS last said.
  let lastRowStatus: string | null = null;
  // The broker's settle envelope, which carries the answer the caller received.
  let settle: ChatItem | null = null;
  // The window holds no terminal status row of the sub-turn, so its closing
  // words are not held either — whatever message it does hold came earlier.
  let endedByEnvelope = false;
  for (const item of shell.bucket) {
    if (item.kind === 'status') {
      const value = payloadString(item.payload, 'status');
      if (value && BLOCK_STATUSES.has(value)) {
        lastRowStatus = value;
        if (ended === null) {
          status = value as CallBlockEntry['status'];
          if (value !== 'running') {
            ended = status;
            settledAt ??= inner.length;
          }
        }
      }
      continue;
    }
    if (item.kind === 'call_result') {
      // A call settled by its envelope alone is bounded by the envelope: what
      // the callee said after it, the caller was never handed either.
      settledAt ??= inner.length;
      settle ??= item;
      // The envelope ENDS the call when no terminal status row came before it.
      // That is how a call reads whose sub-turn ended above the window: its
      // settle arrives as an anchor, the one row of that ending the client
      // holds, and every status row after it is the callee carrying on by
      // itself — whose own `completed` is not how the call ended.
      if (ended === null) {
        ended = callResultStatus(item.payload);
        status = ended;
        endedByEnvelope = true;
      }
    }
    inner.push(item);
  }
  // Either ending — the first terminal status row, or the envelope when it
  // came first (a fan-out's queued call cancelled before its turn began gets
  // only the envelope) — outranks a `running` row written AFTER it: the callee
  // carrying on by itself once the call had settled. The call stays settled;
  // the callee working in it is said separately
  // ({@link CallBlockEntry.calleeWorking}).
  const calleeWorking = ended !== null && lastRowStatus === 'running';
  // A COMPLETED sub-turn's last message is the call's RESULT — pull it out
  // of the flow so the block can frame it (request at the top, result at
  // the bottom). While running the tail message is just the latest stream.
  let result: string | null = null;
  if (pullResult && status === 'completed') {
    if (endedByEnvelope) {
      result = callEnvelopeText(settle?.payload);
    }
    for (
      let i = (settledAt ?? inner.length) - 1;
      i >= 0 && result === null;
      i--
    ) {
      // A message the user sent straight to the callee is never its result,
      // and neither are a sub-agent's words: its thread keeps them.
      if (
        inner[i]!.kind === 'message' &&
        inner[i]!.role !== 'user' &&
        subagentIdOf(inner[i]!) === null
      ) {
        result = payloadString(inner[i]!.payload, 'text');
        if (result !== null) {
          inner.splice(i, 1);
        }
        break;
      }
    }
    // The callee's own closing words are above the window — the settle is an
    // anchor and the message before it is not held. The envelope states the
    // answer the caller was handed, verbatim.
    result ??= callEnvelopeText(settle?.payload);
  }
  // The ok settle envelope is pure bookkeeping once the block shows the
  // result and the done chip; only the error arm keeps a row (in-block).
  const visibleInner = inner.filter(
    (item) =>
      !(
        item.kind === 'call_result' &&
        payloadString(item.payload, 'status') === 'ok'
      ),
  );
  const handOff = latestPoolHandOff(shell);
  const handOffMessage = payloadString(handOff?.payload, 'message');
  const member = callMemberOf(shell, settle, handOff);
  const turns =
    status === 'running'
      ? calleeTurnIn(shell.bucket)
      : { waiting: null, quietSinceWake: false };
  const waiting = turns.waiting;
  return {
    type: 'call-block',
    id: shell.started.id,
    createdAt: shell.started.createdAt,
    callId,
    callIds: [callId],
    // One call is its own conversation until a chain says otherwise, which
    // `buildConversationBlock` is the only thing that can.
    conversationCallIds: [callId],
    calleeMemberId: shell.calleeMemberId,
    callerMemberId: shell.started.memberId,
    mode: payloadString(shell.started.payload, 'mode'),
    message: payloadString(shell.started.payload, 'message'),
    title: payloadString(shell.started.payload, 'title'),
    status,
    result,
    stalled,
    ...(heldOn !== null && OPEN_CALL_STATUSES.has(status) ? { heldOn } : {}),
    ...(waiting !== null ? { waiting } : {}),
    ...(turns.quietSinceWake ? { quietSinceWake: true as const } : {}),
    ...(queuedSeq !== null && status === 'pending'
      ? { queued: true as const, queuedSeq }
      : {}),
    calleeWorking,
    ...(member !== null ? { member } : {}),
    ...(handOff !== null && handOffMessage !== null
      ? { poolHandOff: { message: handOffMessage, seq: handOff.seq } }
      : {}),
    // A callee runs its own delegates, so its sub-turn gets the same fold the
    // main flow gets. Without this a workflow callee's `Task` work spilled
    // loose into the call block, invisible to the panel and to the run badge —
    // and `collectSubagentBlocks`' recursion into call blocks could never find
    // anything, making its "at any depth" claim false.
    //
    // `buildTurnBlocks` LAST, exactly as `Chats.tsx` ends the main flow with
    // it, and its absence here is why a callee's prose read differently from
    // every other agent's: a message that folds into a turn block is drawn as
    // markdown in the flow, and one that does not goes through
    // `MessageBubble` and wears a bordered card of its own. So the callee's
    // sentences sat in grey boxes inside a card that already frames them,
    // where the same agent's words in a 1:1 chat sit bare — reported as
    // "каждое его сообщение все еще в каком-то странном сером блоке… дизайн
    // должен быть такой же, как у обычного треда". Under the block's
    // `NestedThreadContext` those turn blocks render frameless, so what comes
    // out is the ordinary thread's own shape.
    entries: buildTurnBlocks(
      buildWorkflowCards(
        buildSubagentBlocks(
          groupTranscript(withNestedCalls(visibleInner, shell.nested)),
          visibleInner,
        ),
        visibleInner,
      ),
    ),
  };
}

/** A card's own rows with the calls its callee made laid in, in seq order. */
function withNestedCalls(
  own: readonly ChatItem[],
  nested: readonly ChatItem[],
): ChatItem[] {
  return nested.length === 0
    ? [...own]
    : [...own, ...nested].sort((a, b) => a.seq - b.seq);
}

/**
 * Group calls into CONVERSATIONS, oldest first: a call whose `call_started`
 * names an earlier call in `thread` resumes that call's callee session, so it
 * joins that call's chain — transitively, since the earlier call may itself be
 * a continuation. Every member of a chain maps to the same array.
 *
 * TWIN PARSER: `thread` is written by `CallBroker.callAgent`'s `call_started`
 * payload — see `apps/daemon/src/v1/teams/services/call-broker.service.ts`,
 * which accepts only a SETTLED call the same caller made to the same callee.
 *
 * **The parent is looked up in the DAEMON's record as well as in the window,
 * and that is what makes a long conversation add up.** It used to read `items`
 * alone, so a continuation whose parent's `call_started` had paged out past
 * `HISTORY_PAGE` became the root of a chain of its own — a second card, a
 * second instance, and a spend covering only the calls still loaded. MEASURED
 * on a real run whose Engineer held two conversations (`call-1 → call-2 →
 * call-3` and `call-8 → call-9 → call-10 → call-11`): the panel drew EIGHT
 * instances, `call-8` alone at $29.79 while `call-9 → call-10` found each
 * other at $34.70, because the window boundary fell between them. The two
 * conversations are $138.76 and $64.49. REPORTED as exactly that — "у нас
 * должна быть сумма за все вызовы, а не только за последний".
 *
 * `starts` carries each call's `thread` as the daemon recorded it, for calls
 * the window does not hold. The window still wins where both know a call: they
 * are the same row, and preferring the loaded one keeps a chain resolvable
 * before the daemon's answer arrives.
 *
 * A CYCLE is still impossible by construction, through the call NUMBER rather
 * than through array position: a parent must be a call the daemon minted
 * EARLIER (`call-8` may parent `call-9`, never the reverse and never itself),
 * which is exactly what the broker enforces when it accepts only a SETTLED
 * call of the same caller. That keeps the old guarantee — a thread naming
 * itself or a later call leaves the continuation its own root — while working
 * for a parent the window never loaded. The `seen` set below is the backstop
 * for an id that is not `call-<n>`, where no ordering can be read. A branch
 * still MERGES:
 * the daemon lets two calls continue one settled thread, so `call-3`, `call-4`
 * and `call-5` all continuing `call-2` are one conversation, which is what the
 * block's own "open while ANY call is open" rule already assumes.
 *
 * The ONE reading of "which calls are one conversation": the transcript's call
 * blocks and the agents panel's instances both go through it, so a card and
 * the instance it describes cannot disagree about what was continued. Only
 * the first `call_started` of a call id counts, as the fold's own shells do.
 *
 * TWIN PARSER: `conversationCallIds` in
 * apps/daemon/src/v1/agents/utils/history-anchors.ts — the daemon anchors a
 * page with whole conversations by this same rule, so a change here that it
 * does not mirror splits a conversation across cards.
 */
export function resolveCallChains(
  items: readonly ChatItem[],
  starts?: ReadonlyMap<string, { thread: string | null }>,
): Map<string, string[]> {
  // Every call this window or the daemon knows of, and the call each one
  // continued. Discovery ORDER is the window's first, so a conversation whose
  // calls are all loaded keeps reading in the order they were sent.
  const parents = new Map<string, string | null>();
  for (const item of items) {
    if (item.kind !== 'call_started') {
      continue;
    }
    const callId = payloadString(item.payload, 'callId');
    if (callId && !parents.has(callId)) {
      parents.set(callId, payloadString(item.payload, 'thread'));
    }
  }
  for (const [callId, start] of starts ?? []) {
    if (!parents.has(callId)) {
      parents.set(callId, start.thread);
    }
  }

  /**
   * Whether `parent` may be the thread `child` continued: it has to be a call
   * something knows about, and — where both ids carry the daemon's numbering —
   * an EARLIER one. That second clause is the whole cycle guard.
   */
  const joins = (child: string, parent: string | null): parent is string => {
    if (parent === null || !parents.has(parent)) {
      return false;
    }
    const a = callNumberOf(parent);
    const b = callNumberOf(child);
    return a === null || b === null ? parent !== child : a < b;
  };

  /** The oldest call of `callId`'s conversation. */
  const rootOf = (callId: string): string => {
    // Only reachable for ids outside `call-<n>`, where nothing orders the two:
    // the numbering makes the walk strictly decreasing and therefore finite.
    const seen = new Set<string>([callId]);
    let current = callId;
    for (;;) {
      const parent = parents.get(current) ?? null;
      if (!joins(current, parent) || seen.has(parent)) {
        return current;
      }
      seen.add(parent);
      current = parent;
    }
  };

  const byRoot = new Map<string, string[]>();
  for (const callId of parents.keys()) {
    const root = rootOf(callId);
    const members = byRoot.get(root) ?? [];
    members.push(callId);
    byRoot.set(root, members);
  }

  const chains = new Map<string, string[]>();
  for (const members of byRoot.values()) {
    // Ordered by the daemon's own numbering rather than by discovery, since a
    // conversation's calls can arrive from two sources: `call-9` from the
    // window and `call-8` from the readings would otherwise read newest-first,
    // and `callIds.at(-1)` — which every surface takes as the LATEST call —
    // would name the oldest.
    members.sort(byCallNumber);
    for (const callId of members) {
      chains.set(callId, members);
    }
  }
  return chains;
}

/**
 * Order two call ids by the counter the daemon mints them from, keeping any
 * id that is not `call-<n>` after the ones that are, in discovery order.
 *
 * The ids ARE `call-<n>` (see `CallBroker.callAgent`); the fallback is for a
 * row this app did not write — a hand-edited database, a shape a later daemon
 * mints — where a `NaN` comparison would make the sort's result depend on the
 * engine's own ordering.
 */
function byCallNumber(left: string, right: string): number {
  const a = callNumberOf(left);
  const b = callNumberOf(right);
  if (a === null || b === null) {
    return a === b ? 0 : a === null ? 1 : -1;
  }
  return a - b;
}

function callNumberOf(callId: string): number | null {
  const digits = /^call-(\d+)$/.exec(callId);
  return digits ? Number(digits[1]) : null;
}

/**
 * The LATEST call of the conversation a call belongs to — the id its card and
 * its panel instance go by. A call no chain holds is a conversation of its own.
 */
export function conversationHead(
  chains: ReadonlyMap<string, readonly string[]>,
  callId: string,
): string {
  const chain = chains.get(callId);
  return chain?.[chain.length - 1] ?? callId;
}

/**
 * The FIRST call of the conversation a call belongs to — the identity that
 * stays put while continuations are added to it.
 */
export function conversationRoot(
  chains: ReadonlyMap<string, readonly string[]>,
  callId: string,
): string {
  return chains.get(callId)?.[0] ?? callId;
}

/** Whether `item` says its call waited under the cap — see `CallBlockEntry.queued`. */
function isQueuedCall(item: ChatItem): boolean {
  const queued = (item.payload as { queuedCall?: unknown } | null)?.queuedCall;
  return typeof queued === 'object' && queued !== null;
}

/**
 * How many calls a `heldCall` row says its callee is waiting for, or null for
 * any other row — see `CallBlockEntry.heldOn`.
 */
function heldCallWaitingOn(payload: unknown): number | null {
  const held = (payload as { heldCall?: unknown } | null)?.heldCall;
  const waitingOn = payloadNumber(held, 'waitingOn');
  return waitingOn !== null && Number.isInteger(waitingOn) && waitingOn > 0
    ? waitingOn
    : null;
}

/**
 * Whether `item` is a held call's COUNT update — a `heldCall` row with no
 * message, which the daemon writes as the calls it waits for finish
 * (TWIN PARSER: `CallBroker.reviewHold`). Bookkeeping that draws nothing.
 */
function isHeldCountUpdate(item: ChatItem): boolean {
  return (
    item.kind === 'system' &&
    heldCallWaitingOn(item.payload) !== null &&
    payloadString(item.payload, 'message') === null
  );
}

/** A monitor notice `MonitorNoticeRow` draws nothing for: only starts. */
function isUndrawnMonitorNotice(item: ChatItem): boolean {
  if (item.kind !== 'system') {
    return false;
  }
  const notice = readMonitorNotice(item.payload);
  return notice !== null && drawnMonitorEntries(notice).length === 0;
}

/**
 * Rows that neither open nor end a callee turn: the call's own envelope, and a
 * background unit closing after the turn ended.
 */
const WAIT_NEUTRAL_KINDS: ReadonlySet<string> = new Set([
  'call_started',
  'call_result',
  'shell_open',
  'shell_info',
  'subagent_info',
]);

/**
 * Where the callee's turns stand in one call's rows: whether its turn has
 * ended with the call still open, and the monitors of that call still running
 * — see {@link CallBlockEntry.waiting}, null while the callee is mid-turn or
 * has not ended a turn yet — and whether it was woken inside the call and has
 * said nothing since ({@link CallBlockEntry.quietSinceWake}).
 */
function calleeTurnIn(rows: readonly ChatItem[]): {
  waiting: { monitors: readonly string[] } | null;
  quietSinceWake: boolean;
} {
  let turnEnded = false;
  let quietSinceWake = false;
  const resume = (): void => {
    if (turnEnded) {
      quietSinceWake = true;
    }
    turnEnded = false;
  };
  const monitors = new Map<string, string>();
  for (const item of rows) {
    if (item.kind === 'system') {
      const notice = readMonitorNotice(item.payload);
      for (const monitor of notice?.monitors ?? []) {
        if (monitor.event === 'end' || monitor.end !== null) {
          monitors.delete(monitor.id);
        } else {
          monitors.set(monitor.id, monitor.description);
        }
      }
      if (notice?.woke === true || endsHeldWait(item)) {
        resume();
      }
      if (isPoolHandOff(item)) {
        turnEnded = false;
      }
      continue;
    }
    if (WAIT_NEUTRAL_KINDS.has(item.kind) || subagentIdOf(item) !== null) {
      continue;
    }
    if (item.kind === 'status') {
      if (payloadString(item.payload, 'status') === 'running') {
        resume();
      }
      continue;
    }
    if (
      item.kind === 'message' &&
      item.role !== 'user' &&
      (payloadString(item.payload, 'text')?.trim() ?? '') !== ''
    ) {
      quietSinceWake = false;
    }
    turnEnded =
      TERMINAL_KINDS.has(item.kind) &&
      payloadBoolean(item.payload, 'insideTurn') !== true;
  }
  return {
    waiting: turnEnded ? { monitors: [...monitors.values()] } : null,
    quietSinceWake: !turnEnded && quietSinceWake,
  };
}

/** Whether `item` ends a call's wait — see the `heldCalls` fold. */
function endsHeldWait(item: ChatItem): boolean {
  if (item.kind === 'status' || item.kind === 'call_result') {
    return true;
  }
  if (item.kind !== 'system') {
    return false;
  }
  const wake = (item.payload as { wake?: unknown } | null)?.wake;
  return Array.isArray(wake);
}

/**
 * What a conversation's open call is waiting for. One conversation serves one
 * call at a time (`THREAD_BUSY`), so at most one of its open calls is held.
 */
function heldOfOpen(open: readonly CallBlockEntry[]): number | null {
  return open.find((block) => block.heldOn !== undefined)?.heldOn ?? null;
}

/**
 * One block for a conversation of calls (see {@link resolveCallChains}): the
 * LATEST call's header facts over every call's sub-turn in order, with each
 * continuation's `call_started` row kept at the point its ask was sent.
 *
 * OPEN is the exception, and it follows every call rather than the latest:
 * the daemon checks only that a thread names a SETTLED call, so two calls can
 * continue one thread and run at once. While any call is open the block is
 * (running before pending), it is stalled if any open call is, and nothing is
 * pulled out as the RESULT — an answer landing beside a call still at work is
 * not the conversation's result. Otherwise the latest call's final message is.
 */
function buildConversationBlock(
  callIds: readonly string[],
  shells: ReadonlyMap<string, CallShell>,
  stalledCalls: ReadonlySet<string>,
  heldCalls: ReadonlyMap<string, number>,
  queuedCalls: ReadonlyMap<string, number>,
  /**
   * The WHOLE conversation, windowed calls and paged-out ones alike — see
   * {@link CallBlockEntry.conversationCallIds}. Defaults to the drawn calls,
   * so a caller with no chain in hand is exactly as it was.
   */
  conversation: readonly string[] = callIds,
): CallBlockEntry {
  const build = (id: string, pullResult: boolean): CallBlockEntry =>
    buildCallBlock(
      id,
      shells.get(id)!,
      stalledCalls.has(id),
      heldCalls.get(id) ?? null,
      queuedCalls.get(id) ?? null,
      pullResult,
    );
  const last = callIds.length - 1;
  if (last === 0) {
    return {
      ...build(callIds[0]!, true),
      conversationCallIds: [...conversation],
    };
  }
  const blocks = callIds.map((id, index) => build(id, index === last));
  const earlierOpen = blocks
    .slice(0, last)
    .some((block) => OPEN_CALL_STATUSES.has(block.status));
  if (earlierOpen) {
    blocks[last] = build(callIds[last]!, false);
  }
  const open = blocks.filter((block) => OPEN_CALL_STATUSES.has(block.status));
  const heldOn = heldOfOpen(open);
  const first = blocks[0]!;
  const latest = blocks[last]!;
  const status: CallBlockEntry['status'] =
    open.length === 0
      ? latest.status
      : open.some((block) => block.status === 'running')
        ? 'running'
        : 'pending';
  const {
    queued: _latestQueued,
    queuedSeq: _latestQueuedSeq,
    waiting: _latestWaiting,
    ...latestRest
  } = latest;
  const running = open.filter((block) => block.status === 'running');
  const waiting =
    running.length > 0 && running.every((block) => block.waiting !== undefined)
      ? running[running.length - 1]!.waiting
      : undefined;
  const queuedBlock =
    status === 'pending'
      ? open.find((block) => block.queued === true)
      : undefined;
  const poolHandOff = blocks.findLast(
    (block) => block.poolHandOff !== undefined,
  )?.poolHandOff;
  return {
    ...latestRest,
    ...(poolHandOff !== undefined ? { poolHandOff } : {}),
    id: first.id,
    message: first.message,
    callIds: [...callIds],
    conversationCallIds: [...conversation],
    status,
    // Queued only while nothing of the conversation runs and one open call
    // still waits for room.
    ...(queuedBlock?.queuedSeq !== undefined
      ? { queued: true as const, queuedSeq: queuedBlock.queuedSeq }
      : {}),
    stalled: open.some((block) => block.stalled),
    ...(heldOn !== null ? { heldOn } : {}),
    ...(waiting !== undefined ? { waiting } : {}),
    entries: blocks.flatMap((block, index): TranscriptEntry[] =>
      index === 0
        ? block.entries
        : [
            { type: 'item', item: shells.get(callIds[index]!)!.started },
            ...block.entries,
          ],
    ),
  };
}

/**
 * The file a tool RESULT names, when the call itself named none.
 *
 * An agent may disclose nothing about an edit up front and then report the whole
 * diff, path included, on completion (measured on cursor-agent — see
 * `resultDiffsOf`). That path is the only way to tell two edits of the same file
 * from edits of two files, which is the difference between "edited 1 file" and
 * "edited 2 files".
 */
function diffPathOf(result: ChatItem | null): string | null {
  if (result === null) {
    return null;
  }
  const payload = result.payload as { result?: unknown } | null;
  const [first] = resultDiffsOf(payload?.result ?? null);
  return first?.path ?? null;
}

/**
 * The collapsed group's one-line summary, Claude/Cursor-style:
 * "Read 4 files · ran 3 commands · edited 1 file".
 *
 * Every bucket names what the agent DID, because a bare "Used 7 tools" is the
 * one thing a reader cannot act on — seven reads and seven edits are the same
 * number and completely different turns. The buckets cover the tools a coding
 * agent actually spends its calls on: opening files, searching, running
 * commands, editing, writing, fetching, delegating, and calling MCP servers.
 *
 * The tool TOTAL is dropped when the breakdown already accounts for every call
 * in the group, because otherwise the same work is counted twice in one line:
 * a group holding one `Bash` read "Used 1 tool · ran 1 command", two figures
 * for a single action. Once some call falls outside the named buckets the total
 * is the only thing that reports it, so it comes back.
 *
 * `accounted` counts CALLS, while the file figures count DISTINCT paths — three
 * edits to one file are three accounted tools and one edited file, and comparing
 * the displayed numbers instead would have kept the total on exactly the groups
 * that need it least.
 *
 * A file-shaped tool with no `file_path` stays unaccounted ON PURPOSE: it would
 * otherwise be reported as an edit of nothing, and the total is the honest
 * answer for a call this cannot describe.
 */
/**
 * Does this call have a CHANGE TO A FILE to show?
 *
 * REPORTED as "I wanna see all file edits, so it should be automatically open,
 * like claude cli" — the transcript folded every edit behind two presses (the
 * group's chevron, then the row's), so the one part of a turn a reader has to
 * check by eye was the part hidden hardest. It decides what is OPEN, and — since
 * {@link pullFileChangesOutOfGroups} — which rows are lifted out of a group.
 *
 * Only file changes, and deliberately not "everything". A turn's reads, greps
 * and command output are the material an agent worked FROM; unfolding those
 * too would bury the diff in the wall of text this fold exists to prevent.
 *
 * Asked of BOTH directions, because the two shipped transports report a change
 * at opposite ends of one call: claude discloses it in the arguments
 * (`Edit`'s `old_string`/`new_string`, `Write`'s `content`), while an ACP agent
 * discloses no arguments at all and returns `diffs` on the result. Keying on
 * either alone would open the diffs of one CLI and none of the other's — and it
 * is also why the split above runs on the FOLD'S OUTPUT rather than inside it:
 * a result arrives after its call, so a decision taken while grouping would
 * read as "not an edit" for every ACP agent.
 *
 * The last clause is the guard rather than the rule: a tool this classifies as
 * an edit but nothing renders as a diff (`MultiEdit`, whose arguments are a
 * list) still has arguments worth reading, but a row with NO body opens onto
 * blank space and would read as a broken disclosure.
 *
 * Lives here rather than beside its renderer because it is a fact about a
 * {@link ToolPair}, and because the splitter is in this module: `tool-group.tsx`
 * imports from here, so the reverse would close a value cycle.
 */
export function showsFileChange(pair: ToolPair): boolean {
  const payload: unknown = pair.call.payload;
  const name = payloadString(payload, 'name') ?? 'tool';
  const input = (payload as { input?: unknown } | null)?.input;
  const body = toolInputBody(name, input);
  if (body?.kind === 'diff') {
    return true;
  }
  if (pair.result !== null) {
    const result =
      (pair.result.payload as { result?: unknown } | null)?.result ?? null;
    if (toolResultBody(input, result).kind === 'diff') {
      return true;
    }
  }
  const operation = toolOperationOf(payload);
  return (operation === 'edit' || operation === 'create') && body !== null;
}

/**
 * Lift every FILE CHANGE out of its tool group, leaving the calls around it
 * grouped as before.
 *
 * REPORTED: "у нас все еще должны быть группы, сколлапсированные с другими
 * экшенами, но редактирование файлов должно быть вне этой группы … если агент
 * сделал несколько shell-tool колов, у нас должна быть еще одна группа
 * «collapse» … а отдельно блок с редактированием файла". The group already
 * OPENED itself when it held an edit, and that is the shape being fixed: it
 * opened the reads, greps and commands with it, so the diff a reader came for
 * arrived at the bottom of everything the agent had done to find it.
 *
 * So `[bash, bash, edit, read, write]` becomes a collapsed `bash, bash`, the
 * edit on its own, a collapsed `read`, and the write on its own. The
 * surrounding runs keep the fold they always had — they are the material, not
 * the result — and a group holding no change is untouched.
 *
 * Only when the user has left file edits expanded, which is the same condition
 * the auto-open follows: someone who has asked for every step folded is asking
 * for less on screen, and lifting the edits out would put more there.
 *
 * Identity is the segment's OWN first call, exactly as the fold names a group,
 * so the pieces of a split run carry distinct React keys and each keeps its own
 * expansion state instead of inheriting the run's.
 */
export function pullFileChangesOutOfGroups(
  entries: readonly TranscriptEntry[],
): TranscriptEntry[] {
  return entries.flatMap((entry): TranscriptEntry[] => {
    if (entry.type !== 'tools' || !entry.pairs.some(showsFileChange)) {
      return [entry];
    }
    const out: TranscriptEntry[] = [];
    let run: ToolPair[] = [];
    const flushRun = (): void => {
      if (run.length > 0) {
        out.push({ ...entry, id: run[0]!.call.id, pairs: run });
        run = [];
      }
    };
    for (const pair of entry.pairs) {
      if (showsFileChange(pair)) {
        flushRun();
        out.push({
          ...entry,
          id: pair.call.id,
          pairs: [pair],
          standalone: true,
        });
        continue;
      }
      run.push(pair);
    }
    flushRun();
    return out;
  });
}

export function toolGroupSummary(pairs: readonly ToolPair[]): string {
  const { spoken, accounted } = foldToolGroup(pairs);
  const parts = spoken.map((phrase) => phrase.text);
  if (parts.length === 0 || accounted < pairs.length) {
    parts.unshift(`Used ${countOf(pairs.length, 'tool')}`);
    return parts.join(' · ');
  }
  // The breakdown is now the whole line, so it opens the sentence.
  const [first, ...rest] = parts;
  return [first!.charAt(0).toUpperCase() + first!.slice(1), ...rest].join(
    ' · ',
  );
}

/**
 * How many operation glyphs a collapsed group's header carries.
 *
 * Three because the header is a one-line summary sitting in a narrow column and
 * a strip of glyphs long enough to need counting has stopped being a glance —
 * and because the phrases behind them are already spelled out in the sentence
 * beside it, so the icons are an index into that sentence rather than a
 * replacement for it.
 */
const MAX_GROUP_OPERATION_ICONS = 3;

/**
 * The operations a collapsed group's header should draw glyphs for — the same
 * ones {@link toolGroupSummary} SPEAKS, in the same order, capped.
 *
 * Off the same fold as the sentence, deliberately: a second pass over the pairs
 * is how an icon strip comes to disagree with the words next to it (a group
 * reading "read 2 files" under a terminal glyph). It also means the strip
 * inherits the summary's own honesty rules for free — an operation the sentence
 * cannot account for gets no glyph either, rather than a picture asserting
 * something the text declined to.
 *
 * `delegate`, `delete` and `move` are counted by the fold and never spoken, so
 * they draw nothing here either — see the note beside their phrases.
 */
export function toolGroupOperations(
  pairs: readonly ToolPair[],
): ToolOperation[] {
  return foldToolGroup(pairs)
    .spoken.map((phrase) => phrase.operation)
    .slice(0, MAX_GROUP_OPERATION_ICONS);
}

/** `1 file` / `3 files` — the shared pluralizer for the phrases below. */
function countOf(n: number, noun: string): string {
  return `${n} ${noun}${n === 1 ? '' : 's'}`;
}

/** One thing a group is reported to have done: the operation, and its wording. */
interface ToolGroupPhrase {
  operation: ToolOperation;
  text: string;
}

/**
 * The ONE pass over a group's pairs, feeding both the header's sentence and its
 * glyphs.
 *
 * Split out of {@link toolGroupSummary} rather than copied so the two readings
 * cannot drift — the same reason `toolOperationOf` is one classifier serving
 * both the summary and the per-row icon.
 */
function foldToolGroup(pairs: readonly ToolPair[]): {
  spoken: ToolGroupPhrase[];
  accounted: number;
} {
  let commands = 0;
  let searches = 0;
  let fetches = 0;
  let mcpCalls = 0;
  let accounted = 0;
  const opened = new Set<string>();
  const edited = new Set<string>();
  const created = new Set<string>();
  for (const { call, result } of pairs) {
    const input = (call.payload as { input?: unknown } | null)?.input;
    const file =
      input && typeof input === 'object' && 'file_path' in input
        ? String((input as { file_path: unknown }).file_path)
        : null;
    // What the call DID, from the ONE classifier — the agent's own answer when it
    // made one, else its tool name. The name buckets are one CLI's vocabulary:
    // cursor titles its calls "Read File", "Edit File", "grep" and discloses no
    // arguments at all, so before the agent's own answer was consulted a turn
    // that read, edited and ran a command summarised as "Used 2 tools" and named
    // nothing it had done.
    const operation = toolOperationOf(call.payload);
    // Whether the AGENT classified this call itself, which is a different
    // question and decides how a call with no path is counted. An agent-declared
    // kind is trusted with no target (cursor discloses none, so every one of its
    // calls would otherwise go unaccounted); a name-matched file tool is not —
    // it would be reported as an edit of nothing, and the "Used N tools" total is
    // the honest answer for a call this cannot describe.
    const selfDeclared = toolKindOf(call.payload) !== null;
    // A path when one is known — an edit's diff reports it even when the call did
    // not. Counting DISTINCT paths is what makes three edits of one file read as
    // one edited file.
    const path = file ?? diffPathOf(result);
    /** Count this call against a file bucket, or leave it unaccounted. */
    const addPath = (bucket: Set<string>): void => {
      if (path !== null) {
        bucket.add(path);
        accounted += 1;
      } else if (selfDeclared) {
        // No path to tell it apart, so the CALL is the unit. Keyed off the count
        // so two such calls never collapse into one.
        accounted += 1;
        bucket.add(`#${accounted}`);
      }
    };
    switch (operation) {
      case 'read':
        addPath(opened);
        break;
      case 'edit':
        addPath(edited);
        break;
      case 'create':
        addPath(created);
        break;
      case 'search':
        searches += 1;
        accounted += 1;
        break;
      case 'execute':
        commands += 1;
        accounted += 1;
        break;
      case 'fetch':
        fetches += 1;
        accounted += 1;
        break;
      case 'mcp':
        mcpCalls += 1;
        accounted += 1;
        break;
      case 'delegate':
        // Accounted but never SPOKEN — see the note where the other phrases are
        // assembled below.
        accounted += 1;
        break;
      case 'delete':
      case 'move':
        // Accounted but not SPOKEN either: neither has a phrase here, and
        // inventing one ("moved 1 file") for a kind never yet seen on the wire
        // would be guessing at wording no measurement supports.
        accounted += 1;
        break;
      case null:
        break;
    }
  }
  const count = countOf;
  const spoken: ToolGroupPhrase[] = [];
  if (opened.size > 0) {
    spoken.push({
      operation: 'read',
      text: `read ${count(opened.size, 'file')}`,
    });
  }
  if (searches > 0) {
    spoken.push({
      operation: 'search',
      text: `searched ${count(searches, 'time')}`,
    });
  }
  if (commands > 0) {
    spoken.push({
      operation: 'execute',
      text: `ran ${count(commands, 'command')}`,
    });
  }
  if (edited.size > 0) {
    spoken.push({
      operation: 'edit',
      text: `edited ${count(edited.size, 'file')}`,
    });
  }
  if (created.size > 0) {
    spoken.push({
      operation: 'create',
      text: `created ${count(created.size, 'file')}`,
    });
  }
  if (fetches > 0) {
    spoken.push({
      operation: 'fetch',
      text: `fetched ${count(fetches, 'page')}`,
    });
  }
  // `delegations` is counted into `accounted` and then deliberately NOT
  // spoken: a delegation already renders as its own sub-agent block directly
  // below this row, so naming it here says the same thing twice — which is
  // what "Delegated to 5 subagents" sitting over five sub-agent cards actually
  // looked like. It stays ACCOUNTED for so a group that MIXES delegations with
  // real work still reads as its breakdown ("Read 3 files") rather than
  // falling through to the "Used N tools" catch-all. A group of nothing BUT
  // delegations never reaches a reader at all: `buildSubagentBlocks` strips
  // those pairs out and drops the emptied group.
  if (mcpCalls > 0) {
    spoken.push({
      operation: 'mcp',
      text: `called ${count(mcpCalls, 'MCP tool')}`,
    });
  }
  return { spoken, accounted };
}

/** One-line argument preview for a tool row (the command, the path, …). */
export function toolCallSummary(call: ChatItem): string {
  const input = (call.payload as { input?: unknown } | null)?.input;
  if (!input || typeof input !== 'object') {
    return '';
  }
  const record = input as Record<string, unknown>;
  // An agent that named a call and disclosed no arguments has nothing to preview,
  // and `compactJson({})` below would render the literal `{}` — the reported
  // defect, on the line that is visible while the row is COLLAPSED. This is the
  // sibling of the same guard in `tool-render.ts`; it is a separate check rather
  // than a shared call because this function summarizes, it does not decide
  // whether to draw a body. It also covers rows persisted BEFORE the daemon
  // started normalizing the empty bag, which is why replaying an old cursor chat
  // still needs it.
  if (Object.keys(record).length === 0) {
    return '';
  }
  const first = (...keys: string[]): string | null => {
    for (const key of keys) {
      const value = record[key];
      if (typeof value === 'string' && value.length > 0) {
        return value;
      }
    }
    return null;
  };
  const questions = record.questions;
  if (Array.isArray(questions) && questions.length > 0) {
    const q = questions[0] as { question?: unknown };
    if (typeof q?.question === 'string') {
      return q.question;
    }
  }
  return (
    first(
      'command',
      'file_path',
      'pattern',
      'description',
      'query',
      'prompt',
      'path',
      'url',
    ) ?? compactJson(record)
  );
}

function compactJson(value: unknown): string {
  try {
    return JSON.stringify(value) ?? '';
  } catch {
    return String(value);
  }
}

/**
 * Flatten a tool_result payload's `result` for display.
 *
 * MOVED to `tool-render.ts`, which had to normalize the result itself — a diff an
 * agent reported cannot be recognised once it has been stringified. Re-exported
 * here because this module's own callers (and its spec) already read it from this
 * name.
 */
export { toolResultText } from './tool-render';

/**
 * Marks the synthetic entry carrying an agent's not-yet-durable words, so a
 * renderer can style the live tail (and a test can find it) without a new
 * entry kind threading through every switch in this file.
 */
export const LIVE_TEXT_ITEM_PREFIX = 'live:';

/** A live entry's owning node id, from the per-agent map's key. */
function nodeIdOf(key: string): string | null {
  // Through the DECOMPOSER, not the raw key: a callee turn's key is
  // `<node>::<callId>`, and every caller here looks a NODE up by it — so the
  // raw key matched nothing on exactly the threads a call opens.
  return key === CHAT_LIVE_KEY ? null : ownerOfKey(key);
}

/**
 * Append each agent's live tail to the transcript it belongs to.
 *
 * Applied POST-fold, on the finished block list: the tail belongs to the turn
 * that is still being written, which is the LAST block that agent owns. When
 * the agent has no open block yet — its very first words, before any durable
 * item exists — a block is created so the text has somewhere to appear
 * (without this, the first thing you type would show nothing until the whole
 * paragraph landed, which is the entire bug being fixed).
 *
 * The tail rides as an ordinary assistant `message` item so it renders through
 * the same path as the durable text it is about to become. It is injected into
 * the RENDER list only — never into the `items` state — so nothing here can be
 * mistaken for persisted history.
 *
 * `workingAgents` names the agents whose turn is in flight. One that has
 * nothing to show right now — no words, no open reasoning stretch — still gets
 * a row, because the alternative is what the transcript did before: go
 * completely silent between a tool batch and the next words, leaving the chat
 * header as the only place saying anything was happening.
 */
/**
 * The `spend` key for a synthetic live row, or nothing at all.
 *
 * Spread rather than assigned so an unmeasured turn leaves the key ABSENT: the
 * row's renderer reads it with `payloadString`, and a present-but-empty value
 * would draw the separator with no figure after it.
 */
function spendPayload(state: LiveState | null): { spend?: string } {
  const spend = state === null ? null : formatLiveSpend(state);
  return spend === null ? {} : { spend };
}

/**
 * Argument bytes a tool call must reach before the working row names it.
 *
 * The daemon's first progress frame after the open (its `COMPOSE_PUBLISH_STEP`),
 * so an ordinary call — a `Bash`, a `Read`, written in well under a second —
 * never swaps the row's phrase for a blink.
 */
const WRITING_SHOWN_FROM_BYTES = 2048;

/**
 * The `writing` keys for a working row: the tool call the model is writing
 * right now, and how much of it has arrived — or nothing at all.
 *
 * Every call that draws a card already has its own loader (the `composing`
 * row); this is every OTHER call. Their arguments are usually tiny, but not
 * always: a `Write` of a large file, or a host tool whose argument is a whole
 * document, can stream for minutes. REPORTED as a chat that "just continues
 * thinking but doesn't do anything" — an analysis re-emitting a 250KB workflow
 * as `save_workflow_change` arguments for ten minutes under a looping
 * `Sculpting…`, with the output count frozen, because nothing on the row
 * moved while the call was being written.
 */
function writingPayload(state: LiveState | null): {
  writingTool?: string;
  writingBytes?: number;
} {
  if (
    state === null ||
    state.composingTool === null ||
    state.composingBytes === null ||
    state.composingBytes < WRITING_SHOWN_FROM_BYTES
  ) {
    return {};
  }
  return {
    writingTool: formatToolName(state.composingTool),
    writingBytes: state.composingBytes,
  };
}

/**
 * The calls the daemon reads as running, by call id to callee — what
 * {@link withLiveText} takes as `daemonOpenCalls`. A queued call has no turn
 * yet, so its callee is not narrated by it.
 */
export function runningCallCallees(
  calls: readonly RunCallState[],
): Map<string, string> {
  const out = new Map<string, string>();
  for (const call of calls) {
    if (
      call.status === 'running' &&
      !call.queued &&
      call.calleeMemberId !== null
    ) {
      out.set(call.callId, call.calleeMemberId);
    }
  }
  return out;
}

export function withLiveText(
  blocks: readonly TranscriptEntry[],
  liveText: ReadonlyMap<string, LiveState>,
  workingAgents: ReadonlySet<string> = new Set(),
  /**
   * The open run, for {@link geniroCardKindOf} — geniro's MCP server is named
   * per run, and that run id is what makes the name unforgeable.
   *
   * Null simply withholds the composing placeholder rather than falling back to
   * a looser match: a card-shaped loader drawn for a user's own tool is worse
   * than no loader at all, and the row underneath is unchanged either way.
   */
  runId: string | null = null,
  /**
   * Every call the daemon reads as running, by call id to its callee, over the
   * whole run — a call a callee made is never on a root page, so its card is
   * missing from a folded caller card.
   */
  daemonOpenCalls: ReadonlyMap<string, string> = new Map(),
): TranscriptEntry[] {
  if (liveText.size === 0 && workingAgents.size === 0) {
    return blocks as TranscriptEntry[];
  }
  const out = [...blocks];
  /**
   * Callees whose call block is still open — their live rows belong INSIDE it,
   * and their silence is already narrated by it. Read once, so the placement
   * below and the working fallback cannot disagree about which nodes those are.
   */
  const openCallees = openCallCallees(blocks);
  /**
   * Open calls with no card in the window. The working-agents card narrates
   * their callees, so a live row of theirs is dropped, never drawn at the end.
   */
  const drawnCallIds = new Set(
    collectCallBlocks(blocks).flatMap((block) => block.callIds),
  );
  const undrawnOpenCalls = new Set<string>();
  for (const [callId, callee] of daemonOpenCalls) {
    if (!drawnCallIds.has(callId)) {
      undrawnOpenCalls.add(callId);
      openCallees.add(callee);
    }
  }
  /**
   * Every callee whose live rows belong inside a card: the open calls above,
   * plus a callee carrying on by itself inside a call that has already settled
   * ({@link CallBlockEntry.calleeWorking}). Only the open ones NARRATE the
   * callee — a settled card says nothing about work happening in it — so the
   * working fallback below still draws a row for the second kind, inside its
   * card rather than as an empty turn block of its own.
   */
  const enclosingCallees = callCallees(
    blocks,
    (block) => OPEN_CALL_STATUSES.has(block.status) || block.calleeWorking,
  );
  /**
   * Agents already given a row, so the working fallback does not double up —
   * by OWNER NODE, never by raw key. A callee's live plane is keyed
   * `<node>::<callId>` while `workingAgents` names the node, so comparing raw
   * keys could never match and drew `Thinking…` beside `Working…`.
   */
  const spokenFor = new Set<string>();
  const spokenKey = (key: string): string => nodeIdOf(key) ?? key;
  for (const [key, state] of liveText) {
    // A stretch is open when the daemon says which one — never inferred from
    // the token count, which is legitimately 0 on a stretch's first delta.
    // WORDS WIN when both are present: the tail is text the user is already
    // watching appear, and replacing it with a thinking row would take the
    // sentence off the screen until its durable item landed.
    const thinking = state.text === '' && state.thinkingStretch !== null;
    /**
     * The card this agent is WRITING THE CALL FOR right now, if any.
     *
     * A row of its own ALONGSIDE the words rather than instead of them: the
     * sentence that introduces a card ("I'll put this in an artifact") is
     * routinely still live when the call starts, and replacing it would take
     * it off the screen until its durable item landed. Only geniro's own
     * card-drawing tools qualify — every other call is answered within
     * milliseconds of being written, so a placeholder for one would flicker.
     */
    const composing =
      runId === null || state.composingTool === null
        ? null
        : geniroCardKindOf(state.composingTool, runId);
    // An entry can survive carrying only a context figure — the meter reads
    // that after the words went durable. There is no bubble to draw for it.
    if (state.text === '' && !thinking && composing === null) {
      continue;
    }
    spokenFor.add(spokenKey(key));
    const keyCallId = callIdOfKey(key);
    if (keyCallId !== null && undrawnOpenCalls.has(keyCallId)) {
      continue;
    }
    // Words render as the assistant message they are about to become; a
    // reasoning stretch rides the `reasoning` kind, carrying whatever its CLI
    // gives — the thinking TEXT where it discloses it, a running token count,
    // or both.
    //
    // The stretch id is IN the row's identity, which is what makes each wait
    // its own row: React remounts on the new key, so the clock starts at zero
    // and the row lands below whatever ran in between, instead of one row at
    // the bottom whose timer grew for the whole turn while tool groups piled
    // up above it.
    if (state.text !== '' || thinking) {
      const entry = liveEntry(
        key,
        thinking
          ? {
              id: `${LIVE_TEXT_ITEM_PREFIX}${key}:think:${state.thinkingStretch}`,
              kind: 'reasoning',
              payload: {
                live: 'thinking',
                thinkingSince: state.thinkingSince,
                thinkingTokens: state.thinkingTokens ?? 0,
                ...(state.thinkingText === null
                  ? {}
                  : { thinkingText: state.thinkingText }),
              },
            }
          : {
              id: `${LIVE_TEXT_ITEM_PREFIX}${key}`,
              kind: 'message',
              payload: { text: state.text },
            },
      );
      // Into ITS call's card when the key names one: a node serving two calls
      // at once has two open cards, and matching on the node alone put every
      // word into the newer of them.
      attach(out, entry, enclosingCallees, callIdOfKey(key));
    }
    if (composing !== null) {
      // AFTER the words, because that is the order they happened in: the model
      // said what it was about to do and is now doing it.
      attach(
        out,
        liveEntry(key, {
          id: `${LIVE_TEXT_ITEM_PREFIX}${key}:compose:${composing}`,
          kind: 'reasoning',
          payload: {
            live: 'composing',
            composingKind: composing,
            // The count rides the payload rather than being recomputed by the
            // row, for `spend`'s reason: the fold is where the live state is in
            // hand. Omitted when unmeasured so the row draws no figure at all
            // rather than a zero nobody reported.
            ...(state.composingBytes === null
              ? {}
              : { composingBytes: state.composingBytes }),
          },
        }),
        enclosingCallees,
        callIdOfKey(key),
      );
    }
  }
  for (const key of workingAgents) {
    // A callee working inside an open call block is NOT silent: the block says
    // `<callee> is thinking...` and wears a running mark. Calls still out are
    // listed on the working-agents card (`openCallBlocks`), timed from
    // their start — so the transcript draws no second row for them, not even
    // when the conversation has moved past the card.
    const workingNode = nodeIdOf(key);
    if (
      (workingNode !== null && openCallees.has(workingNode)) ||
      spokenFor.has(spokenKey(key))
    ) {
      continue;
    }
    // Measured from the last row this agent put on screen, NEVER from the row's
    // own mount — see {@link WorkingRow}'s `since`. Read from `blocks` rather
    // than `out`: the loop above may already have attached a live row, whose
    // `createdAt` is empty by construction.
    //
    // A callee carrying on inside a settled card is timed off THAT card's rows,
    // the ones the row is drawn beside. The main-thread walk never enters a
    // call block — a card belongs to its CALLER there — so it anchored such a
    // row to the node's last turn of its own, an hour back, or to nothing.
    const card =
      workingNode !== null && enclosingCallees.has(workingNode)
        ? enclosingCallOf(blocks, workingNode, null)
        : null;
    const since = lastMainThreadRowAt(card?.entries ?? blocks, workingNode);
    attach(
      out,
      liveEntry(key, {
        id: `${LIVE_TEXT_ITEM_PREFIX}${key}:working`,
        kind: 'reasoning',
        payload: {
          live: 'working',
          ...(since === null ? {} : { workingSince: since }),
          // This turn's running token bill, formatted at the FOLD because that
          // is where the live state is in hand — the row's own renderer holds a
          // payload and no live plane. Omitted entirely when nothing reported,
          // so the row's `payloadString` reads null and draws nothing rather
          // than an empty figure.
          ...spendPayload(liveText.get(key) ?? null),
          ...writingPayload(liveText.get(key) ?? null),
        },
      }),
      enclosingCallees,
    );
  }
  return out;
}

/**
 * When this agent's MAIN thread last put a row on screen, in epoch ms — the
 * anchor the working row counts from. Null when it never has.
 *
 * Its own thread only, matching {@link attach}'s rule and for a sharper reason
 * than symmetry: a delegate writes rows continuously while the agent that
 * launched it sits silent, so counting those would hold the clock near zero for
 * the whole delegation and answer the opposite of the question. What the row
 * reports is how long the agent you are talking to has shown you nothing.
 *
 * Unparseable and empty `createdAt` values are skipped rather than coerced: the
 * synthetic live entries carry `''`, and `Date.parse('')` is NaN, which would
 * poison a plain `Math.max`.
 */
function lastMainThreadRowAt(
  entries: readonly TranscriptEntry[],
  memberId: string | null,
): number | null {
  let latest: number | null = null;
  const consider = (createdAt: string): void => {
    const at = Date.parse(createdAt);
    if (Number.isFinite(at) && (latest === null || at > latest)) {
      latest = at;
    }
  };
  const walk = (list: readonly TranscriptEntry[]): void => {
    for (const entry of list) {
      if (subagentOwnerOf(entry) !== null || entryNodeId(entry) !== memberId) {
        continue;
      }
      if (entry.type === 'item') {
        consider(entry.item.createdAt);
        continue;
      }
      if (entry.type === 'tools') {
        for (const pair of entry.pairs) {
          consider(pair.result?.createdAt ?? pair.call.createdAt);
        }
        continue;
      }
      if (entry.type === 'browser-screenshot') {
        consider(entry.pair.result?.createdAt ?? entry.createdAt);
        continue;
      }
      if (isCardEntry(entry)) {
        consider(entry.createdAt);
        continue;
      }
      walk(entry.entries);
    }
  };
  walk(entries);
  return latest;
}

/**
 * Call statuses whose sub-turn is still in flight, so the block is an OPEN
 * enclosure: whatever the callee produces now belongs inside it.
 */
const OPEN_CALL_STATUSES = new Set<CallBlockEntry['status']>([
  'pending',
  'running',
]);

/**
 * Every call still running, in transcript order — what the composer shelf's
 * working-agents card lists. Nested calls included (a callee's own calls live inside
 * its card), since each is an agent the user is waiting on.
 */
export function openCallBlocks(
  entries: readonly TranscriptEntry[],
): CallBlockEntry[] {
  return collectCallBlocks(entries).filter((block) =>
    OPEN_CALL_STATUSES.has(block.status),
  );
}

/**
 * The callee nodes whose call block is still open, at any depth.
 *
 * It recurses because a call block is folded into its CALLER's turn block
 * (`ownerOf` attributes it to `callerNodeId`), so it is never a top-level entry
 * in a transcript the caller has said anything in — which is every one of them,
 * the block's own `call_started` row being the caller's — and because a call a
 * callee made is drawn inside its caller's card.
 */
function openCallCallees(entries: readonly TranscriptEntry[]): Set<string> {
  return callCallees(entries, (block) => OPEN_CALL_STATUSES.has(block.status));
}

/** The callee nodes of every call block `matches` accepts, at any depth. */
function callCallees(
  entries: readonly TranscriptEntry[],
  matches: (block: CallBlockEntry) => boolean,
  found: Set<string> = new Set(),
): Set<string> {
  for (const entry of entries) {
    if (entry.type === 'call-block') {
      if (entry.calleeMemberId !== null && matches(entry)) {
        found.add(entry.calleeMemberId);
      }
      callCallees(entry.entries, matches, found);
      continue;
    }
    if (entry.type === 'turn-block') {
      callCallees(entry.entries, matches, found);
    }
  }
  return found;
}

/**
 * The card a live row of this node belongs inside — an open call it is the
 * callee of, or a settled one it is carrying on in — or null when it has none.
 *
 * Newest first, so a node called twice in one turn writes into the call still
 * running rather than into an earlier one that happens to share its status.
 *
 * When the live key names a call, ONLY that call's card qualifies (any call of
 * its conversation, since a continued conversation is one card). Falling back
 * to "any open card of the node" filed a call's first words — spoken before
 * its own card existed — inside a SIBLING call's card, where they then jumped
 * out the moment they went durable. With no card of its own the row goes to
 * the tail like any other agent's. A key that names no call still takes the
 * newest card of the node, which is the only reading it has.
 */
function enclosingCallOf(
  list: readonly TranscriptEntry[],
  memberId: string,
  callId: string | null,
): CallBlockEntry | null {
  for (let i = list.length - 1; i >= 0; i--) {
    const candidate = list[i]!;
    if (candidate.type === 'call-block') {
      const inner = enclosingCallOf(candidate.entries, memberId, callId);
      if (inner !== null) {
        return inner;
      }
      if (
        candidate.calleeMemberId === memberId &&
        (OPEN_CALL_STATUSES.has(candidate.status) || candidate.calleeWorking) &&
        (callId === null || candidate.callIds.includes(callId))
      ) {
        return candidate;
      }
      continue;
    }
    if (candidate.type === 'turn-block') {
      const found = enclosingCallOf(candidate.entries, memberId, callId);
      if (found !== null) {
        return found;
      }
    }
  }
  return null;
}

/**
 * Append a live row to the card {@link enclosingCallOf} names for it.
 *
 * Only the arrays on the path to the block are copied — the block, and the turn
 * blocks enclosing it — which is what keeps every other block's identity, and
 * therefore its memo, stable across a delta (see `durableEntries` in
 * `Chats.tsx`).
 */
function placeInOpenCall(
  list: TranscriptEntry[],
  memberId: string,
  entry: ItemEntry,
  /** The call the row belongs to, when its live key names one. */
  callId: string | null = null,
): boolean {
  const card = enclosingCallOf(list, memberId, callId);
  return (
    card !== null &&
    placeInMatchingCall(list, entry, (candidate) => candidate === card)
  );
}

function placeInMatchingCall(
  list: TranscriptEntry[],
  entry: ItemEntry,
  matches: (candidate: CallBlockEntry) => boolean,
): boolean {
  for (let i = list.length - 1; i >= 0; i--) {
    const candidate = list[i]!;
    if (candidate.type === 'call-block') {
      if (matches(candidate)) {
        list[i] = { ...candidate, entries: [...candidate.entries, entry] };
        return true;
      }
      const inner = [...candidate.entries];
      if (placeInMatchingCall(inner, entry, matches)) {
        list[i] = { ...candidate, entries: inner };
        return true;
      }
      continue;
    }
    if (candidate.type === 'turn-block') {
      const inner = [...candidate.entries];
      if (placeInMatchingCall(inner, entry, matches)) {
        list[i] = { ...candidate, entries: inner };
        return true;
      }
    }
  }
  return false;
}

/** One synthetic row, shaped like the durable item it renders through. */
function liveEntry(
  key: string,
  spec: {
    id: string;
    kind: ChatItem['kind'];
    payload: Record<string, unknown>;
  },
): ItemEntry {
  return {
    type: 'item',
    item: {
      id: spec.id,
      runId: '',
      memberId: nodeIdOf(key),
      // Sorts after everything durable; this list is already ordered, so the
      // value only has to be larger than any real seq.
      seq: Number.MAX_SAFE_INTEGER,
      kind: spec.kind,
      role: 'assistant',
      payload: spec.payload,
      createdAt: '',
    },
  };
}

/**
 * Put a live row at the end of the block its agent is writing, or open one.
 *
 * The owner is read off the entry rather than passed in: two sources for one
 * value that must agree is how a row ends up attached to a block it does not
 * belong to.
 *
 * Only the LAST entry is a candidate, and that is the whole correctness of it.
 * A live row describes what is happening RIGHT NOW, so it belongs after
 * everything already on screen — but the fold breaks a turn block on every
 * user message, `turn_complete` divider and approval card, which leaves the
 * agent's previous block sitting further up. Searching backwards for it put
 * the row INSIDE that older block, and the three reported symptoms are all
 * that one walk:
 *
 * - press stop, send again, and the new turn's "Thinking…" appears above the
 *   message that started it;
 * - answer a question and the streaming reply renders above the answer, then
 *   snaps below it the moment the text goes durable (the durable item's seq
 *   puts it after the verdict, where it always belonged);
 * - the same for the `turn_complete` divider between two turns.
 *
 * When the last entry is not this agent's block, a NEW block is opened at the
 * end. That is also what makes the row's position stable across the
 * live→durable seam: both land after the same divider.
 */
function attach(
  out: TranscriptEntry[],
  entry: ItemEntry,
  /**
   * Callees whose rows belong inside a card — an open call's, or a settled
   * one's the callee is still working in (see `withLiveText`).
   */
  enclosingCallees: ReadonlySet<string> = new Set(),
  /** The call a callee's row belongs to — see {@link placeInOpenCall}. */
  callId: string | null = null,
): void {
  const memberId = entry.item.memberId;
  // Matched on the thread as well as the node, exactly as `ownerOf` does. A
  // live row is the MAIN thread's — the daemon drops a sub-agent's deltas from
  // the live tail — so on nodeId alone it would be appended to a delegate's
  // block whenever one happened to be last, and rendered under that block's
  // `sub-agent` label as the delegate's own words.
  const subagentId = subagentIdOf(entry.item);
  // A CALLEE writes inside the block its caller opened, and nowhere else. Its
  // durable rows are claimed into that block by callId, so a live row placed
  // out here does not merely sit in the wrong place — it puts the callee on
  // screen TWICE, as an all-but-empty block of its own beside the call it is
  // answering, and every word then jumps into the card the moment it goes
  // durable. The block is an enclosure rather than a boundary, so unlike the
  // turn-block search below this one is not restricted to the LAST entry: a
  // fan-out has several calls open at once, and each one's block stays open
  // until its own sub-turn settles.
  if (
    memberId !== null &&
    subagentId === null &&
    enclosingCallees.has(memberId) &&
    placeInOpenCall(out, memberId, entry, callId)
  ) {
    return;
  }
  const last = out[out.length - 1];
  if (
    last?.type === 'turn-block' &&
    last.memberId === memberId &&
    last.subagentId === subagentId
  ) {
    out[out.length - 1] = { ...last, entries: [...last.entries, entry] };
    return;
  }
  out.push({
    type: 'turn-block',
    id: entry.item.id,
    createdAt: entry.item.createdAt,
    memberId,
    subagentId,
    entries: [entry],
  });
}
