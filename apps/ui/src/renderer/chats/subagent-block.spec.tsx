let seq = 0;
function item(kind: ChatItem['kind'], payload: unknown): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    memberId: null,
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function makeBlock({
  withResult = true,
  stopped = false,
  failed = false,
  model,
  card = false,
}: {
  /** The launching Task tool returned. */
  withResult?: boolean;
  /** Its turn ended without the Task tool ever returning. */
  stopped?: boolean;
  /** It returned, but with `isError`. */
  failed?: boolean;
  /** The model its CLI says it resolved to, declared as the daemon declares it. */
  model?: string;
  /**
   * The delegate drew a findings card, carrying the `parentToolUseId` the
   * daemon's own `attributeCard` stamps onto a render-family row.
   */
  card?: boolean;
} = {}): SubagentBlockEntry {
  const items: ChatItem[] = [
    item('tool_call', {
      id: 'task-1',
      name: 'Task',
      input: {
        subagent_type: 'code-reviewer',
        description: 'Review the diff',
        prompt: 'Look for off-by-one errors.',
      },
    }),
    ...(model === undefined
      ? []
      : [item('subagent_info', { id: 'task-1', model })]),
    item('message', {
      text: 'reading the diff now',
      parentToolUseId: 'task-1',
    }),
    // A reasoning row, so the FOURTH caption surface (`TranscriptItem`'s
    // 'sub-agent thinking') and `subagentSteps`' `thought` arm are both
    // reachable from this fixture.
    item('reasoning', {
      text: 'the loop bound looks suspect',
      parentToolUseId: 'task-1',
    }),
    item('tool_call', {
      id: 'g1',
      name: 'Grep',
      input: { pattern: 'idx <=' },
      parentToolUseId: 'task-1',
    }),
    item('tool_result', {
      id: 'g1',
      name: null,
      result: 'two hits',
      parentToolUseId: 'task-1',
    }),
    ...(card
      ? [
          item('report_findings', {
            parentToolUseId: 'task-1',
            findings: [
              {
                file: 'src/parse.ts',
                summary: 'An off-by-one in the loop bound',
              },
            ],
          }),
        ]
      : []),
  ];
  if (stopped) {
    // The turn ends with the delegate's tool never having returned.
    items.push(item('turn_complete', {}));
  } else if (withResult) {
    items.push(
      item('tool_result', {
        id: 'task-1',
        name: null,
        result: failed
          ? 'the delegate could not finish'
          : 'Found one off-by-one in parse().',
        isError: failed,
      }),
      item('turn_complete', {}),
    );
  }
  const blocks = collectSubagentBlocks(
    buildTurnBlocks(buildSubagentBlocks(groupTranscript(items), items)),
  );
  const block = blocks[0];
  if (!block) {
    throw new Error('expected a sub-agent block');
  }
  return block;
}

