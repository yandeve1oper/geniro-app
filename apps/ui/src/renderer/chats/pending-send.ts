import type { ItemDto as ChatItem } from '../autogenerated';
import type { TranscriptEntry } from './transcript-groups';
import { payloadString } from './transcript-payload';

const PENDING_SEND_ITEM_PREFIX = 'pending-send:';

/**
 * A message the user sent whose POST is held while the run's collected task
 * worktree is cut again, before any row of it exists.
 */
export interface PendingSend {
  runId: string;
  text: string;
  imageCount: number;
  sentAt: string;
  /** The newest seq the window held when the send went out. */
  afterSeq: number;
}

function landed(pending: PendingSend, items: readonly ChatItem[]): boolean {
  return items.some(
    (item) =>
      item.kind === 'message' &&
      item.role === 'user' &&
      item.seq > pending.afterSeq &&
      payloadString(item.payload, 'text') === pending.text,
  );
}

function shownText({ text, imageCount }: PendingSend): string {
  if (text !== '' || imageCount === 0) {
    return text;
  }
  return imageCount === 1 ? '1 image' : `${imageCount} images`;
}

/**
 * The transcript with the held message drawn as the user's own row at its end,
 * until the row the daemon wrote for it is in the window.
 */
export function withPendingSend(
  entries: TranscriptEntry[],
  pending: PendingSend | undefined,
  items: readonly ChatItem[],
): TranscriptEntry[] {
  if (pending === undefined || landed(pending, items)) {
    return entries;
  }
  return [
    ...entries,
    {
      type: 'item',
      item: {
        id: `${PENDING_SEND_ITEM_PREFIX}${pending.runId}`,
        runId: pending.runId,
        memberId: null,
        seq: Number.MAX_SAFE_INTEGER,
        kind: 'message',
        role: 'user',
        payload: { text: shownText(pending) },
        createdAt: pending.sentAt,
      },
    },
  ];
}
