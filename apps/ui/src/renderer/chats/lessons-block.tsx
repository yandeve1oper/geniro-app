import { useContext, useEffect, useState } from 'react';

import { agentDisplayName, AgentIdentityContext } from '../agent-identity';
import type { LessonReflectionFactsDto } from '../autogenerated';
import {
  type LessonEdit,
  type LessonMoveUpPlace,
  type LessonRuleEdit,
  type LessonSaveRequest,
  LessonsCard,
  type LessonsLook,
  type LessonsReflectionView,
  type LessonView,
  moveUpOf,
} from '../components/lessons-card';
import type { DaemonApis } from '../daemon-api';
import { formatDuration } from '../stats/stats-format';
import { formatUsd } from './agent-activity';
import {
  described,
  documentsReaderOf,
  LessonsAgentsApiContext,
  LessonsApiContext,
  LessonsJumpContext,
  LessonsKnowledgeApiContext,
  WAITING_LESSON_STATUSES,
} from './lessons-api-context';
import { ThreadUiMemoryContext } from './thread-ui-memory';
import type { LessonsEntry } from './transcript-groups';
import { useModelDisplayName } from './use-model-display-name';

const LOOK: LessonsLook = {
  formatDuration,
  formatUsd,
};

const REFLECTION_POLL_MS = 5_000;

/**
 * A run's figures as the daemon holds them, re-read every few seconds while it
 * is still working. Null until the first answer.
 */
function useRunFacts(
  api: DaemonApis['lessons'] | null,
  runId: string | null,
): LessonReflectionFactsDto | null {
  const [facts, setFacts] = useState<LessonReflectionFactsDto | null>(null);

  useEffect(() => {
    if (api === null || runId === null) {
      return;
    }
    let live = true;
    let timer: ReturnType<typeof setTimeout> | undefined;
    const read = (): void => {
      api
        .getLessonReflection({ reflectionRunId: runId })
        .then((next) => {
          if (!live) {
            return;
          }
          setFacts(next);
          if (next.working) {
            timer = setTimeout(read, REFLECTION_POLL_MS);
          }
        })
        .catch(() => undefined);
    };
    read();
    return () => {
      live = false;
      clearTimeout(timer);
    };
  }, [api, runId]);

  return facts;
}

/**
 * The daemon's "Move up" for each undecided lesson that could move up, read
 * once its card is drawn: only the daemon knows whether the entry the lesson
 * names is already in the memory index. Null while it has not answered, and
 * when no lesson could move up.
 */
function useMoveUps(
  api: DaemonApis['lessons'] | null,
  sourceRunId: string | null,
  lessons: readonly LessonView[],
  outcomes: LessonsEntry['outcomes'],
): Readonly<Record<string, LessonMoveUpPlace | null>> | null {
  const [answer, setAnswer] = useState<{
    key: string;
    moveUps: Readonly<Record<string, LessonMoveUpPlace | null>>;
  } | null>(null);
  const key = lessons
    .filter(
      (lesson) =>
        outcomes[lesson.id] === undefined && moveUpOf(lesson) !== null,
    )
    .map((lesson) => lesson.id)
    .join(',');

  useEffect(() => {
    if (api === null || sourceRunId === null || key === '') {
      return;
    }
    let live = true;
    void api
      .listLessonProposals({ status: WAITING_LESSON_STATUSES, sourceRunId })
      .then(
        ({ proposals }) => {
          if (live) {
            setAnswer({
              key,
              moveUps: Object.fromEntries(
                proposals.map((proposal) => [proposal.id, proposal.moveUp]),
              ),
            });
          }
        },
        () => undefined,
      );
    return () => {
      live = false;
    };
  }, [api, sourceRunId, key]);

  return answer !== null && answer.key === key ? answer.moveUps : null;
}

function footerOf(
  label: LessonsReflectionView['label'],
  agent: string,
  model: string | null,
  facts: LessonReflectionFactsDto | null,
): LessonsReflectionView {
  return {
    label,
    agent,
    model,
    effort: facts?.effort ?? null,
    figures:
      facts === null
        ? null
        : {
            working: facts.working,
            durationMs: facts.durationMs,
            costUsd: facts.costUsd,
          },
  };
}

/**
 * A `lessons` row as its card. The lessons row carries the proposals and the
 * outcomes the user (or the automatic run) has set on them; each run's footer
 * is read from the daemon.
 */
export function LessonsBlock({
  entry,
}: {
  entry: LessonsEntry;
}): React.JSX.Element {
  const api = useContext(LessonsApiContext);
  const knowledgeApi = useContext(LessonsKnowledgeApiContext);
  const jump = useContext(LessonsJumpContext);
  const identities = useContext(AgentIdentityContext);
  const sourceRunId = useContext(ThreadUiMemoryContext);
  const { card } = entry;
  const moveUps = useMoveUps(api, sourceRunId, card.proposals, entry.outcomes);
  const reflectionFacts = useRunFacts(api, card.reflectionRunId);
  const checkFacts = useRunFacts(api, card.check?.runId ?? null);
  const agentsApi = useContext(LessonsAgentsApiContext);
  const reflectionModel = useModelDisplayName(
    agentsApi,
    card.agentKind,
    reflectionFacts?.model ?? card.model,
  );
  const checkModel = useModelDisplayName(
    agentsApi,
    card.check?.agentKind ?? null,
    checkFacts?.model ?? card.check?.model ?? null,
  );

  const reflection = footerOf(
    'Reflection',
    agentDisplayName(identities, card.agentKind),
    reflectionModel,
    reflectionFacts,
  );
  const check =
    card.check === null
      ? null
      : footerOf(
          'Check',
          agentDisplayName(identities, card.check.agentKind),
          checkModel,
          checkFacts,
        );

  return (
    <LessonsCard
      look={LOOK}
      lessons={card.proposals}
      outcomes={entry.outcomes}
      reflection={reflection}
      check={check}
      places={card.places}
      readDocuments={documentsReaderOf(knowledgeApi)}
      moveUps={moveUps}
      onShowInThread={jump ?? undefined}
      onSave={
        api === null
          ? undefined
          : (proposalId: string, request: LessonSaveRequest) =>
              described(api.saveLesson({ proposalId, saveLessonDto: request }))
      }
      onReject={
        api === null
          ? undefined
          : (proposalId: string, reason: string | null) =>
              described(
                api.rejectLesson({
                  proposalId,
                  rejectLessonDto: reason === null ? {} : { reason },
                }),
              )
      }
      onUpdateRule={
        api === null
          ? undefined
          : (proposalId: string, edit: LessonRuleEdit) =>
              described(
                api.updateLessonRule({
                  proposalId,
                  updateLessonRuleDto: edit,
                }),
              )
      }
      onMoveUp={
        api === null
          ? undefined
          : (proposalId: string) => described(api.moveLessonUp({ proposalId }))
      }
      onUndo={
        api === null
          ? undefined
          : (proposalId: string) => described(api.undoLesson({ proposalId }))
      }
      onEdit={
        api === null
          ? undefined
          : (proposalId: string, edit: LessonEdit) =>
              described(api.editLesson({ proposalId, editLessonDto: edit }))
      }
      onApprove={
        api === null
          ? undefined
          : (proposalId: string) => described(api.approveLesson({ proposalId }))
      }
    />
  );
}
