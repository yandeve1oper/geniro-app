/**
 * Live per-agent execution state, derived purely from a run's transcript
 * items. Every turn an agent node runs — DAG-scheduled or a callee sub-turn
 * started by `call_agent` — emits a `status` item `{nodeId, status:'running'}`
 * on spawn and a terminal one on settle, so the currently-live parallel turns
 * are the conversations whose last such row is a `running`. `turn_complete`
 * items carry the CLI's usage, giving the agent's current context footprint
 * and its cumulative spend.
 */
export interface AgentActivity {
  /** Turns of this agent live RIGHT NOW (an orchestrator can run several). */
  activeTurns: number;
  /** How many turns of this agent have STARTED over the run's lifetime. */
  turnStarts: number;
  /**
   * How many of those were the node's OWN turn rather than a turn under a
   * call — a status row carrying no `callId`.
   *
   * What decides whether the agent has a main conversation at all. It used to
   * be inferred as "more turn starts than call threads", which is wrong the
   * moment one call runs more than one turn (a follow-up on its thread, a
   * continuation after a delegate reports back): a callee that never ran a turn
   * of its own was drawn a phantom `Main conversation` instance with no reading,
   * so its card showed one ring for every instance. REPORTED as "we should show
   * context for EACH subagent instance, now it's only one for all".
   */
  mainTurnStarts: number;
  /**
   * The node's OWN conversation has a live turn, read from its rows. Absent
   * where only a node-wide reading is known (`withDurableNodeStatus`), and then
   * the main instance's state is inferred from the live-turn count.
   */
  mainTurnLive?: boolean;
  /**
   * The OWN conversation's context reading, folded from `turn_complete` rows
   * carrying no `callId` — the main instance's ring. {@link contextTokens} is
   * whichever conversation of this node settled last, which is the card's
   * question and not an instance's.
   */
  mainContextTokens: number | null;
  /** Whether {@link mainContextTokens} is geniro's stand-in for a reading. */
  mainContextEstimated: boolean;
  mainContextWindowTokens: number | null;
  /** The node's most recent status transition; null before its first one. */
  lastStatus: NodeRunStatus | null;
  /** Prompt-side tokens of the agent's LATEST settled turn (its context). */
  contextTokens: number | null;
  /**
   * Whether {@link contextTokens} is geniro's stand-in for an occupancy the CLI
   * did not state (`usage.contextEstimated`) — it travels with the count.
   */
  contextEstimated: boolean;
  /** That turn's model window as the CLI reported it; null if it reported none. */
  contextWindowTokens: number | null;
  /**
   * The MODEL that turn ran on, as the CLI named it — never what the graph or
   * the run row ASKED for.
   *
   * The two differ routinely and the difference is the point: a node that names
   * no model runs on the CLI's own current one, and a model the CLI does not
   * offer is refused per turn with the turn running on something else. So this
   * is what the agent is, and the declared value is only what it was told.
   */
  contextModel: string | null;
  /** Cumulative cost across all of the agent's settled turns. */
  spentUsd: number | null;
  /** Of {@link spentUsd}, the part geniro priced itself; null when none. */
  spentEstimatedUsd: number | null;
  /**
   * What the agent has SPENT in tokens, summed over its settled turns — the
   * figure that stands beside {@link spentUsd}.
   *
   * Three counters rather than one, because the app already treats them as
   * three: the Stats page leads with tokens in and out and reports cache
   * separately with a hit rate. A single sum would be dominated by cache reads
   * — measured on one Engineer turn, 48.3B of them against 117.6k of real
   * input and output — so every agent would read the same enormous number and
   * say nothing about the work.
   *
   * Null until a turn reports one: a reported absence is not a zero, the rule
   * every figure on this row follows.
   */
  inputTokens: number | null;
  outputTokens: number | null;
  /** Cache reads and creations together — what the two figures above cost to
   * put in front of the model, kept apart from them for the reason above. */
  cacheTokens: number | null;
  /**
   * How many model requests the agent has made, summed over its settled turns
   * — the CLI's own `numTurns`, on {@link inputTokens}'s own rule (a reported
   * absence is not a zero).
   */
  numTurns: number | null;
  /**
   * The agent's LATEST measured turn-start timings — how long it waited
   * before its first token, and before its first request was even sent.
   *
   * Unlike {@link inputTokens}, these are not summed: they describe how ONE
   * turn started, so a running total would mean nothing. Remembered rather
   * than replaced by silence, on {@link contextTokens}'s own rule — a turn
   * that reports neither has said nothing about this agent's responsiveness.
   */
  ttftMs: number | null;
  timeToRequestMs: number | null;
  /**
   * The agent's call threads — one per `call_agent` conversation targeting it,
   * derived from the caller's call_started/call_result items (which carry the
   * callee node id and, on settle, the thread's CLI session id).
   */
  callThreads: AgentCallThread[];
}

/**
 * One `call_agent` conversation of an agent, as the transcript records it.
 *
 * A CONVERSATION, not a call: a call continuing an earlier call's `thread`
 * resumes the same callee session, so it folds into that call's entry rather
 * than adding one (`resolveCallChains`, the rule the transcript's call blocks
 * follow too). REPORTED as a Manager → Engineer conversation continued twice
 * reading as three Engineers running at once. Every other field is the LATEST
 * call's.
 */
export interface AgentCallThread {
  /** The LATEST call of the conversation — the one that can still be live. */
  callId: string;
  /** Every call of the conversation, oldest first; `callId` is the last. */
  callIds: string[];
  /**
   * The calls of the conversation still running. More than the latest can be:
   * the daemon checks only that a thread names a SETTLED call, so two calls can
   * continue one thread at once — which is why the conversation's `status` is
   * `running` while ANY of these is, and why the panel's foreground-shell gate
   * asks each call rather than assuming every call before the last is over.
   */
  openCallIds: string[];
  /** The latest call's brief — its display label. */
  message: string | null;
  /** How the latest call stands — settled through `callResultStatus`. */
  status: 'running' | 'completed' | 'failed' | 'cancelled';
  /** The thread's CLI session id once settled — its terminal/resume handle. */
  sessionId: string | null;
}

/**
 * The activity-map key for single-agent chat items (their nodeId is null).
 *
 * NUL-prefixed so it cannot collide with a real node id. A team node id is
 * any non-empty string, so `agent` is a legal — and obvious — node name; while
 * the sentinel was that same word, such a node was read as "the chat's agent"
 * and every site that excludes the sentinel (`nodeId !== CHAT_AGENT_KEY`)
 * silently excluded the node too, dropping it from the working-agents set and
 * from the panel's extras list. Same defect, and same fix, as
 * `CHAT_LIVE_KEY` on the live plane (`live-text.ts`).
 */
export const CHAT_AGENT_KEY = '\u0000chat';

/**
 * What one agent has WORKED and how many tools it used — carried as a side map
 * keyed by {@link AgentDisplay.id} rather than as fields on it, so the three
 * sites that build an `AgentDisplay` need no edit.
 *
 * Both null until something answers, on the rule every figure in the panel
 * follows: an agent that has taken no turn draws no line rather than
 * `0s · 0 tools`, which claims a measurement nobody took. Separately nullable
 * because every ACP agent reports no timing while still using tools.
 */
export interface AgentWork {
  workedMs: number | null;
  toolCalls: number | null;
}

/**
 * One agent as the agents panel displays it — team node metadata merged
 * with its live {@link AgentActivity}.
 */
export interface AgentDisplay {
  /** Node id ({@link CHAT_AGENT_KEY} for a single-agent chat). */
  id: string;
  name: string;
  /** The CLI driving it; null for a node no longer in the team. */
  agent: CliKind | null;
  /**
   * The MODEL this agent is on — what its turns have actually RUN on where a
   * turn has reported one, else what it was configured with.
   *
   * Null when neither is known: a node that names no model and has not run yet
   * genuinely has no answer, and printing the CLI's default would be a guess
   * about a vocabulary this app does not own.
   */
  model: string | null;
  /**
   * The agent config directory this node's turns run under, or null.
   *
   * Carried on the DISPLAY row because a profile carries its own MCP servers:
   * two nodes on the same CLI with different config directories genuinely load
   * different sets, so the panel cannot ask one question per CLI and paint the
   * answer on both.
   */
  configDir: string | null;
  /**
   * The node's further agent-pool members (2, 3, …), each with its CLI,
   * configured model and config directory; absent for an agent that is not a
   * pool. A call may run on any of them, so a card naming only member 1
   * states half the agent — and a member's profile carries its own MCP
   * servers, which is why the directory rides along.
   */
  pool?: readonly {
    agent: CliKind;
    model: string | null;
    configDir: string | null;
  }[];
  /**
   * The model pool member 1 — the node's own settings — is configured with;
   * null for its CLI's default. Absent for an agent with no pool, whose
   * {@link model} is the whole answer.
   */
  configuredModel?: string | null;
  /**
   * Which pool member its OWN conversation runs on (1-based), whether the
   * user pinned it there, and the member it moves to at its next turn —
   * absent for an agent with no pool, or before the daemon has answered.
   */
  ownPool?: {
    member: number;
    pinned: boolean;
    next: number | null;
  };
  status: RunStatusKind;
  activeTurns: number;
  contextTokens: number | null;
  /**
   * The window {@link contextTokens} is measured against, as the CLI reported
   * it for the model it ran. Null means UNREPORTED, and is rendered as such —
   * the meter shows the count without a denominator rather than measuring
   * against a window nobody named.
   */
  contextWindowTokens: number | null;
  /** Whether {@link contextTokens} is geniro's stand-in for a reading. */
  contextEstimated?: boolean;
  spentUsd: number | null;
  /** Of {@link spentUsd}, the part geniro priced itself; absent when none. */
  spentEstimatedUsd?: number | null;
  /**
   * Of {@link spentUsd}, what the agent's running turns have spent that no
   * finished turn records yet; absent or null when nothing is running.
   */
  runningCost?: LiveCost | null;
  /** What it has spent in tokens — see {@link AgentActivity.inputTokens}. */
  inputTokens: number | null;
  outputTokens: number | null;
  cacheTokens: number | null;
  /** Every conversation the agent has run — the panel's expandable list. */
  threads: AgentThread[];
}

/**
 * One conversation of an agent, as the agents panel lists it.
 *
 * Which KIND of conversation this is, and the three are genuinely different
 * things rather than three labels: a `main` thread is the node's own, a `call`
 * thread is a sub-session with ANOTHER node over the geniro call runtime, and a
 * `subagent` is one CLI's own in-process delegate — which exists only inside
 * its parent's turn and has no CLI session of its own. That last distinction is
 * load-bearing: it is why a sub-agent row offers no terminal handoff, since
 * there is no session for `--resume` to target.
 *
 * A CALL thread always carries `callIds` — every call of its conversation,
 * oldest first, its `id` being the last — and `openCallIds`, the ones still
 * running (see {@link AgentCallThread}), so narrowing on `kind` is all a reader
 * needs to reach them.
 */
export type AgentThread = AgentThreadFields &
  (
    | { kind: 'call'; callIds: string[]; openCallIds: string[] }
    | { kind: 'main' | 'subagent'; callIds?: never; openCallIds?: never }
  );

interface AgentThreadFields {
  /**
   * 'main' for the node's own DAG/chat conversation, the call id for a call
   * thread, and for a sub-agent the id of the tool call that launched it.
   */
  id: string;
  label: string;
  status: RunStatusKind;
  /**
   * For an `untracked` SUB-AGENT: its hosting process has ended, so its work
   * is over and only its outcome is unknown — settled, unlike one that may
   * still be running.
   */
  processEnded?: boolean;
  /**
   * Resume handle for a call thread's terminal (from its call_result item);
   * null for main threads — the daemon resolves those from node_state — and
   * always null for a sub-agent, which never had one.
   */
  sessionId: string | null;
  /**
   * This CONVERSATION's own context reading, when the live plane has one.
   *
   * On the thread rather than on the card, because a context window belongs to
   * a conversation and a node can hold several at once: the daemon used to key
   * the reading by NODE, so a caller running two of the same callee had both
   * writing to one entry — the panel counted "2 active · 2 threads" honestly
   * above a single ring flickering between two unrelated windows. Null for a
   * thread nothing has reported, and for a sub-agent, which has no window of
   * its own.
   */
  contextTokens?: number | null;
  /** Whether {@link contextTokens} is geniro's stand-in for a reading. */
  contextEstimated?: boolean;
  contextWindowTokens?: number | null;
  /**
   * For a SUB-AGENT: the call thread of its agent it was launched in — which
   * INSTANCE of the agent it belongs to — or null for the node's own
   * conversation. Absent on the other two kinds, which ARE instances.
   *
   * A node called several times holds one conversation per call at once, and
   * each launches its own delegates; without this they were listed as one pool
   * under the node, with nothing saying which conversation had sent which.
   */
  callId?: string | null;
  /**
   * For a CALL thread: what the caller ASKED it, verbatim — or null when the
   * call carried no message. `label` is this with the call id in front, for
   * the surfaces that name a thread in one string; the instance block states
   * the two apart.
   */
  brief?: string | null;
  /**
   * For a CALL thread: where it has got to — what it last SAID, else the
   * newest tool it ran — or null when it has done neither yet. The same two
   * readings its call block's summary band draws in the transcript.
   */
  latest?: string | null;
  /**
   * For a CALL thread: what that conversation alone has spent — input + output
   * tokens, and cost — summed over its own settled turns. Null means
   * UNMEASURED, never zero, on the rule every figure in the panel follows.
   */
  spentTokens?: number | null;
  spentUsd?: number | null;
  /** Of {@link spentUsd}, the part geniro priced itself; null when none. */
  spentEstimatedUsd?: number | null;
  /**
   * For a CALL thread of a POOLED agent: which pool member (1-based) the
   * conversation runs on — its newest call's settle, else its hand-off, else
   * its start. Null when nothing says, and absent for an agent with no pool,
   * where there is nothing to choose between.
   */
  member?: number | null;
  /**
   * When this conversation's prompt cache lapses (ISO) — what tells the reader
   * whether continuing this instance is cheap. Null when its CLI reports no
   * cache lifetime, and absent for a sub-agent.
   */
  promptCacheExpiresAt?: string | null;
  /** For a CALL thread: the clock of each of its calls (`call-clock.ts`). */
  clocks?: readonly CallClock[];
}

/**
 * The id of an agent's OWN conversation among its threads — every other
 * conversation it holds is a call thread, keyed by its call id.
 */
export const MAIN_THREAD_ID = 'main';

/**
 * Whether a sub-agent thread may still be working: running, or untracked
 * while its process lives. The one reading every surface that counts live
 * delegates uses, so an instance cannot read finished and live at once.
 */
export function subagentMayStillRun(thread: AgentThread): boolean {
  return (
    thread.status === 'running' ||
    (thread.status === 'untracked' && thread.processEnded !== true)
  );
}

/**
 * The display threads an agent's activity implies: its main conversation
 * (when the node ran a DAG turn — detected as more turn starts than call
 * threads) followed by each call thread.
 */
export function threadsOf(activity: AgentActivity | undefined): AgentThread[] {
  if (!activity) {
    return [];
  }
  const calls = activity.callThreads.map((thread): AgentThread => ({
    id: thread.callId,
    kind: 'call',
    label: thread.message
      ? `${thread.callId} · ${thread.message}`
      : thread.callId,
    brief: thread.message || null,
    status: thread.status,
    sessionId: thread.sessionId,
    callIds: thread.callIds,
    openCallIds: thread.openCallIds,
  }));
  // A node ran a conversation of ITS OWN only if some turn started outside a
  // call (`mainTurnStarts` — a status row carrying no `callId`). Counting turns
  // against calls instead drew a phantom main conversation for any callee whose
  // one call ran a second turn, a continuation included.
  if (activity.mainTurnStarts === 0) {
    return calls; // a call-only node never ran a turn of its own
  }
  // Counted per CALL for the same reason: two continuations of one thread can
  // run at once, each holding a live turn.
  const runningCalls = activity.callThreads.reduce(
    (sum, thread) => sum + thread.openCallIds.length,
    0,
  );
  const main: AgentThread = {
    id: MAIN_THREAD_ID,
    kind: 'main',
    label: 'Main conversation',
    // The node's own conversation's live turn, where its rows say; else its
    // live turns beyond its live calls — counting a call still queued under
    // the run's cap, which has no turn yet, so the rows' answer comes first.
    // Once settled, the node's last transition is the best record of how it
    // ended.
    status:
      (activity.mainTurnLive ?? activity.activeTurns > runningCalls)
        ? 'running'
        : activity.lastStatus && activity.lastStatus !== 'running'
          ? activity.lastStatus
          : 'completed',
    sessionId: null,
    contextTokens: activity.mainContextTokens,
    contextEstimated: activity.mainContextEstimated,
    contextWindowTokens: activity.mainContextWindowTokens,
  };
  return [main, ...calls];
}

/**
 * The sub-agent threads a folded transcript implies, grouped by the agent that
 * launched each one.
 *
 * Lives here rather than inline in `Chats.tsx` because this module owns the
 * {@link AgentThread} shape and its only other builder ({@link threadsOf}) —
 * and because the status translation below is a real decision that deserves to
 * be reachable without mounting a 3.5k-line component.
 *
 * `stopped` becomes `cancelled`: a delegate whose run or turn ended before it
 * reported back did stop without completing, and `cancelled` is the only word
 * in {@link RunStatusKind} that says that. It is the nearest true term, not a
 * claim that the user cancelled anything.
 */
export function subagentThreadsByAgent(
  blocks: readonly SubagentBlockEntry[],
  chatAgentKey: string,
): Map<string, AgentThread[]> {
  const byAgent = new Map<string, AgentThread[]>();
  for (const block of blocks) {
    const status = subagentBlockStatus(block);
    const key = block.memberId ?? chatAgentKey;
    const threads = byAgent.get(key) ?? [];
    threads.push({
      id: block.id,
      kind: 'subagent',
      label: subagentTitle(block),
      // `stopped` is the RUN vocabulary's `cancelled` — the same translation
      // `block-shell.tsx`'s own table makes. Spelled rather than defaulted, so
      // a new derivation state cannot arrive here wearing a spinner.
      status:
        status === 'completed'
          ? 'completed'
          : status === 'failed'
            ? 'failed'
            : status === 'stopped'
              ? 'cancelled'
              : status === 'untracked'
                ? 'untracked'
                : 'running',
      ...(status === 'untracked' && block.processEnded
        ? { processEnded: true }
        : {}),
      sessionId: null,
      callId: block.callId,
    });
    byAgent.set(key, threads);
  }
  return byAgent;
}

/**
 * The display status an agent's activity implies (any live turn = running).
 *
 * A node with NO activity is `pending`, the same word its own `node_state` row
 * carries — never a second one for the same fact. It used to answer `idle`
 * here and `pending` the moment any status item existed, so one unchanged node
 * changed word on the strength of a row nobody had looked at.
 *
 * `parked` OUTRANKS a live turn, which is the same order — and the same rank 1
 * — {@link displayRunStatus} gives a run with a card open. A parked node's turn
 * IS in flight, so `activeTurns > 0` is true and the card read `running`:
 * reported against a team whose header and sidebar row both said
 * `needs more info` while the node card beside them span a spinner. Nothing
 * moves until the user answers, and the one surface naming which AGENT is
 * waiting was the one claiming it was working.
 */
export function displayStatus(
  activity: AgentActivity | undefined,
  /** This agent has an unanswered card open — nothing advances until it is. */
  parked = false,
): RunStatusKind {
  if (parked) {
    return 'needs-input';
  }
  if (!activity) {
    return 'pending';
  }
  if (activity.activeTurns > 0) {
    return 'running';
  }
  return activity.lastStatus ?? 'pending';
}

/** The open-turn key of a node's OWN conversation — no call id is ever empty. */
const MAIN_CONVERSATION = '';

/** The call a row was written under — the executor stamps it on the payload. */
function callIdOf(item: ChatItem): string | null {
  const callId = asRecord(item.payload)?.callId;
  return typeof callId === 'string' && callId !== '' ? callId : null;
}

function emptyActivity(): AgentActivity {
  return {
    activeTurns: 0,
    turnStarts: 0,
    mainTurnStarts: 0,
    mainContextTokens: null,
    mainContextEstimated: false,
    mainContextWindowTokens: null,
    lastStatus: null,
    contextTokens: null,
    contextEstimated: false,
    contextWindowTokens: null,
    contextModel: null,
    spentUsd: null,
    spentEstimatedUsd: null,
    inputTokens: null,
    outputTokens: null,
    cacheTokens: null,
    numTurns: null,
    ttftMs: null,
    timeToRequestMs: null,
    callThreads: [],
  };
}

/** A node's status as the DAEMON's own `node_state` row states it. */
export interface DurableNodeStatus {
  status: NodeRunStatus;
}

/**
 * Whether the loaded transcript window holds a `status` row for this node —
 * the one test deciding, for the node's status AND for the start of its open
 * turn, whether the window can answer or the daemon's row must.
 */
export function windowHoldsStatus(
  activity: ReadonlyMap<string, AgentActivity>,
  memberId: string,
): boolean {
  return (activity.get(memberId)?.lastStatus ?? null) !== null;
}

/**
 * The agents' activity, completed from the DAEMON's node rows where the loaded
 * window holds none of a node's status history.
 *
 * {@link computeAgentActivity} reads a node's liveness off its `status` rows —
 * `running` when a turn opens, a terminal one when it settles — and a long run
 * loads only its newest `HISTORY_PAGE` items. A node that has been working ONE
 * turn for longer than that window has its `running` row above the page, so it
 * read as having no activity at all: its card said `pending`, the transcript
 * drew no `Working…` row, and a caller parked in `await_agent` lost its
 * `waiting on …` line. REPORTED on a resumed team whose Manager and Engineer
 * had been running since 21:03 and 21:04 — seq 908 and 926 of a 2,817-row run —
 * both drawn `pending` while the daemon's `node_state` said `running`.
 *
 * The window still WINS whenever it holds a status row for the node, and that
 * is what keeps a snapshot fetched once (`useNodeDurableReadings` reads on open
 * and reconnect) from going stale: the node's next transition arrives as a
 * status row, and from then on the transcript answers. Two further limits:
 * - a `running` row is ignored once the RUN row has settled — a daemon that
 *   died mid-turn leaves exactly that row, and believing it would put a
 *   `Working…` row under a finished run for good;
 * - a non-running row only fills in a node the window already knows, or one
 *   in `drawnNodeIds` — the nodes the panel draws a card for whatever the
 *   window holds. Any other node (a trigger, a node a since-edited team
 *   dropped) gets no entry, since an entry is what the panel draws a card from.
 *   Without the second clause a small page left every team node it held
 *   no rows for reading `pending` over a `node_state` that said `completed`.
 *
 * `windowIsTail` false is the one case where the window does NOT win: a window
 * loaded around an old message (the timeline, a search hit) holds the status
 * rows of that moment, and a node whose `running` row is in it had its ending
 * written below it. Believed, a finished team's Manager and Researcher read
 * as working again — REPORTED as an archived chat opened at its first message
 * that "пишет, как будто бы он работает". Off the tail the durable row is the
 * only current answer, and a settled run working nowhere is the other half.
 */
export function withDurableNodeStatus(
  activity: Map<string, AgentActivity>,
  durable: ReadonlyMap<string, DurableNodeStatus>,
  runSettled: boolean,
  windowIsTail = true,
  drawnNodeIds: ReadonlySet<string> = new Set(),
): Map<string, AgentActivity> {
  let out: Map<string, AgentActivity> | null = null;
  for (const [memberId, row] of durable) {
    if (windowIsTail && windowHoldsStatus(activity, memberId)) {
      continue;
    }
    const existing = activity.get(memberId);
    const running = row.status === 'running';
    if (
      running
        ? runSettled
        : existing === undefined && !drawnNodeIds.has(memberId)
    ) {
      continue;
    }
    out ??= new Map(activity);
    const { mainTurnLive: _fromRows, ...rest } = existing ?? emptyActivity();
    out.set(memberId, {
      ...rest,
      lastStatus: row.status,
      activeTurns: running ? 1 : 0,
    });
  }
  if (!windowIsTail && runSettled) {
    for (const [memberId, entry] of out ?? activity) {
      if (entry.activeTurns > 0) {
        out ??= new Map(activity);
        out.set(memberId, { ...entry, activeTurns: 0, mainTurnLive: false });
      }
    }
  }
  return out ?? activity;
}

const NODE_STATUSES: ReadonlySet<string> = new Set([
  'pending',
  'running',
  'completed',
  'failed',
  'cancelled',
  'skipped',
]);

function asRecord(value: unknown): Record<string, unknown> | null {
  return typeof value === 'object' && value !== null
    ? (value as Record<string, unknown>)
    : null;
}

/** Derive each agent's live state from a run's items (seq-ordered). */
export function computeAgentActivity(
  items: readonly ChatItem[],
  /**
   * The daemon's own record of each call's start, so a conversation whose
   * earlier calls have paged out of the window is still ONE instance with ONE
   * spend — see {@link resolveCallChains}, which states what it cost to read
   * the window alone.
   */
  callStarts?: ReadonlyMap<string, { thread: string | null }>,
): Map<string, AgentActivity> {
  const byAgent = new Map<string, AgentActivity>();
  const entry = (key: string): AgentActivity => {
    let existing = byAgent.get(key);
    if (!existing) {
      existing = emptyActivity();
      byAgent.set(key, existing);
    }
    return existing;
  };
  const chains = resolveCallChains(items, callStarts);
  /** Per agent, the conversations with a turn open right now. */
  const openTurns = new Map<string, Set<string>>();
  const openTurnsOf = (key: string): Set<string> => {
    let open = openTurns.get(key);
    if (!open) {
      open = new Set();
      openTurns.set(key, open);
    }
    return open;
  };
  for (const item of items) {
    const key = item.memberId ?? CHAT_AGENT_KEY;
    if (endsContextHistory(item)) {
      // A compaction empties the window, so every reading above this row was
      // taken on a conversation that is over — carrying one past it is what
      // left the ring full directly after a `/compact`. The WINDOW is kept: it
      // is a property of the model, which a compaction does not change, and
      // dropping it would leave the next count with nothing to divide by.
      //
      // A reading the compaction itself reported lands BELOW this row and
      // overwrites the null, which is why this is a reset rather than a stop.
      entry(key).contextTokens = null;
      entry(key).contextEstimated = false;
      if (callIdOf(item) === null) {
        entry(key).mainContextTokens = null;
        entry(key).mainContextEstimated = false;
      }
      continue;
    }
    if (item.kind === 'status') {
      const status = asRecord(item.payload)?.status;
      if (typeof status !== 'string' || !NODE_STATUSES.has(status)) {
        continue;
      }
      const agent = entry(key);
      agent.lastStatus = status as NodeRunStatus;
      const callId = callIdOf(item);
      const open = openTurnsOf(key);
      // Counted per CONVERSATION, never as a bare tally: one conversation is
      // one kept process, which runs one turn at a time, so a second `running`
      // on it SUPERSEDES the first rather than adding a turn. A tally let an
      // unanswered `running` outlive its turn for good — measured on run
      // `b98d7f8c`: the Researcher's off-turn stretch on call-3 wrote `running`
      // and nothing ever ended it, call-5 continued that conversation and
      // completed, and an empty `RESEARCHER · Whittling…` block stood at the
      // end of the transcript for a node doing nothing.
      const conversation =
        callId === null ? MAIN_CONVERSATION : conversationRoot(chains, callId);
      if (status === 'running') {
        open.add(conversation);
        agent.turnStarts += 1;
        if (callId === null) {
          agent.mainTurnStarts += 1;
        }
      } else if (status !== 'pending') {
        // A terminal transition settles its own conversation's turn. One that
        // names no call and finds the node's own conversation idle is a
        // node-wide statement (a teardown's `cancelled`, a `skipped`), and
        // settles ONE live turn, as the tally always did; one whose start is
        // not in the window settles nothing it cannot name.
        if (!open.delete(conversation) && callId === null) {
          const first = open.values().next();
          if (first.done !== true) {
            open.delete(first.value);
          }
        }
      }
      agent.activeTurns = open.size;
      agent.mainTurnLive = open.has(MAIN_CONVERSATION);
      continue;
    }
    // Call items are persisted under the CALLER's node — the thread belongs
    // to the CALLEE named in the payload.
    if (item.kind === 'call_started') {
      const payload = asRecord(item.payload);
      const callId = payload?.callId;
      const calleeMemberId = payload?.calleeNodeId;
      if (typeof callId !== 'string' || typeof calleeMemberId !== 'string') {
        continue;
      }
      const message = payload?.message;
      entry(calleeMemberId).callThreads.push({
        callId,
        callIds: [callId],
        openCallIds: [callId],
        message: typeof message === 'string' ? message : null,
        status: 'running',
        sessionId: null,
      });
      continue;
    }
    if (item.kind === 'call_result') {
      const payload = asRecord(item.payload);
      const callId = payload?.callId;
      const calleeMemberId = payload?.calleeNodeId;
      if (typeof callId !== 'string' || typeof calleeMemberId !== 'string') {
        continue;
      }
      const thread = entry(calleeMemberId).callThreads.find(
        (t) => t.callId === callId,
      );
      if (!thread) {
        continue;
      }
      // The card's own reading of the envelope, so a call its caller stopped
      // is `cancelled` here too rather than a failure the card does not show.
      thread.status = callResultStatus(payload);
      thread.openCallIds = [];
      const sessionId = payload?.sessionId;
      if (typeof sessionId === 'string') {
        thread.sessionId = sessionId;
      }
      continue;
    }
    if (item.kind === 'turn_complete') {
      const usage = asRecord(asRecord(item.payload)?.usage);
      if (!usage) {
        continue;
      }
      const agent = entry(key);
      // A reported 0 is rejected for the same reason as the window below: it
      // is not a measurement, it is a turn that reported nothing. Overwriting
      // a real figure with it made the meter read `0 of 200k` mid-conversation
      // — and the live plane already treats a non-positive count as absent
      // (`live-text.ts`), so accepting it only here was the odd one out.
      // `contextTokens` ALONE. `inputTokens` is the turn's fresh input — a
      // figure like 12 — and the daemon sends a null count precisely when the
      // CLI reported no per-request breakdown, so falling back to it overwrote
      // a real reading with `12 of 1M · 0%`.
      const context = usage.contextTokens;
      const contextEstimated = usage.contextEstimated === true;
      if (typeof context === 'number' && context > 0) {
        agent.contextTokens = context;
        agent.contextEstimated = contextEstimated;
      }
      // REMEMBERED, on exactly the rule the count above follows — and it did
      // not used to be, which is the `ctx 357.2k` with no ring beside it.
      //
      // A turn that reports no window has said NOTHING about the model's
      // window; it is not a measurement of one. Overwriting with its silence
      // wiped a window the previous turn had reported, and since the count IS
      // guarded, what was left was a bare number where the ring had been —
      // for the rest of the chat, until some later turn reported a window
      // again. Measured in the author's own `geniro.db`: five `turn_complete`
      // rows across three runs carry `{inputTokens:0, outputTokens:0,
      // contextTokens:null, contextWindowTokens:null, costUsd:0}` — a turn
      // that ended having reported no accounting at all (one of them followed
      // three seconds later by `Tool permission request failed: AbortError:
      // Stream closed`). That is also why it read as intermittent.
      //
      // The reason recorded for the old wipe was a MODEL CHANGE — a stale 1M
      // window keeping a 200k model at 3% full. It could never have served
      // that: the window and the model are read from the same `modelUsage`
      // entry (`claude-usage.utils.ts` → `readContextWindow`), so a turn that
      // switched model reports the NEW window and overwrites correctly, and a
      // null window comes with a null `contextModel` — an absence of
      // information, never the name of a smaller model. The turns the wipe
      // actually fired on were the ones that measured nothing.
      //
      // A 0 is rejected for the same reason it is on the count: consumers read
      // this as a denominator, and `ContextMeter` would render 0 as "no window
      // reported" anyway.
      const window = usage.contextWindowTokens;
      if (typeof window === 'number' && window > 0) {
        agent.contextWindowTokens = window;
      }
      // Remembered on the same rule as the window it travels with, and for the
      // same reason: the two are read from ONE `modelUsage` entry, so a turn
      // that reported neither has said nothing about which model this agent is
      // on — it has not switched to an unnamed one. Overwriting with that
      // silence would blank the name for the rest of the run.
      const model = usage.contextModel;
      if (typeof model === 'string' && model.length > 0) {
        agent.contextModel = model;
      }
      // The node's OWN conversation's reading, on the same two rules — kept
      // apart because a call's turn settling must not move the main
      // instance's ring.
      if (callIdOf(item) === null) {
        if (typeof context === 'number' && context > 0) {
          agent.mainContextTokens = context;
          agent.mainContextEstimated = contextEstimated;
        }
        if (typeof window === 'number' && window > 0) {
          agent.mainContextWindowTokens = window;
        }
      }
      // ADDED, never remembered like the two readings above: a window is the
      // state of one conversation while these are a running total, so a turn
      // that reported none contributes nothing rather than replacing the sum.
      // Each counter is independent — a CLI that reports output and no input
      // (both shipped ones do, on a cached turn) must still count what it did
      // report, and null + 4 is 4 rather than a null that swallows it.
      agent.inputTokens = addTokens(agent.inputTokens, usage.inputTokens);
      agent.outputTokens = addTokens(agent.outputTokens, usage.outputTokens);
      agent.cacheTokens = addTokens(
        addTokens(agent.cacheTokens, usage.cacheReadTokens),
        usage.cacheCreationTokens,
      );
      if (typeof usage.costUsd === 'number') {
        agent.spentUsd = (agent.spentUsd ?? 0) + usage.costUsd;
      }
      const estimated =
        typeof usage.estimatedCostUsd === 'number'
          ? usage.estimatedCostUsd
          : null;
      if (isEstimatedCost(estimated)) {
        agent.spentEstimatedUsd = (agent.spentEstimatedUsd ?? 0) + estimated;
      }
      // A COUNT of requests, on the same rule as the token counters above.
      agent.numTurns = addTokens(agent.numTurns, usage.numTurns);
      // The LATEST reading, never summed — these describe how ONE turn
      // started, and a turn that reports neither has said nothing about the
      // agent's current responsiveness.
      if (typeof usage.ttftMs === 'number' && Number.isFinite(usage.ttftMs)) {
        agent.ttftMs = usage.ttftMs;
      }
      if (
        typeof usage.timeToRequestMs === 'number' &&
        Number.isFinite(usage.timeToRequestMs)
      ) {
        agent.timeToRequestMs = usage.timeToRequestMs;
      }
    }
  }
  // Folded at the END, once every call_result has settled its own call: the
  // results are addressed by call id, and each call's outcome is still needed
  // to know how the conversation's latest call stands.
  for (const agent of byAgent.values()) {
    agent.callThreads = foldCallConversations(agent.callThreads, chains);
  }
  return byAgent;
}

/**
 * One entry per CONVERSATION (see {@link AgentCallThread}), placed where its
 * latest call was made — the position its transcript card takes too, so live
 * work sorts last in both.
 */
function foldCallConversations(
  threads: readonly AgentCallThread[],
  chains: ReadonlyMap<string, readonly string[]>,
): AgentCallThread[] {
  const out: AgentCallThread[] = [];
  const byRoot = new Map<string, AgentCallThread>();
  for (const thread of threads) {
    const root = conversationRoot(chains, thread.callId);
    const earlier = byRoot.get(root);
    const openCallIds =
      earlier === undefined
        ? thread.openCallIds
        : [...earlier.openCallIds, ...thread.openCallIds];
    /**
     * The WHOLE conversation where the chains know one — paged-out calls
     * included, which accumulating the windowed threads cannot reach.
     *
     * This list IS the instance's spend: `resolveConversationSpend` sums the
     * daemon's per-call totals over exactly these ids, so a conversation whose
     * early calls have scrolled past the window reported a fraction of what it
     * cost — the same defect the transcript card had, and the two must answer
     * alike or a card and the instance describing it disagree about one
     * conversation. `openCallIds` stays the WINDOWED set: what is still
     * running is read from rows, and a call with none says nothing.
     */
    const conversation = chains.get(thread.callId);
    const merged: AgentCallThread =
      earlier === undefined
        ? conversation === undefined
          ? thread
          : { ...thread, callIds: [...conversation] }
        : {
            ...thread,
            callIds: conversation
              ? [...conversation]
              : [...earlier.callIds, thread.callId],
            openCallIds,
            // Open while ANY call is (see `AgentCallThread.openCallIds`).
            status: openCallIds.length > 0 ? 'running' : thread.status,
          };
    if (earlier !== undefined) {
      out.splice(out.indexOf(earlier), 1);
    }
    out.push(merged);
    byRoot.set(root, merged);
  }
  return out;
}

/**
 * Compact token count: 950 → "950", 12_400 → "12.4k", 1_200_000 → "1.2M",
 * 16_603_400_000 → "16.6B".
 *
 * The BILLION step is not hypothetical padding. A month of cache reads reaches
 * it easily — measured on a real 26-day ledger, `cacheReadTokens` was 16.6e9,
 * which without this step rendered as `16603.4M`: five significant digits under
 * a suffix that no longer compacts anything, printed as the largest figure on
 * the Stats page. Anything past a trillion keeps growing the `B` figure rather
 * than gaining another suffix — a `T` of tokens is not a scale this app has a
 * reason to be ready for, and an unfamiliar suffix costs more than a long number.
 */
/**
 * Add one turn's counter to a running total, where null means UNMEASURED.
 *
 * `null + n` is `n` rather than null: a turn that reported nothing must not
 * erase what earlier turns did report, and a total that stays null until every
 * turn has answered would be blank on any CLI that reports a field
 * intermittently — which both shipped ones do.
 */
function addTokens(total: number | null, next: unknown): number | null {
  if (typeof next !== 'number' || !Number.isFinite(next) || next < 0) {
    return total;
  }
  return (total ?? 0) + next;
}

export function formatTokens(count: number): string {
  if (count >= 1_000_000_000) {
    return `${(count / 1_000_000_000).toFixed(1).replace(/\.0$/, '')}B`;
  }
  if (count >= 1_000_000) {
    return `${(count / 1_000_000).toFixed(1).replace(/\.0$/, '')}M`;
  }
  if (count >= 1_000) {
    return `${(count / 1_000).toFixed(1).replace(/\.0$/, '')}k`;
  }
  return String(count);
}

/**
 * Money — the app's sanctioned formats are `formatUsd` and `formatExactUsd`
 * here, plus `formatUsdAxis` (`stats/stats-format.ts`) for chart ticks only,
 * and every dollar on screen comes from one of them. The first two agree
 * everywhere above a cent (`$0.24`, `$21,547.80`) and differ only below it,
 * where a bare 2-decimal rounding would print `$0.00` and claim a turn cost
 * nothing. Neither is willing to say that; they refuse it differently, and
 * which refusal is right depends on the surface.
 *
 * Both are GROUPED, because these render a lifetime total as well as a single
 * turn's cost. Ungrouped, that total was `$21547.80` — seven digits the reader
 * has to count in threes to know whether it is twenty-one thousand or two
 * hundred and fifteen.
 *
 * Both are pinned to `en-US` rather than the machine's locale, unlike the day
 * labels beside them, and that is deliberate: the `$` is hardcoded because the
 * daemon records USD and nothing else, so a machine-locale number would pair a
 * dollar sign with `21.547,80` — a figure that reads as twenty-one dollars to
 * half of Europe. One currency, one notation.
 */
const USD_DIGITS = new Intl.NumberFormat('en-US', {
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
});

const USD_SUBCENT = new Intl.NumberFormat('en-US', {
  minimumFractionDigits: 4,
  maximumFractionDigits: 4,
});

/**
 * A BOUND: sub-cent spend reads `<$0.01`.
 *
 * For aggregates in a column — the Stats breakdowns, the context meter's
 * run total — where every figure is the same width and the reader is comparing
 * rows, not pricing one of them. `$0.0034` in a `tabular-nums` column of
 * two-decimal figures is four characters nothing else has.
 */
export function formatUsd(amount: number): string {
  if (amount > 0 && amount < 0.01) {
    return '<$0.01';
  }
  return `$${USD_DIGITS.format(amount)}`;
}

/**
 * A VALUE: sub-cent spend reads `$0.0034`.
 *
 * For a figure that stands alone and IS the point — the thread header's cost,
 * the `✓ done · 21s · $0.42` note under a finished turn. Cheap turns are most
 * of them, and `<$0.01` on every one of them tells the reader nothing they
 * could compare.
 *
 * Note what it is NOT: four decimals ALWAYS. The transcript note used a bare
 * `toFixed(4)`, so a 42-cent turn read `$0.4200` two hundred pixels under a
 * header saying `$0.42` — the same number, in two notations, on one screen.
 */
export function formatExactUsd(amount: number): string {
  if (amount > 0 && amount < 0.01) {
    return `$${USD_SUBCENT.format(amount)}`;
  }
  return `$${USD_DIGITS.format(amount)}`;
}

/**
 * Whether a cost carries a part geniro PRICED itself — token counts at the
 * public list price — rather than read off the agent's own bill. The daemon
 * states that part beside every cost (`estimatedCostUsd`); null or 0 is none.
 */
export function isEstimatedCost(
  estimatedUsd: number | null | undefined,
): estimatedUsd is number {
  return (
    typeof estimatedUsd === 'number' &&
    Number.isFinite(estimatedUsd) &&
    estimatedUsd > 0
  );
}

/**
 * A formatted amount with its provenance: `≈` ahead of it when any of it is
 * geniro's estimate. A MARK over {@link formatUsd} / {@link formatExactUsd},
 * never a third money format — the same `≈` a delegate's priced cost carries.
 */
export function markEstimate(
  formatted: string,
  estimatedUsd: number | null | undefined,
): string {
  return isEstimatedCost(estimatedUsd) ? `≈${formatted}` : formatted;
}

/**
 * The sentence that says which part of a cost is geniro's estimate, or null
 * when all of it is the agent's own bill. Hover text and readout lines take it
 * so the word reaches a reader the glyph alone may not.
 */
export function costEstimateNote(
  costUsd: number | null,
  estimatedUsd: number | null | undefined,
): string | null {
  if (!isEstimatedCost(estimatedUsd)) {
    return null;
  }
  // "All of it" only within rounding: half a cent, and never more than 0.5% of
  // the cost — so neither a sub-cent turn nor a large period calls a part the
  // agent billed itself geniro's.
  if (
    costUsd === null ||
    costUsd - estimatedUsd <
      Math.min(ESTIMATE_WHOLE_SLACK_USD, costUsd * ESTIMATE_WHOLE_FRACTION)
  ) {
    return "geniro's estimate — priced from token counts at list price, not the agent's own bill";
  }
  return `includes ≈${formatExactUsd(estimatedUsd)} geniro estimated from token counts at list price`;
}

/** {@link costEstimateNote} as a `title` attribute — absent when none. */
export function costEstimateTitle(
  costUsd: number | null,
  estimatedUsd: number | null | undefined,
): string | undefined {
  return costEstimateNote(costUsd, estimatedUsd) ?? undefined;
}

const ESTIMATE_WHOLE_SLACK_USD = 0.005;
const ESTIMATE_WHOLE_FRACTION = 0.005;

/** A context count with its provenance: `≈` ahead of geniro's stand-in. */
export function markContextEstimate(text: string, estimated: boolean): string {
  return estimated ? `≈${text}` : text;
}

/** What a context count geniro stood in for says about itself. */
export const CONTEXT_ESTIMATE_NOTE =
  "geniro's estimate — the agent stated no context reading, so this is its last input count";
