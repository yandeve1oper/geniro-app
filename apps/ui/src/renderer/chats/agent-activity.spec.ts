let seq = 0;
function item(
  kind: ChatItem['kind'],
  memberId: string | null,
  payload: unknown,
): ChatItem {
  seq += 1;
  return {
    id: `i${seq}`,
    runId: 'r1',
    memberId,
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function status(memberId: string, value: string, callId?: string): ChatItem {
  return item('status', memberId, {
    nodeId: memberId,
    status: value,
    ...(callId === undefined ? {} : { callId }),
  });
}

describe('computeAgentActivity', () => {
  it('counts PARALLEL live turns per agent (two starts, one settle → 1 live)', () => {
    // An orchestrator can call_agent the same worker twice concurrently —
    // each callee sub-turn emits its own running/terminal status pair, under
    // its own call.
    const activity = computeAgentActivity([
      status('worker', 'running', 'call-1'),
      status('worker', 'running', 'call-2'),
      status('worker', 'completed', 'call-1'),
    ]);
    expect(activity.get('worker')?.activeTurns).toBe(1);
    expect(activity.get('worker')?.lastStatus).toBe('completed');

    const settled = computeAgentActivity([
      status('worker', 'running', 'call-1'),
      status('worker', 'running', 'call-2'),
      status('worker', 'completed', 'call-1'),
      status('worker', 'failed', 'call-2'),
    ]);
    expect(settled.get('worker')?.activeTurns).toBe(0);
    expect(settled.get('worker')?.lastStatus).toBe('failed');
  });

  it('lets a later turn on the SAME conversation supersede an unanswered one', () => {
    // Run `b98d7f8c`: the Researcher's off-turn stretch on call-3 wrote
    // `running` and nothing answered it; call-5 continued that conversation
    // and completed. One conversation runs one turn at a time, so the node is
    // idle — counted as a tally it read as working for good, and an empty
    // `RESEARCHER · Whittling…` block stood at the end of the transcript.
    const items = [
      item('call_started', 'manager', {
        callId: 'call-1',
        calleeNodeId: 'researcher',
      }),
      status('researcher', 'running', 'call-1'),
      status('researcher', 'completed', 'call-1'),
      item('call_started', 'manager', {
        callId: 'call-3',
        calleeNodeId: 'researcher',
        thread: 'call-1',
      }),
      status('researcher', 'running', 'call-3'),
      status('researcher', 'completed', 'call-3'),
      // The off-turn stretch nothing ended.
      status('researcher', 'running', 'call-3'),
      item('call_started', 'manager', {
        callId: 'call-5',
        calleeNodeId: 'researcher',
        thread: 'call-3',
      }),
      status('researcher', 'running', 'call-5'),
      status('researcher', 'completed', 'call-5'),
    ];
    expect(computeAgentActivity(items).get('researcher')?.activeTurns).toBe(0);
  });

  it('still counts a different conversation of the same node as live', () => {
    // The control for the case above: superseding is per conversation, so a
    // second call's settle must not take down a first call still running.
    const items = [
      item('call_started', 'manager', {
        callId: 'call-1',
        calleeNodeId: 'researcher',
      }),
      status('researcher', 'running', 'call-1'),
      item('call_started', 'manager', {
        callId: 'call-2',
        calleeNodeId: 'researcher',
      }),
      status('researcher', 'running', 'call-2'),
      status('researcher', 'completed', 'call-2'),
    ];
    expect(computeAgentActivity(items).get('researcher')?.activeTurns).toBe(1);
  });

  it('lets a node-wide settle with no call id take down a live call turn', () => {
    // A teardown's `cancelled` names no call; it still ends the one live turn
    // it is about, as the tally always did.
    const activity = computeAgentActivity([
      status('worker', 'running', 'call-1'),
      status('worker', 'cancelled'),
    ]);
    expect(activity.get('worker')?.activeTurns).toBe(0);
  });

  it('never goes negative on a settle without a matching start (skipped nodes)', () => {
    const activity = computeAgentActivity([status('worker', 'skipped')]);
    expect(activity.get('worker')?.activeTurns).toBe(0);
    expect(activity.get('worker')?.lastStatus).toBe('skipped');
  });

  it('sums the part of the spend geniro priced, and marks a stand-in context count', () => {
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: {
          contextTokens: 5_000,
          contextEstimated: true,
          costUsd: 0.1,
          estimatedCostUsd: 0.1,
        },
        stopReason: null,
      }),
      item('turn_complete', 'worker', {
        usage: { contextTokens: 12_000, costUsd: 0.25 },
        stopReason: null,
      }),
    ]);
    const worker = activity.get('worker');
    expect(worker?.spentUsd).toBeCloseTo(0.35);
    expect(worker?.spentEstimatedUsd).toBeCloseTo(0.1);
    // The newer, stated count replaced the stand-in, and the mark with it.
    expect(worker?.contextEstimated).toBe(false);
    expect(
      computeAgentActivity([
        item('turn_complete', 'worker', {
          usage: { contextTokens: 5_000, contextEstimated: true },
          stopReason: null,
        }),
      ]).get('worker')?.contextEstimated,
    ).toBe(true);
  });

  it('tracks context (latest turn) and spend (cumulative) from turn_complete usage', () => {
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { inputTokens: 10, contextTokens: 5_000, costUsd: 0.1 },
        stopReason: null,
      }),
      item('turn_complete', 'worker', {
        usage: { inputTokens: 20, contextTokens: 12_000, costUsd: 0.25 },
        stopReason: null,
      }),
    ]);
    const worker = activity.get('worker');
    expect(worker?.contextTokens).toBe(12_000);
    expect(worker?.spentUsd).toBeCloseTo(0.35);
  });

  it('sums numTurns (a COUNT) and keeps the LATEST ttftMs/timeToRequestMs (a turn-start reading)', () => {
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { numTurns: 2, ttftMs: 400, timeToRequestMs: 60 },
        stopReason: null,
      }),
      item('turn_complete', 'worker', {
        usage: { numTurns: 3, ttftMs: 150, timeToRequestMs: 20 },
        stopReason: null,
      }),
    ]);
    const worker = activity.get('worker');
    // A request count across the agent's whole history — a total, like the
    // token counters beside it.
    expect(worker?.numTurns).toBe(5);
    // How the agent's MOST RECENT turn started — never summed, which a
    // reverted fold would do (500 / 80) instead of the latest turn's own
    // (150 / 20).
    expect(worker?.ttftMs).toBe(150);
    expect(worker?.timeToRequestMs).toBe(20);
  });

  it('leaves numTurns/ttftMs/timeToRequestMs unmeasured when nothing ever reported them', () => {
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { inputTokens: 10 },
        stopReason: null,
      }),
    ]);
    const worker = activity.get('worker');
    expect(worker?.numTurns).toBeNull();
    expect(worker?.ttftMs).toBeNull();
    expect(worker?.timeToRequestMs).toBeNull();
  });

  it('keeps the last real ttftMs/timeToRequestMs when a later turn reports none', () => {
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { ttftMs: 275, timeToRequestMs: 33 },
        stopReason: null,
      }),
      // A turn that says nothing about its own start is not a measurement of
      // an instant start — the same rule the context figure follows above.
      item('turn_complete', 'worker', {
        usage: { inputTokens: 5 },
        stopReason: null,
      }),
    ]);
    const worker = activity.get('worker');
    expect(worker?.ttftMs).toBe(275);
    expect(worker?.timeToRequestMs).toBe(33);
  });

  it('keeps the last real context figure when a turn reports zero', () => {
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { contextTokens: 37_600, contextWindowTokens: 200_000 },
        stopReason: 'end_turn',
      }),
      // A turn that reports nothing is not a measurement of an empty window.
      // Taking its zero made the header read "Context 0% full — 0 of 200k"
      // in the middle of a live conversation.
      item('turn_complete', 'worker', {
        usage: { inputTokens: 0, outputTokens: 0, costUsd: 0 },
        stopReason: null,
      }),
    ]);
    expect(activity.get('worker')?.contextTokens).toBe(37_600);
  });

  it('FORGETS the context once a compaction has emptied the window', () => {
    // Reported as "после компакта кружочек не обновляется. Он все еще так же
    // заполнен с контекстом": on a CLI whose compaction geniro performs, the
    // conversation the figure was measured on is DISCARDED and nothing
    // measures the new one until the next turn — so a fold that carried the
    // old reading left the ring full over an agent starting from a summary.
    const replaced = computeAgentActivity([
      item('turn_complete', null, {
        usage: { contextTokens: 101_500, contextWindowTokens: 1_000_000 },
        stopReason: 'end_turn',
      }),
      item('system', null, {
        message: 'Conversation compacted.',
        severity: 'info',
        conversationReplaced: true,
      }),
    ]);
    expect(replaced.get(CHAT_AGENT_KEY)?.contextTokens).toBeNull();
    // The WINDOW survives: it belongs to the model, which a compaction does
    // not change, and the next count would have nothing to divide by.
    expect(replaced.get(CHAT_AGENT_KEY)?.contextWindowTokens).toBe(1_000_000);
  });

  it('takes the figure a compaction reported about ITSELF', () => {
    // The CLI's own compaction usually says what it left behind, and that
    // reading lands BELOW the marker — which is why the rule above is a reset
    // rather than a refusal to read anything after one.
    const activity = computeAgentActivity([
      item('turn_complete', null, {
        usage: { contextTokens: 162_400, contextWindowTokens: 1_000_000 },
        stopReason: 'end_turn',
      }),
      item('system', null, {
        message: 'This session is being continued…',
        cli: true,
        compaction: { preTokens: 162_400, postTokens: 8_400 },
      }),
      item('turn_complete', null, {
        usage: { contextTokens: 8_400, contextWindowTokens: 1_000_000 },
        stopReason: 'end_turn',
      }),
    ]);
    expect(activity.get(CHAT_AGENT_KEY)?.contextTokens).toBe(8_400);
  });

  it('never reads a turn’s fresh inputTokens as the context figure', () => {
    // REVERSES the old "falls back to inputTokens" pin. The daemon sends a null
    // count precisely when a CLI reported no per-request breakdown, and
    // `inputTokens` is one request's fresh input — so the fallback replaced a
    // real reading with `42 of 1M · 0%`.
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { contextTokens: 120_000, costUsd: null },
        stopReason: null,
      }),
      item('turn_complete', 'worker', {
        usage: { inputTokens: 42, costUsd: null },
        stopReason: null,
      }),
    ]);
    expect(activity.get('worker')?.contextTokens).toBe(120_000);
    expect(activity.get('worker')?.spentUsd).toBeNull();
  });

  it("tracks the latest turn's reported context window", () => {
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { contextTokens: 5_000, contextWindowTokens: 200_000 },
        stopReason: null,
      }),
      item('turn_complete', 'worker', {
        usage: { contextTokens: 28_283, contextWindowTokens: 1_000_000 },
        stopReason: null,
      }),
    ]);
    expect(activity.get('worker')?.contextWindowTokens).toBe(1_000_000);
  });

  it('keeps the remembered window when a later turn reports none', () => {
    // REVERSES an earlier pin ("drops a remembered window when the latest turn
    // reports none"), whose stated reason was a model change — a stale 1M
    // window keeping a 200k model at 3% full. The wipe could never have served
    // that: window and model are read from one `modelUsage` entry, so a turn on
    // a new model reports the new window and overwrites. What it did fire on
    // was a turn that reported NO accounting, of which the author's own
    // `geniro.db` holds five, and the ring then vanished for the rest of the
    // chat leaving a bare `ctx 357.2k`.
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { contextTokens: 5_000, contextWindowTokens: 1_000_000 },
        stopReason: null,
      }),
      item('turn_complete', 'worker', {
        usage: { contextTokens: 6_000 },
        stopReason: null,
      }),
    ]);
    expect(activity.get('worker')?.contextWindowTokens).toBe(1_000_000);
  });

  it('keeps the window across a turn that measured nothing at all', () => {
    // The shape as the CLI really wrote it, transcribed from a `turn_complete`
    // row in the author's own database. Both halves are asserted together
    // because it is the PAIR that is the defect: the count survives such a turn
    // (it is guarded), so a wiped window left a number with no ring — which is
    // the reading the ticket screenshotted.
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { contextTokens: 357_200, contextWindowTokens: 1_000_000 },
        stopReason: 'end_turn',
      }),
      item('turn_complete', 'worker', {
        usage: {
          inputTokens: 0,
          outputTokens: 0,
          contextTokens: null,
          contextWindowTokens: null,
          contextModel: null,
          costUsd: 0,
        },
        stopReason: null,
      }),
    ]);
    expect(activity.get('worker')?.contextTokens).toBe(357_200);
    expect(activity.get('worker')?.contextWindowTokens).toBe(1_000_000);
  });

  it('remembers the MODEL a turn ran on, and never blanks it on a silent turn', () => {
    // The name the agents panel prints under each agent. It follows the window
    // it travels with, and for the same reason: the two are read from one
    // `modelUsage` entry, so a turn reporting neither has said nothing about
    // which model this agent is on rather than switching to an unnamed one.
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: {
          contextTokens: 357_200,
          contextWindowTokens: 1_000_000,
          contextModel: 'claude-opus-5',
        },
        stopReason: 'end_turn',
      }),
      item('turn_complete', 'worker', {
        usage: {
          contextTokens: null,
          contextWindowTokens: null,
          contextModel: null,
          costUsd: 0,
        },
        stopReason: null,
      }),
    ]);
    expect(activity.get('worker')?.contextModel).toBe('claude-opus-5');
  });

  it('takes the model of the LATEST turn that named one', () => {
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { contextModel: 'claude-opus-5' },
        stopReason: 'end_turn',
      }),
      item('turn_complete', 'worker', {
        usage: { contextModel: 'claude-sonnet-5' },
        stopReason: 'end_turn',
      }),
    ]);
    expect(activity.get('worker')?.contextModel).toBe('claude-sonnet-5');
  });

  it('SUMS what each turn spent, and a silent turn adds nothing', () => {
    // The card's own `117.6k tokens · $44.17` line. A total, unlike the window
    // and the model beside it, which are the state of one conversation.
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: {
          inputTokens: 300,
          outputTokens: 1_200,
          cacheReadTokens: 40_000,
          cacheCreationTokens: 500,
          costUsd: 0.4,
        },
        stopReason: 'end_turn',
      }),
      item('turn_complete', 'worker', {
        usage: {
          inputTokens: 10,
          outputTokens: 90,
          cacheReadTokens: 1_000,
          cacheCreationTokens: 0,
          costUsd: 0.1,
        },
        stopReason: 'end_turn',
      }),
      // A turn that measured nothing contributes nothing — and must not erase
      // the two above.
      item('turn_complete', 'worker', { usage: {}, stopReason: null }),
    ]);
    const worker = activity.get('worker');
    expect(worker?.inputTokens).toBe(310);
    expect(worker?.outputTokens).toBe(1_290);
    expect(worker?.cacheTokens).toBe(41_500);
    expect(worker?.spentUsd).toBeCloseTo(0.5);
  });

  it('counts a field a turn DID report even when its siblings are null', () => {
    // Both shipped CLIs report intermittently, so a null must not swallow the
    // number beside it — the whole reason each counter adds independently.
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { inputTokens: null, outputTokens: 40, costUsd: null },
        stopReason: 'end_turn',
      }),
    ]);
    expect(activity.get('worker')?.inputTokens).toBeNull();
    expect(activity.get('worker')?.outputTokens).toBe(40);
    expect(activity.get('worker')?.spentUsd).toBeNull();
  });

  it('still refuses a reported window of zero as a denominator', () => {
    const activity = computeAgentActivity([
      item('turn_complete', 'worker', {
        usage: { contextTokens: 5_000, contextWindowTokens: 0 },
        stopReason: null,
      }),
    ]);
    expect(activity.get('worker')?.contextWindowTokens).toBeNull();
  });

  it("keys a single-agent chat's null-node items under CHAT_AGENT_KEY", () => {
    const activity = computeAgentActivity([
      item('turn_complete', null, {
        usage: { contextTokens: 900, costUsd: 0.02 },
        stopReason: null,
      }),
    ]);
    expect(activity.get(CHAT_AGENT_KEY)?.contextTokens).toBe(900);
  });

  it('ignores malformed status payloads and null usage', () => {
    const activity = computeAgentActivity([
      item('status', 'worker', { nodeId: 'worker', status: 42 }),
      item('status', 'worker', 'not-an-object'),
      item('turn_complete', 'worker', { usage: null, stopReason: null }),
    ]);
    expect(activity.get('worker')).toBeUndefined();
  });
});

describe('call threads', () => {
  // Call items are persisted under the CALLER's node; the thread belongs to
  // the callee named in the payload.
  const callStarted = (callId: string, message: string): ChatItem =>
    item('call_started', 'orch', {
      callId,
      callerNodeId: 'orch',
      calleeNodeId: 'worker',
      mode: 'async',
      message,
    });
  const callResult = (
    callId: string,
    status: 'ok' | 'error',
    sessionId: string | null,
  ): ChatItem =>
    item('call_result', 'orch', {
      callId,
      callerNodeId: 'orch',
      calleeNodeId: 'worker',
      mode: 'async',
      status,
      sessionId,
    });

  it('attributes call threads to the CALLEE with settle status and session id', () => {
    const activity = computeAgentActivity([
      callStarted('call-1', 'haiku about rivers'),
      callStarted('call-2', 'haiku about mountains'),
      callResult('call-1', 'ok', 'sess-1'),
    ]);
    const worker = activity.get('worker')!;
    expect(worker.callThreads).toEqual([
      {
        callId: 'call-1',
        callIds: ['call-1'],
        openCallIds: [],
        message: 'haiku about rivers',
        status: 'completed',
        sessionId: 'sess-1',
      },
      {
        callId: 'call-2',
        callIds: ['call-2'],
        openCallIds: ['call-2'],
        message: 'haiku about mountains',
        status: 'running',
        sessionId: null,
      },
    ]);
    // The caller gained no thread from its own call items.
    expect(activity.get('orch')?.callThreads ?? []).toEqual([]);
  });

  it('reads a call its caller STOPPED as cancelled, the word its card uses', () => {
    // Every non-ok envelope read as a failure here, so one stopped call was
    // `cancelled` on its transcript card and `failed` in the panel beside it.
    const settledWith = (callId: string, error: string): ChatItem =>
      item('call_result', 'orch', {
        callId,
        callerNodeId: 'orch',
        calleeNodeId: 'worker',
        status: 'error',
        error,
        sessionId: null,
      });
    const activity = computeAgentActivity([
      callStarted('call-1', 'first'),
      callStarted('call-2', 'second'),
      settledWith('call-1', 'CALLEE_CANCELLED: the callee turn was cancelled'),
      settledWith('call-2', 'CALLEE_FAILED[crashed]: the CLI exited'),
    ]);
    expect(
      threadsOf(activity.get('worker')).map((thread) => [
        thread.id,
        thread.status,
      ]),
    ).toEqual([
      ['call-1', 'cancelled'],
      ['call-2', 'failed'],
    ]);
  });

  it('a conversation CONTINUED through `thread` is ONE thread, with the latest call’s brief, status and session', () => {
    // REPORTED: an Engineer briefed once and continued twice was drawn as
    // three Engineers at work.
    const continued = (
      callId: string,
      thread: string,
      message: string,
    ): ChatItem =>
      item('call_started', 'orch', {
        callId,
        callerNodeId: 'orch',
        calleeNodeId: 'worker',
        mode: 'sync',
        message,
        thread,
      });
    const activity = computeAgentActivity([
      callStarted('call-22', 'build it'),
      callStatus('running', 'call-22'),
      callStatus('completed', 'call-22'),
      callResult('call-22', 'ok', 'sess-22'),
      continued('call-23', 'call-22', 'add tests'),
      callStatus('running', 'call-23'),
      callStatus('completed', 'call-23'),
      callResult('call-23', 'ok', 'sess-23'),
      callStarted('call-30', 'something unrelated'),
      continued('call-24', 'call-23', 'polish docs'),
      callStatus('running', 'call-24'),
    ]);
    const worker = activity.get('worker')!;
    expect(worker.callThreads).toEqual([
      {
        callId: 'call-30',
        callIds: ['call-30'],
        openCallIds: ['call-30'],
        message: 'something unrelated',
        status: 'running',
        sessionId: null,
      },
      // Drawn where its newest call was made, after the unrelated one.
      {
        callId: 'call-24',
        callIds: ['call-22', 'call-23', 'call-24'],
        openCallIds: ['call-24'],
        message: 'polish docs',
        status: 'running',
        sessionId: null,
      },
    ]);
    // Every turn here started under a call, so the node ran none of its own —
    // three continuations are ONE thread, not a main conversation beside them.
    const threads = threadsOf(worker);
    expect(threads.map((t) => t.id)).toEqual(['call-30', 'call-24']);
    expect(threads[1]!.callIds).toEqual(['call-22', 'call-23', 'call-24']);
  });

  it('a conversation two calls continue AT ONCE stays running until both settle', () => {
    // The daemon checks only that a thread names a settled call, so B and C
    // can both continue A; C settling first says nothing about B.
    const continued = (callId: string): ChatItem =>
      item('call_started', 'orch', {
        callId,
        callerNodeId: 'orch',
        calleeNodeId: 'worker',
        mode: 'async',
        message: callId,
        thread: 'call-A',
      });
    const activity = computeAgentActivity([
      callStarted('call-A', 'first'),
      callResult('call-A', 'ok', 'sess-A'),
      continued('call-B'),
      continued('call-C'),
      callResult('call-C', 'ok', 'sess-C'),
    ]);
    const threads = activity.get('worker')!.callThreads;
    expect(threads).toHaveLength(1);
    expect(threads[0]).toMatchObject({
      callId: 'call-C',
      callIds: ['call-A', 'call-B', 'call-C'],
      openCallIds: ['call-B'],
      status: 'running',
    });
  });
  /** A callee sub-turn's status row — the executor stamps the call on it. */
  const callStatus = (value: string, callId: string): ChatItem =>
    item('status', 'worker', { nodeId: 'worker', status: value, callId });
  /** A settled turn's usage, under a call or (null) the node's own. */
  const turnComplete = (
    contextTokens: number,
    callId: string | null,
  ): ChatItem =>
    item('turn_complete', 'worker', {
      usage: { contextTokens, contextWindowTokens: 1_000_000 },
      ...(callId === null ? {} : { callId }),
    });

  it('threadsOf: a node working its own turn stays running while a call to it waits under the cap', () => {
    // A call queued under the run's active-turn cap is open and has no turn
    // yet; counted as one, it cancelled the node's own live turn out.
    const activity = computeAgentActivity([
      status('worker', 'running'),
      callStarted('call-1', 'go'),
    ]);
    const threads = threadsOf(activity.get('worker'));
    expect(threads.map((thread) => [thread.kind, thread.status])).toEqual([
      ['main', 'running'],
      ['call', 'running'],
    ]);
  });

  it('threadsOf: a call-only node lists ONLY its call threads (no main)', () => {
    const activity = computeAgentActivity([
      callStarted('call-1', 'go'),
      callStatus('running', 'call-1'),
      callStatus('completed', 'call-1'),
      callResult('call-1', 'ok', 'sess-1'),
    ]);
    const threads = threadsOf(activity.get('worker'));
    expect(threads).toHaveLength(1);
    expect(threads[0]).toMatchObject({ id: 'call-1', kind: 'call' });
  });

  it('threadsOf: a callee whose ONE call ran several turns still has no main conversation', () => {
    // REPORTED as "we should show context for EACH subagent instance, now it's
    // only one for all". Main was inferred as "more turn starts than call
    // threads", so a call that ran a second turn (a follow-up on its thread, a
    // continuation) drew a phantom `Main conversation` — which has no reading,
    // leaving the card's single ring for every instance.
    const activity = computeAgentActivity([
      callStarted('call-1', 'go'),
      callStatus('running', 'call-1'),
      callStatus('completed', 'call-1'),
      callStatus('running', 'call-1'),
      callStatus('completed', 'call-1'),
    ]);
    const threads = threadsOf(activity.get('worker'));
    expect(threads.map((t) => t.id)).toEqual(['call-1']);
  });

  it('threadsOf: the main conversation carries its OWN reading, never a call’s', () => {
    const activity = computeAgentActivity([
      status('worker', 'running'),
      turnComplete(100_000, null),
      status('worker', 'completed'),
      callStarted('call-1', 'go'),
      callStatus('running', 'call-1'),
      turnComplete(900_000, 'call-1'),
      callStatus('completed', 'call-1'),
    ]);
    const worker = activity.get('worker')!;
    const [main] = threadsOf(worker);
    expect(main).toMatchObject({
      kind: 'main',
      contextTokens: 100_000,
      contextWindowTokens: 1_000_000,
    });
    // The card's own reading is still whichever conversation settled last.
    expect(worker.contextTokens).toBe(900_000);
  });

  it('threadsOf: a DAG node with calls lists its main conversation FIRST', () => {
    const activity = computeAgentActivity([
      status('worker', 'running'), // the DAG turn
      callStarted('call-1', 'go'),
      callStatus('running', 'call-1'), // the callee sub-turn
      callResult('call-1', 'error', null),
      callStatus('failed', 'call-1'), // the call thread settles
    ]);
    const threads = threadsOf(activity.get('worker'));
    expect(threads.map((t) => t.id)).toEqual(['main', 'call-1']);
    // The DAG turn is still live — one active turn beyond the settled call.
    expect(threads[0]!.status).toBe('running');
    expect(threads[1]).toMatchObject({ status: 'failed', sessionId: null });
  });
});

describe('formatTokens / formatUsd', () => {
  it('formats token counts compactly', () => {
    expect(formatTokens(950)).toBe('950');
    expect(formatTokens(12_400)).toBe('12.4k');
    expect(formatTokens(45_000)).toBe('45k');
    expect(formatTokens(1_200_000)).toBe('1.2M');
  });

  it('compacts a BILLION rather than growing the M figure', () => {
    // Measured on a real 26-day ledger: 16.6e9 cache-read tokens rendered as
    // `16603.4M` — five significant digits under a suffix that had stopped
    // compacting — and it was the largest figure on the Stats page.
    expect(formatTokens(16_603_400_000)).toBe('16.6B');
    expect(formatTokens(2_000_000_000)).toBe('2B');
    // The step is at the billion exactly: one token below it is still an M.
    expect(formatTokens(999_900_000)).toBe('999.9M');
  });

  it('formats spend with a sub-cent floor', () => {
    expect(formatUsd(0.236)).toBe('$0.24');
    expect(formatUsd(0.004)).toBe('<$0.01');
    expect(formatUsd(0)).toBe('$0.00');
  });

  it('groups a total in thousands', () => {
    // This same function renders one agent's run total AND a lifetime total,
    // and the total is where it failed: `$21547.80` is seven digits the reader
    // has to count in threes to place the magnitude of.
    expect(formatUsd(21_547.8)).toBe('$21,547.80');
    expect(formatUsd(1_000)).toBe('$1,000.00');
    expect(formatUsd(16.37)).toBe('$16.37');
  });

  it('formatExactUsd agrees with formatUsd at and above one cent', () => {
    // The two formats exist to differ BELOW a cent and nowhere else. Every
    // figure a reader could see twice on one screen — the thread header and
    // the turn note under it — is in this range, so a divergence here is the
    // app contradicting itself.
    for (const amount of [0, 0.01, 0.42, 16.37, 1_000, 21_547.8]) {
      expect(formatExactUsd(amount)).toBe(formatUsd(amount));
    }
  });

  it('formatExactUsd states a sub-cent spend instead of bounding it', () => {
    // The reason it exists: `<$0.01` on a standalone figure that IS the point
    // tells the reader nothing they can compare between two cheap turns.
    expect(formatExactUsd(0.004)).toBe('$0.0040');
    expect(formatExactUsd(0.0003)).toBe('$0.0003');
    // …and it is NOT four decimals always, which is the bug it replaced: the
    // transcript's own `toFixed(4)` rendered a 42-cent turn as `$0.4200`
    // directly under a header reading `$0.42`. Reverting to that fails here.
    expect(formatExactUsd(0.42)).toBe('$0.42');
    expect(formatExactUsd(0.42)).not.toContain('0.4200');
  });
});

describe('subagentThreadsByAgent', () => {
  function block(over: Partial<SubagentBlockEntry> = {}): SubagentBlockEntry {
    return {
      type: 'subagent-block',
      id: 'task-1',
      createdAt: 'now',
      memberId: null,
      callId: null,
      kind: 'code-reviewer',
      label: 'Review the diff',
      prompt: null,
      returned: false,
      resultIsOwn: false,
      failed: false,
      result: null,
      model: null,
      durationMs: null,
      tokens: null,
      toolUses: null,
      costUsd: null,
      estimatedCostUsd: null,
      requests: null,
      contextTokens: null,
      inputTokens: null,
      outputTokens: null,
      cacheReadTokens: null,
      cacheCreationTokens: null,
      cumulative: false,
      messages: null,
      lastRowAt: null,
      stepsUnavailableReason: null,
      backgroundOpen: null,
      backgroundOutcome: null,
      recoverable: false,
      processEnded: false,
      entries: [],
      ...over,
    };
  }

  it('files each delegate under the agent that launched it', () => {
    const byAgent = subagentThreadsByAgent(
      [
        block({ id: 'a', memberId: null }),
        block({ id: 'b', memberId: 'coder' }),
        block({ id: 'c', memberId: 'coder' }),
      ],
      CHAT_AGENT_KEY,
    );

    expect([...byAgent.keys()]).toEqual([CHAT_AGENT_KEY, 'coder']);
    expect(byAgent.get(CHAT_AGENT_KEY)?.map((t) => t.id)).toEqual(['a']);
    expect(byAgent.get('coder')?.map((t) => t.id)).toEqual(['b', 'c']);
  });

  it('names a thread by the delegate description, then its type, then by its id', () => {
    const labelOf = (over: Partial<SubagentBlockEntry>): string | undefined =>
      subagentThreadsByAgent([block(over)], CHAT_AGENT_KEY).get(
        CHAT_AGENT_KEY,
      )?.[0]?.label;

    expect(labelOf({})).toBe('Review the diff');
    expect(labelOf({ label: null })).toBe('code-reviewer');
    // NOT a constant. Reported against a panel of seven identical `sub-agent`
    // rows: a delegate whose launching call is outside the loaded window has no
    // description and no type, and every one of them then rendered as the same
    // row — so "which spinner is which piece of work" had no answer on screen.
    expect(
      labelOf({ id: 'toolu_01ADkfzGRTjn5M6mo', label: null, kind: null }),
    ).toBe('Sub-agent n5M6mo');
    // Two unnamed delegates are two DIFFERENT rows, which is the whole point.
    expect(
      labelOf({ id: 'toolu_01ADkfzGRTjn5M6mo', label: null, kind: null }),
    ).not.toBe(
      labelOf({ id: 'toolu_01XYqrstuvwxyzAB', label: null, kind: null }),
    );
  });

  it('translates each block state into the panel status vocabulary', () => {
    const statusOf = (over: Partial<SubagentBlockEntry>): string | undefined =>
      subagentThreadsByAgent([block(over)], CHAT_AGENT_KEY).get(
        CHAT_AGENT_KEY,
      )?.[0]?.status;

    expect(statusOf({})).toBe('running');
    expect(statusOf({ returned: true })).toBe('completed');
    expect(statusOf({ failed: true, returned: true })).toBe('failed');
    expect(statusOf({ daemonStatus: 'untracked' })).toBe('untracked');
    expect(statusOf({ daemonStatus: 'stopped' })).toBe('cancelled');
  });

  it('reads a close that named no outcome as untracked only while the delegate can be recovered', () => {
    const statusOf = (over: Partial<SubagentBlockEntry>): string | undefined =>
      subagentThreadsByAgent([block(over)], CHAT_AGENT_KEY).get(
        CHAT_AGENT_KEY,
      )?.[0]?.status;

    // Every close written before recovery refs existed has this shape.
    expect(statusOf({ backgroundOpen: false })).toBe('completed');
    expect(statusOf({ backgroundOpen: false, recoverable: true })).toBe(
      'untracked',
    );
  });

  it('carries a delegate’s ended process onto its thread, only while it is untracked', () => {
    const threadOf = (over: Partial<SubagentBlockEntry>) =>
      subagentThreadsByAgent([block(over)], CHAT_AGENT_KEY).get(
        CHAT_AGENT_KEY,
      )?.[0];

    expect(
      threadOf({ daemonStatus: 'untracked', processEnded: true }),
    ).toMatchObject({ status: 'untracked', processEnded: true });
    expect(
      threadOf({ daemonStatus: 'completed', processEnded: true }),
    ).not.toHaveProperty('processEnded');
  });

  it('reports what the CLI said a settled delegate CAME TO, not merely that it stopped', () => {
    const statusOf = (over: Partial<SubagentBlockEntry>): string | undefined =>
      subagentThreadsByAgent([block(over)], CHAT_AGENT_KEY).get(
        CHAT_AGENT_KEY,
      )?.[0]?.status;

    // A killed delegate, reported through the settle. Both of the paths that
    // used to answer `completed` are covered: the settle itself, and a
    // `returned` launching call — which for a backgrounded delegate is answered
    // within the second, so it is already true by the time the outcome lands.
    expect(
      statusOf({ backgroundOpen: false, backgroundOutcome: 'stopped' }),
    ).toBe('cancelled');
    expect(statusOf({ returned: true, backgroundOutcome: 'stopped' })).toBe(
      'cancelled',
    );
    expect(statusOf({ returned: true, backgroundOutcome: 'failed' })).toBe(
      'failed',
    );
    // Tracking loss is reported separately from an observed outcome.
    expect(
      statusOf({ backgroundOpen: false, backgroundOutcome: 'untracked' }),
    ).toBe('untracked');
    expect(statusOf({ returned: true, backgroundOutcome: 'completed' })).toBe(
      'completed',
    );
  });

  it('never offers a resumable session for a delegate', () => {
    // A sub-agent lives inside its parent's turn, so there is no CLI session
    // for `--resume` to target — which is what withholds the panel's terminal
    // handoff button on these rows.
    const threads = subagentThreadsByAgent([block()], CHAT_AGENT_KEY).get(
      CHAT_AGENT_KEY,
    );
    expect(threads?.[0]?.sessionId).toBeNull();
    expect(threads?.[0]?.kind).toBe('subagent');
  });
});

