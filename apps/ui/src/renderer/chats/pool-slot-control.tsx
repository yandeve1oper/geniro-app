import { useState } from 'react';

import type { CliKind } from '../../shared/contracts';
import type { SetPoolMemberResultDto } from '../autogenerated';
import { MenuAnchorContext } from '../components/ui/menu-anchor';
import { Select } from '../components/ui/select';
import { daemonErrorDetail } from '../daemon-api';
import type { AgentDisplay } from './agent-activity';

/** One member of an agent's pool, as the card lists it. */
export interface PoolSlotMember {
  agent: CliKind;
  model: string | null;
}

/** `Slot 2 of 3 · Codex · gpt-5.5`: one pool member, numbered within its pool. */
export function poolSlotLabel(
  number: number,
  total: number,
  member: PoolSlotMember,
  nameOf: (agent: CliKind) => string,
): string {
  return [`Slot ${number} of ${total}`, nameOf(member.agent), member.model]
    .filter((part): part is string => part !== null && part !== '')
    .join(' · ');
}

/**
 * Which pool member an agent's own conversation runs on, and the picker that
 * moves it to another one and pins it there.
 */
export function PoolSlotControl({
  members,
  ownPool,
  nameOf,
  onSelect,
}: {
  members: readonly PoolSlotMember[];
  ownPool: NonNullable<AgentDisplay['ownPool']>;
  nameOf: (agent: CliKind) => string;
  onSelect?: (member: number) => Promise<SetPoolMemberResultDto>;
}): React.JSX.Element | null {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const current = members[ownPool.member - 1];
  if (current === undefined) {
    return null;
  }
  const label = poolSlotLabel(ownPool.member, members.length, current, nameOf);
  const select = async (value: string): Promise<void> => {
    if (onSelect === undefined) {
      return;
    }
    setBusy(true);
    setError(null);
    try {
      await onSelect(Number(value));
    } catch (err) {
      setError(daemonErrorDetail(err) ?? String(err));
    } finally {
      setBusy(false);
    }
  };
  return (
    <div
      data-slot="pool-slot"
      className="flex min-w-0 flex-col gap-0.5 text-[11px] text-muted-foreground">
      <span className="flex min-w-0 items-center gap-1.5">
        {onSelect === undefined ? (
          <span data-slot="pool-slot-label" className="min-w-0 truncate">
            {label}
          </span>
        ) : (
          // The agents panel scrolls and clips; the menu escapes it.
          <MenuAnchorContext.Provider value="viewport">
            <Select
              variant="ghost"
              side="bottom"
              flexible
              aria-label="Pool slot of its own conversation"
              title="Pick the pool member this agent's own conversation runs on — it stays there until that member fails"
              disabled={busy}
              value={String(ownPool.member)}
              triggerLabel={
                <span data-slot="pool-slot-label" className="min-w-0 truncate">
                  {label}
                </span>
              }
              groups={[
                {
                  items: members.map((member, index) => ({
                    value: String(index + 1),
                    label: poolSlotLabel(
                      index + 1,
                      members.length,
                      member,
                      nameOf,
                    ),
                  })),
                },
              ]}
              onValueChange={(value) => void select(value)}
            />
          </MenuAnchorContext.Provider>
        )}
        {ownPool.pinned ? (
          <span
            data-slot="pool-slot-pinned"
            title="Pinned by you: it does not move back to another slot on its own"
            className="shrink-0">
            pinned
          </span>
        ) : null}
      </span>
      {ownPool.next !== null && ownPool.next !== ownPool.member ? (
        <span data-slot="pool-slot-next">
          Moves to slot {ownPool.next} when its next turn starts
        </span>
      ) : null}
      {error === null ? null : (
        <span data-slot="pool-slot-error" className="text-destructive">
          {error}
        </span>
      )}
    </div>
  );
}
