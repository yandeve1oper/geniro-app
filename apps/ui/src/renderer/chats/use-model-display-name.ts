import type { AgentKind } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { modelDisplayName } from './model-options';
import { useAgentModels } from './use-agent-models';

/** The model's name as the composer's model menu shows it, or null for no model. */
export function useModelDisplayName(
  agentsApi: DaemonApis['agents'] | null,
  agentKind: AgentKind | null,
  model: string | null,
): string | null {
  const { models } = useAgentModels(
    agentsApi,
    model === null ? null : agentKind,
  );
  return model === null ? null : modelDisplayName(models, model);
}
