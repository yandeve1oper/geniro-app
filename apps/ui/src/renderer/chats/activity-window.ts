import type { ChatsApiListChatsRequest } from '../autogenerated';

export interface ActivityWindow {
  since: string;
  until: string | null;
}

export type ActivityPreset =
  'any' | 'today' | 'since-yesterday' | 'this-week' | 'custom';

const localMidnight = (year: number, month: number, day: number): Date =>
  new Date(year, month, day);

export function windowOfPreset(
  preset: 'today' | 'since-yesterday' | 'this-week',
  now: Date,
): ActivityWindow {
  const daysBack =
    preset === 'today'
      ? 0
      : preset === 'since-yesterday'
        ? 1
        : (now.getDay() + 6) % 7;
  const start = localMidnight(
    now.getFullYear(),
    now.getMonth(),
    now.getDate() - daysBack,
  );
  return { since: start.toISOString(), until: null };
}

function parseDate(value: string): Date | null {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  if (match === null) {
    return null;
  }
  const [year, month, day] = [
    Number(match[1]),
    Number(match[2]) - 1,
    Number(match[3]),
  ];
  const date = localMidnight(year, month, day);
  return date.getFullYear() === year &&
    date.getMonth() === month &&
    date.getDate() === day
    ? date
    : null;
}

export function customWindow(
  fromDate: string,
  toDate: string,
): ActivityWindow | null {
  const from = parseDate(fromDate);
  const to = parseDate(toDate);
  if (from === null || to === null || to < from) {
    return null;
  }
  const end = localMidnight(to.getFullYear(), to.getMonth(), to.getDate() + 1);
  return { since: from.toISOString(), until: end.toISOString() };
}

export function inWindow(
  run: { lastActivityAt?: string | null },
  window: ActivityWindow | null,
): boolean {
  if (window === null) {
    return true;
  }
  const at = run.lastActivityAt;
  if (at == null) {
    return false;
  }
  return at >= window.since && (window.until === null || at < window.until);
}

export function windowQuery(
  window: ActivityWindow | null,
): Pick<ChatsApiListChatsRequest, 'activeSince' | 'activeUntil'> {
  if (window === null) {
    return {};
  }
  return window.until === null
    ? { activeSince: window.since }
    : { activeSince: window.since, activeUntil: window.until };
}
