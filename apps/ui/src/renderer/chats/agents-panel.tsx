/**
 * One conversation of one agent, as a row of the card's thread list.
 *
 * Extracted because the list now renders threads from three places — the
 * agent's own conversations, its running delegates, and the settled delegates
 * behind their own disclosure — and three copies of this row is how one of them
 * comes to lose the terminal button or the sub-agent affordance without anyone
 * noticing.
 */
function ThreadRow({
  as = 'li',
  leading = null,
  badge = null,
  hideTerminal = false,
  title,
  hoverTitle,
  agent,
  thread,
  terminal,
  onOpenThread,
  onOpenSubagent,
  onResolveHandoff,
}: {
  /**
   * `div` when the row is the HEADING of an instance block rather than an item
   * of a list — the same row, so an instance cannot come to lose the terminal
   * control or the context ring a list row carries.
   */
  as?: 'li' | 'div';
  /** Drawn before the status glyph — an instance block's own disclosure. */
  leading?: React.ReactNode;
  /** Drawn after the title — the pool member an instance runs on. */
  badge?: React.ReactNode;
  /**
   * Withhold the terminal control. The node's OWN conversation carries it in
   * the card header already, and a second copy of it on the same card would be
   * two buttons for one handoff.
   */
  hideTerminal?: boolean;
  /**
   * What the row says in place of `thread.label` — an instance heading states
   * its brief's first line.
   */
  title?: string;
  /** What the row's hover says, when it should say more than its label. */
  hoverTitle?: string;
  agent: AgentDisplay;
  thread: AgentThread;
  /**
   * This CLI's handoff answer, or null when there is none to render — an agent
   * whose kind the panel does not know, or a capability report that has not
   * landed yet. `reason` non-null means the control is shown inert.
   */
  terminal: { reason: string | null } | null;
  onOpenThread: (agent: AgentDisplay, thread: AgentThread) => void;
  onOpenSubagent?: (subagentId: string) => void;
  onResolveHandoff?: (
    agent: AgentDisplay,
    thread: AgentThread,
  ) => Promise<HandoffTargetDto>;
}): React.JSX.Element {
  // A MAIN thread needs nothing else — the daemon resolves its session from
  // `node_state`. A CALL thread is a sub-session, which can only be targeted
  // once its own session id has been recorded (present after the call settles).
  // A SUB-AGENT has no session at all — it lives inside its parent's turn — so
  // it is excluded outright rather than left to fail the sessionId test by
  // accident.
  //
  // Note what is NOT in this test any more: whether the CLI can resume at all.
  // That is `terminal.reason`, and it makes the control INERT rather than
  // absent — the row still carries the explanation, where before it carried
  // nothing.
  const canOpen =
    !hideTerminal &&
    terminal !== null &&
    thread.kind !== 'subagent' &&
    (thread.kind === 'main' || thread.sessionId !== null);
  // What a sub-agent row offers INSTEAD: its own timeline and conversation, in
  // a panel. Absent the callback the row is inert rather than falsely clickable.
  const openSubagent =
    thread.kind === 'subagent' && onOpenSubagent ? onOpenSubagent : null;
  const cells = (
    <>
      {leading}
      {thread.status === 'untracked' ? (
        <span
          data-slot="untracked-status"
          className="flex shrink-0"
          title={untrackedExplanation(thread.processEnded === true)}>
          <RunStatusIcon status={thread.status} />
        </span>
      ) : (
        <RunStatusIcon status={thread.status} />
      )}
      {openSubagent ? (
        <button
          type="button"
          // `text-xs font-normal` is not decoration — it is an OVERRIDE.
          // `styles/global.css` gives every bare `button` the base 15px at
          // medium weight, so without it this row rendered half again the size
          // of its `Main conversation` sibling, which is a span. Screenshotted
          // against the real stylesheet; jsdom loads no CSS, so no component
          // test could ever have caught it.
          className="min-w-0 flex-1 truncate rounded px-0.5 text-left text-xs font-normal transition-colors hover:text-foreground hover:underline"
          title={`Open ${thread.label}'s timeline and conversation`}
          onClick={() => openSubagent(thread.id)}>
          {thread.label}
        </button>
      ) : (
        <span
          className="min-w-0 flex-1 truncate"
          title={hoverTitle ?? thread.label}>
          {title ?? thread.label}
        </span>
      )}
      {badge}
      {/*
        This CONVERSATION's own window. On the row rather than on the card
        because a node can hold several calls at once and each has its own
        window — the card's single ring could only ever show whichever wrote
        last. `runId` is null: that argument opens the full breakdown, which is
        a question put to the run's ONE live process and cannot answer for a
        particular call thread.
      */}
      <PromptCacheBadge
        expiresAt={thread.promptCacheExpiresAt}
        contextTokens={thread.contextTokens}
        contextWindowTokens={thread.contextWindowTokens}
        live={thread.status === 'running'}
      />
      <ContextMeter
        runId={null}
        contextTokens={thread.contextTokens ?? null}
        contextWindowTokens={thread.contextWindowTokens ?? null}
        contextEstimated={thread.contextEstimated === true}
        spentUsd={null}
        live={thread.status === 'running'}
        className="size-5 shrink-0 justify-center"
      />
      {canOpen ? (
        <OpenInCliButton
          agent={agent}
          thread={thread}
          label={`Open terminal for ${agent.name} — ${thread.id}`}
          unavailableReason={terminal?.reason ?? null}
          onOpen={onOpenThread}
          onResolve={onResolveHandoff}
        />
      ) : null}
    </>
  );
  const rowClass = 'flex items-center gap-1.5 rounded-md px-1 py-0.5 text-xs';
  return as === 'div' ? (
    <div className={rowClass}>{cells}</div>
  ) : (
    <li className={rowClass}>{cells}</li>
  );
}

/**
 * One conversation's delegates: the live ones as rows, the finished ones
 * COUNTED behind a fold that is shut by default.
 *
 * Extracted because it is now drawn in two places — directly under an agent
 * that holds one conversation, and inside each INSTANCE block of an agent that
 * has been called — and two copies of this list is how one of them comes to
 * lose the fold, which is the only thing standing between a fan-out of forty
 * finished analysts and the one live thread the reader came to watch.
 */
function SubagentRows({
  agent,
  subagents,
  terminal,
  settledOpen,
  onToggleSettled,
  onOpenThread,
  onOpenSubagent,
  onResolveHandoff,
  foldSettled = true,
}: {
  agent: AgentDisplay;
  subagents: readonly AgentThread[];
  terminal: { reason: string | null } | null;
  settledOpen: boolean;
  onToggleSettled: () => void;
  onOpenThread: (agent: AgentDisplay, thread: AgentThread) => void;
  onOpenSubagent?: (subagentId: string) => void;
  onResolveHandoff?: (
    agent: AgentDisplay,
    thread: AgentThread,
  ) => Promise<HandoffTargetDto>;
  /**
   * Whether the finished rows sit behind their own fold. Off when NOTHING is
   * running: the section around this list is then itself the fold, shut and
   * captioned `N finished`, so a second one inside it is a second press for the
   * same rows.
   */
  foldSettled?: boolean;
}): React.JSX.Element {
  const live = subagents.filter((thread) => !isSettledRunStatus(thread.status));
  const settled = subagents.filter((thread) =>
    isSettledRunStatus(thread.status),
  );
  if (!foldSettled) {
    return (
      <ul className="m-0 flex list-none flex-col gap-0.5">
        {subagents.map((thread) => (
          <ThreadRow
            key={thread.id}
            agent={agent}
            thread={thread}
            terminal={terminal}
            onOpenThread={onOpenThread}
            onOpenSubagent={onOpenSubagent}
            onResolveHandoff={onResolveHandoff}
          />
        ))}
      </ul>
    );
  }
  return (
    <ul className="m-0 flex list-none flex-col gap-0.5">
      {live.map((thread) => (
        <ThreadRow
          key={thread.id}
          agent={agent}
          thread={thread}
          terminal={terminal}
          onOpenThread={onOpenThread}
          onOpenSubagent={onOpenSubagent}
          onResolveHandoff={onResolveHandoff}
        />
      ))}
      {settled.length > 0 ? (
        <li className="flex flex-col">
          <button
            type="button"
            aria-expanded={settledOpen}
            onClick={onToggleSettled}
            // `font-normal` for the same reason the row label carries it:
            // global.css's base `button` rule would otherwise weight this
            // heavier than the threads it is counting.
            className="flex items-center gap-1.5 rounded-md px-1 py-0.5 text-left text-xs font-normal text-muted-foreground transition-colors hover:text-foreground">
            <ChevronRight
              aria-hidden="true"
              className={cn(
                'size-3 shrink-0 transition-transform',
                settledOpen && 'rotate-90',
              )}
            />
            {/* Counted, not listed: the number is the only thing a reader
                wants from work that is over, and it is what says the rows
                above are the LIVE ones rather than all there ever were. */}
            <span>
              {settled.length} finished sub-agent
              {settled.length === 1 ? '' : 's'}
            </span>
          </button>
          {settledOpen ? (
            <ul className="m-0 flex list-none flex-col gap-0.5 pl-4">
              {settled.map((thread) => (
                <ThreadRow
                  key={thread.id}
                  agent={agent}
                  thread={thread}
                  terminal={terminal}
                  onOpenThread={onOpenThread}
                  onOpenSubagent={onOpenSubagent}
                  onResolveHandoff={onResolveHandoff}
                />
              ))}
            </ul>
          ) : null}
        </li>
      ) : null}
    </ul>
  );
}

