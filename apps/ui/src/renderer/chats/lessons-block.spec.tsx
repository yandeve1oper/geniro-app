// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import {
  LESSON_BROKEN_AGAIN,
  LESSON_CORRECTION,
} from '../__fixtures__/lessons';
import { withVocabulary } from '../__tests__/agent-vocabulary-api';
import type { LessonReflectionFactsDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import {
  LessonsAgentsApiContext,
  LessonsApiContext,
} from './lessons-api-context';
import { LessonsBlock } from './lessons-block';
import { ThreadUiMemoryContext } from './thread-ui-memory';
import type { LessonsEntry } from './transcript-groups';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

const ENTRY: LessonsEntry = {
  type: 'lessons',
  id: 'i-50',
  createdAt: '2026-11-12T10:00:00.000Z',
  seq: 50,
  memberId: null,
  parentToolUseId: null,
  card: {
    reflectionRunId: 'refl-1',
    segmentId: 'seg-1',
    agentKind: 'claude',
    model: 'claude-haiku-5-5',
    proposals: [LESSON_CORRECTION],
    places: { project: true, team: true, projectId: null, members: [] },
    check: null,
  },
  outcomes: {},
};

const FACTS_DONE: LessonReflectionFactsDto = {
  reflectionRunId: 'refl-1',
  agentKind: 'claude',
  model: 'claude-haiku-5-5',
  effort: 'high',
  working: false,
  startedAt: '2026-11-12T10:00:00.000Z',
  durationMs: 38_000,
  costUsd: 0.02,
  tokens: 4200,
};

function lessonsApi(
  overrides: Partial<Record<keyof DaemonApis['lessons'], unknown>> = {},
): DaemonApis['lessons'] {
  return {
    getLessonReflection: vi.fn(async () => FACTS_DONE),
    saveLesson: vi.fn(async () => ({})),
    rejectLesson: vi.fn(async () => ({})),
    undoLesson: vi.fn(async () => ({})),
    editLesson: vi.fn(async () => ({})),
    approveLesson: vi.fn(async () => ({})),
    ...overrides,
  } as unknown as DaemonApis['lessons'];
}

async function render(
  api: DaemonApis['lessons'] | null,
  entry: LessonsEntry = ENTRY,
  agentsApi: DaemonApis['agents'] | null = null,
): Promise<HTMLDivElement> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(
      <ThreadUiMemoryContext.Provider value="run-1">
        <LessonsAgentsApiContext.Provider value={agentsApi}>
          <LessonsApiContext.Provider value={api}>
            <LessonsBlock entry={entry} />
          </LessonsApiContext.Provider>
        </LessonsAgentsApiContext.Provider>
      </ThreadUiMemoryContext.Provider>,
    );
  });
  return container;
}

function primaryButton(el: HTMLElement): HTMLButtonElement {
  const found = el.querySelector<HTMLButtonElement>(
    '[data-slot="split-button"] > button:first-child',
  );
  if (!found) {
    throw new Error('no primary action');
  }
  return found;
}

function buttonNamed(el: HTMLElement, name: string): HTMLButtonElement {
  const found = [...el.querySelectorAll('button')].find(
    (button) => button.textContent?.trim() === name,
  );
  if (!found) {
    throw new Error(`no button named ${name}`);
  }
  return found;
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
}

const BROKEN_AGAIN_ENTRY: LessonsEntry = {
  ...ENTRY,
  card: { ...ENTRY.card, proposals: [LESSON_BROKEN_AGAIN] },
};

function menuOptionLabels(): string[] {
  return [...document.querySelectorAll('[role="option"]')].map(
    (option) => option.textContent?.trim() ?? '',
  );
}

describe('LessonsBlock — Move up', () => {
  it('asks the daemon whether a broken-again lesson can still move up, for the open thread', async () => {
    const api = lessonsApi({
      listLessonProposals: vi.fn(async () => ({
        proposals: [{ id: LESSON_BROKEN_AGAIN.id, moveUp: 'memory_index' }],
      })),
      moveLessonUp: vi.fn(async () => ({})),
    });
    const el = await render(api, BROKEN_AGAIN_ENTRY);

    expect(api.listLessonProposals).toHaveBeenCalledWith({
      status: 'proposed,check_failed',
      sourceRunId: 'run-1',
    });
    expect(primaryButton(el).textContent).toBe('Move up to the memory index');

    await press(primaryButton(el));

    expect(api.moveLessonUp).toHaveBeenCalledWith({
      proposalId: LESSON_BROKEN_AGAIN.id,
    });
  });

  it('never offers Move up once the daemon says the entry is already in the memory index', async () => {
    const api = lessonsApi({
      listLessonProposals: vi.fn(async () => ({
        proposals: [{ id: LESSON_BROKEN_AGAIN.id, moveUp: null }],
      })),
      moveLessonUp: vi.fn(async () => ({})),
    });
    const el = await render(api, BROKEN_AGAIN_ENTRY);

    expect(primaryButton(el).textContent).not.toContain('Move up');
    await press(
      el.querySelector<HTMLElement>('[aria-label="Choose where it goes"]')!,
    );
    const labels = menuOptionLabels();
    expect(labels.length).toBeGreaterThan(0);
    expect(labels.some((label) => label.includes('Move up'))).toBe(false);

    await press(primaryButton(el));

    expect(api.moveLessonUp).not.toHaveBeenCalled();
    expect(api.saveLesson).toHaveBeenCalledWith({
      proposalId: LESSON_BROKEN_AGAIN.id,
      saveLessonDto: { target: LESSON_BROKEN_AGAIN.target },
    });
  });

  it('asks the daemon nothing when no lesson could move up', async () => {
    const api = lessonsApi({
      listLessonProposals: vi.fn(async () => ({ proposals: [] })),
    });
    await render(api);

    expect(api.listLessonProposals).not.toHaveBeenCalled();
  });
});

describe('LessonsBlock', () => {
  it('names in its footer the model the reflection was billed for', async () => {
    const el = await render(
      lessonsApi({
        getLessonReflection: vi.fn(async () => ({
          ...FACTS_DONE,
          model: 'claude-sonnet-5-5',
        })) as never,
      }),
      { ...ENTRY, card: { ...ENTRY.card, model: 'haiku' } },
    );

    expect(el.textContent).toContain('claude-sonnet-5-5');
    expect(el.textContent).not.toContain('· haiku ·');
  });

  it('names the model in its footer as the model menu does', async () => {
    const agentsApi = withVocabulary({
      listAgentModels: vi.fn(async () => [
        {
          id: 'haiku',
          label: 'Haiku 5.5',
          resolvedModel: 'claude-haiku-5-5',
          source: 'cli' as const,
        },
      ]),
    } as never);
    const el = await render(lessonsApi(), ENTRY, agentsApi);
    await act(async () => {
      await Promise.resolve();
    });

    expect(el.textContent).toContain('· Haiku 5.5 · high');
    expect(el.textContent).not.toContain('claude-haiku-5-5');
  });

  it('disables the actions when no lessons API is provided', async () => {
    const el = await render(null);

    expect(primaryButton(el).disabled).toBe(true);
    expect(buttonNamed(el, 'Edit').disabled).toBe(true);
    expect(buttonNamed(el, 'Reject').disabled).toBe(true);
  });

  it('saves the proposal to its scope through the API', async () => {
    const api = lessonsApi();
    const el = await render(api);

    await press(primaryButton(el));

    expect(api.saveLesson).toHaveBeenCalledWith({
      proposalId: 'p-correction',
      saveLessonDto: {
        target: { kind: 'memory', scope: 'project', type: 'feedback' },
      },
    });
  });

  it('rejects the proposal with the reason it was given', async () => {
    const api = lessonsApi();
    const el = await render(api);

    await press(buttonNamed(el, 'Reject'));
    const reason = el.querySelector<HTMLInputElement>(
      'input[aria-label="Reject reason"]',
    )!;
    const setter = Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )!.set!;
    act(() => {
      setter.call(reason, 'already covered');
      reason.dispatchEvent(new Event('input', { bubbles: true }));
    });
    await press(buttonNamed(el, 'Reject'));

    expect(api.rejectLesson).toHaveBeenCalledWith({
      proposalId: 'p-correction',
      rejectLessonDto: { reason: 'already covered' },
    });
  });

  it('shows the daemon message when a save is refused', async () => {
    const api = lessonsApi({
      saveLesson: vi.fn(() =>
        Promise.reject(new Error('no project to save to')),
      ),
    });
    const el = await render(api);

    await press(primaryButton(el));

    expect(el.textContent).toContain('no project to save to');
  });

  it('re-reads a working reflection every 5 s and stops once it is done', async () => {
    vi.useFakeTimers();
    const getLessonReflection = vi
      .fn<() => Promise<LessonReflectionFactsDto>>()
      .mockResolvedValueOnce({ ...FACTS_DONE, working: true, costUsd: null })
      .mockResolvedValueOnce(FACTS_DONE);
    const api = lessonsApi({
      getLessonReflection: getLessonReflection as never,
    });
    const el = await render(api);

    expect(el.textContent).toContain('working…');

    await act(async () => {
      await vi.advanceTimersByTimeAsync(5_000);
    });

    expect(getLessonReflection).toHaveBeenCalledTimes(2);
    expect(el.textContent).toContain('$0.02');
    expect(el.textContent).not.toContain('working…');

    await act(async () => {
      await vi.advanceTimersByTimeAsync(20_000);
    });

    expect(getLessonReflection).toHaveBeenCalledTimes(2);
  });

  it('stops re-reading a working reflection when it unmounts', async () => {
    vi.useFakeTimers();
    const getLessonReflection = vi.fn(async () => ({
      ...FACTS_DONE,
      working: true,
      costUsd: null,
    }));
    const api = lessonsApi({
      getLessonReflection: getLessonReflection as never,
    });
    await render(api);

    act(() => {
      root?.unmount();
    });
    root = null;
    await act(async () => {
      await vi.advanceTimersByTimeAsync(20_000);
    });

    expect(getLessonReflection).toHaveBeenCalledTimes(1);
  });

  it('undoes a saved lesson through the API', async () => {
    const api = lessonsApi();
    const el = await render(api, {
      ...ENTRY,
      outcomes: {
        'p-correction': {
          proposalId: 'p-correction',
          status: 'saved',
          by: 'auto',
          title: LESSON_CORRECTION.title,
          rule: LESSON_CORRECTION.rule,
          target: { kind: 'memory', scope: 'project', type: 'feedback' },
          memoryHandle: 'm21',
          resultRef: null,
          reason: null,
        },
      },
    });

    await press(buttonNamed(el, 'Undo'));

    expect(api.undoLesson).toHaveBeenCalledWith({ proposalId: 'p-correction' });
  });

  it('approves a lesson waiting for review through the API', async () => {
    const api = lessonsApi();
    const el = await render(api, {
      ...ENTRY,
      outcomes: {
        'p-correction': {
          proposalId: 'p-correction',
          status: 'pending',
          by: 'auto',
          title: LESSON_CORRECTION.title,
          rule: LESSON_CORRECTION.rule,
          target: { kind: 'memory', scope: 'project', type: 'feedback' },
          memoryHandle: null,
          resultRef: null,
          reason: null,
        },
      },
    });

    await press(buttonNamed(el, 'Approve'));

    expect(api.approveLesson).toHaveBeenCalledWith({
      proposalId: 'p-correction',
    });
  });

  it('edits a saved lesson’s title and rule through the API', async () => {
    const api = lessonsApi();
    const el = await render(api, {
      ...ENTRY,
      outcomes: {
        'p-correction': {
          proposalId: 'p-correction',
          status: 'saved',
          by: 'user',
          title: LESSON_CORRECTION.title,
          rule: LESSON_CORRECTION.rule,
          target: { kind: 'memory', scope: 'project', type: 'feedback' },
          memoryHandle: 'm21',
          resultRef: null,
          reason: null,
        },
      },
    });

    await press(buttonNamed(el, 'Edit'));
    const title = el.querySelector<HTMLInputElement>(
      'input[aria-label="Lesson title"]',
    )!;
    const setter = Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )!.set!;
    act(() => {
      setter.call(title, 'Use pnpm for every test run');
      title.dispatchEvent(new Event('input', { bubbles: true }));
    });
    await press(buttonNamed(el, 'Save'));

    expect(api.editLesson).toHaveBeenCalledWith({
      proposalId: 'p-correction',
      editLessonDto: {
        title: 'Use pnpm for every test run',
        rule: LESSON_CORRECTION.rule,
      },
    });
  });

  it('reads the check’s own run for a second footer line, from the daemon', async () => {
    const getLessonReflection = vi.fn(
      async (request: { reflectionRunId: string }) =>
        request.reflectionRunId === 'chk-1'
          ? {
              ...FACTS_DONE,
              reflectionRunId: 'chk-1',
              agentKind: 'claude' as const,
              model: 'claude-opus-5-5',
              costUsd: 0.27,
            }
          : FACTS_DONE,
    );
    const api = lessonsApi({
      getLessonReflection: getLessonReflection as never,
    });
    const el = await render(api, {
      ...ENTRY,
      card: {
        ...ENTRY.card,
        check: { runId: 'chk-1', agentKind: 'claude', model: 'opus' },
      },
    });

    expect(getLessonReflection).toHaveBeenCalledWith({
      reflectionRunId: 'chk-1',
    });
    expect(el.textContent).toContain('Check: claude · claude-opus-5-5 · high');
    expect(el.textContent).toContain('$0.27');
  });
});
