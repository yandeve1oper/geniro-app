import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem, RunDto } from '../autogenerated';
import {
  lastTerminalItemAt,
  replayTail,
  settledRunStatus,
  settleMomentOf,
  TERMINAL_KINDS,
} from './settled-status';

function item(
  kind: string,
  payload: unknown = {},
  memberId: string | null = null,
): ChatItem {
  return {
    id: 'i1',
    runId: 'r1',
    memberId,
    seq: 1,
    kind: kind as ChatItem['kind'],
    role: null,
    payload,
    createdAt: 'now',
  };
}

describe('settleMomentOf', () => {
  it('reads the settle from the terminal item, never from a later row write', () => {
    // The row was bumped after the stop by something that is not the turn
    // ending (a delegate's own row, say). Taking the later of the two would
    // answer 11:00 and make "spoke since the settle?" unanswerable.
    const run = { updatedAt: '2026-09-14T11:00:00.000Z' } as RunDto;
    const rows = [
      { ...item('turn_complete'), createdAt: '2026-09-14T10:00:00.000Z' },
    ];

    expect(settleMomentOf(run, rows)).toBe(
      Date.parse('2026-09-14T10:00:00.000Z'),
    );
  });

  it('reads the item when the row was written BEFORE the stop, not the earlier of the two', () => {
    // The row's stamp is not bumped by items, so it can sit before the stop it
    // describes. Taking the earlier of the two would answer that stale stamp.
    const run = { updatedAt: '2026-09-14T09:00:00.000Z' } as RunDto;
    const rows = [
      { ...item('turn_complete'), createdAt: '2026-09-14T10:00:00.000Z' },
    ];

    expect(settleMomentOf(run, rows)).toBe(
      Date.parse('2026-09-14T10:00:00.000Z'),
    );
  });

  it('falls back to the row when the run stopped without a terminal item', () => {
    // A cancel writes no terminal item, so the row is the only record of the stop.
    const run = { updatedAt: '2026-09-14T11:00:00.000Z' } as RunDto;

    expect(settleMomentOf(run, [])).toBe(
      Date.parse('2026-09-14T11:00:00.000Z'),
    );
  });

  it("answers 'unknown' when neither can be read, rather than null", () => {
    // Null would read as "never stopped" and put every spinner back.
    expect(settleMomentOf(null, [])).toBe('unknown');
    expect(settleMomentOf({ updatedAt: 'not a date' } as RunDto, [])).toBe(
      'unknown',
    );
  });
});

describe('settledRunStatus', () => {
  it('refuses a continuation’s result that arrived INSIDE a turn — it ended nothing', () => {
    // Mirrored, it put `completed` on the sidebar row of a thread still working.
    expect(
      settledRunStatus(
        item('turn_complete', { continuation: true, insideTurn: true }),
      ),
    ).toBeNull();
    expect(
      lastTerminalItemAt([
        {
          ...item('turn_complete', { insideTurn: true }),
          createdAt: '2026-09-14T10:00:00.000Z',
        },
      ]),
    ).toBeNull();
  });

  it('reads each terminal kind as the status it implies', () => {
    expect(settledRunStatus(item('turn_complete'))).toBe('completed');
    expect(settledRunStatus(item('turn_cancelled'))).toBe('cancelled');
    expect(settledRunStatus(item('error'))).toBe('failed');
  });

  it('takes a team run’s roll-up from the stopReason, not the kind', () => {
    // Every team run ends in a run-level `turn_complete` whose stopReason
    // carries the verdict, so reading the kind alone reported a failed team
    // run as completed.
    expect(
      settledRunStatus(item('turn_complete', { stopReason: 'team_failed' })),
    ).toBe('failed');
    expect(
      settledRunStatus(item('turn_complete', { stopReason: 'team_cancelled' })),
    ).toBe('cancelled');
    expect(
      settledRunStatus(item('turn_complete', { stopReason: 'team_completed' })),
    ).toBe('completed');
  });

  it('reads the roll-up rows stored before the rename, which say workflow_<status>', () => {
    expect(
      settledRunStatus(
        item('turn_complete', { stopReason: 'workflow_failed' }),
      ),
    ).toBe('failed');
    expect(
      settledRunStatus(
        item('turn_complete', { stopReason: 'workflow_cancelled' }),
      ),
    ).toBe('cancelled');
    expect(
      settledRunStatus(
        item('turn_complete', { stopReason: 'workflow_completed' }),
      ),
    ).toBe('completed');
  });

  it('refuses a NODE’s own turn end', () => {
    // A team node settling says nothing about the run — sibling branches may
    // still be running, and reading one as the run's end re-enabled the composer
    // underneath them.
    expect(settledRunStatus(item('turn_complete', {}, 'coder'))).toBeNull();
    expect(settledRunStatus(item('error', {}, 'coder'))).toBeNull();
  });

  it('answers null for anything that is not a turn end', () => {
    expect(settledRunStatus(item('message', { text: 'hi' }))).toBeNull();
    expect(settledRunStatus(item('tool_call'))).toBeNull();
    // `unanswerable` and `system` rows are written AFTER a settle by the same
    // sweep, and reading either as terminal would settle a run twice.
    expect(settledRunStatus(item('unanswerable'))).toBeNull();
    expect(settledRunStatus(item('system'))).toBeNull();
  });

  it('exports the kinds as one set, so no caller can spell its own', () => {
    expect([...TERMINAL_KINDS].sort()).toEqual([
      'error',
      'turn_cancelled',
      'turn_complete',
    ]);
  });
});

describe('lastTerminalItemAt', () => {
  const at = (
    kind: ChatItem['kind'],
    createdAt: string,
    memberId: string | null = null,
  ): ChatItem => ({
    id: `i-${createdAt}`,
    runId: 'r',
    memberId,
    seq: 1,
    kind,
    role: null,
    payload: {},
    createdAt,
  });

  it('answers with the run’s own record of when it stopped', () => {
    // The defect this closes, with the measured numbers: the row the renderer
    // held said the run stopped at 07:24:48.881 while the daemon had recorded
    // the cancel at 07:24:50.870, and a task announcement written at
    // 07:24:49.462 — inside that gap — read as "produced after the settle", so
    // its in-progress row went on spinning on a run the user had stopped.
    expect(
      lastTerminalItemAt([
        at('task_list', '2026-08-14T07:24:49.462Z'),
        at('turn_cancelled', '2026-08-14T07:24:50.870Z'),
      ]),
    ).toBe(Date.parse('2026-08-14T07:24:50.870Z'));
  });

  it('takes the NEWEST terminal item, so a later turn wins', () => {
    expect(
      lastTerminalItemAt([
        at('turn_complete', '2026-08-14T07:00:00.000Z'),
        at('turn_complete', '2026-08-14T08:00:00.000Z'),
      ]),
    ).toBe(Date.parse('2026-08-14T08:00:00.000Z'));
  });

  it('ignores a team NODE’s own turn end', () => {
    // Same rule `settledRunStatus` enforces: a node's `turn_complete` says
    // nothing about the run, and reading one as the run's stop would close every
    // sibling branch's spinners while they were still working.
    expect(
      lastTerminalItemAt([
        at('turn_complete', '2026-08-14T07:00:00Z', 'writer'),
      ]),
    ).toBeNull();
  });

  it('answers null for a run whose transcript holds no terminal item', () => {
    // Which is what leaves the row's own timestamp as the fallback, rather than
    // claiming the run never stopped.
    expect(
      lastTerminalItemAt([at('message', '2026-08-14T07:00:00.000Z')]),
    ).toBeNull();
    expect(lastTerminalItemAt([])).toBeNull();
  });
});

describe('replayTail', () => {
  // The daemon writes these about work that outlives a turn, after the turn's
  // own ending — so a replay reading the plain last row would read "not ended".
  it.each(['shell_info', 'shell_open', 'subagent_info', 'action_outcome'])(
    'reads past a trailing %s to the turn end before it',
    (kind) => {
      const ended = { ...item('turn_complete'), id: 'end', seq: 1 };
      const trailing = { ...item(kind), id: 'after', seq: 2 };

      expect(replayTail([ended, trailing])).toBe(ended);
    },
  );

  it('reads past geniro’s compaction row, written after the compaction turn ended', () => {
    const ended = { ...item('turn_complete'), id: 'end', seq: 1 };
    const compacted = {
      ...item('system', { message: 'compacted', conversationReplaced: true }),
      id: 'compacted',
      seq: 2,
    };

    expect(replayTail([ended, compacted])).toBe(ended);
  });

  it('answers a trailing system row that is not a compaction', () => {
    const ended = { ...item('turn_complete'), id: 'end', seq: 1 };
    const notice = {
      ...item('system', { message: 'monitor output', severity: 'info' }),
      id: 'notice',
      seq: 2,
    };

    expect(replayTail([ended, notice])).toBe(notice);
  });

  it('answers the last row when it is not bookkeeping', () => {
    const ended = { ...item('turn_complete'), id: 'end', seq: 1 };
    const message = { ...item('message'), id: 'msg', seq: 2 };

    expect(replayTail([ended, message])).toBe(message);
  });

  it('answers undefined when the transcript holds only bookkeeping', () => {
    expect(replayTail([item('shell_info'), item('subagent_info')])).toBe(
      undefined,
    );
  });
});
