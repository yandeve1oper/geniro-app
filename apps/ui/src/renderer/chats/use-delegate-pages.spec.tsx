// @vitest-environment jsdom
import { act, useRef, useState } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { delegateStateOf } from '../__tests__/delegate-state';
import type {
  ChatHistoryDto,
  ChatsApi,
  ItemDto as ChatItem,
} from '../autogenerated';
import { Dialog } from '../components/ui/dialog';
import { useDurableTranscript } from './durable-transcript';
import { SubagentBlock, SubagentDetail } from './subagent-block';
import { collectSubagentBlocks } from './transcript-groups';
import {
  DelegateConversationContext,
  useDelegatePages,
} from './use-delegate-pages';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const DELEGATE = 'task-1';

function row(seq: number, kind: ChatItem['kind'], payload: unknown): ChatItem {
  return {
    id: `r-${seq}`,
    runId: 'run-1',
    memberId: null,
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function stepRow(seq: number, id: string): ChatItem {
  return row(seq, 'tool_call', {
    id,
    name: 'Grep',
    input: { pattern: id },
    parentToolUseId: DELEGATE,
  });
}

const launch = row(1, 'tool_call', {
  id: DELEGATE,
  name: 'Task',
  input: {
    subagent_type: 'code-reviewer',
    description: 'Review the diff',
    prompt: 'Look for off-by-one errors.',
  },
});
const finished = row(2, 'tool_result', {
  id: DELEGATE,
  name: null,
  result: 'done',
  isError: false,
});

/** The window: the two newest steps of the delegate. */
const WINDOW = [launch, finished, stepRow(20, 'w-1'), stepRow(21, 'w-2')];

function page(rows: ChatItem[]): ChatHistoryDto {
  return { items: rows, anchors: [] };
}

function Harness({
  api,
  pageSize,
  daemonCalls,
  panel = false,
}: {
  api: Pick<ChatsApi, 'listRunItems'>;
  pageSize: number;
  daemonCalls: number;
  /** The detail panel open beside the card, as the panel row opens it. */
  panel?: boolean;
}): React.JSX.Element | null {
  const [items] = useState<ChatItem[]>(WINDOW);
  const [anchors, setAnchors] = useState<ChatItem[]>([]);
  const runIdRef = useRef<string | null>('run-1');
  const pageSizeRef = useRef(pageSize);
  const { delegateConversations } = useDelegatePages({
    runIdRef,
    api,
    pageSizeRef,
    commitRows: setAnchors,
  });
  // The chat screen's own fold: the window, the anchors a page brought, and the
  // daemon's reading over both.
  const { entries } = useDurableTranscript({
    items,
    anchors,
    runId: 'run-1',
    taskList: undefined,
    collapseToolSteps: true,
    delegateState: {
      throughSeq: 100,
      delegates: [delegateStateOf({ id: DELEGATE, toolCalls: daemonCalls })],
    },
  });
  const [block] = collectSubagentBlocks(entries);
  if (block === undefined) {
    return null;
  }
  return (
    <DelegateConversationContext.Provider value={delegateConversations}>
      <SubagentBlock block={block} />
      {panel ? (
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={block} chatAgentName="claude" />
        </Dialog>
      ) : null}
    </DelegateConversationContext.Provider>
  );
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

async function settle(): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0));
  });
}

function disclosure(): HTMLButtonElement | null {
  return container.querySelector('button[aria-expanded]');
}

async function open(): Promise<void> {
  await act(async () => {
    disclosure()?.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
  await settle();
}

function olderButton(): HTMLButtonElement | null {
  return container.querySelector('[data-slot="delegate-steps-older-load"]');
}

function windowNote(): string | null | undefined {
  return container.querySelector('[data-slot="subagent-window-note"]')
    ?.textContent;
}

describe('a sub-agent card reads its own earlier steps', () => {
  it('reads the delegate’s newest page when the card is opened', async () => {
    const listRunItems = vi.fn<ChatsApi['listRunItems']>(async () => page([]));
    await act(async () => {
      root.render(
        <Harness api={{ listRunItems }} pageSize={3} daemonCalls={6} />,
      );
    });
    expect(listRunItems).not.toHaveBeenCalled();

    await open();

    expect(listRunItems).toHaveBeenCalledTimes(1);
    expect(listRunItems.mock.calls[0]?.[0]).toEqual({
      runId: 'run-1',
      limit: 3,
      delegate: DELEGATE,
    });
  });

  it('merges the page into the card, states what is still missing, and offers earlier steps', async () => {
    const older = [stepRow(15, 'o-1'), stepRow(16, 'o-2'), stepRow(17, 'o-3')];
    const listRunItems = vi.fn<ChatsApi['listRunItems']>(async () =>
      page(older),
    );
    await act(async () => {
      root.render(
        <Harness api={{ listRunItems }} pageSize={3} daemonCalls={6} />,
      );
    });
    await open();

    expect(windowNote()).toBe('Showing the last 5 of 6 tool calls');
    expect(olderButton()?.textContent).toBe('Show earlier steps');
  });

  it('reads the page before the oldest held, and drops the note once every step is held', async () => {
    const pages = [
      [stepRow(15, 'o-1'), stepRow(16, 'o-2'), stepRow(17, 'o-3')],
      [stepRow(14, 'o-4')],
    ];
    const listRunItems = vi.fn<ChatsApi['listRunItems']>(async () =>
      page(pages.shift() ?? []),
    );
    await act(async () => {
      root.render(
        <Harness api={{ listRunItems }} pageSize={3} daemonCalls={6} />,
      );
    });
    await open();
    await act(async () => {
      olderButton()?.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    await settle();

    expect(listRunItems).toHaveBeenCalledTimes(2);
    expect(listRunItems.mock.calls[1]?.[0]).toEqual({
      runId: 'run-1',
      limit: 3,
      delegate: DELEGATE,
      beforeSeq: 15,
    });
    expect(olderButton()).toBeNull();
    expect(windowNote()).toBeUndefined();
  });

  it('says a failed read failed, and asks again only on a press of Retry', async () => {
    const listRunItems = vi
      .fn<ChatsApi['listRunItems']>()
      .mockRejectedValueOnce(new Error('daemon unreachable'))
      .mockResolvedValueOnce(page([stepRow(16, 'o-2')]));
    await act(async () => {
      root.render(
        <Harness api={{ listRunItems }} pageSize={3} daemonCalls={6} />,
      );
    });
    await open();

    const failed = container.querySelector(
      '[data-slot="delegate-steps-failed"]',
    );
    expect(failed?.textContent).toContain(
      'Couldn’t load this sub-agent’s steps.',
    );
    expect(listRunItems).toHaveBeenCalledTimes(1);

    await act(async () => {
      container
        .querySelector('[data-slot="delegate-steps-failed"] button')
        ?.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    await settle();

    expect(listRunItems).toHaveBeenCalledTimes(2);
    expect(
      container.querySelector('[data-slot="delegate-steps-failed"]'),
    ).toBeNull();
  });
  it('draws the messages an earlier page brings, not only its steps', async () => {
    const reply: ChatItem = {
      ...row(16, 'message', { text: 'older reply', parentToolUseId: DELEGATE }),
      role: 'assistant',
    };
    const listRunItems = vi.fn<ChatsApi['listRunItems']>(async () =>
      page([stepRow(15, 'o-1'), reply, stepRow(17, 'o-3')]),
    );
    await act(async () => {
      root.render(
        <Harness api={{ listRunItems }} pageSize={3} daemonCalls={6} />,
      );
    });
    await open();

    expect(container.textContent).toContain('older reply');
  });
});

describe('a sub-agent panel reads its own earlier steps the card reads', () => {
  it('states what the panel does not hold, offers earlier steps, and reads the newest page', async () => {
    const listRunItems = vi.fn<ChatsApi['listRunItems']>(async () =>
      page([stepRow(15, 'o-1'), stepRow(16, 'o-2'), stepRow(17, 'o-3')]),
    );
    await act(async () => {
      root.render(
        <Harness api={{ listRunItems }} pageSize={3} daemonCalls={6} panel />,
      );
    });
    await settle();

    expect(listRunItems).toHaveBeenCalledTimes(1);
    expect(listRunItems.mock.calls[0]?.[0]).toEqual({
      runId: 'run-1',
      limit: 3,
      delegate: DELEGATE,
    });
    expect(windowNote()).toBe('Showing the last 5 of 6 tool calls');
    expect(olderButton()?.textContent).toBe('Show earlier steps');
  });

  it('reads the page before the oldest held when the panel asks for earlier steps', async () => {
    const pages = [
      [stepRow(15, 'o-1'), stepRow(16, 'o-2'), stepRow(17, 'o-3')],
      [stepRow(14, 'o-4')],
    ];
    const listRunItems = vi.fn<ChatsApi['listRunItems']>(async () =>
      page(pages.shift() ?? []),
    );
    await act(async () => {
      root.render(
        <Harness api={{ listRunItems }} pageSize={3} daemonCalls={6} panel />,
      );
    });
    await settle();
    await act(async () => {
      olderButton()?.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    await settle();

    expect(listRunItems).toHaveBeenCalledTimes(2);
    expect(listRunItems.mock.calls[1]?.[0]).toEqual({
      runId: 'run-1',
      limit: 3,
      delegate: DELEGATE,
      beforeSeq: 15,
    });
    expect(olderButton()).toBeNull();
    expect(windowNote()).toBeUndefined();
  });

  it('reads the delegate once when its card and its panel are open together', async () => {
    const listRunItems = vi.fn<ChatsApi['listRunItems']>(async () =>
      page([stepRow(15, 'o-1')]),
    );
    await act(async () => {
      root.render(
        <Harness api={{ listRunItems }} pageSize={3} daemonCalls={6} panel />,
      );
    });
    await settle();
    await open();

    expect(listRunItems).toHaveBeenCalledTimes(1);
  });
});
