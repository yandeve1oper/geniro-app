import { type RefObject, useMemo, useRef, useState } from 'react';

import type {
  ChatsApi,
  ChatsApiListRunItemsRequest,
  ItemDto as ChatItem,
} from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import type {
  CallConversationLoader,
  CallConversationState,
} from './call-conversation';
import { mergeAnchorRows } from './history-anchors';

/** The part of the daemon's history read that names one conversation. */
export type ConversationFilter = Pick<
  ChatsApiListRunItemsRequest,
  'call' | 'delegate'
>;

export interface ConversationPagesArgs {
  runIdRef: RefObject<string | null>;
  api: Pick<ChatsApi, 'listRunItems'>;
  /** Read at request time; a page is judged full by the size it was asked for. */
  pageSizeRef: RefObject<number>;
  commitRows: (update: (prev: ChatItem[]) => ChatItem[]) => void;
}

const callFilter = (conversation: string): ConversationFilter => ({
  call: conversation,
});

/**
 * Reads one conversation's rows page by page into the rows the caller holds —
 * a conversation is named by `filterOf`, and everything else is the same for a
 * call card and a sub-agent card: the page's rows and anchors merged into the
 * transcript, a failed read parked until asked again, the older page read from
 * the oldest held.
 */
export function useConversationPages({
  runIdRef,
  api,
  pageSizeRef,
  commitRows,
  filterOf,
}: ConversationPagesArgs & {
  filterOf: (conversation: string) => ConversationFilter;
}): {
  loader: CallConversationLoader;
  /** Forget what was read — see {@link useCallPages}. */
  forget: () => void;
} {
  const [pages, setPages] = useState<
    ReadonlyMap<string, CallConversationState>
  >(() => new Map());
  // Written with the state, not after the render: a load asked for in the
  // same tick as a reset must see the reset.
  const pagesRef = useRef(pages);
  const writePages = useLatestCallback(
    (
      update: (
        prev: ReadonlyMap<string, CallConversationState>,
      ) => ReadonlyMap<string, CallConversationState>,
    ): void => {
      const next = update(pagesRef.current);
      pagesRef.current = next;
      setPages(next);
    },
    [],
  );
  /** Moves at every forget, so a read asked for before one cannot land after it. */
  const generationRef = useRef(0);
  const forget = useLatestCallback((): void => {
    generationRef.current += 1;
    writePages(() => new Map());
  }, [writePages]);

  /** The read each conversation has in flight, for a caller that must wait on it. */
  const readsRef = useRef(new Map<string, Promise<void>>());
  const loadPage = useLatestCallback(
    (conversation: string, older: boolean): Promise<void> => {
      const runId = runIdRef.current;
      const held = pagesRef.current.get(conversation);
      if (held?.loading === true) {
        return readsRef.current.get(conversation) ?? Promise.resolve();
      }
      if (
        runId === null ||
        (older ? held?.hasOlder !== true : held !== undefined)
      ) {
        return Promise.resolve();
      }
      const beforeSeq = older ? held?.oldestSeq : null;
      const generation = generationRef.current;
      const current = (): boolean =>
        runIdRef.current === runId && generationRef.current === generation;
      const settle = (next: CallConversationState): void => {
        writePages((prev) => new Map(prev).set(conversation, next));
      };
      settle({
        loading: true,
        failed: false,
        hasOlder: held?.hasOlder ?? false,
        oldestSeq: held?.oldestSeq ?? null,
      });
      const pageSize = pageSizeRef.current;
      const read = api
        .listRunItems({
          runId,
          limit: pageSize,
          ...filterOf(conversation),
          ...(beforeSeq === null || beforeSeq === undefined
            ? {}
            : { beforeSeq }),
        })
        .then(({ items: page, anchors: pageAnchors }) => {
          if (!current()) {
            return;
          }
          // The page's anchors with it: they place what the page names — a
          // tool call above it, a delegate's launch — and, kept with the rows,
          // they outlive a window replaced by a jump.
          commitRows((prev) =>
            mergeAnchorRows(prev, [...page, ...pageAnchors]),
          );
          settle({
            loading: false,
            failed: false,
            hasOlder: page.length === pageSize,
            oldestSeq: page[0]?.seq ?? held?.oldestSeq ?? null,
          });
        })
        .catch(() => {
          if (!current()) {
            return;
          }
          // Parked, never re-asked by itself: the card's pager would otherwise
          // ask again on every render the failure causes. An older page keeps
          // the button it was pressed from.
          settle(
            older && held !== undefined
              ? held
              : {
                  loading: false,
                  failed: true,
                  hasOlder: false,
                  oldestSeq: null,
                },
          );
        })
        .finally(() => {
          if (readsRef.current.get(conversation) === read) {
            readsRef.current.delete(conversation);
          }
        });
      readsRef.current.set(conversation, read);
      return read;
    },
    [api, commitRows, filterOf, pageSizeRef, runIdRef, writePages],
  );
  /**
   * Read a conversation's pages back from its newest until the oldest held
   * reaches `seq` — a jump's way into a card, which keeps the card one stretch
   * from the row it lands on to the conversation's tail, as paging older does.
   * Answers whether `seq` is now held.
   */
  const loadThrough = useLatestCallback(
    async (conversation: string, seq: number): Promise<boolean> => {
      for (;;) {
        const held = pagesRef.current.get(conversation);
        if (held?.loading === true) {
          const inFlight = readsRef.current.get(conversation);
          if (inFlight === undefined) {
            return false;
          }
          await inFlight;
          continue;
        }
        if (held?.failed === true) {
          return false;
        }
        if (held !== undefined) {
          if (
            !held.hasOlder ||
            held.oldestSeq === null ||
            held.oldestSeq <= seq
          ) {
            return true;
          }
        }
        const before = held?.oldestSeq ?? null;
        await loadPage(conversation, held !== undefined);
        const after = pagesRef.current.get(conversation);
        // Nothing moved — the thread was switched or the read refused.
        if (
          after === undefined ||
          after.failed ||
          (held !== undefined && after.oldestSeq === before)
        ) {
          return false;
        }
      }
    },
    [loadPage],
  );

  const load = useLatestCallback(
    (conversation: string, older: boolean): void => {
      void loadPage(conversation, older);
    },
    [loadPage],
  );
  const retry = useLatestCallback(
    (conversation: string): void => {
      writePages((prev) => {
        const next = new Map(prev);
        next.delete(conversation);
        return next;
      });
      void loadPage(conversation, false);
    },
    [loadPage, writePages],
  );
  const stateOf = useLatestCallback(
    (conversation: string): CallConversationState | null =>
      pagesRef.current.get(conversation) ?? null,
    [],
  );
  // A new object at every page-state write, so a reader of `stateOf` re-renders;
  // its functions keep their identity, so a subscriber of `retry` stays put.
  const loader = useMemo<CallConversationLoader>(
    () => ({ load, loadThrough, retry, stateOf }),
    [load, loadThrough, retry, stateOf, pages],
  );

  return { loader, forget };
}

/**
 * Reads call conversations page by page into rows the caller holds: an opened
 * card's in the transcript's structure, the Show all popup's in its own.
 */
export function useCallPages(args: ConversationPagesArgs): {
  callConversations: CallConversationLoader;
  /**
   * Forget what was read, at every place the rows go: a thread opened (the same
   * one again included) or closed, and a window back at the tail, whose return
   * skipped the calls' rows written while it was away. An opened card asks again.
   */
  forgetCallPages: () => void;
} {
  const { loader, forget } = useConversationPages({
    ...args,
    filterOf: callFilter,
  });
  return { callConversations: loader, forgetCallPages: forget };
}
