import { describe, expect, it } from 'vitest';

import type { AgentModel } from '../autogenerated';
import { modelDisplayName } from './model-options';

const MODELS: AgentModel[] = [
  {
    id: 'default',
    label: 'Default (recommended)',
    source: 'cli',
    resolvedModel: 'claude-opus-5-5',
  },
  {
    id: 'opus',
    label: 'Opus 5.5',
    source: 'cli',
    resolvedModel: 'claude-opus-5-5',
  },
  {
    id: 'haiku',
    label: 'Haiku 5.5',
    source: 'cli',
    resolvedModel: 'claude-haiku-5-5',
  },
];

describe('modelDisplayName', () => {
  it('names an alias by its menu label', () => {
    expect(modelDisplayName(MODELS, 'haiku')).toBe('Haiku 5.5');
  });

  it('names a resolved id by the alias that resolves to it, never the default row', () => {
    expect(modelDisplayName(MODELS, 'claude-haiku-5-5')).toBe('Haiku 5.5');
    expect(modelDisplayName(MODELS, 'claude-opus-5-5')).toBe('Opus 5.5');
  });

  it('reads an id the CLI does not list as itself', () => {
    expect(modelDisplayName(MODELS, 'claude-unknown-1')).toBe(
      'claude-unknown-1',
    );
    expect(modelDisplayName([], 'claude-haiku-5-5')).toBe('claude-haiku-5-5');
  });
});
