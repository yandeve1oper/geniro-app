import type { MemoryEntry } from '../autogenerated';
import { Badge } from './ui/badge';

/**
 * Where an entry stands: waiting, forgotten, or — when `indexed` is known —
 * whether every new chat's memory index may list it or only a search finds it.
 */
export function MemoryStatusBadge({
  status,
  indexed,
}: {
  status: MemoryEntry['status'];
  indexed?: boolean;
}): React.JSX.Element | null {
  switch (status) {
    case 'pending':
      return <Badge variant="warning">Waiting for review</Badge>;
    case 'forgotten':
      return <Badge variant="muted">Forgotten</Badge>;
    case 'active':
      if (indexed === undefined) {
        return null;
      }
      return indexed ? (
        <Badge variant="muted">In every chat</Badge>
      ) : (
        <Badge variant="outline">Search only</Badge>
      );
  }
}
