import { MoreHorizontal } from 'lucide-react';
import { useEffect, useRef, useState } from 'react';

import type { MemoryEntry, MemoryTrackRecord } from '../autogenerated';
import { describeDaemonError } from '../daemon-api';
import { ClampedText } from './clamped-text';
import { ConfirmDialog } from './confirm-dialog';
import { forgottenNoteOf, trackLineOf } from './memory-row-text';
import { MemoryStatusBadge } from './memory-status-badge';
import { ProvenanceLine } from './provenance-line';
import { Button } from './ui/button';
import { Menu, type MenuItem } from './ui/menu';
import { cn } from './ui/utils';

/** One more entry of a row's ⋯ menu; a `confirm` asks before `run` fires. */
export interface MemoryRowAction {
  value: string;
  label: string;
  run: () => void | Promise<void>;
  tone?: 'destructive';
  confirm?: {
    question: string;
    description: string;
    confirmLabel: string;
    busyLabel: string;
    destructive?: boolean;
  };
}

/**
 * One shared-memory entry: its title, two lines of its text and one line of
 * where it came from. Approve is the one action drawn on the row, and only for
 * an entry waiting for review; every other action sits in the ⋯ menu, which
 * shows on hover or focus (always on a touch screen).
 */
export function MemoryRow({
  entry,
  projectName,
  teamName = null,
  track,
  focused = false,
  busy = false,
  showStatus = true,
  showReach = false,
  onEdit,
  onForget,
  onRestore,
  onApprove,
  onIndexed,
  forgetDescription = 'Agents no longer see it. It stays restorable under Forgotten.',
  leading,
  details,
  actions = [],
}: {
  entry: MemoryEntry;
  projectName: string | null;
  teamName?: string | null;
  /** How the threads used the entry, from the list's `tracks`; absent where the list carries none. */
  track?: MemoryTrackRecord;
  focused?: boolean;
  busy?: boolean;
  /** Whether a waiting or forgotten entry says so; off where a tab already does. */
  showStatus?: boolean;
  /** Whether an active entry says if every new chat lists it; on where nothing else does. */
  showReach?: boolean;
  onEdit?: () => void;
  onForget?: () => void | Promise<void>;
  onRestore?: () => void;
  onApprove?: () => void;
  /** Move the entry into every new chat's index (true) or to search only (false). */
  onIndexed?: (indexed: boolean) => void;
  /** What the Forget question says will happen. */
  forgetDescription?: string;
  /** Drawn before the row, e.g. a tick for picking it. */
  leading?: React.ReactNode;
  /** Lines under the provenance, e.g. usage figures and why the row is listed. */
  details?: React.ReactNode;
  /** Menu entries after the row's own. */
  actions?: readonly MemoryRowAction[];
}): React.JSX.Element {
  const rowRef = useRef<HTMLDivElement | null>(null);
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const [menuOpen, setMenuOpen] = useState(false);
  const [asking, setAsking] = useState<MemoryRowAction | null>(null);
  const [running, setRunning] = useState(false);
  const [askError, setAskError] = useState<string | null>(null);

  useEffect(() => {
    if (focused) {
      rowRef.current?.scrollIntoView({ block: 'center' });
    }
  }, [focused]);

  const isActive = entry.status === 'active';
  const isLive = isActive || entry.status === 'pending';
  const isForgotten = entry.status === 'forgotten';
  const forgottenNote = isForgotten ? forgottenNoteOf(entry) : null;
  const trackLine = track === undefined ? null : trackLineOf(track);

  const own: MemoryRowAction[] = [
    ...(isActive && onIndexed !== undefined
      ? [
          entry.indexed
            ? {
                value: 'search-only',
                label: 'Search only',
                run: () => onIndexed(false),
              }
            : {
                value: 'index',
                label: 'Load into every chat',
                run: () => onIndexed(true),
              },
        ]
      : []),
    ...(isLive && onEdit !== undefined
      ? [{ value: 'edit', label: 'Edit', run: onEdit }]
      : []),
    ...(isForgotten && onRestore !== undefined
      ? [{ value: 'restore', label: 'Restore', run: onRestore }]
      : []),
    ...(isLive && onForget !== undefined
      ? [
          {
            value: 'forget',
            label: 'Forget…',
            tone: 'destructive' as const,
            run: onForget,
            confirm: {
              question: `Forget ${entry.handle}?`,
              description: forgetDescription,
              confirmLabel: 'Forget',
              busyLabel: 'Forgetting…',
            },
          },
        ]
      : []),
  ];
  const menu = [...own, ...actions];
  const items: MenuItem[] = menu.map(({ value, label, tone }) => ({
    value,
    label,
    tone,
    action: true,
  }));

  const pick = (value: string): void => {
    setMenuOpen(false);
    const chosen = menu.find((action) => action.value === value);
    if (chosen === undefined) {
      return;
    }
    if (chosen.confirm !== undefined) {
      setAskError(null);
      setAsking(chosen);
      return;
    }
    void chosen.run();
  };

  const confirmAsked = async (): Promise<void> => {
    if (asking === null) {
      return;
    }
    setRunning(true);
    try {
      await asking.run();
      setAsking(null);
    } catch (err: unknown) {
      setAskError(describeDaemonError(err));
    } finally {
      setRunning(false);
    }
  };

  return (
    <div
      ref={rowRef}
      data-slot="memory-row"
      data-memory-id={entry.id}
      data-memory-handle={entry.handle}
      data-focused={focused ? '' : undefined}
      className={cn(
        'group/memory-row flex min-w-0 gap-2.5 rounded-md px-2 py-2.5 transition-colors hover:bg-accent/40 focus-within:bg-accent/40',
        focused && 'bg-accent/40 ring-2 ring-ring/60',
      )}>
      {leading}
      <div className="flex min-w-0 flex-1 flex-col gap-1">
        <div className="flex min-w-0 items-start gap-2">
          <span className="min-w-0 flex-1 text-sm font-medium break-words">
            {entry.title}
          </span>
          {(showStatus && !isActive) || (showReach && isActive) ? (
            <MemoryStatusBadge
              status={entry.status}
              indexed={showReach ? entry.indexed : undefined}
            />
          ) : null}
          {entry.status === 'pending' && onApprove !== undefined ? (
            <Button
              type="button"
              size="sm"
              variant="outline"
              disabled={busy}
              className="-my-1 h-7 shrink-0 rounded-control px-2.5 text-xs"
              onClick={onApprove}>
              Approve
            </Button>
          ) : null}
          {menu.length === 0 ? null : (
            <>
              <Button
                ref={triggerRef}
                type="button"
                variant="ghost"
                size="icon"
                disabled={busy}
                aria-label={`Actions for ${entry.handle}`}
                aria-haspopup="menu"
                aria-expanded={menuOpen}
                title="Actions"
                className="-my-1 size-7 shrink-0 rounded-control text-muted-foreground opacity-0 transition-opacity group-hover/memory-row:opacity-100 group-focus-within/memory-row:opacity-100 focus-visible:opacity-100 aria-expanded:opacity-100 pointer-coarse:opacity-100 max-sm:opacity-100 [&_svg]:size-4"
                onClick={() => setMenuOpen((open) => !open)}>
                <MoreHorizontal aria-hidden="true" />
              </Button>
              <Menu
                open={menuOpen}
                align="end"
                side="bottom"
                anchor="viewport"
                triggerRef={triggerRef}
                className="w-52 min-w-0"
                groups={[{ items }]}
                onSelect={pick}
                onClose={() => setMenuOpen(false)}
              />
            </>
          )}
        </div>
        <ClampedText
          text={entry.body}
          lines={2}
          slot="memory-body"
          className="text-sm text-muted-foreground"
        />
        <ProvenanceLine
          entry={entry}
          projectName={projectName}
          teamName={teamName}
          compact
        />
        {forgottenNote === null ? null : (
          <ClampedText
            text={forgottenNote}
            lines={2}
            slot="memory-forget-note"
            className="text-xs text-muted-foreground"
          />
        )}
        {trackLine === null ? null : (
          <p
            data-slot="memory-track"
            className="m-0 text-xs text-muted-foreground">
            {trackLine}
          </p>
        )}
        {details}
      </div>
      {asking?.confirm === undefined ? null : (
        <ConfirmDialog
          open
          busy={running}
          error={askError}
          title={asking.confirm.question}
          confirmLabel={asking.confirm.confirmLabel}
          busyLabel={asking.confirm.busyLabel}
          confirmVariant={
            asking.confirm.destructive === false ? 'default' : 'destructive'
          }
          onCancel={() => setAsking(null)}
          onConfirm={() => void confirmAsked()}>
          {asking.confirm.description}
        </ConfirmDialog>
      )}
    </div>
  );
}
