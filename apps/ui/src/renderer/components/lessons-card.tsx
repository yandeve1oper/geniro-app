/** One proposed lesson as the card draws it. */
export interface LessonView {
  id: string;
  title: string;
  rule: string;
  why: string;
  signalKind: LessonSignalKind;
  evidence: { seq: number; quote: string };
  target: LessonTarget;
  dedup: { verdict: LessonDedupVerdict; handle: string | null };
}

export type LessonOutcomeStatus =
  | 'saved'
  | 'pending'
  | 'rejected'
  | 'undone'
  | 'skipped_duplicate'
  | 'dropped_by_check';

/** The decision on one lesson, as its `lesson_outcome` row states it. */
export interface LessonOutcomeView {
  proposalId: string;
  status: LessonOutcomeStatus;
  by: 'user' | 'auto';
  title: string;
  rule: string | null;
  target: LessonTarget;
  memoryHandle: string | null;
  resultRef: string | null;
  reason: string | null;
}

export interface LessonKnowledgeDocument {
  handle: string;
  title: string;
}

/** The project's active knowledge documents, read when a target picker opens. */
export type LessonDocumentsReader = (
  projectId: string,
) => Promise<readonly LessonKnowledgeDocument[]>;

