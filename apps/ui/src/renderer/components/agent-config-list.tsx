export type AgentStatus = {
  label: string;
  tone: StatusTone;
  /** The probed version, drawn beside the status; null when none answered. */
  version: string | null;
};

/**
 * Readiness of one agent. "Ready" (green) means the binary was detected AND,
 * for a CLI whose own status command was actually asked and answered, it did
 * not say signed-out.
 *
 * `loggedIn === false` is the ONLY thing that renders warn: a CLI that said so
 * itself. `null` — no status command to ask (claude today) or a probe that
 * failed — reads as ready, same as `true`. Treating it as signed-out would
 * tell an already-signed-in user to sign in again, for a fix that would not
 * even address a probe failure.
 */
export function statusFor(
  clis: CliDetection[] | null,
  kind: CliKind,
): AgentStatus {
  if (clis === null) {
    return { label: 'Checking…', tone: 'unknown', version: null };
  }
  const detection = clis.find((c) => c.kind === kind) ?? null;
  if (!detection?.found) {
    // Said as what it means to the user. "not found on PATH" described the
    // lookup, and read as a configuration problem to fix by hand on a machine
    // that simply does not have the CLI — which the card can now install.
    return { label: 'Not installed', tone: 'bad', version: null };
  }
  const version = detection.version ?? null;
  if (detection.loggedIn === false) {
    return { label: 'Not signed in', tone: 'warn', version };
  }
  return { label: 'Ready', tone: 'ok', version };
}

const STATUS_BADGE: Record<StatusTone, string> = {
  ok: 'bg-success/10 text-success',
  warn: 'bg-warning/10 text-warning',
  bad: 'bg-destructive/10 text-destructive',
  unknown: 'bg-muted text-muted-foreground',
};

export interface AgentConfigListProps {
  /** Detection results (null while probing). */
  clis: CliDetection[] | null;
  /** Which agent cards are expanded. */
  open: Partial<Record<CliKind, boolean>>;
  onToggle: (kind: CliKind) => void;
  /** Per-agent binary path override (blank = auto-detect on PATH). */
  binaryPaths: Partial<Record<CliKind, string>>;
  onBinaryPathChange: (kind: CliKind, value: string) => void;
  onBrowse: (kind: CliKind) => void;
  /**
   * Sign one CLI itself back in, in the user's own terminal. Settings-only —
   * onboarding passes nothing, and a card renders no control without it: the
   * decided placement for this action is Settings, not first-run setup.
   */
  onSignIn?: (kind: CliKind) => void;
  /**
   * The CLI whose sign-in has been asked for and not yet answered, or null.
   *
   * The caller's, because the controller is: one sign-in runs at a time across
   * the screen, so a flag kept in here would let two cards each think they own
   * it.
   */
  signingIn?: CliKind | null;
  /**
   * The CLIs whose ACCOUNT is per-config-directory, so this card's row can say
   * which profile it is reporting on. From the daemon's `configDirs[]`
   * capability — see {@link accountRowText}. Absent (onboarding, or before
   * capabilities answer) means no qualifier anywhere, which is the honest
   * rendering rather than a guessed one.
   */
  profileScopedKinds?: ReadonlySet<string>;
  /**
   * Sign one CLI itself OUT, in the user's own terminal. Settings-only, for the
   * reason its sibling is.
   *
   * Separate handler rather than one `onAccountAction(kind, verb)`: the card
   * decides which of the two to OFFER from the detection state, and the two
   * resolve different daemon routes. A single handler would move that choice
   * into the parent, where the detection it depends on is not the parent's to
   * read.
   */
  onSignOut?: (kind: CliKind) => void;
  /**
   * Update one CLI by running its own updater. Settings-only, like the account
   * controls beside it — a card renders no update band without it.
   */
  onUpdate?: (kind: CliKind) => void;
  /** The CLIs whose update is running, as main reports them. */
  updating?: ReadonlySet<CliKind>;
  /**
   * What the last finished update did, per CLI.
   *
   * A record rather than one kind-tagged result, unlike {@link login}: a
   * sign-in panel belongs to the flow that is running, while these outcomes
   * OUTLIVE the press — updating claude and then cursor must not erase what the
   * first card is still reporting.
   */
  updateResults?: Partial<Record<CliKind, CliUpdateResult>>;
  /**
   * Install a CLI this machine does not have, with its vendor's own installer.
   * Offered on BOTH screens — first-run setup is exactly where a missing CLI
   * is met — and drawn only on a card whose CLI was not found.
   */
  onInstall?: (kind: CliKind) => void;
  /** The CLIs whose installer is running — several may run at once. */
  installing?: ReadonlySet<CliKind>;
  /** What the last finished install of each CLI did. */
  installResults?: Partial<Record<CliKind, CliInstallResult>>;
  /**
   * That agent's OWN settings, drawn inside its card — whatever is true of one
   * CLI and of no other.
   *
   * REPORTED as "все специфические, именно к агентам специфичные настройки
   * должны быть там": cursor's Max Mode and claude's browser tools each had a
   * section of their own further down the page, so a reader looking for what
   * they could change about cursor found half of it in the card named cursor
   * and half two screens below, under a heading that named a topic instead.
   *
   * Passed IN rather than built here, which is the rule the daemon's adapters
   * follow as well: this component knows how to draw a card, not what is true
   * of claude. It also keeps onboarding — which shares this list — free of
   * settings that belong to a running app, by simply passing none.
   */
  agentSettings?: Partial<Record<CliKind, React.ReactNode>>;
  /**
   * A sign-in the daemon is running right now, rendered on the card it belongs
   * to. Absent on onboarding, and absent between attempts.
   *
   * The card takes this rather than owning it: polling a daemon route is not a
   * presentational concern, and this component is shared with a screen that has
   * no daemon handle at all.
   */
  login?: {
    kind: CliKind;
    session: LoginSessionDto;
    error: string | null;
    onSubmitCode: (code: string) => void;
    onCancel: () => void;
    onDismiss: () => void;
  } | null;
}

/** How the update row reads, and whether it offers the press. */
export type CliUpdateRow = {
  text: string;
  tone: 'ok' | 'news' | 'muted' | 'bad';
  /** Draw the Update button — there is something a press could achieve. */
  offer: boolean;
};

const UPDATE_TEXT: Record<CliUpdateRow['tone'], string> = {
  ok: 'text-success',
  news: 'text-update',
  muted: 'text-muted-foreground',
  bad: 'text-destructive',
};

/**
 * What one card says about updating that CLI, from the check and the last run.
 *
 * A pure function over the two facts, because the interesting part is not the
 * layout but WHICH STATES OFFER A PRESS, and the answer is not "whenever an
 * update exists":
 *
 * - **A CLI that could not be asked still offers it** (`available: null`).
 *   claude has no check that stops short of installing, so its `update` IS the
 *   check — hiding the button until something told us a version was waiting
 *   would mean nothing ever could. The row says so in the CLI's stead.
 * - **A CLI that answered "up to date" does not.** That is the app's own rule
 *   about controls with nothing behind them, which cost an inert `no effort
 *   control` chip its place in the composer; re-asking is what `Re-check` above
 *   the list already does, and it re-runs this very probe.
 * - **A finished update does not**, whatever the pre-press check said — that
 *   reading is now stale by exactly one install.
 * - **A FAILED one does**, because a retry is the obvious next move and the
 *   failure sentence is beside it.
 *
 * The success wording is derived from the two version READS rather than from
 * the updater's output (see `runCliUpdate`), so it claims a new version only
 * when the binary itself answered differently afterwards — and claims nothing
 * at all when either read failed, which is what `Update finished` is for.
 */
export function cliUpdateRow(
  update: CliUpdateState,
  result: CliUpdateResult | undefined,
): CliUpdateRow {
  if (result) {
    if (!result.ok) {
      return { text: 'Update failed', tone: 'bad', offer: true };
    }
    if (result.version === null || result.previousVersion === null) {
      // The updater exited cleanly and one of the two reads did not land, so
      // there is no comparison to report. Saying "already on the latest" here
      // would be a claim nothing measured.
      return { text: 'Update finished', tone: 'muted', offer: false };
    }
    return result.version === result.previousVersion
      ? { text: 'Already on the latest version', tone: 'muted', offer: false }
      : { text: `Updated to ${result.version}`, tone: 'ok', offer: false };
  }
  if (update.available === true) {
    return {
      text: update.latestVersion
        ? `Update available · ${update.latestVersion}`
        : 'Update available',
      tone: 'news',
      offer: true,
    };
  }
  if (update.available === false) {
    return { text: 'Up to date', tone: 'muted', offer: false };
  }
  return {
    text:
      update.checkUnavailableReason ??
      'Could not check whether a newer version exists.',
    tone: 'muted',
    offer: true,
  };
}

/**
 * The update band, between what identifies the binary and how it behaves —
 * because an update is a fact about the BINARY, and the card reads top-to-bottom
 * as which binary, how it behaves, whose account.
 *
 * Nothing is drawn without `onUpdate` (onboarding passes none: an out-of-date
 * CLI is not a setup step) or on a CLI that was not found, where the header
 * already says so and a press would run a binary that is not there.
 */
function CliUpdateBand({
  kind,
  update,
  result,
  updating,
  onUpdate,
}: {
  kind: CliKind;
  update: CliUpdateState;
  result: CliUpdateResult | undefined;
  /** True while THIS card's update is running. */
  updating: boolean;
  onUpdate: (kind: CliKind) => void;
}): React.JSX.Element {
  const row = cliUpdateRow(update, result);
  const failure = result?.ok === false ? result : null;
  return (
    <div className="flex items-center justify-between gap-3">
      <div className="flex min-w-0 flex-col gap-0.5">
        <span className={cn('text-sm', UPDATE_TEXT[row.tone])}>{row.text}</span>
        {failure?.reason ? (
          // WHY, on the card itself: "Update failed" with the reason only on
          // hover was reported as no reason at all. The updater's whole
          // output stays reachable on hover for a bug report.
          <span
            data-slot="update-failure-reason"
            className="text-xs break-words text-muted-foreground"
            title={failure.output ?? undefined}>
            {failure.reason}
          </span>
        ) : null}
      </div>
      {row.offer || updating ? (
        // Disabled as well as spinning, on the sign-in button's reasoning one
        // band down: a second press would run a second installer over the files
        // the first is writing.
        <Button
          type="button"
          variant={row.tone === 'news' ? 'update' : 'outline'}
          size="sm"
          className="shrink-0"
          disabled={updating}
          onClick={() => onUpdate(kind)}>
          {updating ? (
            <Loader2 aria-hidden="true" className="size-3.5 animate-spin" />
          ) : (
            <Download className="size-3.5" />
          )}
          {updating ? 'Updating…' : 'Update'}
        </Button>
      ) : null}
    </div>
  );
}

/**
 * The install band — the first thing on the card of a CLI this machine does
 * not have, because installing it is the one thing to do there. The binary
 * path field under it stays, as the way to point at a copy installed somewhere
 * detection does not look.
 */
function CliInstallBand({
  kind,
  result,
  installing,
  onInstall,
}: {
  kind: CliKind;
  result: CliInstallResult | undefined;
  /** True while THIS card's installer is running. */
  installing: boolean;
  onInstall: (kind: CliKind) => void;
}): React.JSX.Element {
  const failure = result?.ok === false ? result : null;
  return (
    <div
      data-slot="cli-install"
      className="flex items-center justify-between gap-3">
      <div className="flex min-w-0 flex-col gap-0.5">
        <span className="text-sm text-foreground">
          {installing
            ? `Installing ${kind} — this can take a few minutes.`
            : failure
              ? 'Install failed'
              : `${kind} is not installed on this Mac.`}
        </span>
        {failure?.reason && !installing ? (
          <span
            data-slot="install-failure-reason"
            className="text-xs break-words text-destructive"
            title={failure.output ?? undefined}>
            {failure.reason}
          </span>
        ) : null}
      </div>
      {/* Disabled as well as spinning, on the Update button's reasoning: a
          second press would run a second installer over the first one's files. */}
      <Button
        type="button"
        size="sm"
        className="shrink-0"
        disabled={installing}
        onClick={() => onInstall(kind)}>
        {installing ? (
          <Loader2 aria-hidden="true" className="size-3.5 animate-spin" />
        ) : (
          <Download className="size-3.5" />
        )}
        {installing ? 'Installing…' : failure ? 'Retry' : 'Install'}
      </Button>
    </div>
  );
}

/**
 * What this card's account row is TALKING ABOUT, and the state it is in.
 *
 * The scope prefix is the fix for a real ambiguity: this row's probe and its
 * button both run with no config directory, so they are about the CLI's DEFAULT
 * profile — while a chat can run under a different one, on a different
 * subscription. Unqualified, the row claimed to speak for an account it had
 * never asked about: a user whose chats all run under `~/profiles/work` would
 * read "not signed in" beside runs that were working perfectly.
 *
 * `profileScoped` is per CLI and comes from the daemon's own
 * `configDirs[].unavailableReason`, never from a name: a CLI that cannot run
 * under another account has exactly one, and "Default profile" would invent a
 * distinction it does not have. Unknown — onboarding, or capabilities not yet answered — is
 * treated as NOT scoped: at first run there are no profiles to distinguish, and
 * a prefix is worse than none if it might be wrong.
 *
 * Composed from a scope and a clause rather than written out per combination:
 * three states times two scopes times "is there a handler" is an eight-arm
 * matrix, and the arms that had to agree are exactly the ones a reader would
 * skim past.
 */
function accountRowText({
  kind,
  loggedIn,
  profileScoped,
  canSignIn,
}: {
  kind: CliKind;
  loggedIn: boolean | null;
  profileScoped: boolean;
  canSignIn: boolean;
}): string {
  const clause =
    loggedIn === false
      ? // Signed out with no control is REACHABLE, not theoretical: the sign-in
        // lives on Settings only, and Onboarding — which auto-expands a card
        // that is not ready — passes no handler. Naming where the cure is keeps
        // that screen from being a dead end without moving the control.
        canSignIn
        ? 'not signed in'
        : 'not signed in — sign in from Settings once setup is done'
      : loggedIn === true
        ? `signed in through the ${kind} CLI`
        : // No answer yet, or a CLI that cannot be asked. Says the one thing a
          // user hunting for an API key field needs to know, which is why this
          // wording survives from the row's first version.
          `signs in through the ${kind} CLI itself — no key to enter here`;
  return profileScoped
    ? `Default profile · ${clause}`
    : clause.charAt(0).toUpperCase() + clause.slice(1);
}

/**
 * The list of per-agent configuration cards — the single implementation shared
 * by onboarding and Settings, so both surfaces show detection state and
 * binary-path overrides identically. Fully controlled: the parent owns all
 * state and decides how a change is persisted (completeOnboarding vs.
 * updateSettings).
 */
export function AgentConfigList({
  clis,
  open,
  onToggle,
  binaryPaths,
  onBinaryPathChange,
  onBrowse,
  onSignIn,
  onSignOut,
  signingIn = null,
  onUpdate,
  updating,
  updateResults,
  onInstall,
  installing,
  installResults,
  profileScopedKinds,
  login,
  agentSettings,
}: AgentConfigListProps): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  return (
    <div className="flex flex-col gap-3">
      {CLI_KINDS.map((kind) => {
        const detection = clis?.find((c) => c.kind === kind) ?? null;
        const status = statusFor(clis, kind);
        const isOpen = Boolean(open[kind]);
        const pathId = `agent-path-${kind}`;
        const found = Boolean(detection?.found);
        // Only one sign-in runs at a time, so at most one card shows a panel.
        const cardLogin = login?.kind === kind ? login : null;
        // Offered once detection has ANSWERED: while it is still running a
        // card has not been found yet either, and an Install button flashing
        // on every card during the first second would be a lie on most of them.
        const offerInstall = Boolean(onInstall) && clis !== null && !found;
        return (
          <CollapsibleCard
            key={kind}
            open={isOpen}
            onToggle={() => onToggle(kind)}
            header={
              <>
                {/* Named by the published identity; the body below keeps
                    saying `kind` because those lines are about the binary. */}
                <span
                  data-slot="agent-name"
                  className="flex min-w-0 items-center gap-3 font-medium">
                  <span className="flex size-8 shrink-0 items-center justify-center rounded-lg bg-secondary text-secondary-foreground">
                    <AgentGlyph icon={agentIconName(identities, kind)} />
                  </span>
                  {agentShortName(identities, kind)}
                </span>
                <span className="flex min-w-0 flex-1 items-center justify-end gap-3">
                  {status.version ? (
                    <span className="truncate text-xs text-muted-foreground">
                      {status.version}
                    </span>
                  ) : null}
                  {found &&
                  onUpdate &&
                  detection &&
                  (updating?.has(kind) === true ||
                    cliUpdateRow(detection.update, updateResults?.[kind])
                      .tone === 'news') ? (
                    <Badge
                      data-slot="update-available"
                      className="shrink-0 rounded-full border-transparent bg-update/10 text-update">
                      {updating?.has(kind) === true
                        ? 'Updating…'
                        : 'Update available'}
                    </Badge>
                  ) : null}
                  <Badge
                    className={cn(
                      'gap-1.5 rounded-full border-transparent',
                      STATUS_BADGE[status.tone],
                    )}>
                    <StatusDot tone={status.tone} className="size-1.5" />
                    {status.label}
                  </Badge>
                </span>
              </>
            }>
            {offerInstall && onInstall ? (
              <CliInstallBand
                kind={kind}
                result={installResults?.[kind]}
                installing={installing?.has(kind) === true}
                onInstall={onInstall}
              />
            ) : null}
            <Field
              label={offerInstall ? 'Binary path (optional)' : 'Binary path'}
              htmlFor={pathId}
              hint={
                found
                  ? 'Detected here — edit to pin a different binary.'
                  : offerInstall
                    ? `Already have ${kind} somewhere else? Point at it instead.`
                    : `Set the full path to the ${kind} binary.`
              }>
              <div className="flex gap-2">
                <Input
                  id={pathId}
                  type="text"
                  placeholder="Auto-detect on PATH"
                  value={binaryPaths[kind] ?? ''}
                  onChange={(event) =>
                    onBinaryPathChange(kind, event.target.value)
                  }
                />
                <Button
                  type="button"
                  variant="outline"
                  onClick={() => onBrowse(kind)}>
                  Browse…
                </Button>
              </div>
            </Field>

            {found && onUpdate && detection ? (
              <CliUpdateBand
                kind={kind}
                update={detection.update}
                result={updateResults?.[kind]}
                updating={updating?.has(kind) === true}
                onUpdate={onUpdate}
              />
            ) : null}

            {/* This agent's own settings, between what identifies the binary
                and what says who is signed in — the card reads top-to-bottom
                as which binary, how it behaves, whose account. */}
            {agentSettings?.[kind] ?? null}

            {/* A card FOOTER, not a tinted panel. This used to be a `NoteBox`
                inside the card, which put a box in a box and set a bordered
                button on a filled ground — grey on grey, with the control's own
                fill fighting the panel's. The account state is a property of the
                whole card, so it reads as a band across its foot: the card's own
                background, one hairline rule, and the flat control weight this
                screen already uses for `Re-check`.

                `-mx-4 -mb-4` bleeds through the body's padding so the rule spans
                the full card width; `px-4` puts the content back on the body's
                own gutter. */}
            <div
              className={cn(
                '-mx-4 flex items-center justify-between gap-3 border-t border-border px-4 py-2.5',
                // The bottom bleed belongs to whichever band is LAST. With a
                // login panel open, that is the panel — keeping it here would
                // leave the panel outside the card's rounded corner.
                cardLogin === null && '-mb-4',
              )}>
              <span
                className={cn(
                  'text-sm',
                  // Signed out is the one state that asks something of the user,
                  // so it carries the same warn tone as the header's own dot
                  // rather than sitting in muted text beside it.
                  detection?.loggedIn === false
                    ? 'text-warning'
                    : 'text-muted-foreground',
                )}>
                {accountRowText({
                  kind,
                  loggedIn: detection?.loggedIn ?? null,
                  profileScoped: profileScopedKinds?.has(kind) === true,
                  canSignIn: onSignIn !== undefined,
                })}
              </span>
              {/* `found` matters as much as the handler: the daemon resolves an
                  account target from the bare CLI name without checking it
                  exists, so offering either of these on a card that already says
                  "not installed" opens a terminal that answers `command not
                  found`, where no in-app error can reach the user. */}
              {/* Withheld while THIS card's sign-in is RUNNING: the panel below
                  owns the flow, and a live Sign in button beside it would start a
                  second browser challenge that invalidates the first. A panel
                  left up after the flow ENDED owns nothing, so the button comes
                  back — hiding it until Dismiss left the card with no account
                  control after every sign-in. */}
              {found &&
              (cardLogin === null || isLoginOver(cardLogin.session)) ? (
                <AccountButton
                  loggedIn={detection?.loggedIn ?? null}
                  signingIn={signingIn === kind}
                  onSignIn={onSignIn ? () => onSignIn(kind) : undefined}
                  onSignOut={onSignOut ? () => onSignOut(kind) : undefined}
                />
              ) : null}
            </div>
            {cardLogin !== null ? (
              <div className="-mb-4">
                <CliLoginProgress
                  session={cardLogin.session}
                  error={cardLogin.error}
                  onSubmitCode={cardLogin.onSubmitCode}
                  onCancel={cardLogin.onCancel}
                  onDismiss={cardLogin.onDismiss}
                />
              </div>
            ) : null}
          </CollapsibleCard>
        );
      })}
    </div>
  );
}
