import { Check, Loader2, TriangleAlert } from 'lucide-react';
import { useState } from 'react';

import type { LoginSessionDto } from '../autogenerated';
import { isRemoteRuntime } from '../remote/remote-session';
import type { CliLoginController } from '../use-cli-login';
import { CopyButton } from './copy-button';
import { Button } from './ui/button';
import { Input } from './ui/input';
import { cn } from './ui/utils';

/**
 * What the panel draws from — an agent CLI's sign-in (`LoginSessionDto`) or a
 * share destination's (`ShareSignInSessionDto`, which also ends `timed-out`).
 */
export interface LoginProgressSession {
  status: LoginSessionDto['status'] | 'timed-out';
  url: string | null;
  message: string | null;
}

/**
 * A sign-in happening IN the app, on the agent card that started it.
 *
 * It exists because the sign-in stopped opening a terminal: the terminal window
 * was the progress display, and removing it without replacing it would leave a
 * button that appears to do nothing while a browser tab opens somewhere behind
 * the app. This is that display.
 *
 * Four states, and each earns its place:
 * - `waiting` — the CLI is up and the browser round-trip is unfinished. Carries
 *   the link as a COPYABLE fallback, never auto-opened again: the CLI already
 *   opened the browser itself, and a second tab on the same challenge is a
 *   reliable way to invalidate the first.
 * - `needs_code` — the CLI asked for a pasted code (claude does; cursor polls and
 *   never reaches this). The field appears only here, so it can never be a dead
 *   input in front of a CLI that wants nothing.
 * - `succeeded` / `failed` / `cancelled` — over. Says so briefly; the card's own
 *   status line is the authority on whether the user ended up signed in, because
 *   it comes from re-asking the CLI rather than from an exit code.
 *
 * What "over" MEANS differs by {@link scope}, and getting that wrong is what put
 * "Sign-in finished" above a row still offering a Sign in button: an account
 * sign-in ends here, a server sign-in has only been handed to the browser.
 */
export function CliLoginProgress({
  session,
  onSubmitCode,
  onCancel,
  onDismiss,
  error,
  variant = 'band',
  scope = 'account',
  remote = isRemoteRuntime(),
  cancelRef,
}: {
  session: LoginProgressSession;
  onSubmitCode: (code: string) => void;
  onCancel: () => void;
  onDismiss: () => void;
  error: string | null;
  /**
   * Where this is standing, which decides its EDGES and nothing else.
   *
   * `band` is the original and still the default: a full-bleed strip across
   * the foot of a card, which is what the agent card wants and why the
   * negative margin is there — it cancels the card's own `px-4` so the rule
   * reaches both edges.
   *
   * `inline` is a line sitting among rows, and the negative margin is exactly
   * wrong there: REPORTED as "I have broken UI" against the MCP dialog, where
   * this rendered inside a narrower container and pulled itself 16px past both
   * of its sides, taking the pasted-code field off the edge with it.
   *
   * It is also QUIETER, which is the second half of that report ("make it
   * smaller and without background"). It first landed here as a tinted,
   * bordered box at the band's own type size, and that made a status line
   * heavier than the servers it belongs to — a box drawn around one sentence,
   * in a panel whose content is a list of rows. Inline it is a row: the row's
   * own 12px, the row's own glyph size, no fill and no frame. Nothing about
   * WHAT it says changes with the variant — only its weight.
   */
  variant?: 'band' | 'inline';
  /**
   * WHAT is being signed in, which decides what a clean exit means.
   *
   * An ACCOUNT sign-in finishes here: the CLI asks for the pasted code, checks
   * it, and exits — so `succeeded` is the user being signed in.
   *
   * A SERVER sign-in does not. `claude mcp login <name>` hands the
   * authorization to the browser and exits 0 AT ONCE, and its own closing line
   * says the connector "will be available the next time you start Claude Code"
   * — probe-verified on 2.1.237, exit 0 in under a second with nothing
   * authorized. The daemon's status is honest about being a claim about the
   * COMMAND (`cli-auth.service.ts`), and this component turned that into
   * "Sign-in finished" the instant the press returned. REPORTED as "I can see
   * sign in finished, but its still asking to sign in" — the row underneath was
   * right and this line was not.
   */
  scope?: 'account' | 'server' | 'share';
  /** The Cancel / Dismiss button, for a caller that moves focus onto it. */
  cancelRef?: React.Ref<HTMLButtonElement>;
  /**
   * Whether this panel is on a DIFFERENT device from the CLI — a phone over the
   * LAN gateway. Defaults to asking the runtime; a prop so a spec can say which.
   *
   * It decides what the code field MEANS, which is the whole of "it's just
   * asking for code, but I don't have one — it should be automatic". claude
   * prints `Paste code here if prompted >` on EVERY sign-in, whether or not a
   * code will ever be needed: it opens the browser itself with a link that
   * completes on a localhost callback, and the code is only the fallback for a
   * browser that could not reach that callback. So on the Mac the field is
   * optional and the instruction is to finish in the browser. On a phone it is
   * the opposite: the CLI opened the MAC's browser, the callback is the Mac's
   * localhost, and the only route that works from here is the link below — which
   * ends on a page that shows a code to paste.
   */
  remote?: boolean;
}): React.JSX.Element {
  const [code, setCode] = useState('');
  const over =
    session.status === 'succeeded' ||
    session.status === 'failed' ||
    session.status === 'cancelled' ||
    session.status === 'timed-out';
  const band = variant === 'band';
  // One place the two weights are decided, so a later edit cannot make the
  // glyph small and leave the words large.
  const glyph = band ? 'size-4 shrink-0' : 'size-3.5 shrink-0';
  const control = band ? undefined : 'h-5 px-1.5 text-[11px]';
  const title = headline(session, scope, remote);
  // The CLI's own last line, when it says more than the headline ("Sign-in
  // timed out." under "Not shared — sign-in timed out" says nothing). Held
  // back while a code is asked for: the headline is already the instruction.
  const message =
    session.message !== null &&
    session.status !== 'needs_code' &&
    !restates(title, session.message)
      ? session.message
      : null;

  return (
    <div
      data-slot="cli-login-progress"
      className={cn(
        'flex flex-col',
        band
          ? '-mx-4 gap-2 border-t border-border bg-muted/40 px-4 py-3'
          : 'gap-1 px-1.5 py-1',
      )}>
      <div
        className={cn(
          'flex items-center',
          band ? 'gap-2 text-sm' : 'gap-1.5 text-xs',
        )}>
        {over ? (
          session.status === 'succeeded' ? (
            <Check aria-hidden="true" className={cn(glyph, 'text-success')} />
          ) : (
            <TriangleAlert
              aria-hidden="true"
              className={cn(glyph, 'text-warning')}
            />
          )
        ) : (
          <Loader2
            aria-hidden="true"
            className={cn(glyph, 'animate-spin text-muted-foreground')}
          />
        )}
        <span
          className={cn(
            'shrink-0 whitespace-nowrap',
            session.status === 'succeeded'
              ? 'text-foreground'
              : 'text-muted-foreground',
          )}>
          {title}
        </span>
        {/* Inline, the CLI's line and an error stay on the headline's row,
            cut to fit with the whole text on hover: a status among rows is
            one line, never a block. */}
        {!band && message !== null ? (
          <span
            className="min-w-0 truncate text-muted-foreground"
            title={message}>
            — {message}
          </span>
        ) : null}
        {!band && error !== null ? (
          <span className="min-w-0 truncate text-destructive" title={error}>
            {error}
          </span>
        ) : null}
        <div className="ml-auto flex shrink-0 items-center gap-1">
          {/* Also while a SERVER sign-in is `verifying`: the CLI exited having
              opened the MAC's browser, so on a phone this link is the only way
              to the provider's page at all. */}
          {session.url !== null && !over ? (
            <>
              {/* Opening it is the USER's press, never automatic. The CLI has
                  already opened a tab on this same challenge, and a second one
                  raised on their behalf is a reliable way to invalidate the
                  first — but a browser that did not open, or opened in the
                  wrong profile, leaves them with a copy control and no way to
                  act on it, which is the gap this closes. `window.open` is
                  routed to the OS browser by main's own scheme-checked
                  `setWindowOpenHandler`, so this needs no channel of its own. */}
              <Button
                type="button"
                variant="ghost"
                size="sm"
                className={cn('text-muted-foreground', control)}
                title="Open the sign-in page in your browser"
                onClick={() => window.open(session.url ?? '', '_blank')}>
                Open
              </Button>
              <CopyButton text={session.url} label="Copy sign-in link" />
            </>
          ) : null}
          <Button
            ref={cancelRef}
            type="button"
            variant="ghost"
            size="sm"
            className={cn('text-muted-foreground', control)}
            onClick={over ? onDismiss : onCancel}>
            {over ? 'Dismiss' : 'Cancel'}
          </Button>
        </div>
      </div>

      {session.status === 'needs_code' ? (
        <form
          className="flex items-center gap-2"
          onSubmit={(event) => {
            event.preventDefault();
            if (code.trim() !== '') {
              onSubmitCode(code);
              setCode('');
            }
          }}>
          <Input
            type="text"
            // `aria-label` rather than a visible one: the headline above already
            // says what to paste, and a second label would repeat it.
            aria-label="Sign-in code from the browser"
            placeholder={
              remote
                ? 'Paste the code from the sign-in page'
                : 'Browser shows a code? Paste it here'
            }
            className={cn(band ? undefined : 'h-7 text-xs')}
            value={code}
            onChange={(event) => setCode(event.target.value)}
            // Only where the code is the way through. On the Mac the browser
            // usually finishes by itself, and a focused field reads as the step
            // the user is waiting on.
            autoFocus={remote}
          />
          <Button
            type="submit"
            variant="outline"
            size="sm"
            className={cn('shrink-0', control)}
            disabled={code.trim() === ''}>
            Submit
          </Button>
        </form>
      ) : null}

      {band && message !== null ? (
        <p className="text-xs text-muted-foreground">{message}</p>
      ) : null}
      {band && error !== null ? (
        <p className="text-xs text-destructive">{error}</p>
      ) : null}
    </div>
  );
}

/** Whether the CLI's line only repeats what the headline already ends with. */
function restates(title: string, message: string): boolean {
  const letters = (text: string): string =>
    text.toLowerCase().replace(/[^a-z0-9]/g, '');
  const said = letters(message);
  return said !== '' && letters(title).endsWith(said);
}

function headline(
  session: LoginProgressSession,
  scope: 'account' | 'server' | 'share',
  remote: boolean,
): string {
  switch (session.status) {
    case 'needs_code':
      // NOT "paste the code": the CLI prints its code prompt on every sign-in,
      // and on the Mac the browser normally completes without one.
      return remote
        ? 'Open the sign-in page, sign in, then paste the code it shows'
        : 'Finish signing in in your browser';
    case 'verifying':
      // A share's CLI has signed in and the daemon is checking it, then
      // sharing what waited.
      if (scope === 'share') {
        return 'Signed in — sharing…';
      }
      // The CLI has exited, but a server is signed in only once the daemon has
      // SEEN it connect — it is re-checking it now.
      return 'Finish signing in in your browser — checking the connection…';
    case 'succeeded':
      // For a server this is an observed connect, never just a command that
      // exited — the daemon reports `verifying` until it sees one.
      return scope === 'server'
        ? 'Signed in — connected'
        : scope === 'share'
          ? 'Signed in'
          : 'Sign-in finished';
    case 'failed':
      return scope === 'share'
        ? 'Not shared — sign-in did not complete'
        : 'Sign-in did not complete';
    case 'cancelled':
      return scope === 'share'
        ? 'Not shared — sign-in cancelled'
        : 'Sign-in cancelled';
    case 'timed-out':
      return scope === 'share'
        ? 'Not shared — sign-in timed out'
        : 'Sign-in timed out';
    case 'waiting':
      return 'Waiting for you to finish in the browser…';
    default: {
      const unhandled: never = session.status;
      return unhandled;
    }
  }
}

/** A server's sign-in in flight, drawn under the row that started it; nothing while none is. */
export function CliServerLoginProgress({
  login,
}: {
  login: CliLoginController;
}): React.JSX.Element | null {
  if (login.login === null || login.login.server === null) {
    return null;
  }
  return (
    <CliLoginProgress
      session={login.login.session}
      onSubmitCode={(code) => void login.submitCode(code)}
      onCancel={() => void login.cancel()}
      onDismiss={login.dismiss}
      error={login.error}
      variant="inline"
      scope="server"
    />
  );
}
