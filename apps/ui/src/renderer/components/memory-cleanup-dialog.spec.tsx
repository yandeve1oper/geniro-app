// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type { MemoryForgetBatch } from '../autogenerated';
import {
  batchLabel,
  BatchSummary,
  passLabel,
  passTitles,
} from './memory-cleanup-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

function batch(over: Partial<MemoryForgetBatch> = {}): MemoryForgetBatch {
  return {
    batchId: 'batch-1',
    count: 3,
    forgottenAt: new Date().toISOString(),
    automatic: false,
    kind: 'manual',
    title: null,
    reason: null,
    purgeAt: null,
    ...over,
  };
}

describe('passLabel and passTitles', () => {
  const at = new Date(Date.now() - 2 * 60 * 60 * 1000).toISOString();
  const purgeAt = new Date(
    Date.parse(at) + 30 * 24 * 60 * 60 * 1000,
  ).toISOString();

  it('counts a pass by who forgot its entries, and names no part it has none of', () => {
    const marks = [
      batch({ kind: 'marks', count: 1, forgottenAt: at, purgeAt }),
      batch({ kind: 'marks', count: 1, forgottenAt: at, purgeAt }),
    ];

    expect(passLabel(marks)).toMatch(
      /^Forgot 2 entries in one pass · 2h ago · 2 by agents' marks · deleted for good on [A-Z][a-z]{2} \d{1,2}$/,
    );
  });

  it('names an expired lesson in the singular and in the plural', () => {
    const lesson = batch({
      kind: 'expired_lesson',
      count: 1,
      forgottenAt: at,
      purgeAt,
    });

    expect(passLabel([lesson])).toContain('· 1 auto lesson nobody confirmed');
    expect(passLabel([lesson, { ...lesson, batchId: 'b2' }])).toContain(
      '· 2 auto lessons nobody confirmed',
    );
  });

  it('leaves the deleted-for-good clause out when the batches do not share one purge date', () => {
    const label = passLabel([
      batch({ kind: 'marks', count: 1, forgottenAt: at, purgeAt: null }),
      batch({ kind: 'expired_lesson', count: 1, forgottenAt: at, purgeAt }),
    ]);

    expect(label).toContain("1 by agents' marks");
    expect(label).not.toContain('deleted for good');
  });

  it('lists the titles in order, and reads an untitled batch as its entry count', () => {
    expect(
      passTitles([
        batch({ title: 'Use pnpm' }),
        batch({ title: null, count: 2 }),
      ]),
    ).toBe('Use pnpm · 2 entries');
  });
});

describe('batchLabel', () => {
  it('keeps the line a manual and an automatic cleanup always had', () => {
    expect(batchLabel(batch())).toMatch(/^Forgot 3 entries · /);
    expect(
      batchLabel(batch({ kind: 'automatic', automatic: true, count: 1 })),
    ).toMatch(/^Automatic cleanup · Forgot 1 entry · /);
  });

  it("names a marks cleanup by its entry's title, or by how many entries it forgot", () => {
    expect(
      batchLabel(batch({ kind: 'marks', title: 'Invoice template' })),
    ).toBe("Forgotten by agents' marks — Invoice template");
    expect(batchLabel(batch({ kind: 'marks', title: null, count: 2 }))).toBe(
      "Forgotten by agents' marks — 2 entries",
    );
  });

  it('names an expired-lesson cleanup with its count and when it happened', () => {
    expect(
      batchLabel(batch({ kind: 'expired_lesson', count: 5, reason: 'x' })),
    ).toMatch(/^Auto lessons nobody confirmed in 90 days · 5 entries · /);
  });

  it('appends the day a batch is deleted for good', () => {
    expect(
      batchLabel(
        batch({
          kind: 'marks',
          title: 'Invoice template',
          purgeAt: '2026-12-12T12:00:00.000Z',
        }),
      ),
    ).toBe(
      "Forgotten by agents' marks — Invoice template · deleted for good on Dec 12",
    );
  });
});

describe('BatchSummary', () => {
  it('draws the batch reason, clamped, under its line', () => {
    container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
    act(() => {
      root!.render(
        <BatchSummary
          batch={batch({
            kind: 'marks',
            title: 'Invoice template',
            reason: '2 threads marked it not useful',
          })}
        />,
      );
    });

    const reason = container.querySelector('[data-slot="memory-batch-reason"]');
    expect(reason?.textContent).toBe('2 threads marked it not useful');
    expect(container.textContent).toContain(
      "Forgotten by agents' marks — Invoice template",
    );
  });

  it('draws no reason line for a batch that gave none', () => {
    container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
    act(() => {
      root!.render(<BatchSummary batch={batch()} />);
    });

    expect(
      container.querySelector('[data-slot="memory-batch-reason"]'),
    ).toBeNull();
  });

  it('draws no reason line for an expired-lesson cleanup, whose line already says why', () => {
    container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
    act(() => {
      root!.render(
        <BatchSummary
          batch={batch({
            kind: 'expired_lesson',
            count: 2,
            reason: 'An auto lesson no thread marked helped in 90 days',
          })}
        />,
      );
    });

    expect(
      container.querySelector('[data-slot="memory-batch-reason"]'),
    ).toBeNull();
  });
});
