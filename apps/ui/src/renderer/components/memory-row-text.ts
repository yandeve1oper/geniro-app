import type { MemoryEntry, MemoryTrackRecord } from '../autogenerated';

/** `Dec 15`, in the reader's time zone: the day a forgotten entry is deleted for good. */
export function purgeDayOf(purgeAt: string): string {
  return new Date(purgeAt).toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
  });
}

/** `deleted for good on Dec 15`, the clause a forgotten entry or its batch ends with. */
export function deletedForGood(purgeAt: string): string {
  return `deleted for good on ${purgeDayOf(purgeAt)}`;
}

/** The reason a forgotten entry was given and its purge date, or null when it has neither. */
export function forgottenNoteOf(
  entry: Pick<MemoryEntry, 'forgetReason' | 'purgeAt'>,
): string | null {
  if (entry.purgeAt === null) {
    return entry.forgetReason;
  }
  if (entry.forgetReason === null) {
    return `Deleted for good on ${purgeDayOf(entry.purgeAt)}`;
  }
  return `${entry.forgetReason} · ${deletedForGood(entry.purgeAt)}`;
}

function runs(n: number): string {
  return `${n} ${n === 1 ? 'run' : 'runs'}`;
}

/**
 * How the agents' threads used an entry: `Shown in 3 runs · read 2 · helped 1 ·
 * not useful 0`, or null while none of the four figures is above zero.
 */
export function trackLineOf(track: MemoryTrackRecord): string | null {
  if (
    track.indexShows === 0 &&
    track.reads === 0 &&
    track.helped === 0 &&
    track.notUseful === 0
  ) {
    return null;
  }
  return [
    `Shown in ${runs(track.indexShows)}`,
    `read ${track.reads}`,
    `helped ${track.helped}`,
    `not useful ${track.notUseful}`,
  ].join(' · ');
}
