// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { memoryEntry } from '../__fixtures__/memories';
import { confirmInDialog } from '../__tests__/confirm-in-dialog';
import {
  memoryRowActions,
  pressMemoryRowAction,
} from '../__tests__/memory-row-menu';
import type { MemoryEntry } from '../autogenerated';
import { MemoryRow } from './memory-row';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.restoreAllMocks();
});

function render(node: React.ReactNode): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(node);
  });
  return container;
}

const noop = (): void => undefined;

const AGENT_SOURCE = {
  actor: 'agent',
  agentKind: 'claude',
  model: 'opus',
  runId: 'run-1',
  importedFrom: null,
} as const;

function labels(el: HTMLElement): string[] {
  return [...el.querySelectorAll('button')].map(
    (button) => button.textContent ?? '',
  );
}

function row(
  status: MemoryEntry['status'],
  handlers: Partial<Parameters<typeof MemoryRow>[0]> = {},
): HTMLDivElement {
  return render(
    <MemoryRow
      entry={memoryEntry({ status })}
      projectName={null}
      onEdit={noop}
      onForget={noop}
      onRestore={noop}
      onApprove={noop}
      {...handlers}
    />,
  );
}

function setHeights(scrollHeight: number, clientHeight: number): void {
  vi.spyOn(HTMLElement.prototype, 'scrollHeight', 'get').mockReturnValue(
    scrollHeight,
  );
  vi.spyOn(HTMLElement.prototype, 'clientHeight', 'get').mockReturnValue(
    clientHeight,
  );
}

describe('MemoryRow', () => {
  it('carries the entry id and handle for the pane to find it', () => {
    const el = row('active');
    const block = el.querySelector('[data-slot="memory-row"]')!;
    expect(block.getAttribute('data-memory-id')).toBe('memory-1');
    expect(block.getAttribute('data-memory-handle')).toBe('m1');
  });

  it('keeps an active note’s actions in its menu and draws no Approve, whatever the pane passes', async () => {
    const el = row('active');

    expect(labels(el)).toEqual(['']);
    expect(await memoryRowActions(el)).toEqual(['Edit', 'Forget…']);
  });

  it('names the team a note is filed under', () => {
    const el = render(
      <MemoryRow
        entry={memoryEntry({ teamSlug: 'review-crew' })}
        projectName={null}
        teamName="Review crew"
      />,
    );
    expect(
      el.querySelector('[data-slot="provenance-line"]')!.textContent,
    ).toContain(' · Review crew · ');
  });

  it('draws Approve on a waiting note beside its menu, and badges it unless the pane says not to', async () => {
    const el = row('pending');

    expect(labels(el)).toEqual(['Approve', '']);
    expect(await memoryRowActions(el)).toEqual(['Edit', 'Forget…']);
    expect(el.textContent).toContain('Waiting for review');
    expect(row('pending', { showStatus: false }).textContent).not.toContain(
      'Waiting for review',
    );
  });

  it('offers only Restore on a forgotten note and badges it', async () => {
    const el = row('forgotten');

    expect(await memoryRowActions(el)).toEqual(['Restore']);
    expect(el.textContent).toContain('Forgotten');
  });

  it('offers the move between the index and search only, and names it only when asked to', async () => {
    const onIndexed = vi.fn();
    const searchOnly = row('active', {
      entry: memoryEntry({ source: { ...AGENT_SOURCE } }),
      onIndexed,
      showReach: true,
    });

    expect(searchOnly.textContent).toContain('Search only');
    await pressMemoryRowAction(searchOnly, 'Load into every chat');
    expect(onIndexed).toHaveBeenLastCalledWith(true);

    const loaded = row('active', {
      entry: memoryEntry({
        source: { ...AGENT_SOURCE },
        approvedAt: '2026-10-21T09:00:00.000Z',
      }),
      onIndexed,
    });
    expect(loaded.textContent).not.toContain('In every chat');
    await pressMemoryRowAction(loaded, 'Search only');
    expect(onIndexed).toHaveBeenLastCalledWith(false);
  });

  it('draws no menu when it was given no action', () => {
    const el = render(<MemoryRow entry={memoryEntry()} projectName={null} />);

    expect(el.querySelector('button[aria-label^="Actions for"]')).toBeNull();
  });

  it('draws only the actions it was given a callback for, the extra ones last', async () => {
    const keep = vi.fn();
    const el = row('pending', {
      onApprove: undefined,
      onEdit: undefined,
      actions: [{ value: 'keep', label: 'Keep', run: keep }],
    });

    expect(labels(el)).not.toContain('Approve');
    expect(await memoryRowActions(el)).toEqual(['Forget…', 'Keep']);
    await pressMemoryRowAction(el, 'Keep');
    expect(keep).toHaveBeenCalledTimes(1);
  });

  it('calls the matching callback for each action', async () => {
    const onEdit = vi.fn();
    const onApprove = vi.fn();
    const el = row('pending', { onEdit, onApprove });
    act(() =>
      [...el.querySelectorAll('button')]
        .find((button) => button.textContent === 'Approve')!
        .click(),
    );
    await pressMemoryRowAction(el, 'Edit');

    expect(onApprove).toHaveBeenCalledTimes(1);
    expect(onEdit).toHaveBeenCalledTimes(1);
  });

  it('asks in a dialog before forgetting', async () => {
    const onForget = vi.fn();
    const el = row('active', { onForget });

    await pressMemoryRowAction(el, 'Forget…');
    expect(onForget).not.toHaveBeenCalled();
    await act(async () => confirmInDialog('Forget').click());

    expect(onForget).toHaveBeenCalledTimes(1);
  });

  it('disables Approve and the menu while busy', () => {
    const el = row('pending', { busy: true });
    const buttons = [...el.querySelectorAll('button')];

    expect(buttons).toHaveLength(2);
    expect(buttons.every((button) => button.disabled)).toBe(true);
  });

  it('shows no toggle for a body that fits in three lines', () => {
    setHeights(60, 60);
    expect(labels(row('active'))).not.toContain('Show more');
  });

  it('clamps a long body behind a Show more toggle that expands and collapses it', () => {
    setHeights(200, 60);
    const el = row('active', {
      entry: memoryEntry({ body: 'first\n  indented\nthird\nfourth' }),
    });
    const body = el.querySelector('[data-slot="memory-body"]')!;
    const toggle = (): HTMLButtonElement =>
      [...el.querySelectorAll('button')].find((button) =>
        button.textContent?.startsWith('Show'),
      )!;
    expect(body.className).toContain('line-clamp-2');
    expect(body.className).toContain('whitespace-pre-wrap');
    expect(toggle().textContent).toBe('Show more');
    act(() => toggle().click());
    expect(body.className).not.toContain('line-clamp-2');
    expect(toggle().textContent).toBe('Show less');
    act(() => toggle().click());
    expect(body.className).toContain('line-clamp-2');
  });

  it('scrolls itself to the middle when it becomes focused', () => {
    const scrollIntoView = vi.fn();
    Element.prototype.scrollIntoView = scrollIntoView;
    const entry = memoryEntry();
    const props = { entry, projectName: null };
    const el = render(<MemoryRow {...props} />);
    expect(scrollIntoView).not.toHaveBeenCalled();
    act(() => {
      root!.render(<MemoryRow {...props} focused />);
    });
    expect(scrollIntoView).toHaveBeenCalledWith({ block: 'center' });
    expect(
      el
        .querySelector('[data-slot="memory-row"]')!
        .hasAttribute('data-focused'),
    ).toBe(true);
  });
});
