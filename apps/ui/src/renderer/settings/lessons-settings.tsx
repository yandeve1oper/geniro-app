import { useEffect, useState } from 'react';

import {
  CLI_KINDS,
  type CliDetection,
  type CliKind,
  DEFAULT_LESSONS,
  type LessonsMode,
  type LessonsSettings,
  type MemoryTriageConfig,
  type Settings,
} from '../../shared/contracts';
import type { CapabilitiesDto, LessonsSpendDto } from '../autogenerated';
import { formatUsd } from '../chats/agent-activity';
import { segmentTitle } from '../chats/lesson-labels';
import { TargetSelect } from '../chats/target-select';
import { ErrorBanner } from '../components/error-banner';
import { SettingsPanel, SettingsPanelRow } from '../components/settings-panel';
import { SegmentedControl } from '../components/ui/segmented-control';
import { Switch } from '../components/ui/switch';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import {
  blankTriageChoice,
  ChoiceModelSettings,
} from './memory-triage-settings';

const SPEND_REFRESH_MS = 30_000;

const NO_TEAMS: readonly { slug: string; name: string }[] = [];

const REFLECTION_MODES: { id: LessonsMode; label: string }[] = [
  { id: 'off', label: 'Off' },
  { id: 'auto', label: 'Automatically when a thread is archived' },
];

type ReflectorSource = 'same' | 'chosen';

const REFLECTOR_SOURCES: { id: ReflectorSource; label: string }[] = [
  { id: 'same', label: 'Same as the thread' },
  { id: 'chosen', label: 'Choose an agent' },
];

const CHECK_HINT =
  "A second model re-checks each lesson before it is saved, so what lands in memory unattended passes its judgment. It runs only when the first model found a lesson, and its cost is shown separately. Light models are far cheaper but weaker judges — in published tests a light model reaches about four-fifths of a mid-size model's reasoning score — and the daemon already verifies every quote.";

type Profiles = Pick<Settings, 'recentConfigDirs' | 'configProfiles'>;

function counted(count: number, one: string, many: string): string {
  return `${count} ${count === 1 ? one : many}`;
}

function resolvedReflectorWords(
  installed: readonly CliKind[] | null,
  capabilities: CapabilitiesDto | null,
): string {
  if (installed === null || capabilities === null) {
    return 'Checking which CLIs are installed and their light models…';
  }
  if (installed.length === 0) {
    return 'No CLI is installed to reflect with.';
  }
  const words = installed.map((kind) => {
    const light =
      capabilities.agents.find((agent) => agent.agent === kind)?.lightModel ??
      null;
    return `${kind}: ${light ?? "no light model known, runs on the CLI's default model"}`;
  });
  return `The thread's own CLI and profile, on its light model at high effort — ${words.join(' · ')}`;
}

function spendSummary(spend: LessonsSpendDto): string {
  const { monthByStep } = spend;
  const breakdown =
    monthByStep.check > 0
      ? ` (reflect ${formatUsd(monthByStep.reflect)} · check ${formatUsd(monthByStep.check)})`
      : '';
  return [
    `Today ${formatUsd(spend.todayUsd)}`,
    `this month ${formatUsd(spend.monthUsd)}${breakdown}`,
    counted(spend.reflectedToday, 'thread reflected', 'threads reflected'),
    counted(spend.savedToday, 'lesson saved', 'lessons saved'),
    spend.unpricedRuns > 0
      ? counted(
          spend.unpricedRuns,
          'run reported no cost',
          'runs reported no cost',
        )
      : null,
  ]
    .filter((part): part is string => part !== null)
    .join(' · ');
}

function SpendReadout({
  spend,
}: {
  spend: LessonsSpendDto | null;
}): React.JSX.Element | null {
  if (spend === null) {
    return null;
  }
  return (
    <div data-slot="lessons-spend" className="flex flex-col gap-1 text-sm">
      <p>{spendSummary(spend)}</p>
      {spend.failed.length === 0 ? null : (
        <ul className="flex flex-col gap-0.5 text-xs text-muted-foreground">
          {spend.failed.map((run) => (
            <li key={run.segmentId}>
              {`${segmentTitle({ sourceTitle: run.sourceTitle })} — ${run.reason ?? 'failed'}`}
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

/**
 * Settings → Memory → Lessons: whether an archived thread is reflected on, the
 * CLI, profile, model and effort a reflection runs as, the optional second
 * model that checks what it found, and what that has cost. Desktop only — the
 * choice decides what a reflection spends — so a paired device reads it with
 * the pickers inert.
 */
export function LessonsSettingsPanel({
  agentsApi,
  capabilities,
  capabilitiesLoading = false,
  cliDetections,
  lessonsApi,
  client,
  remote,
}: {
  agentsApi: DaemonApis['agents'] | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading?: boolean;
  /** Per-CLI detection, or null while the probe has not answered. */
  cliDetections: readonly CliDetection[] | null;
  lessonsApi: DaemonApis['lessons'] | null;
  client: Pick<DaemonClient, 'onLessonsChanged'> | null;
  remote: boolean;
}): React.JSX.Element {
  const [lessons, setLessons] = useState<LessonsSettings | null>(null);
  const [profiles, setProfiles] = useState<Profiles>({
    recentConfigDirs: {},
    configProfiles: [],
  });
  const [error, setError] = useState<string | null>(null);
  const [spend, setSpend] = useState<LessonsSpendDto | null>(null);

  useEffect(() => {
    void window.geniro
      .getSettings()
      .then((settings) => {
        setLessons(settings.lessons);
        setProfiles({
          recentConfigDirs: settings.recentConfigDirs,
          configProfiles: settings.configProfiles,
        });
      })
      .catch((err: unknown) => setError(String(err)));
  }, []);

  const reloadSpend = useLatestCallback((): void => {
    if (lessonsApi === null) {
      return;
    }
    void lessonsApi
      .getLessonsSpend()
      .then(setSpend)
      .catch(() => undefined);
  }, [lessonsApi]);

  useEffect(() => {
    reloadSpend();
    if (client === null) {
      const timer = window.setInterval(() => {
        if (document.visibilityState === 'visible') {
          reloadSpend();
        }
      }, SPEND_REFRESH_MS);
      return () => window.clearInterval(timer);
    }
    return client.onLessonsChanged(() => reloadSpend());
  }, [client, reloadSpend]);

  const current = lessons ?? DEFAULT_LESSONS;
  const disabled = lessons === null || remote;
  const installed =
    cliDetections === null
      ? null
      : cliDetections.filter((d) => d.found).map((d) => d.kind);
  const pickable: readonly CliKind[] = installed ?? CLI_KINDS;

  const save = (next: LessonsSettings): void => {
    const before = lessons;
    setLessons(next);
    setError(null);
    void window.geniro
      .updateSettings({ lessons: next })
      .catch((err: unknown) => {
        setLessons(before);
        setError(String(err));
      });
  };

  const firstChoice = (): MemoryTriageConfig | null =>
    pickable[0] === undefined ? null : blankTriageChoice(pickable[0]);

  const pickAgent = (
    target: string,
    apply: (choice: MemoryTriageConfig) => void,
  ): void => {
    const kind = CLI_KINDS.find((candidate) => candidate === target);
    if (kind !== undefined) {
      apply(blankTriageChoice(kind));
    }
  };

  const reflectorSource: ReflectorSource =
    current.reflector === null ? 'same' : 'chosen';
  const checkOn = current.checker !== null;

  return (
    <SettingsPanel>
      <SettingsPanelRow
        layout="block"
        label="Lessons"
        description="A reflection reads an archived thread for what went wrong in it and files at most three lessons into searchable memory, each with the quote it rests on. Undo and Edit sit on the lesson's card.">
        {error === null ? null : (
          <ErrorBanner
            message={error}
            size="sm"
            onDismiss={() => setError(null)}
          />
        )}
      </SettingsPanelRow>
      <SettingsPanelRow
        label="Reflections"
        description="Reflect now on a thread works either way; Off keeps archived threads from being reflected.">
        <SegmentedControl
          ariaLabel="Reflections"
          options={REFLECTION_MODES}
          value={current.mode}
          disabled={disabled}
          onSelect={(mode) => save({ ...current, mode })}
        />
      </SettingsPanelRow>
      <SettingsPanelRow
        layout="block"
        label="Reflect with"
        description="Which CLI, profile, model and effort a reflection runs as. Its cost shows on the thread's lessons card and under Lessons in Stats.">
        <div
          className="flex min-w-0 flex-col items-start gap-2"
          inert={disabled}>
          <SegmentedControl
            ariaLabel="Reflect with"
            options={REFLECTOR_SOURCES}
            value={reflectorSource}
            disabled={disabled}
            onSelect={(source) => {
              if (source === 'same') {
                if (current.reflector !== null) {
                  save({ ...current, reflector: null });
                }
                return;
              }
              const first = firstChoice();
              if (current.reflector === null && first !== null) {
                save({ ...current, reflector: first });
              }
            }}
          />
          {current.reflector === null ? (
            <p
              data-slot="lessons-default-reflector"
              className="text-xs text-muted-foreground">
              {resolvedReflectorWords(installed, capabilities)}
            </p>
          ) : (
            <div className="flex min-w-0 flex-wrap items-center gap-1">
              <TargetSelect
                value={current.reflector.agent}
                teams={NO_TEAMS}
                cliDetections={cliDetections}
                aria-label="Reflection agent"
                onChange={(target) =>
                  pickAgent(target, (choice) =>
                    save({ ...current, reflector: choice }),
                  )
                }
              />
              <ChoiceModelSettings
                value={current.reflector}
                onChange={(next) => save({ ...current, reflector: next })}
                agentsApi={agentsApi}
                capabilities={capabilities}
                capabilitiesLoading={capabilitiesLoading}
                recentConfigDirs={profiles.recentConfigDirs}
                configProfiles={profiles.configProfiles}
              />
            </div>
          )}
        </div>
      </SettingsPanelRow>
      <SettingsPanelRow
        label="Check found lessons with"
        htmlFor="settings-lessons-check"
        description={CHECK_HINT}>
        <Switch
          id="settings-lessons-check"
          checked={checkOn}
          disabled={disabled}
          onCheckedChange={(on) => {
            const first = firstChoice();
            if (on) {
              if (first !== null) {
                save({ ...current, checker: first });
              }
              return;
            }
            save({ ...current, checker: null });
          }}
        />
      </SettingsPanelRow>
      {current.checker === null ? null : (
        <SettingsPanelRow
          layout="block"
          label="Checked with"
          description="Which CLI, profile, model and effort the check runs as. Its cost shows on the lesson's card, apart from the reflection's.">
          <div
            className="flex min-w-0 flex-wrap items-center gap-1"
            inert={disabled}>
            <TargetSelect
              value={current.checker.agent}
              teams={NO_TEAMS}
              cliDetections={cliDetections}
              aria-label="Check agent"
              onChange={(target) =>
                pickAgent(target, (choice) =>
                  save({ ...current, checker: choice }),
                )
              }
            />
            <ChoiceModelSettings
              value={current.checker}
              onChange={(next) => save({ ...current, checker: next })}
              agentsApi={agentsApi}
              capabilities={capabilities}
              capabilitiesLoading={capabilitiesLoading}
              recentConfigDirs={profiles.recentConfigDirs}
              configProfiles={profiles.configProfiles}
            />
          </div>
        </SettingsPanelRow>
      )}
      <SettingsPanelRow
        layout="block"
        label="Spend"
        description="What reflections and checks have cost. A run whose CLI reports no cost counts as none.">
        <SpendReadout spend={spend} />
      </SettingsPanelRow>
    </SettingsPanel>
  );
}
