function lessonsApiMock(proposals: LessonProposal[]) {
  return {
    listLessonProposals: vi.fn(async () => ({ proposals })),
    saveLesson: vi.fn(async () => proposals[0]),
    rejectLesson: vi.fn(async () => proposals[0]),
    updateLessonRule: vi.fn(async () => proposals[0]),
    moveLessonUp: vi.fn(async () => proposals[0]),
    undoLesson: vi.fn(async () => proposals[0]),
    editLesson: vi.fn(async () => proposals[0]),
  };
}

type LessonsApiMock = ReturnType<typeof lessonsApiMock>;

function asLessonsApi(mock: LessonsApiMock): DaemonApis['lessons'] {
  return mock as unknown as DaemonApis['lessons'];
}

function clientMock(): {
  client: Pick<DaemonClient, 'onLessonsChanged'>;
  changed: () => void;
} {
  const listeners: (() => void)[] = [];
  return {
    client: {
      onLessonsChanged: (listener: () => void) => {
        listeners.push(listener);
        return () => undefined;
      },
    } as Pick<DaemonClient, 'onLessonsChanged'>,
    changed: () => listeners.forEach((listener) => listener()),
  };
}

function Harness({
  lessonsApi,
  knowledgeApi = null,
  client = null,
}: {
  lessonsApi: DaemonApis['lessons'] | null;
  knowledgeApi?: DaemonApis['knowledge'] | null;
  client?: Pick<DaemonClient, 'onLessonsChanged'> | null;
}): React.JSX.Element {
  const waiting = useWaitingLessons({ lessonsApi, client });
  return (
    <>
      <p>{`count ${waiting.proposals?.length ?? 'none'}`}</p>
      <WaitingLessons
        waiting={waiting}
        lessonsApi={lessonsApi}
        knowledgeApi={knowledgeApi}
      />
    </>
  );
}

async function render(
  props: Parameters<typeof Harness>[0],
): Promise<HTMLDivElement> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(<Harness {...props} />);
  });
  return container;
}

function buttonNamed(el: HTMLElement, name: string): HTMLButtonElement {
  const found = [...el.querySelectorAll('button')].find(
    (button) => button.textContent?.trim() === name,
  );
  if (!found) {
    throw new Error(`no button named ${name}`);
  }
  return found;
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
}

async function flush(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
  });
}

describe('useWaitingLessons', () => {
  it('reads every lesson still proposed or failed its check, whatever its target', async () => {
    const api = lessonsApiMock([
      proposal({ id: 'p-1' }),
      proposal({ id: 'p-2' }),
    ]);
    const el = await render({ lessonsApi: asLessonsApi(api) });
    await flush();

    expect(api.listLessonProposals).toHaveBeenCalledWith({
      status: 'proposed,check_failed',
    });
    expect(el.textContent).toContain('count 2');
  });

  it('reads again when the daemon says lessons changed', async () => {
    const api = lessonsApiMock([proposal({ id: 'p-1' })]);
    const { client, changed } = clientMock();
    await render({ lessonsApi: asLessonsApi(api), client });
    await flush();
    expect(api.listLessonProposals).toHaveBeenCalledTimes(1);

    await act(async () => {
      changed();
      await Promise.resolve();
    });

    expect(api.listLessonProposals).toHaveBeenCalledTimes(2);
  });

  it('reads nothing without a lessons API, and reports no count', async () => {
    const el = await render({ lessonsApi: null });

    expect(el.textContent).toContain('count none');
  });
});

describe('WaitingLessons list', () => {
  it('says so when nothing waits', async () => {
    const el = await render({ lessonsApi: asLessonsApi(lessonsApiMock([])) });
    await flush();

    expect(el.textContent).toContain('Nothing is waiting for review.');
  });

  it('tags a lesson whose thread was deleted, and not one whose thread still exists', async () => {
    const el = await render({
      lessonsApi: asLessonsApi(
        lessonsApiMock([
          proposal({
            id: 'p-gone',
            sourceTitle: 'Deleted thread',
            sourceExists: false,
          }),
          proposal({
            id: 'p-live',
            sourceTitle: 'Live thread',
            sourceExists: true,
          }),
        ]),
      ),
    });
    await flush();

    const rows = [...el.querySelectorAll('li')];
    const gone = rows.find((row) =>
      row.textContent?.includes('Deleted thread'),
    );
    const live = rows.find((row) => row.textContent?.includes('Live thread'));
    expect(gone?.textContent).toContain('thread deleted');
    expect(live?.textContent).not.toContain('thread deleted');
  });

  it('draws each lesson as its own item, divided from the next by a rule and padding', async () => {
    const el = await render({
      lessonsApi: asLessonsApi(
        lessonsApiMock([
          proposal({ id: 'p-a', sourceTitle: 'First thread' }),
          proposal({ id: 'p-b', sourceTitle: 'Second thread' }),
        ]),
      ),
    });
    await flush();

    const list = el.querySelector('[data-slot="waiting-lessons"]');
    const items = [
      ...el.querySelectorAll('[data-slot="waiting-lesson"]'),
    ] as HTMLElement[];
    expect(list?.className).toContain('divide-y');
    expect(list?.className).toContain('divide-border');
    expect(items.map((item) => item.parentElement)).toEqual([list, list]);
    expect(items[0]?.textContent).toContain('First thread');
    expect(items[1]?.textContent).toContain('Second thread');
    expect(items.every((item) => item.className.includes('py-3'))).toBe(true);
  });

  it('names where each lesson goes', async () => {
    const el = await render({
      lessonsApi: asLessonsApi(
        lessonsApiMock([
          proposal({
            id: 'p-member',
            title: 'WHEN a review finds a missing test → name the test',
            target: {
              kind: 'member_instructions',
              memberId: 'member-reviewer',
            },
          }),
        ]),
      ),
    });
    await flush();

    expect(el.textContent).toContain('Save to Instructions of Reviewer');
  });

  it('saves a lesson to the target it names, then reads the list again', async () => {
    const api = lessonsApiMock([proposal({ id: 'p-1' })]);
    const el = await render({ lessonsApi: asLessonsApi(api) });
    await flush();

    await press(
      el.querySelector<HTMLButtonElement>(
        '[data-slot="split-button"] > button:first-child',
      )!,
    );

    expect(api.saveLesson).toHaveBeenCalledWith({
      proposalId: 'p-1',
      saveLessonDto: {
        target: { kind: 'memory', scope: 'project', type: 'feedback' },
      },
    });
    expect(api.listLessonProposals).toHaveBeenCalledTimes(2);
  });

  it('rejects a lesson with the reason typed, and reads the list again', async () => {
    const api = lessonsApiMock([proposal({ id: 'p-1' })]);
    const el = await render({ lessonsApi: asLessonsApi(api) });
    await flush();

    await press(buttonNamed(el, 'Reject'));
    await press(buttonNamed(el, 'Reject'));

    expect(api.rejectLesson).toHaveBeenCalledWith({
      proposalId: 'p-1',
      rejectLessonDto: {},
    });
    expect(api.listLessonProposals).toHaveBeenCalledTimes(2);
  });

  it('updates the entry a refines lesson names, through the rule update', async () => {
    const api = lessonsApiMock([
      proposal({
        id: 'p-refines',
        dedup: { verdict: 'refines', handle: 'm12' },
      }),
    ]);
    const el = await render({ lessonsApi: asLessonsApi(api) });
    await flush();

    await press(buttonNamed(el, 'Update m12'));

    expect(api.updateLessonRule).toHaveBeenCalledWith({
      proposalId: 'p-refines',
      updateLessonRuleDto: {},
    });
  });

  it('moves a broken-again lesson up, into the memory index', async () => {
    const api = lessonsApiMock([
      proposal({
        id: 'p-broken',
        dedup: { verdict: 'broken_again', handle: 'm7' },
        moveUp: 'memory_index',
      }),
    ]);
    const el = await render({ lessonsApi: asLessonsApi(api) });
    await flush();

    await press(buttonNamed(el, 'Move up to the memory index'));

    expect(api.moveLessonUp).toHaveBeenCalledWith({ proposalId: 'p-broken' });
  });

  it("lists the project's active documents when the picker opens", async () => {
    const api = lessonsApiMock([
      proposal({
        id: 'p-knowledge',
        target: { kind: 'knowledge', handle: null },
      }),
    ]);
    const knowledgeApi = {
      listKnowledge: vi.fn(async () => ({
        documents: PROJECT_DOCUMENTS.map((document) => ({
          ...document,
          id: document.handle,
        })),
        next: null,
      })),
    };
    const el = await render({
      lessonsApi: asLessonsApi(api),
      knowledgeApi: knowledgeApi as unknown as DaemonApis['knowledge'],
    });
    await flush();

    await act(async () => {
      el.querySelector('[aria-label="Choose where it goes"]')!.dispatchEvent(
        new Event('pointerdown', { bubbles: true }),
      );
    });

    expect(knowledgeApi.listKnowledge).toHaveBeenCalledWith({
      place: 'project:proj-1',
      status: 'active',
    });
  });
});

function SavedHarness({
  lessonsApi,
}: {
  lessonsApi: DaemonApis['lessons'];
}): React.JSX.Element {
  const saved = useSavedLessons({ lessonsApi, client: null });
  return <SavedLessons saved={saved} lessonsApi={lessonsApi} />;
}

async function renderSaved(
  lessonsApi: DaemonApis['lessons'],
): Promise<HTMLDivElement> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(<SavedHarness lessonsApi={lessonsApi} />);
  });
  await act(async () => {
    await Promise.resolve();
  });
  return container;
}

function savedProposal(id: string, title: string): LessonProposal {
  return proposal({
    id,
    title,
    status: 'saved',
    memoryHandle: `m-${id}`,
    resultRef: `m-${id}`,
    undoable: true,
  });
}

describe('WaitingLessons cap', () => {
  it('shows the first five waiting lessons and the rest behind Show all', async () => {
    const api = lessonsApiMock(
      Array.from({ length: 8 }, (_, index) => proposal({ id: `w${index}` })),
    );
    const el = await render({ lessonsApi: asLessonsApi(api) });
    await flush();

    expect(el.querySelectorAll('[data-slot="waiting-lesson"]')).toHaveLength(5);
    await press(buttonNamed(el, 'Show all 8 lessons'));
    expect(el.querySelectorAll('[data-slot="waiting-lesson"]')).toHaveLength(8);
  });

  it('draws no Show all for five or fewer', async () => {
    const api = lessonsApiMock(
      Array.from({ length: 5 }, (_, index) => proposal({ id: `w${index}` })),
    );
    const el = await render({ lessonsApi: asLessonsApi(api) });
    await flush();

    expect(el.querySelector('[data-slot="show-all"]')).toBeNull();
  });
});

describe('SavedLessons', () => {
  it('lists only the lessons that own their memory entry, read as saved lessons', async () => {
    const api = lessonsApiMock([
      savedProposal('own', 'WHEN seeding → reset the fixtures first'),
      proposal({
        id: 'refined',
        title: 'WHEN refining → keep it',
        status: 'saved',
        resultRef: 'm7',
        undoable: false,
      }),
      {
        ...savedProposal('held', 'WHEN reviewing → its note still waits'),
        memoryPending: true,
      },
    ]);
    const el = await renderSaved(asLessonsApi(api));

    expect(api.listLessonProposals).toHaveBeenCalledWith({ status: 'saved' });
    expect(el.querySelectorAll('[data-slot="saved-lesson"]')).toHaveLength(1);
    expect(el.textContent).not.toContain(
      'WHEN reviewing → its note still waits',
    );
    expect(el.textContent).toContain('WHEN seeding → reset the fixtures first');
    expect(el.textContent).not.toContain('WHEN refining → keep it');
  });

  it('undoes a saved lesson with the card’s own Undo, and reads the list again', async () => {
    const api = lessonsApiMock([
      savedProposal('own', 'WHEN seeding → reset the fixtures first'),
    ]);
    const el = await renderSaved(asLessonsApi(api));

    await press(buttonNamed(el, 'Undo'));

    expect(api.undoLesson).toHaveBeenCalledWith({ proposalId: 'own' });
    expect(api.listLessonProposals).toHaveBeenCalledTimes(2);
  });

  it('edits a saved lesson with the card’s own Edit', async () => {
    const api = lessonsApiMock([
      savedProposal('own', 'WHEN seeding → reset the fixtures first'),
    ]);
    const el = await renderSaved(asLessonsApi(api));

    await press(buttonNamed(el, 'Edit'));
    await press(buttonNamed(el, 'Save'));

    expect(api.editLesson).toHaveBeenCalledWith({
      proposalId: 'own',
      editLessonDto: {
        title: 'WHEN seeding → reset the fixtures first',
        rule: 'Run tests through pnpm --filter <pkg> test:unit.',
      },
    });
  });

  it('shows the newest five, and the rest behind Show all', async () => {
    const api = lessonsApiMock(
      Array.from({ length: 7 }, (_, index) =>
        savedProposal(`l${index}`, `Lesson ${index}`),
      ),
    );
    const el = await renderSaved(asLessonsApi(api));

    expect(el.querySelectorAll('[data-slot="saved-lesson"]')).toHaveLength(5);
    expect(
      el.querySelector('[data-slot="saved-lessons"] h3')?.textContent,
    ).toBe('Saved to memory · 7');
    await press(buttonNamed(el, 'Show all 7 lessons'));
    expect(el.querySelectorAll('[data-slot="saved-lesson"]')).toHaveLength(7);
    await press(buttonNamed(el, 'Show fewer'));
    expect(el.querySelectorAll('[data-slot="saved-lesson"]')).toHaveLength(5);
  });

  it('draws nothing while no lesson is saved', async () => {
    const el = await renderSaved(asLessonsApi(lessonsApiMock([])));

    expect(el.querySelector('[data-slot="saved-lessons"]')).toBeNull();
  });
});
