import { type StorageCleanOption, StorageCleanTarget } from '../autogenerated';
import { HelpHint, HelpHintPart } from '../components/help-hint';
import { formatBytes } from '../format-bytes';

/** What a Storage action does, how, and whether it is worth pressing. */
export interface ActionHelp {
  /** The action, as the "?" names it: "About <subject>". */
  subject: string;
  what: string;
  how: string;
  worth: string;
}

/** The "?" beside one of the Storage page's buttons. */
export function StorageActionHelp({
  help,
}: {
  help: ActionHelp;
}): React.JSX.Element {
  return (
    <HelpHint subject={help.subject} align="end" slot="storage-action-help">
      <HelpHintPart title="What it does">{help.what}</HelpHintPart>
      <HelpHintPart title="How it works">{help.how}</HelpHintPart>
      <HelpHintPart title="Worth pressing?">{help.worth}</HelpHintPart>
    </HelpHint>
  );
}

/** A compaction frees little enough below this that it is rarely worth a restart. */
const COMPACT_WORTH_BYTES = 256 * 1024 ** 2;

function compactWorth(free: number | null, file: number): string {
  if (free === null) {
    return 'Worth it after deleting many chats. Press it once every chat is idle.';
  }
  const share = file > 0 ? ` of the ${formatBytes(file)} file` : '';
  const room = `${formatBytes(free)}${share} is empty room.`;
  return free >= COMPACT_WORTH_BYTES
    ? `Yes: ${room} Press it once every chat is idle.`
    : `Not much to gain: only ${room} Worth it after deleting many chats.`;
}

/** The explanation of one of the daemon's clean-ups. */
export function cleanHelp(
  option: StorageCleanOption,
  databaseBytes: number,
): ActionHelp {
  switch (option.target) {
    case StorageCleanTarget.CompactDatabase:
      return {
        subject: 'Compact the database',
        what: 'Makes the database file smaller. Deleting chats leaves empty room inside the file instead of shrinking it; compacting gives that room back to the disk. No chat is changed or deleted.',
        how: 'Geniro’s background service restarts and rewrites the file without the empty room before it serves anything again, which can take a minute for a large file. It needs about twice the database’s size free on the disk, and is refused while an agent is working; if one starts just before the restart, the compaction runs at Geniro’s next start instead.',
        worth: compactWorth(option.bytes, databaseBytes),
      };
    case StorageCleanTarget.OrphanChatFiles:
      return {
        subject: 'Delete orphaned chat folders',
        what: 'Deletes folders of pictures and pages whose chat no longer exists.',
        how: 'Only folders whose chat is gone and that have not changed for a while are deleted; every chat you can open keeps its files.',
        worth: 'Yes: nothing you can open uses them.',
      };
    case StorageCleanTarget.OrphanTaskFiles:
      return {
        subject: 'Delete orphaned task folders',
        what: 'Deletes folders of pictures whose board card no longer exists.',
        how: 'Only folders whose card is gone and that have not changed for a while are deleted; every card on the board keeps its pictures.',
        worth: 'Yes: nothing you can open uses them.',
      };
    case StorageCleanTarget.TeamBackups:
      return {
        subject: 'Delete team backups',
        what: 'Deletes the copies Geniro saved before a team was replaced, changed by an analysis or restored.',
        how: 'Your teams and their version history stay as they are; only these copy files are deleted.',
        worth:
          'Yes, unless you want to roll a team back by hand to one of these copies.',
      };
    case StorageCleanTarget.Logs:
      return {
        subject: 'Delete old logs',
        what: 'Deletes the older debug log files.',
        how: 'The log Geniro is writing now stays, so nothing stops working.',
        worth:
          'Yes, unless you are about to attach a debug log to a bug report.',
      };
    case StorageCleanTarget.Leftovers:
      return {
        subject: 'Delete leftovers',
        what: 'Deletes files older versions of Geniro wrote and nothing reads any more.',
        how: 'Geniro does not open these files, so nothing changes in the app.',
        worth: 'Yes.',
      };
    case StorageCleanTarget.SettingsCopies:
      return {
        subject: 'Delete settings copies',
        what: 'Deletes copies of the settings file.',
        how: 'Geniro saves one when it cannot read the settings file, so a copy can be the only place what that file held still exists.',
        worth:
          'Only once your settings look right. Otherwise open the copy from the data folder first.',
      };
    case StorageCleanTarget.ArchivedChats:
      return ARCHIVED_CHATS_HELP;
  }
}

