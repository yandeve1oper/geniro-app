// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  type CliDetection,
  DEFAULT_SETTINGS,
  type LessonsSettings,
  type MemoryTriageConfig,
  type Settings,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { CapabilitiesDto, LessonsSpendDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient, LessonsChangedEvent } from '../daemon-client';
import { LessonsSettingsPanel } from './lessons-settings';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;
let writes: Partial<Settings>[];

const CAPABILITIES = {
  agents: [
    {
      agent: 'claude',
      displayName: 'Claude Code',
      shortName: 'Claude',
      lightModel: 'haiku',
    },
    {
      agent: 'codex',
      displayName: 'Codex',
      shortName: 'Codex',
      lightModel: 'gpt-6-luna',
    },
    {
      agent: 'cursor-agent',
      displayName: 'Cursor',
      shortName: 'Cursor',
      lightModel: null,
    },
  ],
  configDirs: [],
} as unknown as CapabilitiesDto;

const DETECTIONS = [
  { kind: 'claude', found: true },
  { kind: 'codex', found: true },
  { kind: 'cursor-agent', found: false },
] as unknown as CliDetection[];

const SPEND: LessonsSpendDto = {
  todayUsd: 0.31,
  monthUsd: 4.12,
  todayByStep: { reflect: 0.31, check: 0 },
  monthByStep: { reflect: 1.02, check: 3.1 },
  reflectedToday: 14,
  savedToday: 3,
  unpricedRuns: 2,
  failed: [
    {
      segmentId: 'segment-1',
      runId: 'run-1',
      sourceTitle: 'Refactor the parser',
      reason: 'claude is signed out',
    },
  ],
};

const REFLECTOR: MemoryTriageConfig = {
  agent: 'claude',
  configDir: null,
  model: 'opus',
  effort: 'high',
  contextWindow: null,
  modelParameters: {},
};

function install(lessons: LessonsSettings): void {
  writes = [];
  let stored: Settings = { ...DEFAULT_SETTINGS, lessons };
  window.geniro = createPreloadStub({
    getSettings: () => Promise.resolve(stored),
    updateSettings: (patch) => {
      writes.push(patch);
      stored = { ...stored, ...patch };
      return Promise.resolve(stored);
    },
  });
}

function spendApi(read = vi.fn(() => Promise.resolve(SPEND))) {
  return {
    api: { getLessonsSpend: read } as unknown as DaemonApis['lessons'],
    read,
  };
}

async function settle(): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0));
  });
}

async function render(
  options: {
    remote?: boolean;
    lessonsApi?: DaemonApis['lessons'] | null;
    client?: Pick<DaemonClient, 'onLessonsChanged'> | null;
    cliDetections?: readonly CliDetection[] | null;
  } = {},
): Promise<void> {
  await act(async () => {
    root.render(
      <LessonsSettingsPanel
        agentsApi={null}
        capabilities={CAPABILITIES}
        cliDetections={
          options.cliDetections === undefined
            ? DETECTIONS
            : options.cliDetections
        }
        lessonsApi={options.lessonsApi ?? null}
        client={options.client ?? null}
        remote={options.remote ?? false}
      />,
    );
  });
  await settle();
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
  await settle();
}

function segment(group: string, label: string): HTMLButtonElement {
  const button = [
    ...container.querySelectorAll<HTMLButtonElement>(
      `[role="group"][aria-label="${group}"] button`,
    ),
  ].find((node) => node.textContent?.trim() === label);
  if (!button) {
    throw new Error(`no "${label}" in ${group}`);
  }
  return button;
}

function picker(label: string): HTMLButtonElement | null {
  return container.querySelector<HTMLButtonElement>(
    `button[aria-label="${label}"]`,
  );
}

function option(kind: string): HTMLElement {
  return document.querySelector<HTMLElement>(
    `[role="option"][title="${kind}"]`,
  )!;
}

function text(): string {
  return container.textContent ?? '';
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('Lessons settings', () => {
  it('turns reflections off and saves that pick alone', async () => {
    install(DEFAULT_SETTINGS.lessons);
    await render();

    expect(segment('Reflections', 'Off').disabled).toBe(false);
    await press(segment('Reflections', 'Off'));

    expect(writes).toEqual([
      { lessons: { ...DEFAULT_SETTINGS.lessons, mode: 'off' } },
    ]);
  });

  it('shows the light model of each installed CLI as the default reflection, and none of the missing ones', async () => {
    install(DEFAULT_SETTINGS.lessons);
    await render();

    expect(text()).toContain('Same as the thread');
    expect(text()).toContain(
      "The thread's own CLI and profile, on its light model at high effort",
    );
    expect(text()).toContain('claude: haiku · codex: gpt-6-luna');
    expect(text()).not.toContain('cursor-agent');
  });

  it('names a CLI with no light model as running on its own default model', async () => {
    install(DEFAULT_SETTINGS.lessons);
    await render({
      cliDetections: [{ kind: 'cursor-agent', found: true }] as CliDetection[],
    });

    expect(text()).toContain(
      "cursor-agent: no light model known, runs on the CLI's default model",
    );
  });

  it('choosing an agent starts from the first installed CLI, with the shared agent and model pickers', async () => {
    install(DEFAULT_SETTINGS.lessons);
    await render();

    await press(segment('Reflect with', 'Choose an agent'));

    expect(writes).toEqual([
      {
        lessons: {
          ...DEFAULT_SETTINGS.lessons,
          reflector: {
            agent: 'claude',
            configDir: null,
            model: null,
            effort: null,
            contextWindow: null,
            modelParameters: {},
          },
        },
      },
    ]);
    expect(picker('Reflection agent')?.textContent).toMatch(/claude/i);
    expect(picker('Model and its settings')).not.toBeNull();
  });

  it('a new CLI for the reflection starts from its own default, not the last model', async () => {
    install({ ...DEFAULT_SETTINGS.lessons, reflector: REFLECTOR });
    await render();

    await press(picker('Reflection agent')!);
    await press(option('codex'));

    expect(writes).toEqual([
      {
        lessons: {
          ...DEFAULT_SETTINGS.lessons,
          reflector: {
            agent: 'codex',
            configDir: null,
            model: null,
            effort: null,
            contextWindow: null,
            modelParameters: {},
          },
        },
      },
    ]);
  });

  it('the check is off by default, and switching it on reveals its own agent and model pickers', async () => {
    install(DEFAULT_SETTINGS.lessons);
    await render();

    expect(text()).toContain(
      'A second model re-checks each lesson before it is saved',
    );
    expect(picker('Check agent')).toBeNull();
    const toggle = container.querySelector<HTMLButtonElement>(
      'button[role="switch"]',
    )!;
    expect(toggle.getAttribute('aria-checked')).toBe('false');

    await press(toggle);

    expect(writes).toEqual([
      {
        lessons: {
          ...DEFAULT_SETTINGS.lessons,
          checker: {
            agent: 'claude',
            configDir: null,
            model: null,
            effort: null,
            contextWindow: null,
            modelParameters: {},
          },
        },
      },
    ]);
    expect(
      container.querySelector('[aria-label="Check agent"]'),
    ).not.toBeNull();
    expect(picker('Model and its settings')).not.toBeNull();
  });

  it('reads the spend today and this month, its split, and each failed run with its reason', async () => {
    install(DEFAULT_SETTINGS.lessons);
    const spend = spendApi();
    await render({ lessonsApi: spend.api });

    expect(spend.read).toHaveBeenCalled();
    const readout = container.querySelector('[data-slot="lessons-spend"]');
    expect(readout?.textContent).toContain(
      'Today $0.31 · this month $4.12 (reflect $1.02 · check $3.10) · 14 threads reflected · 3 lessons saved · 2 runs reported no cost',
    );
    expect(readout?.textContent).toContain(
      'Refactor the parser — claude is signed out',
    );
  });

  it('re-reads the spend when the daemon reports a lessons change', async () => {
    install(DEFAULT_SETTINGS.lessons);
    const spend = spendApi();
    let announce: ((event: LessonsChangedEvent) => void) | null = null;
    const client = {
      onLessonsChanged: (listener: (event: LessonsChangedEvent) => void) => {
        announce = listener;
        return () => undefined;
      },
    };
    await render({ lessonsApi: spend.api, client });
    expect(spend.read).toHaveBeenCalledTimes(1);

    await act(async () => {
      announce?.({ runId: null });
    });
    await settle();

    expect(spend.read).toHaveBeenCalledTimes(2);
  });

  it('no longer lists lessons that were not reflected yet', async () => {
    install(DEFAULT_SETTINGS.lessons);
    await render({ lessonsApi: spendApi().api });

    expect(text()).not.toContain('Not reflected yet');
  });

  it('is read-only on a paired device, which may not choose what a reflection spends', async () => {
    install(DEFAULT_SETTINGS.lessons);
    await render({ remote: true });

    expect(segment('Reflections', 'Off').disabled).toBe(true);
    expect(
      container
        .querySelector('[role="group"][aria-label="Reflect with"]')
        ?.closest('[inert]'),
    ).not.toBeNull();
    expect(
      container.querySelector<HTMLButtonElement>('button[role="switch"]')
        ?.disabled,
    ).toBe(true);
  });
});
