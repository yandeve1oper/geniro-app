async function flush(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
  });
}

function buttonNamed(text: string): HTMLButtonElement {
  const button = [...container.querySelectorAll('button')].find((b) =>
    b.textContent?.includes(text),
  );
  if (!button) {
    throw new Error(`no button "${text}"`);
  }
  return button;
}

function dialogButton(text: string): HTMLButtonElement {
  const dialog = document.body.querySelector('[role="dialog"]');
  const button = [...(dialog?.querySelectorAll('button') ?? [])].find(
    (b) => b.textContent?.trim() === text,
  );
  if (!button) {
    throw new Error(`no "${text}" in a confirm dialog`);
  }
  return button;
}

function dialogText(): string {
  return document.body.querySelector('[role="dialog"]')?.textContent ?? '';
}

async function unfold(rowName: string): Promise<void> {
  await act(async () => buttonNamed(rowName).click());
}

function rowNamed(name: string): HTMLElement {
  const row = [
    ...container.querySelectorAll<HTMLElement>('[data-slot="storage-row"]'),
  ].find(
    (candidate) => candidate.querySelector('button')?.textContent === name,
  );
  if (!row) {
    throw new Error(`no row "${name}"`);
  }
  return row;
}

function figureOf(name: string): string | null | undefined {
  return rowNamed(name).querySelector('.tabular-nums')?.textContent;
}

function dotOf(name: string): Element | null | undefined {
  return rowNamed(name).querySelector('button > [aria-hidden="true"]');
}

async function pickPeriod(label: string): Promise<void> {
  const trigger = container.querySelector<HTMLButtonElement>(
    '[aria-label="Which archived chats to delete"]',
  );
  await act(async () => trigger?.click());
  const option = [...document.body.querySelectorAll('[role="option"]')].find(
    (row) => row.textContent?.includes(label),
  );
  if (!(option instanceof HTMLElement)) {
    throw new Error(`no period "${label}"`);
  }
  await act(async () => option.click());
}

async function remount(api: StorageClient): Promise<void> {
  act(() => root.unmount());
  root = createRoot(container);
  await act(async () => root.render(<Storage api={api} remote={false} />));
}

function deferred<T>(): {
  promise: Promise<T>;
  resolve: (value: T) => void;
} {
  let resolve: (value: T) => void = () => undefined;
  const promise = new Promise<T>((settle) => {
    resolve = settle;
  });
  return { promise, resolve };
}

async function pressTwice(text: string): Promise<void> {
  await act(async () => buttonNamed(text).click());
  await act(async () => dialogButton('Delete').click());
}

