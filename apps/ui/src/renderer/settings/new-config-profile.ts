import type { AgentMcpConfigDto } from '../autogenerated';
import type { McpServerDefinitions } from '../components/mcp-server-form';

/** One configuration whose MCP servers a new configuration may copy. */
export interface McpSource {
  /** What the user calls it: "Default", or the configuration's name. */
  label: string;
  /** Null for the CLI's own default configuration. */
  configDir: string | null;
}

export type McpSourceDocument = Pick<
  AgentMcpConfigDto,
  'servers' | 'path' | 'unavailableReason'
>;

/** One server offered for copying, with the definition of the first source naming it. */
export interface McpServerChoice {
  name: string;
  definition: McpServerDefinitions[string];
  /** The sources defining a server of that name, as one phrase. */
  from: string;
  /** Its definition holds environment values or headers, where keys usually live. */
  carriesKeys: boolean;
}

function hasEntries(value: unknown): boolean {
  return (
    typeof value === 'object' && value !== null && Object.keys(value).length > 0
  );
}

/**
 * Every server the sources define, by name, first source winning. A source
 * whose document is the same file as an earlier one's adds nothing (a CLI that
 * keeps one MCP file for every configuration answers each with it).
 */
export async function collectMcpServerChoices(
  sources: readonly McpSource[],
  read: (source: McpSource) => Promise<McpSourceDocument>,
): Promise<{
  choices: McpServerChoice[];
  unreadable: string[];
  /** Every readable source, two or more, answered with one and the same file. */
  shared: boolean;
}> {
  const documents = await Promise.all(
    sources.map((source) =>
      read(source).then(
        (document) => ({ source, document }),
        () => ({ source, document: null }),
      ),
    ),
  );
  const byName = new Map<
    string,
    { definition: McpServerChoice['definition']; from: string[] }
  >();
  const unreadable: string[] = [];
  const seenPaths = new Set<string>();
  let readable = 0;
  for (const { source, document } of documents) {
    if (document === null || document.servers === null) {
      unreadable.push(source.label);
      continue;
    }
    readable += 1;
    if (document.path !== null) {
      if (seenPaths.has(document.path)) {
        continue;
      }
      seenPaths.add(document.path);
    }
    for (const [name, definition] of Object.entries(document.servers)) {
      const known = byName.get(name);
      if (known) {
        known.from.push(source.label);
      } else {
        byName.set(name, { definition, from: [source.label] });
      }
    }
  }
  const choices = [...byName.entries()]
    .map(([name, { definition, from }]) => ({
      name,
      definition,
      from: from.join(', '),
      carriesKeys: hasEntries(definition.env) || hasEntries(definition.headers),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
  return {
    choices,
    unreadable,
    shared: readable >= 2 && seenPaths.size === 1,
  };
}

/**
 * The target document with the picked servers added. A name the target already
 * defines is left as it is, so copying never overwrites a server.
 */
export function withCopiedMcpServers(
  target: McpServerDefinitions,
  picked: readonly McpServerChoice[],
): { servers: McpServerDefinitions; added: string[] } {
  const servers = { ...target };
  const added: string[] = [];
  for (const choice of picked) {
    if (!(choice.name in servers)) {
      servers[choice.name] = choice.definition;
      added.push(choice.name);
    }
  }
  return { servers, added };
}
