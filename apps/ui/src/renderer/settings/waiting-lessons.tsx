import { useEffect, useState } from 'react';

import type { LessonProposal } from '../autogenerated';
import {
  described,
  documentsReaderOf,
  WAITING_LESSON_STATUSES,
} from '../chats/lessons-api-context';
import {
  DecidedRow,
  type LessonEdit,
  LessonRow,
  type LessonRuleEdit,
  type LessonSaveRequest,
  type LessonView,
} from '../components/lessons-card';
import { ShowAllButton, useShowAll } from '../components/show-all';
import { Badge } from '../components/ui/badge';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

export interface WaitingLessonsState {
  /** Null until the first read answers; the tab's count is its length. */
  proposals: readonly LessonProposal[] | null;
  reload: () => void;
}

const SAVED_SHOWN = 5;
const WAITING_SHOWN = 5;

function useLessonProposals({
  lessonsApi,
  client,
  status,
}: {
  lessonsApi: DaemonApis['lessons'] | null;
  client: Pick<DaemonClient, 'onLessonsChanged'> | null;
  status: string;
}): WaitingLessonsState {
  const [proposals, setProposals] = useState<readonly LessonProposal[] | null>(
    null,
  );
  const [generation, setGeneration] = useState(0);
  const reload = useLatestCallback(
    () => setGeneration((value) => value + 1),
    [],
  );

  useEffect(() => {
    if (lessonsApi === null) {
      return;
    }
    let live = true;
    void lessonsApi.listLessonProposals({ status }).then(
      (list) => {
        if (live) {
          setProposals(list.proposals);
        }
      },
      () => undefined,
    );
    return () => {
      live = false;
    };
  }, [lessonsApi, status, generation]);

  useEffect(() => client?.onLessonsChanged(reload), [client, reload]);

  return { proposals, reload };
}

/**
 * Every lesson still waiting on the user, whatever its target and whatever
 * thread it came from, re-read on each lessons change the daemon announces.
 */
export function useWaitingLessons(options: {
  lessonsApi: DaemonApis['lessons'] | null;
  client: Pick<DaemonClient, 'onLessonsChanged'> | null;
}): WaitingLessonsState {
  return useLessonProposals({ ...options, status: WAITING_LESSON_STATUSES });
}

export function useSavedLessons(options: {
  lessonsApi: DaemonApis['lessons'] | null;
  client: Pick<DaemonClient, 'onLessonsChanged'> | null;
}): WaitingLessonsState {
  const saved = useLessonProposals({ ...options, status: 'saved' });
  return {
    proposals:
      saved.proposals?.filter(
        (proposal) => proposal.undoable && !proposal.memoryPending,
      ) ?? null,
    reload: saved.reload,
  };
}

function lessonOf(proposal: LessonProposal): LessonView {
  return {
    id: proposal.id,
    title: proposal.title,
    rule: proposal.rule,
    why: proposal.why,
    signalKind: proposal.signalKind,
    evidence: proposal.evidence,
    target: proposal.target,
    dedup: proposal.dedup,
  };
}

function SourceLine({
  proposal,
}: {
  proposal: LessonProposal;
}): React.JSX.Element {
  return (
    <span className="inline-flex max-w-full min-w-0 items-center gap-1.5">
      <span className="min-w-0 truncate">
        {proposal.sourceTitle ?? 'Untitled thread'}
      </span>
      {proposal.sourceExists ? null : (
        <Badge variant="muted" className="px-1.5 py-0 text-[11px]">
          thread deleted
        </Badge>
      )}
    </span>
  );
}

/** The lessons waiting on the user, one row each, decided with the card's own actions. */
export function WaitingLessons({
  waiting,
  lessonsApi,
  knowledgeApi,
}: {
  waiting: WaitingLessonsState;
  lessonsApi: DaemonApis['lessons'] | null;
  knowledgeApi: DaemonApis['knowledge'] | null;
}): React.JSX.Element {
  const readDocuments = documentsReaderOf(knowledgeApi);
  const all = waiting.proposals ?? [];
  const {
    shown: proposals,
    expanded,
    setExpanded,
  } = useShowAll(all, WAITING_SHOWN);
  if (all.length === 0) {
    return (
      <p className="m-0 text-xs text-muted-foreground">
        Nothing is waiting for review.
      </p>
    );
  }
  return (
    <div className="flex flex-col gap-2">
      <ul
        data-slot="waiting-lessons"
        className="m-0 flex list-none flex-col divide-y divide-border p-0">
        {proposals.map((proposal) => (
          <li
            key={proposal.id}
            data-slot="waiting-lesson"
            className="min-w-0 py-3 first:pt-0 last:pb-0">
            <LessonRow
              lesson={lessonOf(proposal)}
              places={proposal.places}
              moveUp={proposal.moveUp}
              readDocuments={readDocuments}
              source={<SourceLine proposal={proposal} />}
              onSave={
                lessonsApi === null
                  ? undefined
                  : (proposalId: string, request: LessonSaveRequest) =>
                      described(
                        lessonsApi.saveLesson({
                          proposalId,
                          saveLessonDto: request,
                        }),
                      ).then(waiting.reload)
              }
              onReject={
                lessonsApi === null
                  ? undefined
                  : (proposalId: string, reason: string | null) =>
                      described(
                        lessonsApi.rejectLesson({
                          proposalId,
                          rejectLessonDto: reason === null ? {} : { reason },
                        }),
                      ).then(waiting.reload)
              }
              onUpdateRule={
                lessonsApi === null
                  ? undefined
                  : (proposalId: string, edit: LessonRuleEdit) =>
                      described(
                        lessonsApi.updateLessonRule({
                          proposalId,
                          updateLessonRuleDto: edit,
                        }),
                      ).then(waiting.reload)
              }
              onMoveUp={
                lessonsApi === null
                  ? undefined
                  : (proposalId: string) =>
                      described(lessonsApi.moveLessonUp({ proposalId })).then(
                        waiting.reload,
                      )
              }
            />
          </li>
        ))}
      </ul>
      <ShowAllButton
        total={all.length}
        limit={WAITING_SHOWN}
        expanded={expanded}
        noun="lessons"
        onToggle={() => setExpanded(!expanded)}
      />
    </div>
  );
}

export function SavedLessons({
  saved,
  lessonsApi,
}: {
  saved: WaitingLessonsState;
  lessonsApi: DaemonApis['lessons'] | null;
}): React.JSX.Element | null {
  const proposals = saved.proposals ?? [];
  const { shown, expanded, setExpanded } = useShowAll(proposals, SAVED_SHOWN);
  if (proposals.length === 0) {
    return null;
  }
  return (
    <section
      aria-label="Saved to memory"
      data-slot="saved-lessons"
      className="flex flex-col gap-2">
      <div className="flex flex-col gap-0.5">
        <h3 className="m-0 text-sm font-medium">
          Saved to memory · {proposals.length}
        </h3>
        <p className="m-0 text-xs text-muted-foreground">
          Lessons that went into memory as entries of their own. Undo forgets
          the entry; Edit makes it yours.
        </p>
      </div>
      <ul className="m-0 flex list-none flex-col gap-3 p-0">
        {shown.map((proposal) => (
          <li key={proposal.id} data-slot="saved-lesson" className="min-w-0">
            <p className="m-0 mb-1 text-xs text-muted-foreground">
              <SourceLine proposal={proposal} />
            </p>
            <DecidedRow
              lesson={lessonOf(proposal)}
              places={proposal.places}
              outcome={{
                proposalId: proposal.id,
                status: 'saved',
                by: 'user',
                title: proposal.title,
                rule: proposal.rule,
                target: proposal.target,
                memoryHandle: proposal.memoryHandle,
                resultRef: proposal.resultRef,
                reason: null,
              }}
              onUndo={
                lessonsApi === null
                  ? undefined
                  : (proposalId: string) =>
                      described(lessonsApi.undoLesson({ proposalId })).then(
                        saved.reload,
                      )
              }
              onEdit={
                lessonsApi === null
                  ? undefined
                  : (proposalId: string, edit: LessonEdit) =>
                      described(
                        lessonsApi.editLesson({
                          proposalId,
                          editLessonDto: edit,
                        }),
                      ).then(saved.reload)
              }
            />
          </li>
        ))}
      </ul>
      <ShowAllButton
        total={proposals.length}
        limit={SAVED_SHOWN}
        expanded={expanded}
        noun="lessons"
        onToggle={() => setExpanded(!expanded)}
      />
    </section>
  );
}
