/**
 * Every CLI profile settings.json names, then every profile a library
 * team's agent or pool member runs on, for the import to read beside each
 * CLI's default one. The daemon decides which CLI keeps memory there.
 */
export function importProfiles(
  settings: Pick<
    AppSettings,
    'configDirs' | 'recentConfigDirs' | 'configProfiles'
  >,
  teams: readonly Team[] = [],
): ImportProfile[] {
  const seen = new Set<string>();
  const out: ImportProfile[] = [];
  const add = (
    agentKind: ImportProfile['agentKind'],
    dir: string | undefined,
  ) => {
    if (!dir?.startsWith('/') || seen.has(`${agentKind}\n${dir}`)) {
      return;
    }
    seen.add(`${agentKind}\n${dir}`);
    out.push({ agentKind, dir });
  };
  for (const kind of CLI_KINDS) {
    add(kind, settings.configDirs[kind]);
    for (const dir of settings.recentConfigDirs[kind] ?? []) {
      add(kind, dir);
    }
  }
  for (const profile of settings.configProfiles) {
    add(profile.agent, profile.dir);
  }
  for (const team of teams) {
    for (const member of team.members) {
      add(member.agent, member.configDir);
      for (const entry of member.pool ?? []) {
        add(entry.agent, entry.configDir);
      }
    }
  }
  return out.slice(0, IMPORT_PROFILES_MAX);
}

async function libraryTeams(teams: TeamsClient | null): Promise<Team[]> {
  if (teams === null) {
    return [];
  }
  const summaries = await teams.listTeams().catch(() => []);
  const files = await Promise.allSettled(
    summaries.map((summary) => teams.getTeam({ slug: summary.slug })),
  );
  return files.flatMap((file) =>
    file.status === 'fulfilled' ? [file.value.team] : [],
  );
}

function plural(count: number, one: string, many: string): string {
  return `${count} ${count === 1 ? one : many}`;
}

/** What an import did, in one line: what landed, what was left out, and the switch it flipped. */
export function importNote({
  imported,
  skipped,
  unimportable,
  switchedNativeOff,
}: {
  imported: number;
  skipped: readonly MemoryImportResultDto['skipped'][number][];
  unimportable: number;
  switchedNativeOff: boolean;
}): string {
  const parts = [`Imported ${plural(imported, 'note', 'notes')}`];
  if (skipped.length > 0) {
    parts.push(
      `${skipped.length} skipped (${skipped
        .map((skip) => skip.reason)
        .slice(0, 3)
        .join('; ')})`,
    );
  }
  if (unimportable > 0) {
    parts.push(
      `${plural(unimportable, 'note', 'notes')} could not be imported`,
    );
  }
  const line = `${parts.join('; ')}.`;
  return switchedNativeOff
    ? `${line} Each CLI's own memory is now off for new chats, so they use only this one.`
    : line;
}

/** The place a scope filter previews a new chat's index for: a chat in no project unless it names one. */
function previewPlace(scope: string): {
  projectId?: string;
  teamSlug?: string;
} {
  if (scope === ALL_SCOPES || scope === GLOBAL_SCOPE) {
    return {};
  }
  const teamSlug = teamSlugOfScope(scope);
  return teamSlug !== null ? { teamSlug } : { projectId: scope };
}

function tracksOf(
  ...lists: readonly (readonly MemoryTrackRecord[])[]
): ReadonlyMap<string, MemoryTrackRecord> {
  return new Map(
    lists
      .flat()
      .map((track): [string, MemoryTrackRecord] => [track.memoryId, track]),
  );
}

function listRequest(
  filters: Filters,
  focus: string | null,
): MemoriesApiListMemoriesRequest {
  if (focus !== null) {
    return { handle: focus };
  }
  const q = filters.q.trim();
  const type = typeOf(filters.type);
  const teamSlug = teamSlugOfScope(filters.scope);
  return {
    ...TAB_REQUEST[filters.status],
    ...(filters.scope === ALL_SCOPES
      ? {}
      : filters.scope === GLOBAL_SCOPE
        ? { scope: 'global' }
        : teamSlug !== null
          ? { scope: 'team', teamSlug }
          : { scope: 'project', projectId: filters.scope }),
    ...(type === undefined ? {} : { type }),
    ...(q === '' ? {} : { q }),
  };
}

/** The Clean up panel's line: what the memory holds and what Least used proposes. */
export function cleanupLine(summary: MemoryReviewSummaryDto): string {
  const parts = [
    `${summary.active.toLocaleString('en-US')} active`,
    `${summary.read.toLocaleString('en-US')} read`,
    `${summary.neverRead.toLocaleString('en-US')} never read`,
    summary.proposed > 0 || summary.younger === 0
      ? `${summary.proposed.toLocaleString('en-US')} proposed now`
      : `none proposed yet: ${summary.younger.toLocaleString('en-US')} cold ${summary.younger === 1 ? 'entry is' : 'entries are'} under ${summary.minAgeDays} days old`,
  ];
  const since =
    summary.countedSince === null
      ? ''
      : ` Reads counted since ${new Date(`${summary.countedSince}T00:00:00Z`).toLocaleDateString('en-US', { month: 'short', day: 'numeric', timeZone: 'UTC' })}${summary.counting ? ', earlier chats still being counted' : ''}.`;
  return `${parts.join(' · ')}.${since}`;
}

