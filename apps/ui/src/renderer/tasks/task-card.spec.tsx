// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { AgentIdentityContext } from '../agent-identity';
import type { AgentIdentityCapability, TaskDto } from '../autogenerated';
import { aTask } from './__tests__/fixtures';
import { TaskCard, VISIBLE_LABELS } from './task-card';

/** cursor's own short name, for the one test that names a working agent's CLI. */
const CURSOR_IDENTITY: AgentIdentityCapability = {
  agent: 'cursor-agent',
  displayName: 'Cursor',
  shortName: 'cursor',
  summary: '',
  details: [],
  icon: 'terminal',
  callerEscalatesQuestions: false,
  lightModel: null,
};

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const task = (over: Partial<TaskDto> = {}): TaskDto =>
  aTask({ title: 'Wire the board', status: 'in_progress', ...over });

function render(node: React.ReactElement): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(node);
  });
  return container;
}

const card = (
  over: Partial<TaskDto> = {},
  props = {},
  /** Default [] mirrors `AgentIdentityContext`'s own default — no Provider. */
  identities: readonly AgentIdentityCapability[] = [],
): HTMLButtonElement => {
  const el = render(
    <AgentIdentityContext.Provider value={identities}>
      <TaskCard
        task={task(over)}
        selected={false}
        dragging={false}
        onOpen={vi.fn()}
        onDragStart={vi.fn()}
        onDragEnd={vi.fn()}
        {...props}
      />
    </AgentIdentityContext.Provider>,
  );
  return el.querySelector('button') as HTMLButtonElement;
};

describe('TaskCard', () => {
  it('announces its column and the keyboard move on the accessible name', () => {
    // On aria-label and not title: an aria-label wins the accessible-name
    // computation, so an affordance stated only in a tooltip is silent to the
    // screen reader that most needs it. The sibling queued-strip puts its
    // arrow hint on `title` and is the pattern NOT to copy here.
    const name = card().getAttribute('aria-label') ?? '';

    expect(name).toContain('In progress');
    expect(name.toLowerCase()).toContain('arrow');
  });

  it('is draggable and carries its id for the drop handler', () => {
    const el = card();

    expect(el.getAttribute('draggable')).toBe('true');
    expect(el.dataset.taskId).toBe('t1');
  });

  it('folds labels past the visible few into a count', () => {
    // Derived from the component's own constant rather than a literal, so
    // changing how many chips a card shows does not silently leave this test
    // asserting the old design.
    const extra = 2;
    const labels = Array.from(
      { length: VISIBLE_LABELS + extra },
      (_, i) => `label-${i}`,
    );

    const el = card({ labels });

    expect(el.textContent).toContain(`+${extra}`);
    expect(el.textContent).toContain(labels[0]);
    expect(el.textContent).not.toContain(labels[VISIBLE_LABELS]);
  });

  it('dims itself while it is the card being dragged', () => {
    const plain = card();
    const plainClass = plain.className;
    act(() => {
      root?.unmount();
    });
    container?.remove();

    const el = card({}, { dragging: true });

    expect(plainClass).not.toContain('opacity-40');
    expect(el.className).toContain('opacity-40');
  });
});

describe('the richer card', () => {
  it('does not repeat the status the column already states', () => {
    // A deliberate design decision, pinned because it is easy to undo by
    // accident: the card sits IN its status column, so printing "In progress"
    // on every card was noise. Screen readers still hear it — see below.
    const el = card({ status: 'in_progress' });

    expect(el.textContent).not.toContain('In progress');
  });

  it('still names the column in the accessible name', () => {
    // The other half of the decision. A sighted user reads the column header;
    // a screen-reader user has no column to look at, so dropping it from the
    // visible card must not drop it from the name.
    expect(
      card({ status: 'in_progress' }).getAttribute('aria-label'),
    ).toContain('In progress');
  });

  it('previews the description so a card says what the task is', () => {
    const el = card({ description: '## Context\n\nThe cards are too thin.' });

    expect(el.textContent).toContain('The cards are too thin.');
    expect(el.textContent).not.toContain('##');
  });

  // The REVERSE of what an earlier pass pinned, and deliberately so. A card
  // carried its update time on a row of its own — the one fact on it with no
  // glyph, that nothing here sorts or filters by, costing a full line under
  // two lines of title and up to two of metadata. It is on the detail panel,
  // which is where a timestamp is worth its room.
  it('spends no row on a timestamp', () => {
    const el = card({
      updatedAt: new Date(Date.now() - 7_200_000).toISOString(),
    });

    expect(el.querySelector('time')).toBeNull();
    expect(el.textContent).not.toContain('2h');
  });

  it('draws every fact as the SAME pill, with the label’s colour on its dot', () => {
    // Linear's board card, given as the reference. Priority, labels, the due
    // date and the branch were four arrangements of a small glyph and some
    // muted text, so a card's tags were indistinguishable from its dates —
    // REPORTED first as "они какие-то кривые и непонятные". One shape for all
    // of them is what makes the row readable; the DOT is what says which
    // label, which is why the pill itself stays neutral.
    const el = card({
      labels: ['design', 'infra'],
      priority: 'urgent',
      dueDate: '2030-01-01',
      branch: 'geniro/task-1',
    });

    // priority + 2 labels + due + branch
    expect(el.querySelectorAll('[data-slot="task-chip"]').length).toBe(5);
    const dots = [...el.querySelectorAll('span')].filter((node) =>
      node.className.includes('bg-group-'),
    );
    expect(dots.length).toBe(2);
    // Different names, different swatches — the point of colouring them.
    expect(dots[0]?.className).not.toBe(dots[1]?.className);
  });

  it('closes with the date it was created, not the date it moved', () => {
    // REVERSES an earlier cut of the update time, which was a third metadata
    // row holding a lone figure. There is one metadata row now, and a quiet
    // dateline under it is what closes the card — Linear's own footer.
    // `updated` moves whenever anything touches the card and says nothing a
    // reader can act on; its age is a fact about the card.
    const el = card({ createdAt: '2026-08-19T10:00:00.000Z' });

    expect(el.textContent).toContain('Created Aug 19');
  });
});

/**
 * A card whose agent is working RIGHT NOW.
 *
 * REPORTED as "на тех задачах, которые сейчас делает агент, автоматически
 * должна быть иконка агента и какой-то лоадер на карточках задач" — the board
 * drew a working card exactly like a resting one, so the only way to tell was
 * to open it.
 */
describe('TaskCard — while an agent is on it', () => {
  const live = (agentKind: string | null) => ({
    id: 't1',
    runId: 'r1',
    agentKind,
  });

  it('names the CLI and spins', () => {
    const el = card({}, { active: live('claude') });

    expect(el.textContent).toContain('claude');
    expect(el.querySelector('.animate-spin')).not.toBeNull();
  });

  it('says `cursor`, the word the rest of the app uses', () => {
    // The daemon spells it `cursor-agent`, which is the binary's name. One
    // shared fold (`agentShortName`) rather than a second mapping here.
    expect(
      card({}, { active: live('cursor-agent') }, [CURSOR_IDENTITY]).textContent,
    ).toContain('cursor');
  });

  it('falls back to the kind itself before identities have loaded — never a guess', () => {
    // No identity list supplied (the default `[]`): the card must not invent
    // a shortening, so it names the CLI exactly as the daemon spells it.
    expect(card({}, { active: live('cursor-agent') }).textContent).toContain(
      'cursor-agent',
    );
  });

  it('calls a team run a team rather than nothing', () => {
    // A graph run records no single CLI — its agents are per node — so the
    // honest word is what the run IS.
    expect(card({}, { active: live(null) }).textContent).toContain('team');
  });

  it('puts it on the accessible name AHEAD of the column', () => {
    // The column says `In progress`, which is equally true of a card whose
    // agent finished minutes ago and is waiting to be reviewed.
    const name = card({}, { active: live('claude') }).getAttribute(
      'aria-label',
    );

    expect(name).toContain('claude is working on it');
    expect(name?.indexOf('working on it')).toBeLessThan(
      name?.indexOf('In progress') ?? -1,
    );
  });

  it('draws none of it on a card at rest', () => {
    // `task.runId` is NOT the test — it outlives the run it names, since a
    // settled card's report is read through exactly that id — so a card with
    // a finished run must look at rest.
    const el = card({ runId: 'r1' });

    expect(el.querySelector('.animate-spin')).toBeNull();
    expect(el.getAttribute('aria-label')).not.toContain('working on it');
  });
});

/**
 * The priority is a GLYPH on the card, and a glyph nobody can decode is chrome.
 *
 * REPORTED against the urgent one: "у меня есть иконка с восклицательным
 * знаком в треугольничке напротив таски… Я не понимаю, что она значит. Там
 * никакой информации нет." It is a warning triangle on a board that had just
 * started marking cards the autopilot refuses, so it read as an error about
 * that card — and the accessible name, which has carried the word all along,
 * is not something a sighted reader can reach.
 */
describe('TaskCard — the priority glyph', () => {
  const glyphTitle = (el: HTMLElement): string | null =>
    el.querySelector('span[title]')?.getAttribute('title') ?? null;

  it('names itself on hover', () => {
    expect(glyphTitle(card({ priority: 'urgent' }))).toBe('Urgent priority');
  });

  it('puts the tooltip on a WRAPPER, since an svg takes none from `title`', () => {
    // An SVG element's tooltip comes from a `<title>` CHILD; the attribute
    // lucide would forward draws nothing at all. So the pin is that the
    // titled node is not the icon itself.
    const titled = card({ priority: 'high' }).querySelector('[title]');

    expect(titled?.tagName).toBe('SPAN');
  });

  it('draws no glyph, and no tooltip, on an untriaged card', () => {
    // `none` is off the scale rather than the bottom of it — a card with no
    // priority set says nothing about one.
    expect(glyphTitle(card({ priority: 'none' }))).toBeNull();
  });
});

/**
 * What a card is CALLED.
 *
 * ASKED FOR as Linear's own scheme — "нужно добавить номер, вот как в linear,
 * то есть по первым буквам проекта и номер" — and the point is that `GEN-12`
 * goes in a commit message, a chat or a note to somebody else, where a UUID
 * cannot.
 */
describe('TaskCard — the identifier', () => {
  it('draws it, and puts it on the accessible name first', () => {
    const el = card({ number: 12 }, { taskKey: 'GEN' });

    expect(el.textContent).toContain('GEN-12');
    expect(el.getAttribute('aria-label')?.startsWith('GEN-12')).toBe(true);
  });

  it('draws nothing for a card with no number', () => {
    // `GEN-0` names a card that does not exist; the two halves also arrive on
    // different rows, so either can be missing on its own.
    expect(
      card({ number: null }, { taskKey: 'GEN' }).textContent,
    ).not.toContain('GEN');
    expect(card({ number: 12 }).textContent).not.toContain('-12');
  });
});

/**
 * What the work PRODUCED, on the board itself.
 *
 * ASKED FOR as the pull-request number being on the card's preview as well as
 * inside it. The preview names it; OPENING the card is what links to it.
 */
describe('TaskCard — the pull request', () => {
  const pr = (number: number) => ({
    owner: 'geniro-io',
    repo: 'geniro-app',
    number,
    url: `https://github.com/geniro-io/geniro-app/pull/${String(number)}`,
    seq: number,
  });

  it('names the newest one, and says so on the accessible name', () => {
    const el = card({ pullRequests: [pr(76), pr(110)] });

    // Built from the fixture rather than written out: the renderer draws a
    // hash before the number, and a hash followed by three hex digits is a
    // colour literal to this package's own eslint rule.
    expect(el.textContent).toContain(`#${String(110)}`);
    expect(el.textContent).not.toContain(`#${String(76)}`);
    // The earlier one is not LOST — the count says it exists, and the card's
    // own panel lists it.
    expect(el.textContent).toContain('+1');
    expect(el.getAttribute('aria-label')).toContain('110');
  });

  it('is a LABEL, never a link — the card is one button', () => {
    // An anchor nested in a button is invalid markup that also steals the
    // card's own click, which is what opens the panel the link lives in.
    expect(card({ pullRequests: [pr(110)] }).querySelector('a')).toBeNull();
  });

  it('draws nothing for a card whose run opened none', () => {
    expect(card().querySelector('[data-slot="task-chip"]')).toBeNull();
  });
});

describe('TaskCard — its thread waiting on the user', () => {
  it('marks a card whose thread asks, and says so on the accessible name', () => {
    const el = card({ number: 7 }, { wait: 'asking' });
    expect(
      el
        .querySelector('[data-slot="wait-mark"]')
        ?.getAttribute('data-wait-state'),
    ).toBe('asking');
    expect(el.getAttribute('aria-label')).toContain(
      'its thread: waiting on you',
    );
  });

  it('marks an unread reply on a card at rest — the run settling does not clear it', () => {
    const el = card({ status: 'in_review' }, { wait: 'unseen' });
    expect(
      el
        .querySelector('[data-slot="wait-mark"]')
        ?.getAttribute('data-wait-state'),
    ).toBe('unseen');
  });

  it('draws no mark for a thread that is only working', () => {
    const el = card({ number: 7 }, { wait: 'working' });
    expect(el.querySelector('[data-slot="wait-mark"]')).toBeNull();
  });
});

describe('TaskCard — its run’s stage line', () => {
  const line = (el: HTMLElement): HTMLElement | null =>
    el.querySelector('[data-slot="task-stage"]');

  it('names the current stage and the daemon’s n/m under the title', () => {
    const el = card({ stage: { title: 'Review', index: 2, total: 4 } });
    expect(line(el)?.textContent).toBe('Review·2/4');
    expect(el.getAttribute('aria-label')).toContain('stage 2 of 4: Review');
  });

  it('says the stages are done once the run has none left', () => {
    const el = card({ stage: { title: null, index: 4, total: 4 } });
    expect(line(el)?.textContent).toBe('Stages done');
    expect(el.getAttribute('aria-label')).toContain('all stages done');
  });

  it('draws no line for a card whose run has no stage graph', () => {
    const el = card({ stage: null });
    expect(line(el)).toBeNull();
    expect(el.getAttribute('aria-label')).not.toContain('stage');
  });
});
