import type { GeniroApi, RunSettings } from '../../shared/contracts';
import type { ProjectDto, TaskDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { daemonErrorCode, daemonErrorStatus } from '../daemon-api';

/**
 * The daemon refusals that mean ANOTHER start of the same card holds it.
 *
 * TWIN: `apps/ui/src/main/autopilot-conductor.ts` `ANOTHER_START_HOLDS_IT`,
 * which names the daemon's throw sites. Spelled on each side because main and
 * the renderer share no module for it.
 */
const ANOTHER_START_HOLDS_IT: ReadonlySet<string> = new Set([
  'TASK_RUN_STARTING',
  'TASK_ALREADY_RUNNING',
]);

/** The main-process calls a start makes around its POST. */
export type TaskRunBridge = Pick<
  GeniroApi,
  'prepareTaskWorktree' | 'getGitStamp' | 'pruneTaskWorktree'
>;

export interface StartTaskRunInput {
  apis: Pick<DaemonApis, 'tasks'>;
  bridge: TaskRunBridge;
  /** Read at the moment of the start, so the run carries the current settings. */
  readRunSettings: () => Promise<RunSettings>;
  task: TaskDto;
  project: ProjectDto;
  /** What the user typed for this start; blank is the same as none. */
  prompt?: string;
  /** Sent only when given, so a caller that omits it sends the same request as before. */
  startedBy?: 'user';
}

/**
 * Make the worktree for a card through main, then start its run in it.
 *
 * The ORDER is the whole safety of it. Main creates the worktree first, because
 * the daemon needs a real directory to run in and runs no git itself; the daemon
 * then starts the chat. If that second half fails, a worktree THIS call made is
 * given back, otherwise every failed start leaves a checkout on disk for a card
 * whose work may never be finished, which is all the reaper collects. One that
 * was the task's own, still standing, is left where it is.
 *
 * Throws the worktree's own failure when it could not be made (nothing is
 * posted then), and the daemon's refusal when the start is refused.
 */
export async function startTaskRun({
  apis,
  bridge,
  readRunSettings,
  task,
  project,
  prompt = '',
  startedBy,
}: StartTaskRunInput): Promise<TaskDto> {
  const made = await bridge.prepareTaskWorktree({
    taskId: task.id,
    // The card's folder if it names one, else the project's: a project's folder
    // is the default for its board, not the law, since one board routinely holds
    // work across several checkouts.
    folder: task.folder ?? project.folder,
  });
  if (!made.ok || made.path === null || made.branch === null) {
    throw new Error(made.error ?? 'the worktree could not be created');
  }
  try {
    // The client's own reading of the folder, taken now: the fixed point the
    // chat's diff view measures against, exactly as the composer takes it when a
    // chat is opened by hand.
    const stamp = await bridge.getGitStamp(made.path);
    const runSettings = await readRunSettings();
    const started = await apis.tasks.startTaskRun({
      taskId: task.id,
      startTaskRunDto: {
        cwd: made.path,
        branch: made.branch,
        // The card as the caller last saw it, so a start computed against a card
        // someone else already moved is refused.
        from: task.status,
        startSha: stamp.sha ?? undefined,
        startDirty: stamp.dirty ?? undefined,
        ...runSettings,
        ...(startedBy === undefined ? {} : { startedBy }),
        // Omitted rather than sent blank: absent is what the daemon reads as "the
        // start said nothing", and a card being continued then gets its own brief
        // again rather than an empty message.
        ...(prompt.trim() === '' ? {} : { prompt: prompt.trim() }),
      },
    });
    return started;
  } catch (err: unknown) {
    // A reused worktree stays: a refused start may mean its run is working in it
    // right now. So does one this call made when another start of the card is
    // using it, see `mayGiveBackWorktree`.
    if (!made.reused && (await mayGiveBackWorktree(apis, task.id, err))) {
      await bridge.pruneTaskWorktree(task.id);
    }
    throw err;
  }
}

/**
 * Whether a worktree THIS call made may go back after its start was refused.
 *
 * Making it is not the same as being its only user. A task's worktree lives at
 * ONE path per task, so the autopilot starting the same card a moment later is
 * handed this very directory as `reused` — and when that start is the one the
 * daemon took, this refusal is the loser's, and pruning the clean tree takes
 * the cwd out from under the agent it just started. So the daemon is asked: a
 * refusal naming another start of the card keeps it outright (that start may
 * not have moved the card yet), and otherwise a card now `in_progress` is
 * being worked. A card that is GONE holds nothing; any other failure to read
 * it keeps the worktree — a stray costs disk, a wrong guess costs an agent its
 * working directory.
 *
 * TWIN: `apps/ui/src/main/autopilot-conductor.ts` `mayGiveBack`, the timer's
 * half of the same race.
 */
export async function mayGiveBackWorktree(
  apis: Pick<DaemonApis, 'tasks'>,
  taskId: string,
  refusal: unknown,
): Promise<boolean> {
  const code = daemonErrorCode(refusal);
  if (code !== null && ANOTHER_START_HOLDS_IT.has(code)) {
    return false;
  }
  try {
    return (await apis.tasks.readTask({ taskId })).status !== 'in_progress';
  } catch (err: unknown) {
    return daemonErrorStatus(err) === 404;
  }
}
