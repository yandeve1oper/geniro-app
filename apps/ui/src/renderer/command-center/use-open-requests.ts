import { useEffect, useRef, useState } from 'react';

import type {
  ItemDto,
  RunAwaiting,
  SendMessageDtoImagesInner,
} from '../autogenerated';
import { payloadString } from '../chats/transcript-payload';
import { useLatestCallback } from '../components/use-latest-callback';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

/** A thread the user owes an answer, as the board knows it. */
export interface AskingThread {
  runId: string;
  title: string;
  isTeam: boolean;
  awaiting: RunAwaiting;
  /** Moves whenever the thread writes a row, so a new card is read again. */
  lastActivityAt: string;
}

/** One card a thread holds open for the user. */
export interface OpenRequest {
  runId: string;
  title: string;
  isTeam: boolean;
  requestId: string;
  item: ItemDto;
}

export interface OpenRequestsState {
  requests: readonly OpenRequest[];
  error: string | null;
  /**
   * Answer one card the way its thread answers it: the verdict over the
   * socket, then any pasted screenshots as the next message of that thread.
   */
  answer: (
    request: OpenRequest,
    allow: boolean,
    answer?: string,
    images?: SendMessageDtoImagesInner[],
    optionId?: string,
  ) => void;
}

function firstQuestion(payload: unknown): string | null {
  const questions = (payload as { questions?: unknown } | null)?.questions;
  const first: unknown = Array.isArray(questions) ? questions[0] : null;
  const text = (first as { question?: unknown } | null)?.question;
  return typeof text === 'string' && text.trim() !== '' ? text.trim() : null;
}

/** Whether the card asks the user something, or holds a tool call for a yes or a no. */
export function askKindOf(request: OpenRequest): 'question' | 'approval' {
  return firstQuestion(request.item.payload) === null ? 'approval' : 'question';
}

/** What the thread's card says it waits on: the question it asks, or the call it wants to make. */
export function askLineOf(request: OpenRequest): string {
  const question = firstQuestion(request.item.payload);
  if (question !== null) {
    return `Asks: ${question}`;
  }
  const tool = payloadString(request.item.payload, 'toolName') ?? 'a tool';
  const input = (request.item.payload as { input?: unknown } | null)?.input;
  const command = (input as { command?: unknown } | null)?.command;
  return typeof command === 'string' && command.trim() !== ''
    ? `Wants to run: ${command.trim()}`
    : `Wants to use ${tool}`;
}

/** What makes the open cards worth reading again: which threads wait, on what, as of when. */
export function askingKey(threads: readonly AskingThread[]): string {
  return threads
    .map(
      (thread) => `${thread.runId}:${thread.awaiting}:${thread.lastActivityAt}`,
    )
    .sort()
    .join('|');
}

/**
 * The question and approval cards the user's threads hold open, read from
 * each waiting thread's own run state — the same cards, with the same request
 * ids, the thread pins above its composer — oldest first per thread.
 */
export function useOpenRequests(
  apis: DaemonApis,
  client: DaemonClient | null,
  threads: readonly AskingThread[],
): OpenRequestsState {
  const [requests, setRequests] = useState<OpenRequest[]>([]);
  const [error, setError] = useState<string | null>(null);
  const [settled, setSettled] = useState<ReadonlySet<string>>(() => new Set());
  const generation = useRef(0);
  const key = askingKey(threads);

  const read = useLatestCallback(() => {
    const mine = ++generation.current;
    void Promise.all(
      threads.map(async (thread) => {
        const state = await apis.chats.readRunState({ runId: thread.runId });
        return state.openRequests.flatMap((item): OpenRequest[] => {
          const requestId = payloadString(item.payload, 'id');
          return requestId === null
            ? []
            : [
                {
                  runId: thread.runId,
                  title: thread.title,
                  isTeam: thread.isTeam,
                  requestId,
                  item,
                },
              ];
        });
      }),
    )
      .then((perThread) => {
        if (mine !== generation.current) {
          return;
        }
        setRequests(perThread.flat());
        setSettled(new Set());
        setError(null);
      })
      .catch((err: unknown) => {
        if (mine === generation.current) {
          setError(describeDaemonError(err));
        }
      });
  }, [apis, threads]);

  useEffect(() => {
    read();
  }, [key, read]);

  const answer = useLatestCallback(
    (
      request: OpenRequest,
      allow: boolean,
      text?: string,
      images?: SendMessageDtoImagesInner[],
      optionId?: string,
    ): void => {
      if (client === null) {
        setError('Not connected to the daemon — try again in a moment');
        return;
      }
      if (optionId === undefined) {
        client.sendVerdict(request.runId, request.requestId, allow, text);
      } else {
        client.sendVerdict(
          request.runId,
          request.requestId,
          allow,
          text,
          optionId,
        );
      }
      setSettled(
        (held) => new Set([...held, `${request.runId}:${request.requestId}`]),
      );
      if (!images?.length) {
        return;
      }
      const message = {
        runId: request.runId,
        sendMessageDto: { text: '', images },
      };
      void (
        request.isTeam
          ? apis.teams.sendTeamRunMessage(message)
          : apis.chats.sendChatMessage(message)
      ).catch((err: unknown) => setError(describeDaemonError(err)));
    },
    [apis, client],
  );

  return {
    requests: requests.filter(
      (request) => !settled.has(`${request.runId}:${request.requestId}`),
    ),
    error,
    answer,
  };
}
