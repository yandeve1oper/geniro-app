// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeAll, describe, expect, it, vi } from 'vitest';

import type { ItemDto } from '../autogenerated';
import { NeedsYouPanel, type NeedsYouPanelProps } from './needs-you-panel';
import type { OpenRequest } from './use-open-requests';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

beforeAll(() => {
  Element.prototype.scrollIntoView = vi.fn();
});

afterEach(() => {
  act(() => root?.unmount());
  container?.remove();
  root = null;
  container = null;
});

function request(
  runId: string,
  requestId: string,
  payload: Record<string, unknown>,
): OpenRequest {
  return {
    runId,
    title: `Thread ${runId}`,
    isTeam: false,
    requestId,
    item: {
      id: `item-${requestId}`,
      runId,
      kind: 'approval_request',
      payload: { id: requestId, ...payload },
    } as unknown as ItemDto,
  };
}

const QUESTION = request('long-worker', 'q-1', {
  toolName: 'AskUserQuestion',
  input: {
    questions: [
      {
        question: 'Which colour do you want?',
        options: [{ label: 'Red' }, { label: 'Blue' }],
      },
    ],
  },
  questions: [
    {
      question: 'Which colour do you want?',
      options: [{ label: 'Red' }, { label: 'Blue' }],
    },
  ],
});

const APPROVAL = request('plain-chat', 'a-1', {
  toolName: 'Bash',
  input: { command: 'ls' },
});

function render(over: Partial<NeedsYouPanelProps> = {}): HTMLElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() =>
    root!.render(
      <NeedsYouPanel
        requests={[QUESTION, APPROVAL]}
        error={null}
        focusRunId={null}
        onAnswer={vi.fn()}
        onOpenThread={vi.fn()}
        {...over}
      />,
    ),
  );
  return container;
}

const buttonNamed = (el: Element, text: string): HTMLButtonElement =>
  [...el.querySelectorAll<HTMLButtonElement>('button')].find(
    (button) => button.textContent === text,
  )!;

const entryOf = (el: HTMLElement, runId: string): HTMLElement =>
  el.querySelector<HTMLElement>(
    `[data-slot="needs-you-request"][data-run-id="${runId}"]`,
  )!;

describe('NeedsYouPanel', () => {
  it('lists every open card under its thread, the question and the approval alike', () => {
    const el = render();

    expect(el.querySelectorAll('[data-slot="needs-you-request"]')).toHaveLength(
      2,
    );
    expect(entryOf(el, 'long-worker').textContent).toContain(
      'Which colour do you want?',
    );
    expect(entryOf(el, 'plain-chat').textContent).toContain('Approve');
  });

  it('answers a question from the panel with the option picked', () => {
    const onAnswer = vi.fn();
    const el = render({ onAnswer });

    act(() => buttonNamed(entryOf(el, 'long-worker'), 'Red').click());

    expect(onAnswer).toHaveBeenCalledTimes(1);
    expect(onAnswer.mock.calls[0]!.slice(0, 3)).toEqual([
      QUESTION,
      true,
      'Red',
    ]);
  });

  it('approves a held tool call from the panel', () => {
    const onAnswer = vi.fn();
    const el = render({ onAnswer });

    act(() => buttonNamed(entryOf(el, 'plain-chat'), 'Approve').click());

    expect(onAnswer).toHaveBeenCalledTimes(1);
    expect(onAnswer.mock.calls[0]![0]).toBe(APPROVAL);
    expect(onAnswer.mock.calls[0]![1]).toBe(true);
  });

  it('still opens the thread from its Go to thread button', () => {
    const onOpenThread = vi.fn();
    const el = render({ onOpenThread });

    act(() =>
      entryOf(el, 'plain-chat')
        .querySelector<HTMLButtonElement>('[data-slot="thread-card-go"]')!
        .click(),
    );

    expect(onOpenThread).toHaveBeenCalledWith('plain-chat');
  });

  it('marks the thread it was opened for, and says when nothing waits', () => {
    expect(
      entryOf(render({ focusRunId: 'plain-chat' }), 'plain-chat').className,
    ).toContain('ring-2');
    act(() => root?.unmount());
    container?.remove();

    expect(render({ requests: [] }).textContent).toContain(
      'No thread is waiting on you.',
    );
  });
});
