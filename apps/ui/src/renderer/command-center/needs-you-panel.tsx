import { CircleCheck } from 'lucide-react';
import { useEffect, useRef } from 'react';

import type { SendMessageDtoImagesInner } from '../autogenerated';
import { ApprovalCard } from '../chats/approval-card';
import { payloadString } from '../chats/transcript-payload';
import { EmptyState } from '../components/empty-state';
import { ErrorText } from '../components/error-text';
import { cn } from '../components/ui/utils';
import { GoToThreadButton } from './thread-card';
import type { OpenRequest } from './use-open-requests';

export interface NeedsYouPanelProps {
  requests: readonly OpenRequest[];
  error: string | null;
  /** The thread whose cards to bring into view, or null. */
  focusRunId: string | null;
  onAnswer: (
    request: OpenRequest,
    allow: boolean,
    answer?: string,
    images?: SendMessageDtoImagesInner[],
    optionId?: string,
  ) => void;
  onOpenThread: (runId: string) => void;
  className?: string;
}

function RequestEntry({
  request,
  focused,
  onAnswer,
  onOpenThread,
}: {
  request: OpenRequest;
  focused: boolean;
  onAnswer: NeedsYouPanelProps['onAnswer'];
  onOpenThread: (runId: string) => void;
}): React.JSX.Element {
  const ref = useRef<HTMLLIElement>(null);
  useEffect(() => {
    if (focused) {
      ref.current?.scrollIntoView({ block: 'nearest', behavior: 'smooth' });
    }
  }, [focused]);
  const payload = request.item.payload as {
    input?: unknown;
    questions?: unknown;
    options?: unknown;
  } | null;
  return (
    <li
      ref={ref}
      data-slot="needs-you-request"
      data-run-id={request.runId}
      className={cn(
        'flex flex-col gap-2 rounded-card border border-border bg-background p-3',
        focused && 'ring-2 ring-warning/60',
      )}>
      <div className="flex min-w-0 items-center gap-2">
        <span
          title={request.title}
          className="min-w-0 flex-1 truncate text-sm font-semibold">
          {request.title}
        </span>
        <GoToThreadButton onGo={() => onOpenThread(request.runId)} />
      </div>
      <ApprovalCard
        toolName={payloadString(request.item.payload, 'toolName') ?? 'tool'}
        input={payload?.input ?? null}
        questions={payload?.questions}
        options={payload?.options}
        requestId={request.requestId}
        threadTitle={payloadString(request.item.payload, 'threadTitle')}
        threadText={payloadString(request.item.payload, 'threadText')}
        verdict={null}
        onRespond={(allow, answer, images, optionId) =>
          onAnswer(request, allow, answer, images, optionId)
        }
      />
    </li>
  );
}

/**
 * Every question and approval the user's threads hold open, each the very card
 * its thread pins above its composer and answered the same way — so the user
 * runs every thread's asks from the command center without opening one.
 */
export function NeedsYouPanel({
  requests,
  error,
  focusRunId,
  onAnswer,
  onOpenThread,
  className,
}: NeedsYouPanelProps): React.JSX.Element {
  return (
    <section
      aria-label="Needs you"
      data-slot="command-center-needs-you"
      className={cn(
        'flex min-h-0 w-full flex-1 flex-col bg-card text-card-foreground',
        className,
      )}>
      {error === null ? null : (
        <ErrorText className="mx-4 mt-3 shrink-0 rounded-md bg-destructive/10 px-3 py-2 text-sm">
          {error}
        </ErrorText>
      )}
      <div className="min-h-0 flex-1 overflow-y-auto px-4 pt-3 pb-4">
        {requests.length === 0 ? (
          <EmptyState icon={<CircleCheck />}>
            No thread is waiting on you.
          </EmptyState>
        ) : (
          <ol className="flex flex-col gap-3">
            {requests.map((request) => (
              <RequestEntry
                key={`${request.runId}:${request.requestId}`}
                request={request}
                focused={request.runId === focusRunId}
                onAnswer={onAnswer}
                onOpenThread={onOpenThread}
              />
            ))}
          </ol>
        )}
      </div>
    </section>
  );
}
