import type { DaemonHandle } from '../../shared/contracts';
import type { AgentKind, RunDto } from '../autogenerated';
import { HostedChatDock } from '../chats/hosted-chat-dock';
import type { WorkingThread } from '../chats/working-threads-card';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { currentRunSettings } from '../run-settings';

/**
 * The command center's manager, filling the page: one conversation for the
 * whole app. The user writes in plain words and the manager works out
 * which threads they mean. Opening it with `agentKind` matters only the first
 * time — an existing manager keeps its own agent and settings.
 */
export function ManagerDock({
  apis,
  handle,
  client,
  agentKind,
  hidden,
  workingThreads,
  onOpenThread,
  onTurnSettled,
}: {
  apis: DaemonApis;
  handle: DaemonHandle;
  client: DaemonClient;
  agentKind: AgentKind;
  hidden: boolean;
  /** The manager's threads at work or waiting on the user, for the chat's corner card. */
  workingThreads: readonly WorkingThread[];
  onOpenThread: (runId: string) => void;
  onTurnSettled: () => void;
}): React.JSX.Element {
  const open = useLatestCallback(
    async (): Promise<RunDto> =>
      apis.commandCenter.openCommandCenterChat({
        startCommandCenterChatDto: {
          agentKind,
          ...(await currentRunSettings()),
        },
      }),
    [apis, agentKind],
  );
  const discard = useLatestCallback(async (): Promise<void> => {
    await apis.commandCenter.discardCommandCenterChat();
  }, [apis]);

  return (
    <HostedChatDock
      label="Command center manager"
      panelName="manager panel"
      storageKey="commandCenter.panelHeight"
      handle={handle}
      client={client}
      hidden={hidden}
      fill
      confirmStartOver={{
        title: 'Reset the manager?',
        body: 'Its conversation and its roster — the threads it manages and its notes on them — are deleted. The threads themselves are not touched. This cannot be undone.',
        confirmLabel: 'Reset',
      }}
      thread={{
        open,
        discard,
        queueScope: 'command-center',
        emptyText:
          'Tell the manager what you want in plain words — "ask billing and cache to rebase on main", "start a thread to fix the login redirect in Web". It works out which threads you mean, and asks back when it cannot tell.',
        composerLabel: 'Message the manager',
        composerPlaceholder: 'What should your threads do?',
        onTurnSettled,
        workingThreads,
        onOpenThread,
      }}
    />
  );
}
