import { describe, expect, it } from 'vitest';

import type { CommandCenterTimelineEvent } from '../autogenerated';
import { mergeNewestPage } from './use-command-center-timeline';

function event(id: string, at: string): CommandCenterTimelineEvent {
  return {
    id,
    at,
    kind: 'thread_message',
    threadRunId: 'run-1',
    threadTitle: 'Billing',
    text: id,
    detail: null,
    awaitingReply: false,
  };
}

describe('mergeNewestPage', () => {
  it('takes the newest page alone while no older page has been read', () => {
    const held = [event('old', '2026-11-17T09:00:00.000Z')];
    const page = [event('new', '2026-11-17T11:00:00.000Z')];

    expect(mergeNewestPage(held, page, true)).toEqual(page);
  });

  it('keeps the older events already read behind a fresh newest page, replacing what it repeats', () => {
    const held = [
      event('a', '2026-11-17T11:00:00.000Z'),
      event('b', '2026-11-17T10:00:00.000Z'),
      event('c', '2026-11-17T09:00:00.000Z'),
    ];
    const page = [
      { ...event('n', '2026-11-17T12:00:00.000Z') },
      { ...event('a', '2026-11-17T11:00:00.000Z'), awaitingReply: true },
      event('b', '2026-11-17T10:00:00.000Z'),
    ];

    expect(
      mergeNewestPage(held, page, false).map((item) => [
        item.id,
        item.awaitingReply,
      ]),
    ).toEqual([
      ['n', false],
      ['a', true],
      ['b', false],
      ['c', false],
    ]);
  });
});
