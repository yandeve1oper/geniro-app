import type { Meta, StoryObj } from '@storybook/react-vite';

import type { ItemDto } from '../autogenerated';
import { NeedsYouPanel } from './needs-you-panel';
import type { OpenRequest } from './use-open-requests';

function request(
  runId: string,
  title: string,
  requestId: string,
  payload: Record<string, unknown>,
): OpenRequest {
  return {
    runId,
    title,
    isTeam: false,
    requestId,
    item: {
      id: `item-${requestId}`,
      runId,
      kind: 'approval_request',
      payload: { id: requestId, ...payload },
    } as unknown as ItemDto,
  };
}

const QUESTION_INPUT = {
  questions: [
    {
      question: 'Which colour do you want?',
      header: 'Colour',
      options: [
        { label: 'Red', description: 'Warm and loud' },
        { label: 'Blue', description: 'Calm and quiet' },
      ],
    },
  ],
};

const meta = {
  title: 'Command center/NeedsYouPanel',
  component: NeedsYouPanel,
  args: {
    requests: [
      request('long-worker', 'Long worker', 'q-1', {
        toolName: 'AskUserQuestion',
        input: QUESTION_INPUT,
        questions: QUESTION_INPUT.questions,
      }),
      request('plain-chat', 'Plain ordinary chat', 'a-1', {
        toolName: 'Bash',
        input: { command: 'ping -c 4 127.0.0.1' },
      }),
    ],
    error: null,
    focusRunId: null,
    onAnswer: () => {},
    onOpenThread: () => {},
  },
  decorators: [
    (story) => (
      <div className="flex h-[640px] w-[400px] flex-col border border-border">
        {story()}
      </div>
    ),
  ],
} satisfies Meta<typeof NeedsYouPanel>;

export default meta;
type Story = StoryObj<typeof meta>;

/** A question and a held tool call from two threads, each answerable in place. */
export const QuestionAndApproval: Story = {};

/** Opened from a card's Answer button: that thread's card is marked. */
export const Focused: Story = { args: { focusRunId: 'plain-chat' } };

/** Nothing waits on the user. */
export const Empty: Story = { args: { requests: [] } };
