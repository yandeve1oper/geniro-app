import { useEffect, useRef, useState } from 'react';

import type { CommandCenterTimelineEvent } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

const PAGE_SIZE = 100;

/** How long a burst of board changes is gathered before the newest page is read again. */
const REFRESH_DELAY_MS = 1500;

export interface CommandCenterTimelineState {
  events: readonly CommandCenterTimelineEvent[];
  loading: boolean;
  error: string | null;
  hasMore: boolean;
  loadOlder: () => void;
}

/**
 * The newest page with the older events already held after it: an event the
 * new page carries replaces its held copy, and nothing older than the page is
 * dropped.
 */
export function mergeNewestPage(
  held: readonly CommandCenterTimelineEvent[],
  page: readonly CommandCenterTimelineEvent[],
  pageIsWhole: boolean,
): CommandCenterTimelineEvent[] {
  if (pageIsWhole || page.length === 0) {
    return [...page];
  }
  const oldest = page.at(-1)!.at;
  const ids = new Set(page.map((event) => event.id));
  return [
    ...page,
    ...held.filter((event) => event.at < oldest && !ids.has(event.id)),
  ];
}

/**
 * The command center's timeline while its panel is open: the newest page on
 * open, read again a moment after the board changes or a message passes,
 * and older pages on request.
 */
export function useCommandCenterTimeline(
  apis: DaemonApis,
  client: DaemonClient | null,
  open: boolean,
): CommandCenterTimelineState {
  const [events, setEvents] = useState<CommandCenterTimelineEvent[]>([]);
  const [nextBefore, setNextBefore] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const generation = useRef(0);
  const olderLoaded = useRef(false);

  const readNewest = useLatestCallback(() => {
    const mine = ++generation.current;
    setLoading(true);
    void apis.commandCenter
      .listCommandCenterTimeline({ limit: PAGE_SIZE })
      .then((page) => {
        if (mine !== generation.current) {
          return;
        }
        setEvents((held) =>
          mergeNewestPage(held, page.events, !olderLoaded.current),
        );
        if (!olderLoaded.current) {
          setNextBefore(page.nextBefore);
        }
        setError(null);
      })
      .catch((err: unknown) => {
        if (mine === generation.current) {
          setError(describeDaemonError(err));
        }
      })
      .finally(() => {
        if (mine === generation.current) {
          setLoading(false);
        }
      });
  }, [apis]);

  const loadOlder = useLatestCallback(() => {
    if (nextBefore === null || loading) {
      return;
    }
    const mine = ++generation.current;
    setLoading(true);
    void apis.commandCenter
      .listCommandCenterTimeline({ before: nextBefore, limit: PAGE_SIZE })
      .then((page) => {
        if (mine !== generation.current) {
          return;
        }
        olderLoaded.current = true;
        setEvents((held) => {
          const ids = new Set(held.map((event) => event.id));
          return [
            ...held,
            ...page.events.filter((event) => !ids.has(event.id)),
          ];
        });
        setNextBefore(page.nextBefore);
        setError(null);
      })
      .catch((err: unknown) => {
        if (mine === generation.current) {
          setError(describeDaemonError(err));
        }
      })
      .finally(() => {
        if (mine === generation.current) {
          setLoading(false);
        }
      });
  }, [apis, nextBefore, loading]);

  useEffect(() => {
    if (!open) {
      return;
    }
    olderLoaded.current = false;
    readNewest();
  }, [open, readNewest]);

  useEffect(() => {
    if (!open || client === null) {
      return;
    }
    let timer: ReturnType<typeof setTimeout> | null = null;
    const soon = (): void => {
      if (timer === null) {
        timer = setTimeout(() => {
          timer = null;
          readNewest();
        }, REFRESH_DELAY_MS);
      }
    };
    const offChanged = client.onCommandCenterChanged(soon);
    const offContact = client.onCommandCenterContact(soon);
    const offReconnect = client.onReconnect(soon);
    return () => {
      offChanged();
      offContact();
      offReconnect();
      if (timer !== null) {
        clearTimeout(timer);
      }
    };
  }, [open, client, readNewest]);

  return {
    events,
    loading,
    error,
    hasMore: nextBefore !== null,
    loadOlder,
  };
}
