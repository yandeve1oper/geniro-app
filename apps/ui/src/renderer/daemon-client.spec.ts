// A fake Socket.IO socket whose 'connect' handler and onAny dispatcher the test
// can drive directly. vi.hoisted so the vi.mock factory can close over it.
const mocks = vi.hoisted(() => {
  const handlers: Record<string, (...args: unknown[]) => void> = {};
  const ref: { any: ((event: string, data: unknown) => void) | null } = {
    any: null,
  };
  const emit = vi.fn();
  const close = vi.fn();
  const engineClose = vi.fn();
  const socket = {
    connected: false,
    io: { engine: { close: engineClose } },
    on: (event: string, h: (...args: unknown[]) => void) => {
      handlers[event] = h;
    },
    onAny: (h: (event: string, data: unknown) => void) => {
      ref.any = h;
    },
    emit,
    close,
  };
  return {
    handlers,
    ref,
    emit,
    close,
    engineClose,
    socket,
    io: vi.fn(() => socket),
  };
});

vi.mock('socket.io-client', () => ({ io: mocks.io }));

const remote = vi.hoisted(() => ({ paired: false }));

vi.mock('./remote/remote-session', () => ({
  isRemoteRuntime: () => remote.paired,
}));

const handle: DaemonHandle = {
  host: '127.0.0.1',
  port: 8123,
  token: 'tok',
  version: '1',
  startedAt: '2026-01-01T00:00:00.000Z',
};

function fireConnect(): void {
  mocks.socket.connected = true;
  mocks.handlers.connect?.();
}

function fireJoined(runId: string): void {
  mocks.ref.any?.('joined', { runId });
}

/** Let every pending microtask run — a macrotask drains the whole queue. */
function flushMicrotasks(): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, 0));
}

beforeEach(() => {
  remote.paired = false;
  mocks.emit.mockClear();
  mocks.close.mockClear();
  mocks.engineClose.mockClear();
  mocks.io.mockClear();
  mocks.socket.connected = false;
  mocks.ref.any = null;
  for (const key of Object.keys(mocks.handlers)) {
    delete mocks.handlers[key];
  }
});

describe('DaemonClient', () => {
  it('fires onReconnect only after the active room is re-joined', async () => {
    const client = new DaemonClient(handle, {});
    const reconnects: number[] = [];
    client.onReconnect(() => reconnects.push(1));
    client.connect();
    const initialJoin = client.joinRun('r1');

    // First connect is NOT a reconnect: no onReconnect, but the active room is
    // (re-)joined so live items resume.
    mocks.emit.mockClear();
    fireConnect();
    expect(reconnects).toHaveLength(0);
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });
    fireJoined('r1');
    await initialJoin;

    // Second connect IS a reconnect, but replay is held until the joined event.
    mocks.emit.mockClear();
    fireConnect();
    expect(reconnects).toHaveLength(0);
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });
    fireJoined('r1');
    // A macrotask, so every pending microtask has run: the assertion above —
    // still zero with the join event withheld — is what pins the HOLD, and
    // counting ticks here only pins how many promises the re-join is built
    // from.
    await flushMicrotasks();
    expect(reconnects).toHaveLength(1);
  });

  // Two surfaces can each be following a run — the chat screen stays mounted
  // while the team builder's chat panel is open — and a reconnect that
  // re-joined one of them left the other live and permanently silent.
  it('re-joins EVERY joined room after a reconnect, and waits for all of them', async () => {
    const client = new DaemonClient(handle, {});
    const reconnects: number[] = [];
    client.onReconnect(() => reconnects.push(1));
    client.connect();
    const first = client.joinRun('r1');
    const second = client.joinRun('r2');
    fireConnect();
    fireJoined('r1');
    fireJoined('r2');
    await Promise.all([first, second]);

    mocks.emit.mockClear();
    fireConnect();
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r2' });

    fireJoined('r1');
    await flushMicrotasks();
    expect(reconnects).toHaveLength(0);

    fireJoined('r2');
    await flushMicrotasks();
    expect(reconnects).toHaveLength(1);
  });

  it('stops re-joining a room that was left', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    const joining = client.joinRun('r1');
    fireConnect();
    fireJoined('r1');
    await joining;
    client.leaveRun('r1');

    mocks.emit.mockClear();
    fireConnect();

    expect(mocks.emit).not.toHaveBeenCalledWith('join', { runId: 'r1' });
  });

  it('routes only `item` events from onAny to onItem subscribers', () => {
    const client = new DaemonClient(handle, {});
    const items: ChatItem[] = [];
    client.onItem((i) => items.push(i));
    client.connect();

    const item: ChatItem = {
      id: 'i0',
      runId: 'r1',
      memberId: null,
      seq: 0,
      kind: 'message',
      role: 'assistant',
      payload: { text: 'hi' },
      createdAt: 'now',
    };
    mocks.ref.any?.('item', item);
    mocks.ref.any?.('other', { x: 1 });

    expect(items).toEqual([item]);
  });

  it('forwards a question answer in the exact verdict payload', () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    fireConnect();

    client.sendVerdict('r1', 'req-1', true, 'Blue');

    expect(mocks.emit).toHaveBeenCalledWith('verdict', {
      runId: 'r1',
      requestId: 'req-1',
      allow: true,
      answer: 'Blue',
    });
  });

  it('reports a failed connection ATTEMPT, with the reason', () => {
    // Socket.IO retries forever and reports nothing else, so without this the
    // renderer cannot tell "still connecting" from "will never connect" — and
    // a daemon that is down produced no signal in the UI at all.
    const onError = vi.fn();
    const client = new DaemonClient(handle, { onError });
    client.connect();

    mocks.handlers.connect_error?.(
      new Error('xhr poll error: connect ECONNREFUSED 127.0.0.1:8123'),
    );

    expect(onError).toHaveBeenCalledWith(
      'xhr poll error: connect ECONNREFUSED 127.0.0.1:8123 (127.0.0.1:8123)',
    );
  });

  it('names the endpoint, because Socket.IO’s own wording does not', () => {
    // Observed against a dead port: the whole reason reaching the UI was
    // "websocket error". True, and useless for the one thing the user can
    // act on — which port are we dialling, and is anything on it. Host and
    // port are negotiated per launch, so this client is the only place that
    // knows them.
    const onError = vi.fn();
    const client = new DaemonClient(handle, { onError });
    client.connect();

    mocks.handlers.connect_error?.(new Error('websocket error'));

    expect(onError).toHaveBeenCalledWith('websocket error (127.0.0.1:8123)');
  });

  it('never hands the renderer an empty reason to render', () => {
    // A transport error with a blank message would put an empty sentence on
    // the connection strip, which reads as a broken UI rather than a failure.
    const onError = vi.fn();
    const client = new DaemonClient(handle, { onError });
    client.connect();

    mocks.handlers.connect_error?.(new Error(''));

    expect(onError).toHaveBeenCalledWith(
      'could not reach the daemon (127.0.0.1:8123)',
    );
  });

  it('passes the disconnect REASON on, rather than just the fact', () => {
    // "transport close" (the daemon exited) and "io server disconnect" (it
    // rejected us) are different problems with different fixes.
    const onClose = vi.fn();
    const client = new DaemonClient(handle, { onClose });
    client.connect();
    fireConnect();

    mocks.handlers.disconnect?.('transport close');

    expect(onClose).toHaveBeenCalledWith('transport close');
  });

  // A phone's browser cuts a backgrounded page's connection without a close
  // frame, so the socket still reads `connected` while every join goes into
  // the void until Socket.IO's own ping timeout. REPORTED as `timed out
  // joining run` through a tunnel.
  it('drops a transport that leaves a join unanswered, so the room is restored', async () => {
    vi.useFakeTimers();
    try {
      const client = new DaemonClient(handle, {});
      client.connect();
      fireConnect();

      const joining = client.joinRun('r1');
      const settled = joining.catch((err: unknown) => err);
      await vi.advanceTimersByTimeAsync(5_000);

      expect(await settled).toEqual(new Error('timed out joining run r1'));
      // The ENGINE, so the manager reconnects under its own backoff — a
      // `disconnect()` would switch reconnection off.
      expect(mocks.engineClose).toHaveBeenCalledTimes(1);
      expect(mocks.close).not.toHaveBeenCalled();

      // …and the reconnect puts the room back, since the timeout did not
      // forget it.
      mocks.emit.mockClear();
      fireConnect();
      expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });
    } finally {
      vi.useRealTimers();
    }
  });

  it('leaves a transport that is already down to its own reconnection', async () => {
    vi.useFakeTimers();
    try {
      const client = new DaemonClient(handle, {});
      client.connect();

      const settled = client.joinRun('r1').catch((err: unknown) => err);
      await vi.advanceTimersByTimeAsync(5_000);

      expect(await settled).toBeInstanceOf(Error);
      expect(mocks.engineClose).not.toHaveBeenCalled();
    } finally {
      vi.useRealTimers();
    }
  });

  it('leaveRun clears the active room so a later reconnect does not rejoin it', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    fireConnect();
    const joined = client.joinRun('r1');
    fireJoined('r1');
    await joined;
    client.leaveRun('r1');

    mocks.emit.mockClear();
    fireConnect();
    expect(mocks.emit).not.toHaveBeenCalledWith('join', { runId: 'r1' });
  });

  // The team dock and an analysis popup follow their run over the same socket
  // as the chat screen; one surface letting go must not take the room from
  // the other.
  it('keeps a room two surfaces joined until both have left it', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    fireConnect();
    const first = client.joinRun('r1');
    const second = client.joinRun('r1');
    fireJoined('r1');
    await Promise.all([first, second]);

    mocks.emit.mockClear();
    client.leaveRun('r1');
    expect(mocks.emit).not.toHaveBeenCalledWith('leave', { runId: 'r1' });
    fireConnect();
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });

    mocks.emit.mockClear();
    client.leaveRun('r1');
    expect(mocks.emit).toHaveBeenCalledWith('leave', { runId: 'r1' });
    fireConnect();
    expect(mocks.emit).not.toHaveBeenCalledWith('join', { runId: 'r1' });
  });

  it('keeps a second surface’s join pending when the first leaves before the answer', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    fireConnect();
    const first = client.joinRun('r1');
    const second = client.joinRun('r1');
    client.leaveRun('r1');

    fireJoined('r1');

    await expect(first).resolves.toBeUndefined();
    await expect(second).resolves.toBeUndefined();
  });
});

describe('parseRunStatus — the run_status twin', () => {
  it('reads the unread moments, and drops one that is not an instant', () => {
    expect(
      parseRunStatus({
        runId: 'r1',
        status: null,
        attentionAt: '2026-10-06T10:00:00.000Z',
        seenAt: '2026-10-06T10:05:00.000Z',
      }),
    ).toMatchObject({
      attentionAt: '2026-10-06T10:00:00.000Z',
      seenAt: '2026-10-06T10:05:00.000Z',
    });
    const skewed = parseRunStatus({
      runId: 'r1',
      status: null,
      attentionAt: 'soon',
      seenAt: 7,
    });
    expect(skewed).not.toHaveProperty('attentionAt');
    expect(skewed).not.toHaveProperty('seenAt');
  });

  it('carries the run’s lead, a null included, and drops one that is not a string', () => {
    expect(
      parseRunStatus({ runId: 'r1', status: null, currentLead: 'bob' }),
    ).toMatchObject({ currentLead: 'bob' });
    expect(
      parseRunStatus({ runId: 'r1', status: null, currentLead: null }),
    ).toMatchObject({ currentLead: null });
    expect(
      parseRunStatus({ runId: 'r1', status: null, currentLead: 3 }),
    ).not.toHaveProperty('currentLead');
    expect(parseRunStatus({ runId: 'r1', status: null })).not.toHaveProperty(
      'currentLead',
    );
  });

  it('carries the monitors-changed marker, and drops one that is not a number', () => {
    expect(
      parseRunStatus({ runId: 'r1', status: null, monitorsChangedAt: 1700 }),
    ).toMatchObject({ monitorsChangedAt: 1700 });
    expect(
      parseRunStatus({ runId: 'r1', status: null, monitorsChangedAt: 'now' }),
    ).not.toHaveProperty('monitorsChangedAt');
  });

  it('carries the running-monitor count, zero included, and drops one that is not a number', () => {
    expect(
      parseRunStatus({ runId: 'r1', status: null, monitorsOpen: 2 }),
    ).toMatchObject({ monitorsOpen: 2 });
    expect(
      parseRunStatus({ runId: 'r1', status: null, monitorsOpen: 0 }),
    ).toMatchObject({ monitorsOpen: 0 });
    expect(
      parseRunStatus({ runId: 'r1', status: null, monitorsOpen: 'two' }),
    ).not.toHaveProperty('monitorsOpen');
  });

  it('carries which announced pull requests the run opened, reading a missing mark as touched', () => {
    const ref = (number: number) => ({
      owner: 'o',
      repo: 'r',
      number,
      url: `https://github.com/o/r/pull/${number}`,
      seq: number,
    });
    expect(
      parseRunStatus({
        runId: 'r1',
        status: null,
        pullRequests: [{ ...ref(1), opened: true }, ref(2)],
      })?.pullRequests?.map((row) => ({
        number: row.number,
        opened: row.opened,
      })),
    ).toEqual([
      { number: 1, opened: true },
      { number: 2, opened: false },
    ]);
  });

  it("carries each pull request's recorded outcome, and none for a missing or partial one", () => {
    const ref = (number: number) => ({
      owner: 'o',
      repo: 'r',
      number,
      url: `https://github.com/o/r/pull/${number}`,
      seq: number,
      opened: true,
    });
    const outcome = {
      seq: 40,
      draft: false,
      reviewRounds: 2,
      acceptance: 'accepted',
      questionsAsked: 3,
    };
    expect(
      parseRunStatus({
        runId: 'r1',
        status: null,
        pullRequests: [
          { ...ref(1), outcome },
          ref(2),
          { ...ref(3), outcome: { ...outcome, acceptance: 'merged' } },
          { ...ref(4), outcome: { ...outcome, reviewRounds: undefined } },
        ],
      })?.pullRequests?.map((row) => row.outcome),
    ).toEqual([outcome, null, null, null]);
  });

  it('admits an announced empty list, and drops one holding nothing usable', () => {
    expect(
      parseRunStatus({ runId: 'r1', status: null, pullRequests: [] })
        ?.pullRequests,
    ).toEqual([]);
    expect(
      parseRunStatus({
        runId: 'r1',
        status: null,
        pullRequests: [{ url: '' }],
      }),
    ).not.toHaveProperty('pullRequests');
  });

  describe('goals and outcome', () => {
    const goal = {
      id: 'g1',
      text: 'the export saves a csv',
      source: 'agent',
      status: 'achieved',
      evidence: 'saved report.csv',
      memberId: 'dev',
      createdAt: '2026-11-01T00:00:00.000Z',
      closedAt: '2026-11-01T00:05:00.000Z',
    };
    const outcome = {
      kind: 'success',
      summary: null,
      source: 'goals',
      seq: null,
    };

    it('reads the goal list whole and the outcome', () => {
      const event = parseRunStatus({
        runId: 'r1',
        status: null,
        goals: [goal],
        outcome,
      });
      expect(event?.goals).toEqual([goal]);
      expect(event?.outcome).toEqual(outcome);
    });

    it('drops a list with an unreadable goal, keeps an empty one and a null outcome', () => {
      expect(
        parseRunStatus({
          runId: 'r1',
          status: null,
          goals: [goal, { ...goal, status: 'won' }],
        }),
      ).not.toHaveProperty('goals');
      const cleared = parseRunStatus({
        runId: 'r1',
        status: null,
        goals: [],
        outcome: null,
      });
      expect(cleared?.goals).toEqual([]);
      expect(cleared).toHaveProperty('outcome', null);
      expect(
        parseRunStatus({
          runId: 'r1',
          status: null,
          outcome: { kind: 'great' },
        }),
      ).not.toHaveProperty('outcome');
    });
  });

  describe('stages', () => {
    const progress = {
      rev: 2,
      current: 'review',
      position: { index: 2, total: 3 },
      stages: [
        {
          id: 'build',
          title: 'Build',
          status: 'done',
          next: ['review'],
          by: { kind: 'agent', nodeId: 'manager', callId: 'call-1' },
          text: 'built',
          at: '2026-10-27T10:00:00.000Z',
        },
        { id: 'review', title: 'Review', status: 'current', next: ['ship'] },
        { id: 'ship', title: 'Ship', status: 'pending', next: [] },
      ],
    };

    it('carries the run’s stage progress whole', () => {
      expect(
        parseRunStatus({ runId: 'r1', status: null, stages: progress })?.stages,
      ).toEqual(progress);
    });

    it('carries a stage’s rev, the move that resolved it', () => {
      const withRev = {
        ...progress,
        stages: [
          { ...progress.stages[0], rev: 2 },
          ...progress.stages.slice(1),
        ],
      };
      const read = parseRunStatus({
        runId: 'r1',
        status: null,
        stages: withRev,
      })?.stages;
      expect(read?.stages[0]?.rev).toBe(2);
      expect(read?.stages[1]).not.toHaveProperty('rev');
    });

    it('reads a non-integer stage rev as no stages at all', () => {
      for (const rev of [1.5, '2', null]) {
        expect(
          parseRunStatus({
            runId: 'r1',
            status: null,
            stages: {
              ...progress,
              stages: [
                { ...progress.stages[0], rev },
                ...progress.stages.slice(1),
              ],
            },
          }),
        ).not.toHaveProperty('stages');
      }
    });

    it('asserts nothing when the announce carries no stages', () => {
      expect(parseRunStatus({ runId: 'r1', status: null })).not.toHaveProperty(
        'stages',
      );
    });

    it('reads a malformed value as absent rather than drawing a partial list', () => {
      const broken = [
        'review',
        { ...progress, position: { index: 2 } },
        { ...progress, current: 4 },
        { ...progress, stages: 'none' },
        {
          ...progress,
          stages: [
            progress.stages[0],
            { ...progress.stages[1], status: 'late' },
          ],
        },
        {
          ...progress,
          stages: [{ ...progress.stages[0], by: { kind: 'robot' } }],
        },
      ];
      for (const stages of broken) {
        expect(
          parseRunStatus({ runId: 'r1', status: null, stages }),
        ).not.toHaveProperty('stages');
      }
    });

    it('admits a finished run, whose current stage is null', () => {
      expect(
        parseRunStatus({
          runId: 'r1',
          status: null,
          stages: { ...progress, current: null },
        })?.stages?.current,
      ).toBeNull();
    });
  });

  it('carries whether the stamped context count is geniro’s stand-in', () => {
    expect(
      parseRunStatus({
        runId: 'r1',
        status: null,
        contextTokens: 900,
        contextWindowTokens: 200_000,
        contextEstimated: true,
      }),
    ).toMatchObject({ contextTokens: 900, contextEstimated: true });
    expect(
      parseRunStatus({ runId: 'r1', status: null, contextTokens: 900 }),
    ).toMatchObject({ contextTokens: 900, contextEstimated: false });
  });

  it('reads the prompt-cache expiry a settle carries, and drops one that is not an instant', () => {
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        promptCacheExpiresAt: '2026-10-09T11:00:00.000Z',
      }),
    ).toMatchObject({ promptCacheExpiresAt: '2026-10-09T11:00:00.000Z' });
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        promptCacheExpiresAt: 'later',
      }),
    ).not.toHaveProperty('promptCacheExpiresAt');
  });

  it('reads the lifetime and its reason only beside an expiry', () => {
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        promptCacheExpiresAt: '2026-10-09T10:05:00.000Z',
        promptCacheTtlMs: 300_000,
        promptCacheTtlReason: 'extra-usage',
      }),
    ).toMatchObject({
      promptCacheTtlMs: 300_000,
      promptCacheTtlReason: 'extra-usage',
    });
    // A null reason CLEARS: the newer lifetime has none.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        promptCacheExpiresAt: '2026-10-09T11:00:00.000Z',
        promptCacheTtlMs: 3_600_000,
        promptCacheTtlReason: null,
      }),
    ).toMatchObject({ promptCacheTtlReason: null });
    // Without the expiry they explain, neither is read; nor is a reason this
    // build does not know.
    const orphan = parseRunStatus({
      runId: 'r1',
      status: 'completed',
      promptCacheTtlMs: 300_000,
      promptCacheTtlReason: 'extra-usage',
    });
    expect(orphan).not.toHaveProperty('promptCacheTtlMs');
    expect(orphan).not.toHaveProperty('promptCacheTtlReason');
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        promptCacheExpiresAt: '2026-10-09T11:00:00.000Z',
        promptCacheTtlReason: 'mystery',
      }),
    ).not.toHaveProperty('promptCacheTtlReason');
  });

  it('reads an activity-only announce as carrying NO status', () => {
    // The daemon's activity announce fires on every tool call and never reads
    // the run, so it sends `status: null`. Read as a status, it would write a
    // guess onto the row — which is how a cancelled run went back to running.
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: 'running Bash' }),
    ).toEqual({ runId: 'r1', status: null, activity: 'running Bash' });
  });

  it('reads a MISSING status the same way', () => {
    expect(parseRunStatus({ runId: 'r1', activity: 'running Bash' })).toEqual({
      runId: 'r1',
      status: null,
      activity: 'running Bash',
    });
  });

  it('keeps whether a task group was stated whole, reading anything but true as patched', () => {
    const event = parseRunStatus({
      runId: 'r1',
      status: null,
      activity: null,
      taskList: [
        {
          memberId: 'eng',
          callId: 'call-1',
          tasks: [{ id: '1' }],
          snapshot: true,
        },
        {
          memberId: 'eng',
          callId: 'call-2',
          tasks: [{ id: '1' }],
          snapshot: 1,
        },
        { memberId: 'eng', callId: 'call-3', tasks: [{ id: '1' }] },
      ],
    });
    expect(event?.taskList?.map((group) => group.snapshot)).toEqual([
      true,
      false,
      false,
    ]);
  });

  it('reads the pending usage-limit continues, the empty list included, dropping a malformed one', () => {
    const wake = {
      instant: 1_000,
      continuesAt: 61_000,
      resetsAt: '6:10pm (UTC)',
      callIds: ['call-11'],
    };
    expect(
      parseRunStatus({
        runId: 'r1',
        status: null,
        resetWakes: [wake, { instant: 'soon' }, null],
      })?.resetWakes,
    ).toEqual([wake]);
    // EMPTY is a real reading: the last promise was kept or called off.
    expect(
      parseRunStatus({ runId: 'r1', status: null, resetWakes: [] })?.resetWakes,
    ).toEqual([]);
    // Absent asserts nothing.
    expect(
      parseRunStatus({ runId: 'r1', status: null })?.resetWakes,
    ).toBeUndefined();
  });

  it('keeps the write moment a status announce carries, and only a real date', () => {
    // The sidebar's ORDER rides this field and compares the strings lexically,
    // so a value that is merely non-empty would not degrade to "no reorder" —
    // it would sort, wrongly, and stay there until the next refetch.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'running',
        activity: null,
        at: '2026-03-01T00:00:00.000Z',
      }),
    ).toEqual({
      runId: 'r1',
      status: 'running',
      activity: null,
      at: '2026-03-01T00:00:00.000Z',
    });
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'running',
        activity: null,
        at: 'soon',
      }),
    ).toEqual({ runId: 'r1', status: 'running', activity: null });
  });

  it('still rejects an UNRECOGNISED status outright', () => {
    // Version skew must degrade to no update at all. Folding it in as "no
    // status" would silently downgrade a real status change into an activity
    // update, which is worse than dropping the frame.
    expect(
      parseRunStatus({ runId: 'r1', status: 'zombie', activity: null }),
    ).toBeNull();
  });

  it('still reads a real status change', () => {
    expect(
      parseRunStatus({ runId: 'r1', status: 'completed', activity: null }),
    ).toEqual({ runId: 'r1', status: 'completed', activity: null });
  });

  it('keeps a settle’s NULL summary, so a wordless turn clears the last one', () => {
    // Three states, and the middle one is the whole fix: the client holds the
    // last sentence it was given, so a settle that said nothing has to say so
    // out loud. Dropped, a `/compact` turn — which produces no assistant
    // message at all — notified with the answer from the turn before it.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: null,
      }),
    ).toEqual({
      runId: 'r1',
      status: 'completed',
      activity: null,
      summary: null,
    });
    // …while an ABSENT one still asserts nothing, which is what lets an
    // activity announce fire mid-turn without erasing the last settle's words.
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: 'running Bash' }),
    ).not.toHaveProperty('summary');
  });

  it('reads the housekeeping marker, and only when it is true', () => {
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: null,
        housekeeping: true,
      }),
    ).toMatchObject({ housekeeping: true });
    // A settle that did real work says nothing here rather than `false`, and a
    // daemon that predates the field is the same case — both must read as "not
    // housekeeping" without the key appearing.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: 'done',
      }),
    ).not.toHaveProperty('housekeeping');
  });

  it('reads the no-terminal-item marker, and only when it is true', () => {
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        noTerminalItem: true,
      }),
    ).toMatchObject({ noTerminalItem: true });
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        noTerminalItem: 'yes',
      }),
    ).not.toHaveProperty('noTerminalItem');
  });

  it('reads the host-turn marker, and only when it is true', () => {
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        hostTurn: true,
      }),
    ).toMatchObject({ hostTurn: true });
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        hostTurn: 'yes',
      }),
    ).not.toHaveProperty('hostTurn');
  });

  it('reads the restored marker, and only when it is true', () => {
    // A delegate lease expiring hands an already-settled status back. It has to
    // arrive distinguishable from a fresh ending, or the client fires a second
    // `turn ended` banner for a turn that ended minutes ago.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        restored: true,
      }),
    ).toMatchObject({ restored: true });
    // A real settle says nothing here rather than `false`, and a daemon that
    // predates the field is the same case.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: 'done',
      }),
    ).not.toHaveProperty('restored');
  });

  it('leaves activity ABSENT when the announce carried none', () => {
    // The middle link of the naming-does-not-wipe-activity chain: the renderer
    // test asserts on a hand-built event, so without this the parser is free to
    // fold an absent key back into `null` and restore the bug.
    const parsed = parseRunStatus({ runId: 'r1', status: null, title: 'X' });

    expect(parsed).not.toHaveProperty('activity');
  });

  it('still clears on an explicit null activity', () => {
    // The other arm: a producer that DID read the run and found it idle has to
    // be able to say so.
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: null }),
    ).toMatchObject({ activity: null });
  });

  it('reads the title a naming announce carries', () => {
    // `ChatTitleService` names a chat once its first turn ends, and sends it as
    // an activity-only announce — a null status, so the badge is left alone.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: null,
        activity: null,
        title: 'Fix Conflicts Worktree',
      }),
    ).toEqual({
      runId: 'r1',
      status: null,
      activity: null,
      title: 'Fix Conflicts Worktree',
    });
  });

  it('says nothing about the title on every other announce', () => {
    // Absent stays absent, like `awaiting` and `summary` beside it: an ordinary
    // settle must not be read as renaming the run to undefined.
    expect(
      parseRunStatus({ runId: 'r1', status: 'completed', activity: null }),
    ).not.toHaveProperty('title');
  });

  it('drops a blank or non-string title rather than clearing the name', () => {
    // A run is never UNnamed by this event, so an empty string is a skew to
    // ignore — applied, it would blank the sidebar row.
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: null, title: '' }),
    ).not.toHaveProperty('title');
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: null, title: 42 }),
    ).not.toHaveProperty('title');
  });
});

