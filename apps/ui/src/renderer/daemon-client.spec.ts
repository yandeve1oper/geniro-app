describe('DaemonClient browser relay', () => {
  const browserAgentRequest = vi.fn();
  const browserForgetRun = vi.fn();

  beforeEach(() => {
    browserAgentRequest.mockReset();
    browserForgetRun.mockReset().mockResolvedValue(undefined);
    vi.stubGlobal('window', {
      geniro: { browserAgentRequest, browserForgetRun },
    });
  });

  afterEach(() => {
    vi.unstubAllGlobals();
  });

  function run(overrides: Record<string, unknown>): Record<string, unknown> {
    return {
      id: 'r1',
      createdAt: '2026-01-01T00:00:00.000Z',
      archivedAt: null,
      ...overrides,
    };
  }

  it('announces browser_host on connect and not on a paired device', () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    fireConnect();
    fireConnect();
    expect(
      mocks.emit.mock.calls.filter(([event]) => event === 'browser_host'),
    ).toHaveLength(2);

    mocks.emit.mockClear();
    remote.paired = true;
    fireConnect();
    expect(mocks.emit).not.toHaveBeenCalledWith('browser_host');
  });

  it('relays a browser_request to main and answers browser_reply', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    const reply = { id: 'q1', ok: true, text: 'Opened' };
    browserAgentRequest.mockResolvedValueOnce(reply);
    const request = { id: 'q1', runId: 'r1', op: { kind: 'tabs' } };
    mocks.ref.any?.('browser_request', request);
    await flushMicrotasks();
    expect(browserAgentRequest).toHaveBeenCalledWith(request);
    expect(mocks.emit).toHaveBeenCalledWith('browser_reply', reply);
  });

  it('answers a refusal when the IPC throws', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    browserAgentRequest.mockRejectedValueOnce(new Error('no window'));
    mocks.ref.any?.('browser_request', { id: 'q2', runId: 'r1' });
    await flushMicrotasks();
    expect(mocks.emit).toHaveBeenCalledWith('browser_reply', {
      id: 'q2',
      ok: false,
      error: "Geniro's window could not run that browser operation",
    });
  });

  it('does not run a browser_request on a paired device', async () => {
    remote.paired = true;
    const client = new DaemonClient(handle, {});
    client.connect();
    mocks.ref.any?.('browser_request', { id: 'q3' });
    await flushMicrotasks();
    expect(browserAgentRequest).not.toHaveBeenCalled();
  });

  it('forgets a deleted run’s browser', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    mocks.ref.any?.('run_deleted', { runId: 'r9' });
    await flushMicrotasks();
    expect(browserForgetRun).toHaveBeenCalledWith('r9');
  });

  it('forgets an archived run’s browser once, and again after an unarchive', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    const archived = run({ archivedAt: '2026-02-01T00:00:00.000Z' });
    mocks.ref.any?.('runs_changed', { runs: [run({ id: 'live' }), archived] });
    await flushMicrotasks();
    expect(browserForgetRun.mock.calls).toEqual([['r1']]);

    mocks.ref.any?.('runs_changed', { runs: [archived] });
    await flushMicrotasks();
    expect(browserForgetRun).toHaveBeenCalledTimes(1);

    mocks.ref.any?.('runs_changed', { runs: [run({})] });
    mocks.ref.any?.('runs_changed', { runs: [archived] });
    await flushMicrotasks();
    expect(browserForgetRun).toHaveBeenCalledTimes(2);
  });

  it('forgets nothing on a paired device', async () => {
    remote.paired = true;
    const client = new DaemonClient(handle, {});
    client.connect();
    mocks.ref.any?.('run_deleted', { runId: 'r9' });
    mocks.ref.any?.('runs_changed', {
      runs: [run({ archivedAt: '2026-02-01T00:00:00.000Z' })],
    });
    await flushMicrotasks();
    expect(browserForgetRun).not.toHaveBeenCalled();
  });
});
